WHERE law_id = (SELECT id FROM laws WHERE law_no = 91 AND law_year = 2005 AND kind = 'law')
  AND article_no = 106 AND article_suffix_order = 0;

UPDATE article_versions SET
    body = $b085_1$يتبع فى تحصيل الضرائب والمبالغ الأخرى المستحقة بمقتضى هذا القانون أحكام القانون رقم 308 لسنة 1955 فى شأن الحجز الإدارى والأحكام المنصوص عليها فى هذا القانون .
وتسرى أحكام الفقرة السابقة على الشركات والمنشآت أيًا كان النظام القانونى المنشأة وفقًا له ، ويلغى كل حكم يخالف ذلك .$b085_1$,
    effective_from = '2007-01-21'::date,
    amended_by_law_no = 1,
    amended_by_law_year = 2007,
    change_note = $n085_1$أُضيفت فقرة ثانية بموجب المادة الأولى من القانون 1/2007 - مدّ نطاق سريان الفقرة الأولى (أحكام الحجز الإدارى فى التحصيل) ليشمل الشركات والمنشآت أياً كان شكلها القانونى، وإلغاء كل حكم يخالف ذلك.$n085_1$
WHERE article_id = (
    SELECT a.id FROM articles a JOIN laws l ON l.id = a.law_id
    WHERE l.law_no = 91 AND l.law_year = 2005 AND l.kind = 'law'
      AND a.article_no = 106 AND a.article_suffix_order = 0
) AND version_no = 1;

