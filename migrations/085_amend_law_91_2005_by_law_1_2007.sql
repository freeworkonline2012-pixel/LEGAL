    v_law_id uuid;
    v_art_body text;
    v_ver_body text;
    v_amended_no int;
    v_amended_year int;
    v_status text;
BEGIN
    SELECT id INTO v_law_id FROM laws WHERE law_no = 91 AND law_year = 2005 AND kind = 'law';
    IF v_law_id IS NULL THEN
        RAISE EXCEPTION 'migration 085: سجل قانون 91/2005 غير موجود - يجب تشغيل migration 076 أولاً.';
