UPDATE articles SET body = $b085_1$يتبع فى تحصيل الضرائب والمبالغ الأخرى المستحقة بمقتضى هذا القانون أحكام القانون رقم 308 لسنة 1955 فى شأن الحجز الإدارى والأحكام المنصوص عليها فى هذا القانون .
