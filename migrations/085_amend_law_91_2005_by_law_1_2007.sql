        RAISE EXCEPTION 'migration 085: نص المادة 106 (articles.body) لا يطابق المتوقع.';
    END IF;
    IF v_ver_body <> $vb085_1$يتبع فى تحصيل الضرائب والمبالغ الأخرى المستحقة بمقتضى هذا القانون أحكام القانون رقم 308 لسنة 1955 فى شأن الحجز الإدارى والأحكام المنصوص عليها فى هذا القانون .
وتسرى أحكام الفقرة السابقة على الشركات والمنشآت أيًا كان النظام القانونى المنشأة وفقًا له ، ويلغى كل حكم يخالف ذلك .$vb085_1$ THEN
        RAISE EXCEPTION 'migration 085: نص المادة 106 (article_versions.body) لا يطابق المتوقع.';
    END IF;
    IF v_amended_no <> 1 OR v_amended_year <> 2007 THEN
        RAISE EXCEPTION 'migration 085: amended_by_law_no/year للمادة 106 غير مطابق (متوقع 1/2007).';
    END IF;

