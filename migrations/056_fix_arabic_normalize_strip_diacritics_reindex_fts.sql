-- السبب الجذرى (مُثبَت بدليل مباشر، لا افتراض):
-- ═══════════════════════════════════════════════════════════════════════
-- اكتُشف هذا أثناء التحقيق فى فشل استشهاد العقوبة لخدمة الحوكمة (راجع
-- تقرير "إصلاح جذرى ثالث..." وتقرير "إصلاح جذرى رابع..." فى قاعدة معرفة
-- Projects لنفس اليوم). الفحص الحى (عبر سجلات Railway الفعلية) أظهر أن
-- المادة 15 (الفقرة 0) من قانون 80 لسنة 2002 — التى تنص حرفياً على عقوبة
-- مخالفة المواد 8 و9 و11 (وهى بالضبط الاستشهاد الصحيح المطلوب فى الحالة
-- المُختبَرة) — لم تصل إطلاقاً إلى قائمة مرشحى العقوبة، رغم رفع الحد
-- الأقصى للاسترجاع (migration 040) ورغم إصلاح تمرير article_suffix_order
-- (migration/كوميت سابق فى نفس اليوم). التشخيص المباشر لنص المادة كما هو
-- مخزَّن فعلياً (migrations/026_fix_aml_cft_law_80_2002.sql):
--
--   المادة 15/0: "يُعاقب بالحبس ..."   ← تحمل حركة الضمة (ُ) فوق الياء
--   المادة 15/1: "يعاقب بالحبس ..."    ← بلا أى تشكيل
--
-- استعلام fetchPenaltyCandidates() فى governance.service.ts يبحث عن الكلمة
-- المفتاحية "يعاقب" (بلا تشكيل) عبر:
--   to_tsvector('simple', arabic_normalize(body)) @@ to_tsquery('simple', 'يعاقب | ...')
--
-- ودالة arabic_normalize() (001_init.sql) كانت تُطبّع فقط الهمزات/الألف
-- المقصورة/التاء المربوطة (translate) — ولا تُزيل أى حركة تشكيل إطلاقاً.
-- النتيجة: to_tsvector('simple', 'يُعاقب...') ينتج lexeme حرفى "يُعاقب"
-- (بالحركة كجزء من النص) — وهو **ليس نفس النص** "يعاقب" الذى يبحث عنه
-- to_tsquery، فيفشل التطابق @@ بصمت تام، بلا أى خطأ أو تحذير.
--
-- تحقّق مباشر (محلياً، PostgreSQL 16 — نفس إصدار الإنتاج)، بنص المادتين
-- الحقيقى المخزَّن فعلياً:
--   art_15_0_matches (بالتشكيل، الدالة القديمة) = false  ← الخلل مُثبَت
--   art_15_1_matches (بلا تشكيل)                = true
--
-- ═══════════════════════════════════════════════════════════════════════
-- حجم المشكلة الفعلى (لماذا هذا إصلاح نظامى لا إصلاح مادة واحدة):
-- ═══════════════════════════════════════════════════════════════════════
-- فحص برمجى لكل نصوص المواد المزروعة عبر migrations/*.sql (12,907 كتلة نص)
-- أظهر أن 4,617 كتلة (~36%) تحمل حركة تشكيل أو تطويل (ـ) واحدة على الأقل،
-- موزَّعة على 45 ملف migration مختلف — أى: أى بحث نصى فى المنصة (خدمة
-- الحوكمة، المدقق القانونى للعقود، خدمة الأسئلة/الإجابات العامة) قد يُسقِط
-- بصمت أى من هذه المواد كلما تطابقت الكلمة المفتاحية تحديداً مع الجزء
-- المُشكَّل من النص. هذا يفسّر أيضاً — احتمالياً، بلا حاجة لإصلاح إضافى
-- الآن — حالات "لا نتيجة" غامضة سابقة عبر الخدمات الثلاث لم تُشخَّص وقتها.
--
-- ═══════════════════════════════════════════════════════════════════════
-- الإصلاح:
-- ═══════════════════════════════════════════════════════════════════════
-- 1) توسعة arabic_normalize() لإزالة حركات التشكيل العربى الأساسية
--    (فتحة/ضمة/كسرة/شدة/سكون/تنوين) وعلامة التطويل (ـ) بالإضافة للتطبيع
--    الحالى — قبل أى translate. الدالة IMMUTABLE كما كانت (سلوك نقى، بلا
--    اعتماد على حالة خارجية).
-- 2) REINDEX إلزامى للفهرسين المبنيين على هذه الدالة (idx_article_versions_fts
--    وidx_guidance_documents_fts) — توثيق PostgreSQL الرسمى صريح: تغيير
--    دالة IMMUTABLE مستخدَمة داخل فهرس تعبير (expression index) يترك
--    مدخلات الفهرس القديمة "متجمّدة" على السلوك القديم حتى REINDEX صريح؛
--    الاعتماد على إعادة حساب تلقائية غير مضمون البتة عبر خطط استعلام
--    مختلفة (Bitmap/Index scans) وأحجام جداول مختلفة — REINDEX هو الضمان
--    الوحيد الحتمى، وتكلفته مقبولة تماماً هنا (فهرسان فقط، حجم الجدول
--    محدود، ينفَّذ مرة واحدة ضمن نفس معاملة migration هذا الملف).
--
-- ⚠️ ملاحظة نطاق مقصودة: هذا الإصلاح **لا يمس** أى نص مخزَّن فعلياً فى
-- عمود body — فقط طبقة الفهرسة/البحث المُشتقة. النص القانونى الرسمى
-- (بتشكيله كما هو منشور فى الوقائع المصرية) يبقى محفوظاً حرفياً بلا أى
-- تعديل — وهذا مقصود: الدقة القانونية للنص المخزَّن تبقى غير قابلة للمساس،
-- فقط آلية المطابقة النصية أصبحت غير حساسة للتشكيل (وهو السلوك الصحيح
-- والمتوقَّع لأى محرك بحث نصوص عربية).
--
-- src/ingestion/normalize.ts (normalizeArabic/cleanText — المكافئ فى
-- TypeScript) عمداً **لم يُعدَّل** هنا: تلك الدالة تُستخدَم أيضاً لتطبيع
-- النص *قبل التخزين* فى خط التجميع (ingestion.service.ts, cleanText) —
-- توسعتها لإزالة التشكيل ستُغيّر محتوى النص القانونى المخزَّن فعلياً لكل
-- مادة تُستورَد مستقبلاً (قرار سياسة أوسع، منفصل تماماً عن إصلاح خلل بحث)،
-- بخلاف هذا الإصلاح الذى يقتصر على SQL/طبقة الفهرسة فقط ولا يغيّر أى بيانات
-- مخزَّنة. أى قرار بشأن تطبيع التشكيل عند التخزين نفسه يحتاج قراراً صريحاً
-- منفصلاً من رجل الأعمال، وليس جزءاً من إصلاح خلل بحث.

CREATE OR REPLACE FUNCTION arabic_normalize(input text) RETURNS text
LANGUAGE sql IMMUTABLE PARALLEL SAFE
AS $$
  SELECT translate(
    regexp_replace(lower(trim(input)), '[ًٌٍَُِّْٰـ]', '', 'g'),
    'أإآىةؤئ', 'ااايهوي'
  )
$$;

-- REINDEX إلزامى — بلا هذا، تبقى نتائج البحث غير حتمية (متوقفة على خطة
-- الاستعلام) لكل مادة موجودة مسبقاً فى قاعدة البيانات.
REINDEX INDEX idx_article_versions_fts;
REINDEX INDEX idx_guidance_documents_fts;
