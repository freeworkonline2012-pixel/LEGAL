-- ===== الجزء 2: guidance_documents (محتوى إرشادى غير مرقّم رسمياً) =====
CREATE TABLE IF NOT EXISTS guidance_documents (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  issuing_authority text,
  category text NOT NULL DEFAULT 'other'
    CHECK (category IN ('labor','rent','personal_status','traffic','consumer_protection','insurance','aml_cft','other')),
  related_law_id uuid REFERENCES laws(id) ON DELETE SET NULL,
  official_url text,
  issued_at date,
  quality_note text,
  body text NOT NULL,
  plain_summary text,
  embedding vector(1536),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_guidance_documents_url UNIQUE (official_url)
);
-- CREATE OR REPLACE TRIGGER (متاحة من Postgres 14، والإنتاج على 16) بدل CREATE
-- TRIGGER العادية — تتجنّب خطأ 'already exists' (42710) المتكرر الذى يظهر فى
-- سجلات كل نشر لاحق لـ 001_init.sql (trg_users_updated_at) بسبب عدم دعم
-- CREATE TRIGGER IF NOT EXISTS أصلاً — حل دائم هنا بدل تكرار نفس الضجيج.
CREATE OR REPLACE TRIGGER trg_guidance_documents_updated_at BEFORE UPDATE ON guidance_documents
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
CREATE INDEX IF NOT EXISTS idx_guidance_documents_fts
  ON guidance_documents USING GIN (to_tsvector('simple', arabic_normalize(body)));
CREATE INDEX IF NOT EXISTS idx_guidance_documents_related_law
  ON guidance_documents(related_law_id);

