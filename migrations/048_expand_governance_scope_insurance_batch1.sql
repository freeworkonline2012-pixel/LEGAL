-- التحقق: قابلة لإعادة التشغيل بأمان (idempotent).

BEGIN;

UPDATE laws SET governance_scope = true
WHERE country_code = 'EG'
  AND category = 'insurance'
  AND (law_no, law_year) IN (
    (155, 2024), (15, 2025), (69, 2025), (70, 2026), (90, 2025), (114, 2021),
    (229, 2025), (236, 2024), (237, 2024), (265, 2025), (278, 2024), (320, 2025),
    (3973, 2025)
  )
  AND governance_scope IS DISTINCT FROM true;

DO $verify$
DECLARE
  v_count int;
  v_expected int := 45;
  v_ins_count int;
  v_ins_expected int := 23;
BEGIN
  SELECT count(*) INTO v_count FROM laws WHERE governance_scope = true;
  SELECT count(*) INTO v_ins_count FROM laws WHERE governance_scope = true AND category = 'insurance';
  IF v_count <> v_expected OR v_ins_count <> v_ins_expected THEN
    RAISE WARNING 'governance_scope: % قانوناً موسوماً (منها % من insurance)، المتوقَّع % (منها %) — تحقّق يدوياً', v_count, v_ins_count, v_expected, v_ins_expected;
  ELSE
    RAISE NOTICE 'governance_scope: % قانوناً موسوماً كما هو متوقَّع (منها % من insurance — اكتملت مراجعة WEAK لكل الفئات الأربع)', v_count, v_ins_count;
  END IF;
END;
$verify$;

COMMIT;
