-- ===== تنظيف غير مشروط لأى صف يتيم خارج البنية النظيفة (يحمى من التلوث فى
-- كل نشر مستقبلى) =====
--
-- اكتُشف أثناء اختبار محلى ثلاثى (3 تشغيلات متتالية لسلسلة الهجرات الكاملة،
-- كما تقتضى منهجية المشروع): إعادة تشغيل هذه الهجرة ضمن سلسلة كاملة (وهو ما
-- يحدث فى *كل* نشر إنتاجى فعلياً — راجع scripts/run-migration.js الذى يعيد
-- تطبيق كل ملفات migrations/*.sql بالترتيب فى كل تشغيل، لا 054 فقط) يجعل
-- migrations/006 يُعيد إدراج مادته التالفة القديمة (article_no=2 بلا
-- article_suffix_order صريح، أى القيمة الافتراضية 0) من جديد. هذا الصف لا
-- يصطدم بقيد ON CONFLICT (law_id, article_no, article_suffix_order) لأى من
-- كتل الإدراج الـ21 أعلاه — لأن الفصل 2 الجديد يشغل فقط article_suffix_order
-- من 1 إلى 6 (فروع فرعية مسمّاة)، ولا يشغل أبداً 0 — فتُدرَج نسخة تالفة
-- إضافية بصمت بلا أى خطأ، ويُخدَع فحص العتبة أعلاه (> 15 يعتبرها "مُصلَحة
-- بالفعل") فيتركها للأبد. هذا عطل حقيقى فى الاتساق الذاتى (idempotency) كان
-- سيُصيب الإنتاج فى النشر الثانى مباشرة لولا اكتشافه بالاختبار المحلى قبل
-- التسليم.
--
-- الحل الجذرى (لا حل مؤقت): تعريف صريح للمجموعة الوحيدة الصحيحة من أزواج
-- (article_no, article_suffix_order) لهذا القانون تحديداً، وحذف أى صف خارجها
-- دون شرط، فى كل مرة تُطبَّق فيها هذه الهجرة — لا اعتماد هش على تصادم
-- ON CONFLICT وحده لصد صفوف قديمة قد تُعاد زراعتها من هجرات سابقة فى نفس
-- السلسلة. هذا يجعل الهجرة ذاتية الشفاء (self-healing) بصرف النظر عن كم مرة
-- تُعاد سلسلة الهجرات بالكامل مستقبلاً.
DO $cleanup100$
DECLARE
  v_law_id uuid;
  v_deleted int;
BEGIN
  SELECT id INTO v_law_id FROM laws WHERE law_no = 100 AND law_year = 2020;
  IF v_law_id IS NULL THEN
    RETURN;
  END IF;

  DELETE FROM articles
  WHERE law_id = v_law_id
    AND (article_no, article_suffix_order) NOT IN (
      (1,-1),(2,-1),(3,-1),(4,-1),
      (1,1),(1,2),(1,3),(1,4),
      (2,1),(2,2),(2,3),(2,4),(2,5),(2,6),
      (3,0),(4,0),(5,0),
      (6,1),(6,2),
      (7,0),(8,0)
    );
  GET DIAGNOSTICS v_deleted = ROW_COUNT;
  IF v_deleted > 0 THEN
    RAISE NOTICE '100/2020: حُذف % صف يتيم/تالف خارج البنية النظيفة النهائية (تنظيف غير مشروط، يحمى من إعادة زراعة migrations/006 فى كل نشر لاحق).', v_deleted;
  END IF;
END;
$cleanup100$;

