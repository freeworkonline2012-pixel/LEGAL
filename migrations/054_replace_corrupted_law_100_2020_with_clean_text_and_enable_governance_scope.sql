DO $fix100$
DECLARE
  v_law_id uuid;
  v_article_count int;
BEGIN
  SELECT id INTO v_law_id FROM laws WHERE law_no = 100 AND law_year = 2020;

  IF v_law_id IS NULL THEN
    RAISE WARNING '100/2020: لم يُعثر على الصف فى جدول laws — تخطٍّ، يحتاج مراجعة يدوية.';
    RETURN;
  END IF;

  SELECT count(*) INTO v_article_count FROM articles WHERE law_id = v_law_id;

  IF v_article_count <= 5 THEN
    DELETE FROM articles WHERE law_id = v_law_id;
    RAISE NOTICE '100/2020: حُذفت % مادة تالفة قديمة، جارٍ الإدراج النظيف.', v_article_count;
  ELSIF v_article_count > 15 THEN
    RAISE NOTICE '100/2020: يبدو مُصلَحاً بالفعل (% مادة) — تخطٍّ (idempotent).', v_article_count;
  ELSE
    RAISE WARNING '100/2020: عدد مواد غير متوقَّع (%) — تحقّق يدوياً قبل المتابعة.', v_article_count;
  END IF;
END;
$fix100$;

