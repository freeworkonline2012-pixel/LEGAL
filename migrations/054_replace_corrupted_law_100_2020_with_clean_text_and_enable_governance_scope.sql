  IF v_article_count < 18 THEN
    RAISE WARNING '100/2020: بعد الهجرة % مادة فقط (متوقَّع 21) — راجع يدوياً.', v_article_count;
  ELSE
    RAISE NOTICE '100/2020: % مادة و% نسخة بعد الهجرة.', v_article_count, v_version_count;
  END IF;

  UPDATE laws SET governance_scope = true, enacted_at = COALESCE(enacted_at, '2020-06-23')
  WHERE id = v_law_id;

