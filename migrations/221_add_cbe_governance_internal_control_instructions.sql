أهم متطلبات السياسات الداخلية المتعلقة بالحوكمة الواجب توافرها لدى البنوك كحد أدنى: أولاً: سياسة ادارة تعارض المصالح وتتضمن ما يلي كحد أدنى:

1- تحديد الحالات التي قد تؤدي إلى وجود شبهة تعارض في المصالح بما قد يحقق خسائر لأي من الأطراف المعنية متضمنة عملاء البنك.

2- إرساء الإجراءات الواجب إتباعها للتعامل مع حالات تعارض المصالح متضمنة تحديد آلية وإجراءات الإفصاح التي يتعين إتباعها بما فيها الإفصاح عن تلقي الهدايا، مع وجود آلية للتوثيق والاحتفاظ ببيانات تلك الحالات.

3- الإفصاح للأطراف المعنية وأصحاب المصالح بما فيهم عملاء البنك عن حالات التعارض في المصالح وابلاغهم عن الإجراءات المتخذة في هذا الشأن.

4- تحديد حالات تعارض المصالح لكل من أعضاء مجلس الإدارة والإدارة العليا والعاملين.

5- تحديد الجهة المنوط بها الرقابة على تعارض المصالح بالبنك.

6- تعريف تعارض المصالح، ودرجة القرابة المباشرة، والنماذج المستخدمة، والأطراف ذوي العلاقة، والإجراءات التصعيدية.

7- تعاملات الداخليين والحفاظ على سرية المعلومات والبيانات (إساءة استخدام المعلومات من قبل موظفي البنك).

8- فحص الاتفاقيات والمعاملات المبرمة التي قد ينتج عنها تعارض في المصالح خاصة فيما يتعلق بأعضاء مجلس الإدارة والإدارة العليا والمساهمين وكافة الأطراف ذوي المصالح. ثانياً: سياسة المسئولية المجتمعية وتتضمن ما يلي كحد أدنى:

1- الأهداف المرجوة من سياسة المسئولية المجتمعية والإجراءات التي تُتخذ للحفاظ على مصالح كافة الأطراف المعنية.

2- القنوات والأدوات التي يستخدمها البنك لتعزيز المسئولية المجتمعية، على سبيل المثال التمويل، والتعاون مع الجهات الأخرى ذات العلاقة، وتضمين المسئولية المجتمعية ببيئة العمل داخل البنك، والتنمية المستدامة... إلخ.

3- إجراءات البنك لقياس وتحديد أثر أعماله على المجتمع والبيئة وكذا كيفية قيامه بتعزيز الأعمال التي تؤثر إيجاباً عليهما وكذا سمعة البنك وإدارته.

4- المعايير التي يقوم البنك على أساسها باختيار الجهات التي يقوم بدعمها لتحقيق الأهداف المرجوة من سياسة المسئولية المجتمعية.

ثالثاً: سياسة الإبلاغ عن المخالفات والممارسات غير المشروعة وتتضمن ما يلي كحد أدنى:

1- القنوات المتاحة للإبلاغ، مع تحديد الحالات التي يتعين الإبلاغ عنها للبنك المركزي مباشرة ووضع معايير محددة لذلك، وكذا إجراءات التحقق من البلاغات، وإجراءات حماية المُبلغين حال طلبهم لذلك، والإجراءات المتبعة للتحقيق في الحالات المُبلغ عنها، واتخاذ القرارات بشأنها.

2- العمل على التأكد من عدم قيام أي من العاملين بالبنك بإلحاق الضرر بالمُبلغين والإجراءات التأديبية المحددة حال حدوث ذلك.

3- سياسة البنك فيما يخص الاحتفاظ بالبلاغات المقدمة.

4- تحديد الأشخاص المنوط بهم إرساء سياسات وإجراءات الإبلاغ بالبنك، وكذا المسئولين عن التعامل مع حالات الإبلاغ، متضمنة اللجان التي تختص بالنظر فيها.

5- قيام البنك بإبلاغ البنك المركزي مباشرة في حالة عدم قيام البنك بمعالجة المخالفات / الممارسات غير المشروعة خلال فترة زمنية محددة.

