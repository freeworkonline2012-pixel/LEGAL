المقدمة

تم إعداد هذه التعليمات بما يتوافق مع أحكام قانون البنك المركزي والجهاز المصرفي الصادر بالقانون رقم 194 لسنة 2020 (ويشار إليه فيما يلي بقانون البنك المركزي) بهدف تعزيز وتطوير مفهوم الحوكمة ونظم الرقابة الداخلية بالقطاع المصرفي، وذلك في ضوء أهميتهما في الحفاظ على الاستقرار المصرفي ومواجهة التحديات المختلفة.

وتنقسم التعليمات الى جزئين، الجزء الأول يتعلق بالحوكمة التي تنظم العلاقة بين مجلس إدارة البنك والإدارة العليا وحملة الأسهم وأصحاب المصالح الأخرى، وتحدد واجبات ومسئوليات كل منهم، بالإضافة إلى تحديد النهج الذي يتبعه المجلس والإدارة العليا لتوجيه البنك ومباشرة شئونه وأنشطته، وكذا الأسس المتبعة للإشراف على الأداء بما يؤدي إلى الاستخدام الأمثل لموارد البنك والمحافظة على استقراره. أما بالنسبة للجزء الثاني فيشمل ضرورة توافر نظاماً شاملاً للرقابة الداخلية بكل بنك يتم بمقتضاه مراقبة ومراجعة كافة أنشطة وعمليات البنك بشكل مستمر من خلال كل من مجلس الإدارة واللجان المنبثقة عنه، والإدارة العليا، وكافة العاملين بالبنك، وبمراعاة خضوع النظام للتقييم والتطوير الدوري.

نطاق التطبيق

تسري هذه التعليمات على كافة البنوك العاملة بجمهورية مصر العربية، ويتعين على فروع البنوك الأجنبية الالتزام بهذه التعليمات بالقدر الذي ينطبق عليها، أو بتلك المطبقة بالمركز الرئيسي للبنك، أيهما أكثر تحفظاً، وفي حالة وجود تعارض فيما بينهما، يجب تقديم المبررات اللازمة والحصول على موافقة البنك المركزي المصري.

يتعين على كل بنك التأكد من التزام كافة فروعه الخارجية بهذه التعليمات بالقدر الذي لا يتعارض مع القوانين والتعليمات المنظمة لها بالدولة التي تعمل بها، وفي حالة وجود أي تعارض يتعين الحصول على موافقة البنك المركزي المصري على كيفية معالجة الأمر، وكذا إخطار المركز الرئيسي للبنك.

ثانياً: الرقابة الداخلية

1- مفهوم الرقابة الداخلية

هي العملية التي يتم بمقتضاها مراقبة ومراجعة كافة أنشطة وعمليات البنك بشكل مستمر من خلال كل من مجلس الإدارة والإدارة العليا، واللجان المشكلة بالبنك والعاملين به باعتبارهم جزء من منظومة متكاملة تهدف إلى تدعيم مستوى الرقابة الداخلية بالبنك. ويقع على عاتق مجلس الإدارة والإدارة العليا مسئولية إرساء ثقافة الرقابة الداخلية بما يجعل كافة العاملين على اختلاف مستوياتهم الإدارية مدركين لطبيعة دور ومسئولية كل منهم.

2- أهداف الرقابة الداخلية

تهدف الرقابة الداخلية إلى التحقق من مدى كفاءة إدارة كافة أنشطة وعمليات البنك بما يحقق الاستخدام الأمثل لموارده وإدارة أصوله بغرض تعظيم الأرباح وتجنب الخسائر، وذلك من خلال التحقق مما يلي كحد أدنى:

2-1 كفاءة وظيفة الالتزام وكذا مدى توافق أنشطة وعمليات البنك مع القوانين والتعليمات الرقابية، واتساقها مع السياسات والإجراءات واللوائح الداخلية بالبنك.

2-2 كفاءة وظيفة إدارة المخاطر وإتباع الإجراءات المناسبة للحد من المخاطر.

2-3 كفاءة وفاعلية وظيفة المراجعة الداخلية بما يشمل المراجعة على كافة أنشطة البنك.

2-4 فاعلية نظم إدارة المعلومات ودقة وكفاية التقارير التي يتم اعدادها بما يدعم عملية اتخاذ القرار.

3- عناصر الرقابة الداخلية

3-1 يتعين على البنوك مراعاة ما يلي لضمان كفاءة نظام الرقابة الداخلية:

3-1-1 فاعلية دور مجلس الإدارة والإدارة العليا بالبنك.

3-1-2 تناسق واستقلالية الوظائف الرقابية (المراجعة الداخلية، والمخاطر، والالتزام).

3-1-3 كفاية نظم الرقابة على المخاطر.

3-1-4 كفاءة نظم المعلومات وقنوات الاتصال بالبنك.

3-1-5 كفاءة إجراءات الرقابة الداخلية المتبعة لضمان تحقيق الرقابة الثنائية والفصل في المهام.

3-1-6 مراجعة سياسات وإجراءات الرقابة الداخلية وتقييم مدى صلاحيتها بصفة دورية، واتخاذ الإجراءات التصحيحية اللازمة في هذا الشأن.

4- مسئوليات مجلس الإدارة

4-1 الاعتماد والمراجعة الدورية لمدى كفاءة وفاعلية السياسات الخاصة بالرقابة الداخلية ومناقشتها مع مسئولي الوظائف الرقابية بالبنك، وذلك لضمان وجود نظام ملائم وفعال للرقابة الداخلية.

4-2 التأكد من أن الهيكل التنظيمي يعكس الفصل في المهام بين الوظائف الرقابية والوظائف التنفيذية وقطاعات الأعمال المختلفة وكذا تجنب تعارض المصالح فيما يتعلق بتنفيذ العمليات والموافقة عليها، وذلك بما يحقق حُسن توزيع السلطات والمسئوليات ورفع التقارير.

4-3 التأكد من تطبيق مبدأ الرقابة الثنائية في كل نشاط على حده.

4-4 متابعة تنفيذ الإجراءات التصحيحية التي أسفرت عنها ملاحظات المراجعة الداخلية ومراقبي الحسابات والبنك المركزي بشأن تقييم نظام الرقابة الداخلية وذلك بالتنسيق مع لجنة المراجعة والإدارة العليا.

4-5 اعتماد اختيار مسئولي الوظائف الرقابية بالبنك (المخاطر والمراجعة والالتزام)، والإشراف على كفاءة أدائهم وذلك من خلال التقييم السنوي الذي يتم لرؤساء تلك القطاعات من قبل لجان المجلس ذات الصلة.

4-6 التحقق من أن السياسات تكفل عرض كافة المنتجات والعمليات على مسئولي المخاطر والالتزام بعد دراستها من قبل مسئولي القطاعات المعنية قبل عرضها على اللجان ذات الصلة والمجلس.

4-7 التأكد من وجود نظام معلومات فعال يضمن كفاءة التقارير وتوافر المعلومات الهامة في الوقت المناسب إلى كافة المستويات الإدارية.

4-8 يتمثل إطار الرقابة الداخلية في خطوط الدفاع الأربعة الآتية:

4-8-1 خط الدفاع الأول:

يتمثل في القطاعات التنفيذية (على سبيل المثال لا الحصر: قطاع المؤسسات والشركات، والتجزئة المصرفية، وتمويل الشركات متناهية الصغر والصغيرة والمتوسطة، وقطاع الاستثمار،... إلخ)، ويقع على عاتقها مسئولية الالتزام بالسياسات المعتمدة بهدف الحد من المخاطر المتعلقة بأنشطتها مع تحديد والاقرار عن أي مخاطر بصفة مستمرة.

4-8-2 خط الدفاع الثاني:

يتمثل في قطاعي المخاطر والالتزام ويعاونهم في هذا الشأن القطاعات الداعمة بالبنك (على سبيل المثال لا الحصر: القانونية، وتكنولوجيا المعلومات، والموارد البشرية، وأمن المعلومات والقطاع المالي... إلخ).

ويجب على قطاع المخاطر بالبنك تحديد وتقييم والرقابة على المخاطر على مستوى البنك ككل، ويكون على قطاع الالتزام التأكد من التزام البنك بكافة المتطلبات القانونية والرقابية، مع مراعاة استقلالية تلك القطاعات عن القطاعات التنفيذية من خلال التبعية المباشرة للجان المجلس المعنية.

4-8-3 خط الدفاع الثالث:

يتمثل في قطاع المراجعة الداخلية الذي يقوم بإجراء مراجعة شاملة مستقلة للتأكد من توافر السياسات والإجراءات المناسبة لكافة أعمال البنك وكذا الالتزام بها ويشمل هذا التأكيد على فعالية خطي الدفاع الأول والثاني، على أن يكون هذا القطاع مستقلاً عن كافة قطاعات البنك.

4-8-4 خط الدفاع الرابع:

يتمثل في مراقبي الحسابات الخارجيين والبنك المركزي بحيث تعتبر أعمالهما مراجعة إضافية مستقلة للبنك للتأكد من مدى التزامه بكافة المتطلبات القانونية والرقابية.

5- مسئوليات الإدارة العليا

5-1 اعداد وتنفيذ ومراجعة سياسات وخطط العمل الخاصة بقطاعات الرقابة الداخلية واعتمادها من مجلس الإدارة خاصة فيما يتعلق بإدارة المخاطر التي قد يتعرض لها البنك وذلك بما يتوافق مع القوانين والتعليمات الرقابية.

5-2 تقييم ومتابعة مدى كفاءة نظام الرقابة الداخلية بالبنك، والتأكد من مدى فاعليته لإحكام الرقابة على كافة العمليات المصرفية بشكل مستمر، وإخطار مجلس الإدارة في حالة مخالفة أي من إجراءات الرقابة الداخلية أو المتطلبات الرقابية أو القانونية.

5-3 رفع التوصيات لمجلس الإدارة بشأن ما يتعلق بالتغييرات المطلوبة في الهيكل التنظيمي أو في السياسات الخاصة بتيسير العمل داخل البنك، وكذا التغيرات الجوهرية في حجم واتجاه المخاطر وأثر ذلك على الإيرادات وسلامة المركز المالي للبنك.

6- قطاعات الرقابة الداخلية

تتمثل الرقابة الداخلية في قطاعات المراجعة الداخلية، والمخاطر والالتزام، ويتعين التأكد من استقلالية مهام مسئولي تلك القطاعات عن بعضهم البعض، وكذا عن باقي قطاعات البنك، ويكون الاتصال مباشر بين القطاعات الرقابية ومجلس الإدارة ولجانه، كما يتعين على مسئولي تلك القطاعات - من خلال لجان المجلس ذات الصلة - إخطار مجلس الإدارة بأي مخالفات تم تحديدها من قبلهم. وفيما يلي مهام ومتطلبات القطاعات المشار إليها:

6-1 قطاع المراجعة الداخلية

6-1-1 يلتزم كل بنك بوضع ميثاق عمل لقطاع المراجعة الداخلية ومراجعته وتطويره بصفة دورية وعرضه على لجنة المراجعة واعتماده من مجلس الإدارة، ويجب أن يشمل بوجه عام أهداف وغرض القطاع والمهام المسندة إليه وكذا تحديد واضح لصلاحيات ومسئوليات العاملين به ومعايير الأداء، على أن يشمل نطاق عمل المراجعة الداخلية كافة أنشطة البنك بما فيها المعاملات مع مقدمي الخدمات وجهات الإسناد الخارجية (التعهيد).

6-1-2 يجب أن تتسم وظيفة المراجعة الداخلية بالاستقلالية التامة عن الأنشطة التي يتم مراجعتها ويتم ذلك من خلال الهيكل التنظيمي للبنك والسلطات المخولة لهذه الوظيفة مما يدعم قدرة القائمين عليها على ممارسة مهام عملهم بموضوعية وحيادية تامة وبما يضمن سهولة حصولهم على المعلومات الكافية التي تمكنهم من أداء مهامهم على أكمل وجه، ويتبع قطاع المراجعة الداخلية لجنة المراجعة ويقوم برفع تقاريره مباشرةً إليها، حيث تقوم بدورها برفع تلك التقارير إلى مجلس الإدارة بالبنك.

6-1-3 يجب أن يتوافر لدى البنك خطة سنوية للمراجعة الداخلية تحدد نطاق ودورية المراجعة كحد أدنى ويتم اعتمادها ومتابعتها من قبل لجنة المراجعة، مع مراعاة أن يتم مراجعة أعمال كل إدارة بالبنك بحد أقصى مرة كل ثلاث سنوات وفقا لدرجة المخاطر، ويجب أن تخضع تلك الخطة وكافة توصياتها لمتابعة دورية من قبل لجنة المراجعة.

6-1-4 يقع على عاتق رئيس قطاع المراجعة الداخلية مسئولية أداء قطاعه وتقييم كفاءة العاملين به والتحقق من اتفاقه مع المعايير السائدة للمراجعة الداخلية وميثاق سلوك العمل المصرفي.

6-1-5 يتعين على رئيس قطاع المراجعة الداخلية التواصل مع البنك المركزي للإخطار بالقرارات والتطورات ذات التأثير على المركز المالي للبنك ومناقشة الإجراءات المتخذة ومتابعة معالجة البنك لها وفقاً للإطار الزمني المتفق عليه.

6-1-6 تلتزم البنوك بالحصول على موافقة البنك المركزي على تعيين رئيس قطاع المراجعة الداخلية وفقاً للقواعد المنظمة في هذا الشأن، وكذا إبلاغه لدى ترك العمل أو انهاء الخدمة، كما يتعين الافصاح عن أسباب الموافقة على قرار الاستقالة أو الإقالة، وذلك بعد موافقة مجلس إدارة البنك.

6-1-7 يتعين على العاملين بقطاع المراجعة الداخلية التمتع بالكفاءة والخبرة العملية والالتزام بالمعايير المهنية من استقلالية ونزاهة بما في ذلك الحفاظ على سرية المعلومات المتاحة لهم وتجنب تعارض المصالح، مع ضرورة تقييم تلك الخبرات دورياً وتوافر منهجية لتدريب العاملين بشكل مستمر.

6-1-8 يتولى قطاع المراجعة الداخلية المهام الرئيسية التالية كحد أدنى:

6-1-8-1 تقييم مدى كفاية السياسات والإجراءات الداخلية في ضوء التطورات الرقابية وتطورات السوق والتزام كافة القطاعات بها ومدى فاعلية تطبيقها.

6-1-8-2 متابعة الإجراءات التصحيحية المتخذة في ضوء ملاحظات قطاع المراجعة الداخلية ومراقبي الحسابات الخارجيين والبنك المركزي.

6-1-8-3 تقييم مدى كفاية نظام الرقابة الداخلية بالبنك (بما يتضمن قطاعي المخاطر والالتزام)، ورفع التقارير بالملاحظات ذات الصلة.

6-1-9 يتعين على كل بنك إجراء تقييمات خارجية للمراجعة الداخلية مرة واحدة على الأقل كل خمس سنوات بواسطة جهة خارجية مستقلة بعد الحصول على موافقة البنك المركزي، كما يتم موافاة البنك المركزي بنسخة من تقرير التقييم بعد العرض على مجلس إدارة البنك ولجنة المراجعة مرفقاً به خطط الإجراءات التصحيحية للتوصيات التي تضمنها التقرير.

6-1-10 يتعين التأكد من قيام مراقبي الحسابات بإعداد تقرير تفصيلي يتضمن مدى كفاية نظام الرقابة الداخلية في البنك بجميع مستوياته وموافاة البنك المركزي بنسخة منه وذلك وفقاً لأحكام قانون البنك المركزي والتعليمات الصادرة في هذا الشأن.

6-2 المراجعة على فروع البنك بالخارج

يجب على البنك مراعاة اتخاذ مجموعة من التدابير الرقابية بشأن فروعه بالخارج، بالقدر الذي لا يتعارض مع القوانين السارية في البلد المضيف، بحيث تتضمن ما يلي كحد أدنى:

6-2-1 التأكد من توافق أنشطة فروع البنك بالخارج مع السياسات والأهداف الاستراتيجية للبنك أو المجموعة ككل.

6-2-2 تلتزم إدارة المراجعة المركزية للبنك أو المجموعة بإجراء مراجعة داخلية في إطار قوانين البلد المضيف على الفروع بالخارج بصفة دورية (كل ثلاث سنوات كحد أقصى).

6-2-3 التأكد من التزام فروع البنك بالخارج بكافة التعليمات السارية بالدولة المضيفة التي يعمل بها، وكذا التزامه بتعليمات البنك المركزي المصري.

6-2-4 التحقق من قيام الفروع بالخارج بإجراء مراجعة داخلية وإرسال تقارير دورية عن ذلك لإدارة المراجعة بالمركز الرئيسي بالبنك أو المجموعة.

6-2-5 تلتزم البنوك بموافاة قطاع الرقابة والإشراف بالبنك المركزي بكافة التقارير الرقابية المعدة بصفة دورية عن فروعها بالخارج.

6-3 علاقة المراجعة الداخلية بمراقبي الحسابات

6-3-1 تدعم أعمال مراقبي الحسابات جودة وتطوير نظام الرقابة الداخلية بالبنك وذلك من خلال توصياتهم وكذا المناقشات التي تتم مع الإدارة العليا ومجلس الإدارة أو لجنة المراجعة، أخذاً في الاعتبار أن أعمال المراجعة الداخلية تساهم في تحديد طبيعة وتوقيت ونطاق المراجعة الخارجية، ويظل المراجع الخارجي هو المسئول الأول عن إبداء الرأي في مدى صحة القوائم المالية للبنك.

6-3-2 يجب إخطار مراقبي الحسابات بتقارير المراجعة الداخلية ذات الصلة، وإبقائه على علم بأي أمر مهم يلفت انتباه المراجعة الداخلية، كما يجب إخطاره بالأمور الجوهرية التي تُعد ذات حيثية بالنسبة للبنك المركزي، ويقوم المراجع الخارجي بإبلاغ رئيس قطاع المراجعة الداخلية بأي من الأمور الهامة التي قد تؤثر سلباً على عمل قطاع المراجعة الداخلية.

6-3-3 يجب على قطاع المراجعة الداخلية التنسيق مع مراقبي الحسابات خاصةً عند مناقشة التوصيات الخاصة بتطوير نظام الرقابة الداخلية مع الإدارة العليا ومجلس الإدارة ولجنة المراجعة.

6-3-4 مراعاة وجود اتصال مباشر بين مراقبي الحسابات ولجنة المراجعة وإرسال التقارير مباشرة لها.

6-3-5 يتعين التنسيق بين قطاع المراجعة الداخلية ومراقبي الحسابات ومناقشة الأنشطة المعرضة للمخاطر ونقاط الضعف التي تم الوقوف عليها والإجراءات المتخذة في هذا الشأن.

6-3-6 يتعين تعظيم الاستفادة من نتائج أعمال مراقبي الحسابات وقطاعات الرقابة الداخلية أخذاً في الاعتبار الملاحظات الواردة بتقارير مراقبي الحسابات للبنك بما يساعد على التحقق من صحة المعلومات المقدمة بشأن عمليات البنك وأدائه.

6-3-7 ضرورة تعزيز دور مراقبي الحسابات بما يضمن التأكد من أن القوائم المالية تعكس أداء البنك في كافة النواحي الهامة بما فيها الالتزام بأسس الحوكمة والرقابة الداخلية، وتوضح مركزه المالي الحقيقي.

6-4 قطاع الالتزام

6-4-1 يتولى قطاع الالتزام إدارة مخاطر الالتزام على مستوى البنك وتكون تبعية هذا القطاع المباشرة للجنة المراجعة، على أن يقوم مسئول الالتزام برفع تقاريره مباشرةً إلى لجنة المراجعة والتي تقوم بدورها برفع التقارير إلى مجلس الإدارة.

6-4-2 يجب أن يتوافر لدى البنوك سياسة للالتزام معتمدة من مجلس الإدارة تهدف إلى التأكد من الالتزام بالقوانين والتعليمات الرقابية فضلاً عن سياسات وإجراءات البنك، والتحقق من تعميمها على جميع العاملين بالبنك كل فيما يخصه.

6-4-3 ينبغي ألا يكون رئيس قطاع الالتزام مسئولاً عن أي وظائف رقابية أو تنفيذية أخرى بالبنك، وتلتزم البنوك بالحصول على موافقة البنك المركزي المسبقة على تعيينه، وكذا إبلاغ البنك المركزي لدى ترك العمل أو انهاء الخدمة، كما يتعين الافصاح عن أسباب الموافقة على قرار الاستقالة أو الإقالة، وذلك بعد موافقة مجلس إدارة البنك.

6-4-4 يتولى قطاع الالتزام المهام والمسئوليات التالية كحد أدنى:

6-4-4-1 إعداد الخطة السنوية للالتزام ومتابعتها بصفة دورية وعرضها على لجنة المراجعة للاعتماد، والتأكد من مدى التزام كافة أنشطة البنك بالقوانين والتعليمات الرقابية السارية والسياسات والإجراءات الداخلية، مع اتخاذ الإجراءات المناسبة لضمان الابلاغ عن المخالفات ورفع التقارير عنها للجنة المراجعة ومجلس الإدارة في الوقت المناسب.

6-4-4-2 المتابعة المستمرة لمدى فاعلية الإجراءات التصحيحية المتخذة لتصويب أوجه القصور فيما يخص الالتزام ورفع تقارير دورية عنها للجنة المراجعة ومجلس الإدارة.

6-4-4-3 تلقي شكاوى العاملين بالبنك والتحقق منها في إطار سياسة الإبلاغ عن المخالفات والممارسات غير المشروعة.

6-4-4-4 التأكد من توافق المنتجات الجديدة وكافة انشطة البنك مع السياسات والاجراءات الداخلية، وكذا القوانين والتعليمات السارية ذات الصلة.

6-4-4-5 التأكد من المام العاملين بالبنك بالقوانين والضوابط والتعليمات الرقابية السارية والالتزام بها.

6-4-4-6 وضع آلية لدراسة أي تعديلات على القوانين والتعليمات الرقابية السارية، وتقييم مدى تأثيرها على أنشطة البنك وآلية الالتزام بها، مع إبلاغ لجنة المراجعة والعاملين المعنيين ومجلس الإدارة بتلك التغييرات.

6-4-4-7 التأكد من الالتزام بالقوانين والضوابط الخاصة بمكافحة غسل الأموال وتمويل الإرهاب من خلال وجود نظام آلي ورقابي فعال لمتابعة أي عمليات أو عملاء مشتبه فيهم.

6-4-4-8 إجراء تقييم دوري لمخاطر الالتزام على مستوى البنك وعرض نتائجه على لجنة المراجعة ومجلس الإدارة.

6-5 قطاع المخاطر

6-5-1 يتولى قطاع المخاطر تحديد وقياس ومتابعة والرقابة على المخاطر التي قد يتعرض لها البنك بالإضافة لتحديد اتجاهاتها وتطورها والحد منها، وكذا إعداد سياسة للمخاطر وإعداد تقارير عن كافة أنواع المخاطر لكل الأنشطة على مستوى البنك أو المجموعة ككل، أخذاً في الاعتبار درجة واحتمالية التداخل بين أنواع المخاطر المختلفة وبما يتوافق مع مستوى المخاطر المقبول فضلاً عن الحدود القصوى للمخاطر المعتمدة من قبل مجلس الإدارة، وتكون تبعية هذا القطاع المباشرة للجنة المخاطر ويتم رفع التقارير لها من قبل رئيس قطاع المخاطر وتقوم بدورها برفع تلك التقارير إلى مجلس الإدارة، ويكون قطاع المخاطر مسئولاً عن الآتي:

6-5-1-1 تحديد المنتجات والخدمات والأنشطة والقطاعات المستهدفة ومعايير المخاطر المقبولة لكل منها وكذا آليات التسعير الخاصة بها.

6-5-1-2 وجود نظام فعال لتحديد وقياس ومتابعة المخاطر بهدف تقييم أنواعها واتجاهاتها.

6-5-1-3 التأكد من تحديد وتوثيق مستويات المخاطر المقبولة بالبنك وكذا اقتراح السياسات والحدود الخاصة بها واعتمادها من قبل المجلس ومراجعتها بشكل دوري.

6-5-1-4 التأكد من أن السياسات والإجراءات تضمن التزام كافة العاملين بحدود المخاطر المقبولة للبنك، والتأكد من عدم تجاوزها.

6-5-1-5 إعداد سياسات وخطة عمل تحتوي على الحدود القصوى المسموح بها لكل نوع من أنواع المخاطر، بالإضافة إلى الحدود القصوى على مستوى العملاء، والقطاعات، والعملات، والاستثمارات ... إلخ لضمان تنوع محفظة البنك (وبما لا يجاوز الحدود المقررة من البنك المركزي إن وُجدت).

6-5-1-6 تحديد المخاطر التي قد يتعرض لها البنك نتيجة لسلوك العاملين به، أو عدم الالتزام بالمتطلبات الرقابية، أو القيام بأعمال غير مهنية.

6-5-1-7 توافر هيكل تنظيمي محدد لقطاع المخاطر ينبثق منه إدارات فرعية لكل نوع من أنواع المخاطر الرئيسية (الائتمان، السوق، التشغيل، ... إلخ) بما يعكس الفصل بين سلطات ومسئوليات ومهام القائمين عليها لتلافى وجود أي تعارض في المصالح.

6-5-1-8 توافر نظم معلومات واتصال فعالة تُمكن قطاع المخاطر من إمداد لجنة المخاطر ومجلس الإدارة بتقارير دورية (ربع سنوية على الأقل) تشمل كافة أنواع المخاطر بالبنك ومدى التزام البنك بالحدود القصوى لكل منها والتجاوزات (إن وُجدت) وأسبابها والخطة التصحيحية المقترحة في هذا الشأن.

6-5-1-9 توافر نظام للإنذار المبكر عن المخاطر المحتملة بما يتماشى مع مستوى المخاطر المقبول للبنك والحدود القصوى المقررة لها.

6-5-1-10 أن تتضمن سياسات إدارة المخاطر آلية محددة لاختبارات التحمل.

6-5-2 يقع على عاتق رئيس قطاع المخاطر مسئولية إدارة كافة أنواع المخاطر على مستوى البنك أو المجموعة ككل، ويكون مسئولاً عن دعم مجلس الإدارة في فهم مستوى المخاطر المقبول، ووضع حدود قصوى لتلك المخاطر على مستوى قطاعات الأعمال المختلفة، ومراقبة أي تجاوزات عن تلك الحدود، مع ضرورة مراعاة ما يلي كحد أدنى:

6-5-2-1 تمتع رئيس قطاع المخاطر بالخبرة والمؤهلات الكافية للقيام بدوره بصورة فعالة بما في ذلك الالمام التام بالمستجدات التي تطرأ على القطاع المصرفي، بالإضافة إلى قدرته على التعاون والعمل المشترك مع قطاعات البنك المختلفة.

6-5-2-2 التزام البنك بالحصول على موافقة البنك المركزي المُسبقة على تعيين رئيس قطاع المخاطر، وكذا إبلاغ البنك المركزي لدى ترك العمل أو انهاء الخدمة، كما يتعين الافصاح عن أسباب الموافقة على قرار الاستقالة أو الإقالة، وذلك بعد موافقة مجلس إدارة البنك.

6-5-2-3 استقلالية رئيس قطاع المخاطر عن باقي الوظائف التنفيذية والرقابية الأخرى بالبنك، الأمر الذي يمكنه من المشاركة في القرارات المتعلقة بالمخاطر الرئيسية بالبنك، وبشكل يتيح له رفع تقارير عن كافة أنواع المخاطر دون وجود أية عوائق إلى لجنة المخاطر ومجلس الإدارة مباشرةً إذا استلزم الأمر.

6-5-2-4 مشاركة رئيس قطاع المخاطر في اتخاذ القرارات الرئيسية (مثل التخطيط الاستراتيجي وتخطيط رأس المال والسيولة وإصدار المنتجات والخدمات الجديدة، وكذا تقديم توصياته بشأن سياسة المرتبات والمكافآت المرتبطة بإدارة المخاطر).

6-5-3 الرقابة على المخاطر

يجب على البنك اتباع أسلوب رقابة استباقي على المخاطر يشمل الرقابة المستمرة والدورية عليها وذلك وفقاً لحجم وطبيعة نشاط البنك، أخذاً في الاعتبار ما يأتي:

6-5-3-1 ضرورة التحقق من تحديد وتقييم ومتابعة وإدارة المخاطر بصفة مستمرة سواء على مستوى البنك أو على مستوى المجموعة ككل، وكذا تقييم جودة نظام التقارير الذي يتم بموجبه الإقرار عن المخاطر ورفع التقارير إلى مجلس الإدارة ولجانه.

6-5-3-2 توافر إطار عام يتضمن أساليب ونماذج للقياس الكمي للمخاطر وكذا التحليل النوعي لها، هذا ويتعين على قطاع المخاطر تحديد الافتراضات التي يتم على أساسها إعداد نماذج القياس المستخدمة بالبنك وأوجه القصور بها (إن وُجدت).

6-5-3-3 وضع إجراءات لإدارة المخاطر الخاصة بتجديد أو تقديم المنتجات والخدمات الجديدة.

6-5-3-4 مراجعة مصفوفة المخاطر بالبنك بشكل دوري، بالإضافة إلى إجراء اختبارات لدقة النتائج من خلال مقارنة النتائج الفعلية للنشاط مع النتائج المتوقعة لتقييم مدى دقة وفاعلية عملية إدارة المخاطر وإجراء التعديلات اللازمة عند الضرورة.

6-5-3-5 أن يتوافر لدى البنك نظم للرقابة على جميع أنواع المخاطر بحيث يشمل المخاطر التالية كحد أدنى:

(أ) مخاطر الائتمان.

(ب) مخاطر التشغيل.

(ج) مخاطر السوق.

(د) مخاطر السيولة.

(ه) مخاطر أسعار العائد لغير أغراض المتاجرة.

(و) مخاطر أمن المعلومات بما فيها الأمن السيبراني.

6-5-3-6 يجب كحد أدنى مراعاة ما يلي لدى إعداد سياسة الاستعانة بمقدمي خدمات التعهيد:

(أ) أن يكون ذلك بموجب عقد مكتوب - يتم مراجعته قانونياً بين مقدم الخدمة الخارجي وبين البنك.

(ب) وضع مقاييس مناسبة للتحقق من قدرة مقدم الخدمات الخارجي على أداء مهامه بالكفاءة المطلوبة وفقا لالتزاماته التعاقدية.

6-5-3-7 يجب أن يضمن البنك من خلال تعاقده مع مقدمي الخدمات الخارجيين ما يلي:

(أ) جودة أداء الخدمات المتعاقد عليها وفقا للمعايير المحددة مسبقاً والقدرة على تنفيذها في حالة الطوارئ.

(ب) التزام مقدمي الخدمة بضمان الحماية الكاملة لسرية المعلومات فيما يتعلق بالبنك والعملاء.

(ج) قابلية العقود المبرمة مع مقدم الخدمة للفسخ من جانب البنك إذا ما اقتضت الضرورة ذلك مثل الاخلال بالتزامات وحقوق كل طرف دون ترتيب أي التزام مالي على البنك مع أهمية وجود البدائل التي تكفل استمرارية وجودة تقديم الخدمات للعملاء من خلال خطة لاستمرارية الأعمال.

(د) عدم قيام مقدمي الخدمة بإجراء أي تغييرات على الخدمات المسندة إليهم بدون استيفاء موافقة البنك بشكل مسبق.

(ه) الالتزام بالإجراءات المحددة من البنك فيما يتعلق بالإشراف على الخدمات المقدمة بما فيها عرض التقارير الدورية على إدارة البنك بشأن مستوي أدائها.

(و) التزام مقدمي الخدمة من خلال العقود المبرمة معهم باطلاع البنك على المعلومات التي تتعلق بالخدمات المسندة إليهم وفقا لما تقضى به أحكام الإفصاح وشفافية المعلومات.

(ز) التزام مقدمي الخدمة من خلال العقود المبرمة معهم بإخطار البنك عن أية أحداث يمكن أن يكون لها أثر كبير على مقدرتهم بالاضطلاع بالمهام الموكلة إليهم بالفاعلية المطلوبة.

(ح) التزام مقدمي الخدمة من خلال العقود المبرمة معهم باطلاع قطاع الرقابة والإشراف بالبنك المركزي المصري - إذا طلب منهم ذلك - على المعلومات المتعلقة بالمهام المسندة إليهم بما في ذلك الفحص الميداني.

7- دور الإدارة القانونية فى إطار الرقابة الداخلية

7-1 تلعب الإدارة القانونية دورا هاماً في تسيير أعمال البنوك بما يتفق وأنظمة وقوانين الدولة، حيث يجب لهذا الدور مراعاة حقوق كل من العملاء والعاملين بالبنك والتزامات كل منهم ليكون الهدف النهائي هو إرساء قواعد العدالة وتطبيق النصوص القانونية، كما تعمل أيضاً على الحد من المخاطر القانونية التي قد تؤدي إلى إلحاق خسائر بالبنك أو تخفيض ربحيته، ومن الأهمية الحفاظ على استقلالية تلك الإدارة وأن يقاس أدائها في ضوء تحقيقها للمهام الموكلة إليها.

7-2 يعتبر رئيس / مدير الإدارة القانونية هو المسئول عن عمل الإدارة بشكل عام وإدارة علاقاتها مع الجهات ذات الصلة، كما أنه المسئول عن تطوير إستراتيجية الإدارة القانونية وتوافقها مع الإستراتيجية العامة للبنك، على أن تضمن تلك الإستراتيجية كيفية استقطاب الكفاءات المؤهلة علمياً وعملياً للعمل بهذه الإدارة، وكيفية تنمية الثقافة والوعي القانوني لدى كافة العاملين بالبنك، ولتعظيم دور الإدارة القانونية في الحفاظ على مناخ مناسب للرقابة الداخلية فان عليها القيام بالمهام التالية كحد أدني:

7-2-1 إبداء الآراء القانونية في كل ما يحال إليها من الإدارات المختصة وبما يضمن اتفاق كافة سياسات وإجراءات وقرارات وأنشطة ومنتجات البنك مع القوانين والأعراف المصرفية وتعليمات البنك المركزي المصري والجهات الرقابية وتعليمات البنك الداخلية.

7-2-2 اتخاذ كافة إجراءات التقاضي وأية إجراءات أخري بما فيها رفع القضايا وتحريك الدعاوى بما يضمن المحافظة على أصول البنك وحقوقه لدي الغير وتمثيل البنك أمام المحاكم والجهات ذات الصلة أو تفويض من يلزم للقيام بذلك بعد موافقة السلطات المختصة.

7-2-3 الإعداد والمراجعة والصياغة القانونية لكافة المستندات ومنها على سبيل المثال نماذج فتح الحساب والعقود والارتباطات التي يبرمها البنك مع الأطراف الأخرى - بما فيها العمليات الائتمانية - والمتابعة القانونية لما قد يطرأ عليها من مشكلات تعترض تنفيذها.

7-2-4 اتخاذ كافة الإجراءات القانونية اللازمة خاصة فيما يتعلق بإجراءات الرهون بأنواعها ومتابعتها والتنفيذ على الضمانات المقابلة.

7-2-5 التحقيق في الوقائع والمخالفات المنسوبة إلى موظفي البنك والمحالة من السلطة المختصة واتخاذ اللازم بشأنها.

7-2-6 التنسيق مع إدارة المخاطر والإدارة المالية وكذا إدارة الالتزام بالبنك بشأن تقدير المخاطر القانونية التي قد يتعرض لها البنك وتقدير المخصصات اللازمة لمواجهة أية أعباء أو خسائر أو بشأن تفسير القوانين واللوائح.

7-2-7 أية اختصاصات أخرى ذات علاقة بطبيعة عمل الإدارة، وتكلف بها من السلطة المختصة مثل المشاركة في اللجان التي قد تحتاج لخبرة قانونية.

7-3 في حالة الاستعانة بمكاتب قانونية - أو أشخاص - ذات خبرة عملية في بعض الأمور مثل التحكيم أو التراخيص أو التوثيق أو صياغة العقود متعددة الأطراف أو في تمثيل البنك أمام المحاكم يتم مراعاة ما يلي:

7-3-1 أن يكون المكتب - الإسناد الخارجي - ذو سمعة وخبرة طيبة في هذا المجال.

7-3-2 أن يكون له سابقة أعمال مشهود لها بالكفاءة في أمور مماثلة.

7-3-3 أن يكون ذلك من خلال الإدارة القانونية / المستشار القانوني في شكل عقد خبرة أو استشاره محدد الهدف.

7-3-4 الأخذ في الاعتبار ما تفرضه دواعي قانون سرية الحسابات أو أية قوانين أخرى.

8- نظم المعلومات والتقارير

8-1 نظم المعلومات

يتعين على البنوك وضع سياسة واضحة لنظم المعلومات يتم مراجعتها وتحديثها بشكل دوري، بحيث تدعم دقة اتخاذ القرار وإدارة المخاطر، مع مراعاة توافر ما يأتي:

8-1-1 نظم متكاملة لإدارة المعلومات مع تدفق مناسب للبيانات عبر كافة مستويات الهيكل التنظيمي.

8-1-2 نظام لإدارة المعلومات يتيح إعداد تقارير دقيقة في التوقيت المناسب وعرضها بصفة دورية على الإدارة العليا واللجان ذات الصلة ومجلس الإدارة لاتخاذ القرارات المناسبة.

8-1-3 نظم محاسبية وأنظمة مستندية تضمن تسجيل المعاملات بشكل لحظي وتعكس المركز المالي بما يتوافق مع قواعد إعداد وتصوير القوائم المالية وأسس القياس للبنوك الصادرة عن البنك المركزي.

8-1-4 نظم لتسجيل وحفظ المستندات والسجلات والقيود المحاسبية واسترجاع البيانات بما يمكن من فحصها ومراجعتها، وإتاحتها عند الطلب لكل من الإدارة العليا ومجلس الإدارة ومراقبي الحسابات الخارجيين والبنك المركزي.

8-1-5 آلية للتأكد من جودة المعلومات المالية والبيانات المقدمة للبنك المركزي المصري.

8-1-6 توثيق إجراءات العمل لكافة أنشطة البنك وتحديثها بانتظام وتحديد صلاحيات إجراء المعاملات.

8-1-7 نظم لحماية سلامة وسرية البيانات الخاصة بالبنك وعملائه.

8-2 نظم التقارير

يتعين على البنوك وضع نظم وإجراءات عمل تتيح تداول التقارير بين المستويات الإدارية والقطاعات المختلفة، مع تحديد إجراءات التصعيد للمستوى الإداري الأعلى، بما يضمن متابعة اتخاذ القرارات في التوقيت المناسب، على أن تشمل التقارير الدورية التالية كحد أدنى:

8-2-1 تقرير بشأن مصفوفة المخاطر التي تعبر عن حجم واتجاه المخاطر التي يتعرض لها البنك ومقارنتها بالحدود القصوى المعتمدة.

8-2-2 تقرير يتضمن الاستثناءات والتجاوزات عن الحدود القصوى المعتمدة، والآجال المحددة أو شروط الموافقات الائتمانية الصادرة للعملاء، أو المستندات منتهية الصلاحية ... إلخ.

8-2-3 تقرير يوضح تنوع محفظة الائتمان بالبنك.

8-2-4 تقرير عن مدى كفاءة وكفاية نموذج قياس مخاطر الائتمان بالبنك وحساب خسائر الاضمحلال بالنسبة لكافة عملاء البنك.

8-2-5 تقرير عن القاعدة الرأسمالية بالبنك.

8-2-6 تقرير عن نتائج اختبارات التحمل شاملاً سيناريوهات أسوأ الظروف.

8-2-7 تقرير عن المخاطر المصاحبة للمشتقات المالية.

8-2-8 تقرير يعكس مخاطر التشغيل بالبنك.

8-2-9 تقرير يعكس حجم مخاطر أسعار العائد ومقارنتها بالحدود المعتمدة.

8-2-10 تقرير عن نتائج اختبارات الحساسية لمخاطر أسعار العائد.

8-2-11 تقرير عن ملاحظات المراجعة الداخلية ومراقبي الحسابات والبنك المركزي والإجراءات التصحيحية.

8-2-12 تقرير يعكس نتائج أعمال المراجعة الداخلية والالتزام.

8-2-13 تقرير عن مدى فاعلية نظام الرقابة الداخلية بالفروع الخارجية.

8-2-14 تقرير سنوي يعكس كفاءة ونظام الرقابة الداخلية على مستوى المجموعة.

