المقدمة

تم إعداد هذه التعليمات بما يتوافق مع أحكام قانون البنك المركزي والجهاز المصرفي الصادر بالقانون رقم 194 لسنة 2020 (ويشار إليه فيما يلي بقانون البنك المركزي) بهدف تعزيز وتطوير مفهوم الحوكمة ونظم الرقابة الداخلية بالقطاع المصرفي، وذلك في ضوء أهميتهما في الحفاظ على الاستقرار المصرفي ومواجهة التحديات المختلفة.

وتنقسم التعليمات الى جزئين، الجزء الأول يتعلق بالحوكمة التي تنظم العلاقة بين مجلس إدارة البنك والإدارة العليا وحملة الأسهم وأصحاب المصالح الأخرى، وتحدد واجبات ومسئوليات كل منهم، بالإضافة إلى تحديد النهج الذي يتبعه المجلس والإدارة العليا لتوجيه البنك ومباشرة شئونه وأنشطته، وكذا الأسس المتبعة للإشراف على الأداء بما يؤدي إلى الاستخدام الأمثل لموارد البنك والمحافظة على استقراره. أما بالنسبة للجزء الثاني فيشمل ضرورة توافر نظاماً شاملاً للرقابة الداخلية بكل بنك يتم بمقتضاه مراقبة ومراجعة كافة أنشطة وعمليات البنك بشكل مستمر من خلال كل من مجلس الإدارة واللجان المنبثقة عنه، والإدارة العليا، وكافة العاملين بالبنك، وبمراعاة خضوع النظام للتقييم والتطوير الدوري.

نطاق التطبيق

تسري هذه التعليمات على كافة البنوك العاملة بجمهورية مصر العربية، ويتعين على فروع البنوك الأجنبية الالتزام بهذه التعليمات بالقدر الذي ينطبق عليها، أو بتلك المطبقة بالمركز الرئيسي للبنك، أيهما أكثر تحفظاً، وفي حالة وجود تعارض فيما بينهما، يجب تقديم المبررات اللازمة والحصول على موافقة البنك المركزي المصري.

يتعين على كل بنك التأكد من التزام كافة فروعه الخارجية بهذه التعليمات بالقدر الذي لا يتعارض مع القوانين والتعليمات المنظمة لها بالدولة التي تعمل بها، وفي حالة وجود أي تعارض يتعين الحصول على موافقة البنك المركزي المصري على كيفية معالجة الأمر، وكذا إخطار المركز الرئيسي للبنك.

أولاً: الحوكمة

1- مفهوم الحوكمة

الحوكمة هي الإطار الذي ينظم العلاقات بين مجلس إدارة البنك والإدارة العليا وحملة الأسهم وأصحاب المصالح الأخرى، وتتناول الحوكمة الأسس التي يتبعها البنك لتحديد أهدافه والموارد اللازمة لتحقيقها، وكذا الإشراف على الأداء، كما تحدد الحوكمة مسئوليات وواجبات جميع الأطراف المعنية بالبنك وكذا النهج الذي يتبعه مجلس الإدارة والإدارة العليا لمباشرة شئون البنك والإشراف على أنشطته اليومية، والتي تتناول ما يأتي:

1-1 وضع الاستراتيجيات وتحديد الأهداف.

1-2 تحقيق التوازن بين الالتزام بالمسئولية تجاه المساهمين وحماية مصالح المودعين، أخذا في الاعتبار أصحاب المصالح الأخرى.

1-3 التأكد من أن نشاط البنك يتم في إطار آمن وسليم، مع الالتزام بالقوانين والضوابط السارية.

1-4 وضع سياسات داخلية فعالة فيما يتعلق بمبادئ الحوكمة والتأكد من تطبيقها.

1-5 مباشرة أعمال وأنشطة البنك اليومية.

1-6 تحديد مستوى المخاطر المقبول للبنك.

2- مجلس إدارة البنك

2-1 أحكام عامة

2-1-1 يجب أن يدير كل بنك مجلس إدارة كفء يكون مسئولاً بصفة رئيسية عن وضع استراتيجية للبنك تتضمن أهدافه الرئيسية وسبل تحقيقها، وكذا الإشراف على أداء الإدارة العليا بما يضمن تحقيق هذه الأهداف، مع التأكد من أن إدارة البنك تتم وفقاً لإستراتيجية حصيفة وسياسة مخاطر واضحة تضمن الالتزام بكافة المتطلبات القانونية والرقابية، وكذا التأكد من فاعلية نظام الرقابة الداخلية بالبنك بما يضمن استقرار البنك والحفاظ على سمعته.

2-1-2 يتعين وضع هيكل تنظيمي للبنك يوضح مسئوليات وصلاحيات كل من مجلس الإدارة ولجانه والإدارة العليا، مع ضرورة أن يعكس هيكل البنك مبدأ الشفافية والمساءلة والفصل بين المهام وذلك من خلال إرساء إطار فعال يضمن الإشراف المستمر والرقابة الفعالة على مختلف المستويات الوظيفية، على أن يتم موافاة البنك المركزي بالهيكل المشار إليه بعد اعتماده من المجلس وكذا بأية تعديلات تطرأ عليه.

2-1-3 يتعين توافر أربعة مستويات إدارية في الهيكل التنظيمي للبنك كحد أدنى - مع تحديد لسلطات ومسئوليات كلٍ منهم، وذلك على النحو الآتي:

2-1-3-1 المستوي الإشرافي المتمثل في مجلس الإدارة واللجان المنبثقة عنه.

2-1-3-2 المستوى الإداري المتمثل في الإدارة العليا.

2-1-3-3 المستوى التنفيذي المتمثل في المسئولين عن الإشراف المباشر على إدارات البنك المختلفة.

2-1-3-4 المستوى الرقابي المتمثل في وظائف الرقابة الداخلية المستقلة بالبنك (قطاعات المخاطر والالتزام والمراجعة الداخلية).

2-1-4 يتعين أن يتوافر لدى كل بنك إجراءات عمل توضح السلطات والمسئوليات على مستوى البنك ويشتمل على أهم واجبات كل من المجلس والإدارة العليا للبنك.

2-1-5 يقوم مجلس الإدارة باعتماد المعايير المهنية الواجب إتباعها من قبل أعضاء المجلس والإدارة العليا وجميع العاملين بالبنك، مع ضرورة تعزيز المسئولية الفردية والجماعية على النحو الآتي:

2-1-5-1 العمل على نشر ثقافة الحوكمة لدى المستويات الإدارية العليا بالبنك، بما ينعكس على أداء كافة المستويات الإدارية الأخرى.

2-1-5-2 وضع ميثاق سلوك العمل المصرفي لكافة العاملين بالبنك يشمل معايير واضحة وكذا السلوكيات المقبولة وغير المقبولة والقيم التي يتعين الالتزام بها، على أن يتم إتاحة نسخة منه لجميع العاملين، مع قيامهم بالتوقيع بما يفيد اطلاعهم عليه والالتزام بما ورد به.

2-2 تشكيل مجلس الإدارة

2-2-1 مع عدم الإخلال بأحكام الاتفاقيات الدولية والقوانين الخاصة بإنشاء بعض البنوك والمادة (134) من قانون البنك المركزي، يتولى إدارة البنك مجلس إدارة يتكون من عدد ملائم من الأعضاء تختارهم الجمعية العامة لمدة ثلاث سنوات، ويختار المجلس من بين أعضائه رئيساً غير تنفيذياً للبنك، كما يعين رئيساً تنفيذياً / عضواً منتدباً.

2-2-2 يتعين أن يتمتع أعضاء المجلس بالمهارات والخبرات المتنوعة بما فيها الأعمال المصرفية والمالية والاقتصادية والمحاسبية والقانونية وتكنولوجيا المعلومات وإدارة المخاطر، بما يدعم كفاءة المجلس وينعكس على أدائه وقراراته، ويُمكنه من تقييم أداء البنك والإدارة العليا، وذلك بما يتفق مع شروط الجدارة والصلاحية الفنية.

2-2-3 يراعى وجود عضو مجلس إدارة لتمثيل الأقلية من المساهمين إذا كان إجمالي مساهماتهم يُمثل 5% أو أكثر من إجمالي المساهمات، كما يراعى ألا يقل تمثيل المرأة في مجلس إدارة البنك عن عضوتين على الأقل.

2-2-4 لا يجوز لعضو مجلس إدارة أي بنك بصفته الشخصية أو بصفته ممثلاً لغيره أن يجمع إلى عضويته عضوية مجلس إدارة بنك آخر أو جهة منح ائتمان أو أن يقوم بأية أعمال من أعمال الإدارة أو الاستشارة في أي منها.

2-2-5 يتعين أن يكون رئيس مجلس الإدارة عضو غير تنفيذي، كما يتعين الفصل التام بين مسئوليات ومهام ومنصبي كلٍ من رئيس مجلس الإدارة والرئيس التنفيذي / العضو المنتدب، ولا يجوز أن يتولى ذات الشخص رئاسة مجلس إدارة البنك ومهام الرئيس التنفيذي / العضو المنتدب، ويتم تحديد اختصاصات ومسئوليات كلٍ منهما وفقاً للتعليمات السارية وتوثيق ذلك كتابياً واعتماده من مجلس الإدارة.

2-2-6 أن يكون رئيس مجلس الإدارة (غير التنفيذي) مسئولاً بصفة رئيسية عن حسن أداء المجلس ولجانه وضمان فاعلية أدائهم، ويجب أن يتسم بالخبرة والكفاءة التي تمكنه من الوفاء بمسئولياته والتي تتضمن ما يلي كحد أدنى:

2-2-6-1 التأكد من اتخاذ قرارات مجلس الإدارة على أساس سليم وبناءً على دراية شاملة بالموضوعات قيد المناقشة، مع ضرورة التأكد من وجود آلية مناسبة لضمان تنفيذ تلك القرارات في الوقت المناسب ومتابعتها.

2-2-6-2 تشجيع النقاش والمشاركة الفعالة من قبل كافة الأعضاء وخاصة الأعضاء غير التنفيذيين، والسماح بالتعبير عن الآراء المعارضة ومناقشتها في إطار عملية اتخاذ القرار.

2-2-6-3 التأكد من التزام المجلس بإنجاز مهامه علي أكمل وجه بما يحقق مصلحة البنك وعملائه، والعمل على إدارة التعارض في المصالح.

2-2-6-4 إتاحة الفرصة الكافية للأعضاء غير التنفيذيين لمتابعة أداء الإدارة العليا.

2-2-6-5 تدعيم علاقة المجلس ككل بالإدارة العليا بالبنك من خلال دعوتهم لحضور اجتماعات المجلس ولجانه عند الحاجة.

2-2-6-6 التأكد من إتاحة المعلومات اللازمة بشكل وافي ودقيق في الوقت المناسب لأعضاء المجلس والمساهمين.

2-2-6-7 التأكد من فاعلية أداء المجلس ولجانه تطبيقاً لنظم الحوكمة المقررة.

2-2-6-8 التأكد من قيام كافة أعضاء المجلس بإجراء التقييم الذاتي بشكل سنوي.

2-2-6-9 دعوة مجلس الإدارة للانعقاد بصفة دورية منتظمة مع التأكد من اتساق اجتماعات المجلس مع النظام الأساسي للبنك والقوانين والتعليمات ذات الصلة.

2-2-6-10 التنسيق مع الإدارة العليا وأمانة سر المجلس فيما يخص جدول أعمال المجلس.

2-2-6-11 التأكد من توفير برنامج تعريفي لأعضاء مجلس الإدارة الجدد بما يضمن إلمامهم بمهامهم والقيام بمسئولياتهم بشكل فعال.

2-2-6-12 التأكد من توافر خطة تدريب سنوية لتنمية المهارات الفنية لأعضاء المجلس بصفة مستمرة خاصةً الأعضاء من خارج القطاع المصرفي.

2-3 التوازن والاستقلالية في تشكيل مجلس إدارة البنك

2-3-1 يتعين مراعاة تحقيق التوازن والاستقلالية لدى تشكيل مجلس إدارة البنك على أن يتضمن عدد ملائم من الأعضاء التنفيذيين وغير التنفيذيين، وبمراعاة أن يكون الحد الأقصى لعدد الأعضاء التنفيذيين ثلاثة أعضاء، وأن يكون من بين الأعضاء غير التنفيذيين عضوين مستقلين على الأقل.

2-3-2 يشترط في العضو غير التنفيذي أن يكون من ذوي الكفاءة والخبرة وألا يكون موظفاً أو مديراً بالبنك، وألا يتقاضى راتباً شهرياً أو سنوياً منه ولا يقدم له أية استشارات مدفوعة الأجر، وألا تزيد مدة عضويته كعضو غير تنفيذي عن 6 سنوات متصلة أو منفصلة؛ يجوز مدها لمدة 3 سنوات بمبررات قوية وبموافقة البنك المركزي.

2-3-3 يشترط أن يتوافر التالي في عضو مجلس الإدارة غير التنفيذي المستقل:

2-3-3-1 ألا يكون موظفاً أو مديراً بالبنك أو أحد الأطراف المرتبطة به خلال السنوات الثلاث السابقة.

2-3-3-2 ألا يكون عضو بمجلس إدارة أياً من الأطراف المرتبطة بالبنك.

2-3-3-3 ألا تكون له أية صلات قرابة بأي من أعضاء المجلس أو الإدارة العليا أو مستشاري البنك أو أي من الأطراف المرتبطة بهم حتى الدرجة الثانية.

2-3-3-4 ألا تكون له أي مصالح تتعارض مع واجباته أو يكون من شأنها أن تؤثر في حياديته لدى اتخاذ القرارات.

2-3-3-5 ألا يكون له أية مصالح مشتركة مع أعضاء مجلس الإدارة والإدارة العليا بالبنك من خلال المساهمة في شركات أو مؤسسات أخرى.

2-3-3-6 ألا يتقاضى من البنك أي راتب أو مبلغ مالي باستثناء ما يتقاضاه مقابل عضويته في المجلس أو لجانه.

2-3-3-7 ألا يكون (أو يمثل) مساهماً بالبنك بشكل مباشر او غير مباشر.

2-3-3-8 ألا يكون شريكاً لمراقبي حسابات البنك الخارجي أو موظفاً لديهما خلال السنوات الثلاث السابقة.

2-3-3-9 ألا تزيد مدة عضويته عن ست سنوات متصلة أو منفصلة.

2-3-4 يجب أن يُفصح المجلس في تقريره السنوي ونماذج الحوكمة عن جميع الأعضاء غير التنفيذيين المستقلين، ويتم تقديم مقترحات بشأن ترشيحهم من خلال لجنة الحوكمة والترشيحات ويُعرض ذلك على المجلس تمهيداً للحصول على موافقة الجمعية العامة، وبعد الحصول على موافقة البنك المركزي عليهم.

2-4 مسئوليات والتزامات مجلس الإدارة

2-4-1 يكون مجلس إدارة البنك مسئولاً عن الإشراف على إدارة البنك بوجه عام، وكذا متابعة تنفيذ أهداف البنك من قبل الإدارة العليا، ويتعين القيام بما يلي كحد أدنى لتدعيم نظام الحوكمة بالبنك وضمان فاعليته:

2-4-1-1 اعتماد استراتيجية البنك والسياسات والأهداف الرئيسية والإشراف على تنفيذها والتأكد من نشرها بين العاملين بالبنك، ووضع خطة عمل تحتوي على التالي كحد أدنى:

2-4-1-1-1 نطاق أعمال البنك والمخاطر التي يتعرض لها.

2-4-1-1-2 أهداف البنك الحالية والمستقبلية، على أن تكون محددة وقابلة للقياس.

2-4-1-1-3 موازنة تقديرية مستقلة لكل نشاط بالبنك وكذا النتائج المالية المتوقعة.

2-4-1-2 اعتماد القوائم المالية البنك بعد موافقة لجنة المراجعة.

2-4-1-3 اعتماد الهيكل التنظيمي وتحديد هيكل الصلاحيات والمسئوليات في البنك، وكذا اختيار كبار المسئولين من الإدارة العليا.

2-4-1-4 الاجتماع دورياً بالإدارة العليا وقطاع المراجعة الداخلية بالبنك لمراجعة ومناقشة السياسات المعمول بها ومتابعة ما تم إنجازه من تنفيذ أهداف البنك الاستراتيجية، ويتعين على أعضاء المجلس غير التنفيذيين الاجتماع بحضور رئيس المجلس مرة على الأقل سنوياً وبدون الأعضاء التنفيذيين.

2-4-1-5 عقد اجتماع بين أعضاء المجلس غير التنفيذيين على الأقل مرة سنوياً مع مراقبي الحسابات بدون الأعضاء التنفيذيين بحضور رئيسي قطاع المراجعة الداخلية وقطاع الالتزام.

2-4-1-6 عقد اجتماع بين أعضاء مجلس الإدارة غير التنفيذيين ورئيس قطاع المخاطر بدون الأعضاء التنفيذيين على الأقل مرة سنوياً.

2-4-1-7 التأكد من موافاة البنك المركزي بنسخة من محاضر الاجتماعات المشار إليها بالبنود 2-4-1-4، و2-4-1-5، و2-4-1-6 خلال شهر من تاريخ انعقادها.

2-4-1-8 الرقابة والإشراف على أعمال البنك، دون أن تتضمن مهام المجلس ممارسة الأعمال التنفيذية.

2-4-1-9 وضع إطار عام لإدارة أي تعارض محتمل في مصالح البنك وكل من أعضاء مجلس الإدارة والإدارة العليا والعاملين بالبنك والمساهمين والمستشارين وأية أطراف أخرى ذات صلة.

2-4-1-10 تجنب وجود أي تعارض في المصالح في مهام مجلس الإدارة والتزاماته، وفي حالة ظهور أية شبهة لتعارض المصالح في مهام أو التزامات أحد أعضاء المجلس، يتعين عليه الإفصاح عن ذلك وعدم المشاركة في اتخاذ القرار أو التصويت.

2-4-1-11 العمل على تحقيق مصالح المساهمين والمودعين والعاملين وأصحاب المصالح الأخرى، على أن تكون الأولوية لمصالح المودعين.

2-4-1-12 الإدراك والفهم الكافي للبيئة القانونية والرقابية التي يعمل بها البنك، والتأكد من الالتزام بالقوانين والضوابط الرقابية.

2-4-1-13 تخصيص الوقت الكافي والجهود المناسبة من جميع الأعضاء لضمان حُسن إنجاز المجلس لمهامه.

2-4-2 يُعد من أهم مسئوليات المجلس اعتماد سياسة الحوكمة والسياسات ذات الصلة وتحديد الأسلوب الأمثل لتطبيق الحوكمة وفقاً لحجم أنشطة البنك ومدى تعقدها، ومستوى المخاطر، ونموذج أعماله، وكذا التقييم الدوري المستمر لكفاءة وفاعلية سياسة وممارسات الحوكمة والرقابة الداخلية بالبنك، ويتعين على المجلس القيام بما يأتي:

2-4-3-1 إرساء سياسة للإبلاغ عن المخالفات والممارسات غير المشروعة تضمن وجود آلية لحماية المبلغين وضمان السرية التامة؛ لتشجيع العاملين على المبادرة بالكشف عن المخالفات والإبلاغ عنها، على أن يكون الإبلاغ بناءً على مستندات أو معلومات محددة.

2-4-3-2 التأكد من اعتماد سياسة داخلية بالبنك بشأن إدارة أي تعارض محتمل في المصالح تتضمن المتطلبات الواردة بالمرفق رقم 1 كحد أدنى، وذلك للتأكد من أن المعاملات المتعلقة بكافة الأطراف المرتبطة بالبنك يتم إجراؤها باستقلالية، مع مراعاة عدم الإضرار بمصلحة المساهمين والمودعين والبنك بشكل عام، على أن يقوم المجلس بالإفصاح اللازم، بما في ذلك الإفصاح للبنك المركزي عن المعاملات التي قد تحتمل وجود تعارض في المصالح.

2-4-3-3 إرساء سياسة للمسئولية المجتمعية للبنك توضح مشاركة البنك في تنمية المجتمع من خلال القنوات الاقتصادية والاجتماعية والبيئية.

2-4-3-4 اعتماد سياسة الإفصاح ومراجعتها دورياً والإشراف على تنفيذها وذلك في إطار أحكام قانون البنك المركزي والتعليمات ذات الصلة.

2-4-3-5 اعتماد السياسة الداخلية للتوظيف تتضمن معايير وضوابط لضمان تناسب خبرات ومؤهلات العاملين بالبنك مع متطلباتهم الوظيفية، على أن تشمل آلية لترشيح وتعيين مسئولي الإدارة العليا بالبنك وكذا الإشراف عليهم ومتابعة أدائهم ومساءلتهم، مع اعتماد خطة للتعاقب الوظيفي.

2-4-3-6 قيام مجلس الإدارة باعتماد كافة سياسات البنك الداخلية على سبيل المثال لا الحصر: سياسة إدارة المخاطر، وتكنولوجيا المعلومات وحوكمة تكنولوجيا المعلومات وأمن وسرية المعلومات، ومكافحة غسل الأموال وتمويل الإرهاب، والمرتبات والمكافآت.

2-4-3-7 التأكد من قيام البنك بمراجعة سياساته الداخلية كل 3 سنوات بحد أقصى وتحديثها إذا لزم الأمر، مع مراعاة اعتماد المراجعة أو التحديث من مجلس الإدارة، وكذا التأكد من تحديث إجراءات العمل - في الحالات التي تستدعي ذلك - لتعكس أي تعديلات تم إجراؤها على السياسات ذات الصلة.

2-5 اجتماعات مجلس الإدارة

2-5-1 يتعين على المجلس الاجتماع بصفة دورية منتظمة لا تقل عن ستة مرات خلال العام (على ألا يقل الحضور الفعلي عن أربعة مرات)[2]، وذلك بناءً على دعوة رئيس المجلس، أو أغلبية أعضائه، وللرئيس التنفيذي / العضو المنتدب بالبنك أن يطلب من رئيس المجلس دعوته للانعقاد على أن يكون مصحوباً بجدول الأعمال التي يرغب في عرضها.

2-5-2 لا يجوز أن يتغيب أي من أعضاء المجلس عن أكثر من ثلث جلسات المجلس خلال العام، وإلا وجب علي رئيس المجلس إخطار الجمعية العامة للبنك، لكي تتخذ ما تراه مناسباً بشأن ذلك.

2-5-3 يجوز لأعضاء مجلس الإدارة تفويض بعضهم البعض في حضور اجتماعات المجلس ولجانه بحد أقصى مرتين خلال العام الواحد، ولا يعد الحضور من خلال التفويض حضوراً فعلياً.

2-5-4 يجوز مشاركة الأعضاء في اجتماعات مجالس إدارة البنوك من خلال الاتصال الهاتفي أو الاتصال عبر الفيديو، وذلك وفقاً للشروط الآتية:

2-5-4-1 أن يتيح النظام الأساسي للبنك إمكانية المشاركة في الاجتماعات من خلال الاتصال الهاتفي أو الاتصال عبر الفيديو، بالإضافة إلى إجراءات واضحة يتم اعتمادها من قبل مجلس الإدارة لعقد الاجتماعات بواسطة تلك الوسائل.

2-5-4-2 أن يكون الأصل هو الحضور الفعلي للأعضاء، وفي حالة تعذر ذلك، يجوز المشاركة عبر الفيديو أو الهاتف بعد اخطار رئيس المجلس وإبلاغ أمين سر المجلس، مع مراعاة حضور أغلبية أعضاء مجلس الإدارة حضوراً فعلياً.[3]

2-5-4-3 تعتبر مشاركة عضو مجلس الإدارة عبر الفيديو أو الهاتف مشاركة فعلية في اجتماع مجلس الإدارة، ويحق له التصويت، ويتم حسابه في النصاب القانوني لانعقاد المجلس وصحة القرارات الصادرة عنه.

2-5-5 على البنوك الالتزام بالضوابط الفنية التالية فيما يخص مشاركة الأعضاء في الاجتماعات من خلال الاتصال الهاتفي أو الاتصال عبر الفيديو:

2-5-5-1 التأكد من توفير مستوى مناسب من تأمين التطبيقات المستخدمة للمشاركة في الاجتماعات من خلال الاتصال الهاتفي أو الاتصال عبر الفيديو، مع قيام قطاع المراجعة الداخلية بتقييم الإجراءات والممارسات التي يتم تطبيقها للحد من المخاطر الناتجة عن استخدام هذه التقنيات ورفع التوصيات ذات الصلة إلى لجنة المراجعة، على أن يتم متابعة اتخاذ الإجراءات التصحيحية اللازمة حال وجود أي قصور، مع مراعاة الممارسات التالية كحد أدني والحصول على موافقة البنك المركزي:

(أ) تطبيق كافة الاجراءات والضوابط التي تضمن التحقق من هوية المشاركين في الاجتماعات.

(ب) التأكد من تأمين أجهزة مستخدمي الخدمة بشكل فعال سواء المتصلة بشبكة البنك أو من خارج الشبكة المؤمنة للبنك.

(ج) توافر خاصية التحكم في عملية إدارة ومراقبة الولوج لمنع الدخول غير المصرح به للاجتماعات سواء على مستوى مستخدمي الخدمة أو مديري النظام.

(د) استخدام التكنولوجيا اللازمة لضمان سرية وسلامة وإتاحة البيانات والمعلومات المخزنة على الأجهزة أو أي وسائط تخزين أخرى عند تداولها.

(ه) فحص الملفات على أجهزة مستخدمي الخدمة قبل حفظها للتأكد من عدم وجود أية فيروسات بها.

(و) حماية غرف الاجتماعات الافتراضية بكلمة مرور ومنع تداولها إلا من خلال القنوات المؤمنة.

(ز) توفير خاصية تسجيل الاجتماعات في الخدمة مصحوبة بالموافقة من جميع المشاركين قبل بدء التسجيل مع التزام البنك بالتأكد من أن التطبيق المستخدم يوفر التقنيات الكافية لحماية أي تسجيلات من أي اختراق غير مصرح به.

(ح) تطبيق التصديق المتعدد - إن أمكن - على مستوى مستخدمي الخدمة وليس فقط مديري النظام.

(ط) السماح بمشاركة الملفات مع الأطراف المصرح لهم بحق الاطلاع عليها على مستوى مستخدمي الخدمة.

(ي) القيام باختبارات الاختراق وذلك لعمل تقييم مُفصل للوضع الأمني للنظام قبل البدء في استخدامه وعقب إجراء أية تعديلات جوهرية بالنظام.

2-6 تقييم كفاءة أداء مجلس إدارة البنك

2-6-1 يجب أن يقوم مجلس إدارة البنك بإتباع نظام محدد لإجراء تقييم ذاتي سنوي - سواء بمفرده أو بالاستعانة بجهة مستقلة بعد الحصول على موافقة البنك المركزي عليها - يقوم بموجبه كل عضو بتقييم أداؤه وكذا أداء المجلس كوحدة واحدة، ولجانه، بالإضافة إلى إجراء تقييمات متبادلة بين كافة أعضاء مجلس الإدارة بما يشمل رئيس المجلس؛ بحيث يشمل التقييم مدى الالتزام بالمهام وكذا تحديد الإجراءات اللازمة لرفع كفاءة أعضاء المجلس، على أن يتم موافاة البنك المركزي بنتائج هذا التقييم والإجراءات المقترحة في هذا الشأن، أخذاً في الاعتبار ما يأتي:

2-6-1-1 ضرورة تصميم نموذج للتقييم الذاتي يتناسب مع حجم وطبيعة أعماله وفقاً للمعايير والمحددات الواردة بالمرفق رقم 2، على أن يتم اعتماده من مجلس الإدارة.

2-6-1-2 يجب أن يشمل التقييم أداء العضو ومشاركته في اجتماعات مجلس الإدارة واللجان بفاعلية.

2-6-1-3 يتم عرض تقرير مجمع بأهم ما جاء في كافة التقييمات وكذا المقترحات والتوصيات على لجنة الحوكمة والترشيحات، والتي تقوم بعرضه على مجلس الإدارة لاعتماده.

2-6-1-4 يكون رئيس المجلس مسئول عن اتخاذ ما يراه مناسباً من إجراءات وفقاً لنتائج التقييمات المُشار إليها، بما يضمن حسن أداء المجلس.

2-6-1-5 يتعين على المجلس اتخاذ ما يراه مناسباً في حالة عدم التزام أحد أعضائه بالحد الأدنى المقبول من أدائه.

2-7 أمانة سر المجلس

2-7-1 يتعين على كل بنك تحديد مسئول من ذوي الكفاءة وعلى دراية وإلمام كافي بالأعمال المصرفية، يُعهد إليه بمسئولية "أمانة سر المجلس"، ويجوز تشكيل إدارة لأمانة السر، وتشمل أهم مهام تلك الإدارة فيما يلي على سبيل المثال لا الحصر:

2-7-1-1 الإعداد لاجتماعات المجلس وتحضير جدول الأعمال، مع توفير المعلومات والتفاصيل اللازمة وإرسالها إلى أعضاء المجلس بوقت كاف قبل الاجتماع.

2-7-1-2 إعداد محاضر الاجتماعات وتوقيعها وإرسالها لأعضاء مجلس الإدارة لمراجعتها - سواء الحاضرين فعلياً أو المشاركين عبر وسائل الاتصال، بالإضافة إلى حفظ تسجيلات الاجتماعات - عن طريق استخدام جهاز تسجيل مخصص لذلك يسمح بتأمين التسجيلات - ضمن سجلات البنك لمدة زمنية مناسبة وفقاً لسياسات البنك وكذا المتطلبات القانونية والضوابط الرقابية المعمول بها.

2-7-1-3 تقديم محاضر اجتماعات مجلس الإدارة ولجانه بجلساتها التالية لاعتمادها، على أن يتم موافاة البنك المركزي بنسخة من محاضر الاجتماعات خلال شهر من تاريخ الانعقاد (باللغة العربية).

2-7-1-4 التأكد من استلام الأعضاء لكافة المستندات وجدول أعمال الاجتماع في حالة مشاركتهم عبر الهاتف أو الفيديو.

2-7-1-5 حصر عدد اجتماعات المجلس المنعقدة خلال العام وتسجيل الحضور في الاجتماعات وتوثيق ما إذا كان الحضور فعلياً، أو من خلال الاتصال الهاتفي، أو الاتصال عبر الفيديو، والتأكد من تطبيق القواعد المعمول بها في هذا الشأن.

2-7-1-6 متابعة تنفيذ قرارات المجلس في إطار الآلية الموضوعة لهذا الغرض، مع عرض هذا البند في بداية كافة اجتماعات المجلس.

2-7-1-7 حفظ وتوثيق البيانات والمستندات الخاصة بقرارات المجلس والموضوعات المعروضة عليه، مع التأكد من اتاحتها للبنك المركزي.

2-7-1-8 التنسيق مع كافة رؤساء إدارات وقطاعات البنك لعرض نتائج أعمالها على المجلس.

2-7-1-9 التنسيق مع كافة لجان مجلس الإدارة بما يكفل الاتصال الفعال بينها وبين المجلس.

2-7-1-10 اتاحة قنوات مناسبة للاتصال الفعال وتبادل المعلومات بصورة كاملة ودقيقة وفي الوقت المناسب بين أعضاء مجلس الإدارة والإدارة العليا.

2-7-1-11 العمل على أن يكون أعضاء المجلس على علم بما يُستجد من مسئوليات إشرافية أو قانونية نتيجة تغير عمليات أو أنشطة البنك أو الإطار القانوني والرقابي المنظم له.

2-7-1-12 تقديم المعلومات اللازمة عن البنك للأعضاء الجدد والمساعدة في توفير البرنامج التعريفي لهم.

2-7-1-13 تدوين مناقشات وتوصيات كل عضو باجتماعات المجلس واللجان المنبثقة عنه بشكل مفصل، مع إثبات أسماء الحضور (من أعضاء المجلس أو غيرهم) في محضر الجلسة.

3- لجان مجلس الإدارة

3-1 أحكام عامة

3-1-1 يكون للجان المجلس دور هام في دعم مجلس الإدارة خلال عملية اتخاذ القرار.

3-1-2 يقوم مجلس إدارة البنك بوضع القواعد والإجراءات اللازمة لتشكيل اللجان المنبثقة عنه واعتماد ميثاق العمل الخاص بها والمتضمن مهامها واختصاصاتها وصلاحياتها ومدة عملها، والنصاب القانوني لها ودورية انعقاد كل منها بالإضافة إلى آلية اتخاذ القرار، وكذا إجراءات العمل الخاصة بها متضمنة كيفية قيام اللجنة بعرض أعمالها على المجلس. كما ينبغي أن يقوم المجلس بالمتابعة المستمرة لأعمال اللجان للتأكد من فاعلية دورها.

3-1-3 يتعين ضمان سهولة حصول اللجان على المعلومات الكافية من الإدارة العليا وكذلك إمكانية استعانتها بالموارد والاستشارات الخارجية، وذلك حتى تتمكن من إتمام المهام الموكلة إليها، كما يتعين على اللجان تسجيل نتائج اجتماعاتها وتوصياتها وعرض المحاضر على المجلس بصفة دورية.

3-1-4 مع عدم الإخلال بحق مجلس إدارة كل بنك في تشكيل ما يراه من لجان، تُشكل في كل بنك لجان للمراجعة، والمخاطر، والمرتبات والمكافآت، والحوكمة والترشيحات، كحد أدنى.

3-1-5 لا يجوز الدمج بين لجنتي المراجعة والمخاطر مع مراعاة عدم تماثل تشكيل كل من اللجنتين.

3-1-6 مراعاة أن يتولى رئاسة لجان مجلس الإدارة أعضاء غير تنفيذيين ويُفضل أن يكونوا من الأعضاء المستقلين، ويجوز للعضو الواحد أن يتولى رئاسة أكثر من لجنة فيما عدا رئيس لجنة المراجعة.

3-1-7 يجوز أن يحضر أعضاء اللجان الاجتماعات من خلال الاتصال الهاتفي أو الاتصال عبر الفيديو شريطة الالتزام بالضوابط الفنية الواردة بالبند 2-5-5.

3-1-8 في حالة تغيب العضو عن أكثر من ثلث جلسات اللجنة خلال العام، يتم اخطار رئيس مجلس الإدارة لاتخاذ الإجراءات اللازمة بما يضمن الانتظام في الحضور.

3-1-9 إعداد تقرير دوري يتضمن نتائج أعمال كل لجنة وتوصياتها للعرض على مجلس الإدارة.

3-1-10 مراعاة توفير قنوات الاتصال اللازمة بين اللجان وبعضها بما يُمكنها من أداء أعمالها.

3-2 لجنة المراجعة

3-2-1 تُشكل في كل بنك لجنة للمراجعة من ثلاثة من أعضاء مجلس إدارة البنك غير التنفيذيين يختارهم مجلس إدارة البنك ويفضل أن يكون رئيسها من الأعضاء غير التنفيذيين المستقلين ولا يتولى رئاسة أي لجنة أخرى، مع ضرورة توافر الخبرة الملائمة وضمان تحقيق التوازن المطلوب في القدرات والمعرفة والدراية الكافية بالموضوعات المالية ومجالات المراجعة والمحاسبة.

3-2-2 يجوز أن يُضم إلى تشكيل اللجنة عضواً خارجياً من ذوي الخبرة بعد الحصول على موافقة محافظ البنك المركزي على انضمامه.

3-2-3 تتمثل أهم وظائف لجنة المراجعة في الموافقة على ترشيح المسئولين عن قطاعي المراجعة الداخلية والالتزام قبل الحصول على موافقة البنك المركزي، فضلاً عن متابعة أعمال القطاعين، وتحديداً فيما يخص سلامة نظم الرقابة الداخلية، ويقوم كل من رئيس قطاع المراجعة الداخلية ورئيس قطاع الالتزام برفع التقارير مباشرة إلى لجنة المراجعة التي تقوم بدورها بعرضها على مجلس الإدارة.

3-2-4 يجب أن تعقد لجنة المراجعة اجتماعاً كل ثلاثة أشهر على الأكثر يحضره مراقبا الحسابات - بدعوة من رئيسها أو بطلب من أي من مراقبي الحسابات، وللجنة أن تستعين في عملها بمن تراه مناسباً ويعرض رئيس اللجنة محاضر اجتماعاتها وتوصياتها على مجلس إدارة البنك ليتخذ ما يراه بشأنها.

3-2-5 يحضر اجتماعات اللجنة رئيس قطاع المراجعة الداخلية، ورئيس قطاع الالتزام بالبنك بالإضافة إلى من ترى اللجنة دعوته دون أن يكون لهم صوت معدود.

3-2-6 يجب على لجنة المراجعة عرض تقرير ربع سنوي يتضمن نتائج أعمال القطاعات المعنية، ومناقشته بمجلس الإدارة وتحديد الإجراءات التصحيحية الواجب اتخاذها في الوقت المناسب.

3-2-7 تتولى لجنة المراجعة الاختصاصات الآتية:

3-2-7-1 مناقشة ما تراه اللجنة من موضوعات مع رئيس قطاع المراجعة الداخلية، ورئيس قطاع الالتزام بالبنك، ومراقبي الحسابات، والمسئولين المختصين.

3-2-7-2 دراسة القوائم المالية الدورية (ربع السنوية) والسنوية للموافقة عليها قبل عرضها على مجلس الادارة لاعتمادها وذلك بحضور رئيس القطاع المالي.

3-2-7-3 الاطلاع على القوائم المالية المُعدة للنشر والتأكد من اتساقها مع قواعد اعداد وتصوير القوائم المالية للبنوك الصادرة عن البنك المركزي.

3-2-7-4 مراجعة الخطة السنوية لكل من قطاعي المراجعة الداخلية والالتزام واعتمادهما، مع المتابعة الدورية المنتظمة وفقاً للمحقق منهما.

3-2-7-5 مراجعة التقارير المُعدة من قبل قطاع المراجعة الداخلية بما في ذلك التقارير المتعلقة بمدى كفاية نظم الرقابة الداخلية بالبنك.

3-2-7-6 مراجعة التقارير المعدة من قبل المسئول عن قطاع الالتزام بالبنك وخاصة فيما يتعلق بمخالفة القوانين والتعليمات الصادرة عن البنك المركزي واللوائح الداخلية للبنك وإجراءات مكافحة غسل الأموال وتمويل الإرهاب.

3-2-7-7 مراجعة التقارير المُعدة بشأن خبرات العاملين بقطاعي المراجعة والالتزام ومستويات تدريبهم وتأهيلهم.

3-2-7-8 دراسة المعوقات التي تواجه عملية المراجعة الداخلية أو عمل مسئول الالتزام واقتراح سبل تذليلها.

3-2-7-9 مراجعة سياسات ولوائح المراجعة الداخلية والالتزام وعرضها على المجلس لاعتمادها.

3-2-7-10 مراجعة الاجراءات المُتخذة من قبل البنك للالتزام بالضوابط الرقابية الصادرة عن البنك المركزي والتحقق من اتخاذ الإجراءات التصحيحية اللازمة في حالة مخالفتها.

3-2-7-11 إجراء تقييم سنوي لكل من رئيس قطاع المراجعة الداخلية، ورئيس قطاع الالتزام ورفع نتائج هذا التقييم لمجلس الإدارة وربطه بالأجور والمكافآت والزيادات السنوية، وكذلك رفع التوصيات لمجلس الإدارة للموافقة على تعيين أو إقالة أو قبول استقالة أي منهما.

3-2-7-12 عرض الهيكل التنظيمي الخاص بقطاعي المراجعة الداخلية والالتزام بما يشمل مهامهما واختصاصاتهما واعتمادهم من مجلس الإدارة.

3-2-7-13 دراسة ملاحظات البنك المركزي الواردة بتقارير الرقابة والإشراف وكذا تلك الخاصة بالقوائم المالية وإبلاغ مجلس الادارة بها مصحوبة بتوصيات اللجنة، مع متابعة تصويبها.

3-2-7-14 مراجعة أي إجراءات قانونية قد تؤثر على المركز المالي للبنك.

3-2-7-15 مراجعة التقارير الواردة من وحدة حماية حقوق العملاء والنظر في الإجراءات المقترحة والاشراف على تنفيذها في حالة الموافقة عليها.

3-2-7-16 مراجعة التقارير الدورية الخاصة بحالات الإبلاغ عن المخالفات والممارسات غير المشروعة وتقييم نظام الإبلاغ عنها وحماية المبلغ بالبنك.

3-2-8 يكون للجنة المراجعة دور هام فيما يخص أعمال مراقبي حسابات البنك من خلال ما يأتي:

3-2-8-1 تقديم المقترحات بشأن ترشيح وتعيين مراقبي الحسابات وتحديد أتعابهما، أو النظر في تغيير أي منهما وذلك بما لا يتعارض مع أحكام قانون البنك المركزي وقانون الجهاز المركزي للمحاسبات والتعليمات الصادرة في هذا الشأن.

3-2-8-2 التنسيق بين مهام المراجعة الداخلية والخارجية والتأكد من توافر قنوات للاتصال بين رئيس قطاع المراجعة الداخلية ومراقبي الحسابات وكل من مجلس الادارة ولجنة المراجعة.

3-2-8-3 الاتفاق على نطاق المراجعة مع مراقبي الحسابات واعتماده والإشراف على السياسات المحاسبية المطبقة بالبنك.

3-2-8-4 دراسة ملاحظات مراقبي الحسابات الواردة بتقريرهما على القوائم المالية للبنك وبتقاريرهما الأخرى المُرسلة للبنك خلال العام، ورفعها لمجلس الإدارة مصحوبة بتوصيات اللجنة، والتأكد من اتخاذ البنك الإجراءات التصحيحية اللازمة في الوقت المناسب بما في ذلك نواحي القصور ونقاط الضعف في نظام الرقابة الداخلية وعدم الالتزام بالسياسات والقوانين السارية.

3-3 لجنة المخاطر

3-3-1 تشكل اللجنة من عدد فردي لا يقل عن ثلاثة أعضاء، ويكون أغلبية أعضائها من أعضاء المجلس غير التنفيذيين، ويكون رئيس اللجنة عضو غير تنفيذي ويفضل أن يكون عضو غير تنفيذي مستقل، على أن يتم دعوة رئيس قطاع المخاطر لحضور اجتماعات اللجنة، كما يتعين أن يكون لدى بعض أعضاء اللجنة خبرة بأعمال إدارة المخاطر.

3-3-2 يجب أن تعقد اللجنة اجتماعاً بحد أدنى كل ثلاثة أشهر، وللجنة أن تستعين بمن تراه في القيام بعملها، وتعرض توصياتها على مجلس إدارة البنك.

3-3-3 من أهم اختصاصات اللجنة الموافقة على ترشيح المسئول عن قطاع المخاطر قبل الحصول على موافقة البنك المركزي، فضلاً عن الموافقة على إجراءات عمل القطاع ومتابعة مهامه واختصاصاته، كما تقوم اللجنة بمتابعة مدى الالتزام بالسياسات المتعلقة بالمخاطر، وكذلك التأكد من تطبيق تلك السياسات من قبل الإدارة العليا وذلك من خلال التقارير المُرسلة لها من رئيس قطاع المخاطر والإدارات والقطاعات المعنية الأخرى، ومن جهة أخرى ترفع اللجنة تقارير دورية ربع سنوية إلى المجلس.

3-3-4 يتم عرض الهيكل التنظيمي الخاص بقطاع المخاطر بما يشمل مهامها واختصاصاتها على لجنة المخاطر ويتم اعتماده من مجلس الإدارة.

3-3-5 تقوم اللجنة بتقديم مقترحاتها بشأن السياسات الخاصة بإدارة البنك للمخاطر متضمنة الحدود المقبولة لها، وكذا التأكد من توافقها مع الحدود المقررة من مجلس إدارة البنك، (بما في ذلك تلك الخاصة بمؤشرات رأس المال وإدارة السيولة ومخاطر الائتمان والسوق والمخاطر التشغيلية ومخاطر أمن المعلومات وأية مخاطر أخرى قد يتعرض لها البنك)، وعلى مجلس إدارة البنك الموافقة والتصديق على تلك السياسات.

3-3-6 تقوم اللجنة بالتأكد من قيام قطاع المخاطر بإجراء تقييم ربع سنوي على الأقل لكافة المخاطر لدى البنك، بما يشمل أي إجراءات تم اتخاذها في هذا الشأن، ويُعرض هذا التقييم على اللجنة ويُعتمد من مجلس الإدارة في أول اجتماع تالي لهذا التقييم.

3-3-7 تقوم اللجنة بالتأكد من قيام قطاع المخاطر بمراجعة قيم الضمانات العينية المقدمة ضماناً للتسهيلات الائتمانية بشكل دوري، وتحديد الإجراءات الواجب اتخاذها لمواجهة أي انخفاض في هذه القيم، مع عرض تقرير في هذا الشأن على اللجنة بصفة سنوية.

3-3-8 إجراء تقييم سنوي لرئيس قطاع المخاطر، ورفع نتائج التقييم لمجلس الإدارة وربطه بالأجور، والمكافآت والزيادات السنوية ورفع التوصيات للمجلس للموافقة على تعيينه أو تجديد تعيينه أو إقالته أو قبول استقالته.

3-4 لجنة المرتبات والمكافآت

3-4-1 تُشكل اللجنة من عدد فردي لا يقل عن ثلاثة من أعضاء المجلس غير التنفيذيين ويُفضل أن يكون رئيس اللجنة من الأعضاء غير التنفيذيين المستقلين وتعقد اللجنة اجتماعاً مرة واحدة على الأقل سنوياً.

3-4-2 تكون اللجنة مسئولة عن تقديم مقترحاتها بشأن مكافآت أعضاء المجلس التنفيذيين على أن يشمل ذلك كافة المعاملات المالية؛ بما فيها المرتبات والبدلات والمزايا العينية وأسهم التحفيز ومكافآت التقاعد ونهاية الخدمة وأية عناصر أخرى ذات طبيعة مالية، ويتم وضع التوصيات أخذاً في الاعتبار أهداف البنك واستراتيجيته ومستوى المخاطر المقبول لديه، وتقوم اللجنة بعرض الأمر على مجلس الإدارة للموافقة.

3-4-3 يقع على عاتق اللجنة الاهتمام بوظائف الرقابة الداخلية بالبنك (قطاع المخاطر والالتزام والمراجعة الداخلية) من حيث المعاملات المالية بشكل عام وكذا معدل الإثابة والذي يُحدد وفقاً لتقييم الأداء وما تم تحقيقه من أهداف تخصهم وبما لا يخل باستقلاليتهم.

3-4-4 تتولى اللجنة تحليل نتائج دراسة ومراجعة مستوى المرتبات الممنوحة بالبنك ومقارنتها بمتوسط المرتبات بالبنوك والمؤسسات المثيلة للتحقق من قدرة البنك على استقطاب أفضل العناصر والاحتفاظ بها، مع إمكانية الاستعانة برئيس قطاع الموارد البشرية ودعوته لحضور اجتماعات اللجنة.

3-4-5 تكون اللجنة مسئولة عن إرساء سياسات واضحة وموثقة فيما يخص المرتبات والمكافآت ويتم مراجعتها دورياً وإعادة تقييمها بما يتماشى مع مستوى المخاطر الذي يتعرض له البنك، مع إيضاح الأسس المعتمد عليها، ويتعين أن يقوم المجلس بالتصديق عليها ويتم الإفصاح عن تلك السياسات بما في ذلك الإفصاح عن القيمة الإجمالية لما يتقاضاه العشرون أصحاب المكافآت والمرتبات الأكبر في البنك مجتمعين، على أن يشمل ذلك المرتبات والبدلات والمزايا العينية وأسهم التحفيز وأية عناصر أخرى ذات طبيعة مالية.

3-4-6 يتعين أن تأخذ اللجنة في اعتبارها ما يلي عند القيام بأعمالها:

3-4-6-1 أن يتم مراعاة أهداف البنك طويلة الأجل لدى اقتراح سياسات المرتبات والمكافآت وبالأخص عدم ربط مكافآت مسئولي الإدارة العليا بالبنك بأهداف قصيرة الأجل فقط.

3-4-6-2 اقتراح البدلات والمكافآت والمزايا الأخرى المقررة لأعضاء المجلس غير التنفيذيين والتي يتم اعتمادها من قبل الجمعية العامة، ولا يتم مكافأتهم بمنحهم راتب شهري أو سنوي أو من خلال الأسهم أو الأجور المتغيرة. ويحدد مجلس إدارة البنك مرتبات ومكافآت وبدلات والمزايا الأخرى للأعضاء التنفيذيين.

3-4-6-3 تحديد حجم الأجور المتغيرة، مع إمكانية وضع حد أقصى لها، وطريقة توزيعها على إدارات البنك.

3-4-6-4 عند منح مكافآت في صورة أسهم أو حقوق ملكية، يجب أن تكون وفقاً للمستوى الوظيفي، مع وضع حد أدنى للحيازة وفترة الاحتفاظ بتلك الأدوات.

3-4-6-5 بالنسبة للعاملين الذين يكون لوظائفهم أثر كبير على مستوى المخاطر، ينبغي أن تعكس أجورهم المتغيرة مستوى أداء البنك والمخاطر التي يتعرض لها، وأن يتم تحديدها بصفة دورية لمدة لا تزيد عن سنة، وصرفها وفقاً لمعايير قياس الأداء المحددة من قبل البنك.

3-4-7 يجب أن يتوافر لدى البنك نظام للمرتبات والمكافآت، مع مراعاة ما يلي:

3-4-7-1 وضع سياسة واضحة للمرتبات والمكافآت تتماشى مع أهداف البنك الإستراتيجية طويلة الأجل ويتم اعتمادها من قبل مجلس الإدارة، على أن تتضمن أسس توزيع الأرباح السنوية على العاملين، مع مراعاة حصول العامل المستقيل على نصيبه من الأرباح الموزعة عن فترة عمله بالبنك.

3-4-7-2 أن تتضمن السياسة آلية تحديد المزايا والمكافآت النقدية والعينية الممنوحة لأعضاء مجلس الإدارة والرئيس التنفيذي / العضو المنتدب وربطها بأداء البنك خلال فترة زمنية محددة.

3-4-7-3 أن تكون الأجور والمكافآت مرتبطة بعناصر قياس الأداء خلال فترة زمنية محددة، مع التأكد من عدم منح المكافآت في حالة تجاوز الحدود المقبولة للمخاطر بالبنك.

3-4-7-4 الامتناع عن دفع المكافآت للعاملين الذين قاموا بارتكاب مخالفات جسيمة أو خطأ جوهري متعمد.

3-4-7-5 تحديد المكافآت والبدلات لكل من رئيس مجلس الإدارة وأعضاء المجلس غير التنفيذيين باستقلالية وموضوعية، مع مراعاة الحد من حجم المكافآت المتغيرة المخصصة للسنة المالية حال وجود خسائر.

3-5 لجنة الحوكمة والترشيحات

3-5-1 تُشكل اللجنة من عدد فردي لا يقل عن ثلاثة من أعضاء المجلس غير التنفيذيين على الأقل، ويُفضل أن يكون رئيس اللجنة من الأعضاء غير التنفيذيين المستقلين، وتعقد اللجنة اجتماعاً كل 6 أشهر بحد أدنى، ويقع على عاتق اللجنة مسئولية التأكد مما يأتي:

3-5-1-1 التقييم الدوري لنظام الحوكمة بالبنك.

3-5-1-2 تقديم مقترحاتها بشأن سياسة الحوكمة.

3-5-1-3 إعداد تقرير الحوكمة للبنك وعرضه على المجلس لاعتماده بشكل سنوي على الأقل مع موافاة البنك المركزي بنسخة منه.

3-5-1-4 مراجعة التقرير السنوي للبنك فيما يتعلق بالبنود الخاصة بالحوكمة.

3-5-1-5 دراسة ملاحظات تفتيش البنك المركزي على نظام الحوكمة وأخذها في الاعتبار ومتابعة تنفيذ الاجراءات التصويبية بشأنها.

3-5-1-6 حفظ وتوثيق ومتابعة التقارير الخاصة بتقييم أداء المجلس.

3-5-1-7 تقديم مقترحات بشأن ترشيح الأعضاء غير التنفيذيين المستقلين، وكذا تقديم مقترحات بشأن تعيين أو تجديد عضوية أو استبعاد أي من أعضاء مجلس الإدارة بناءً على التقييم السنوي لهم.

3-5-1-8 مراجعة التقارير المعدة عن دورية انعقاد لجان المجلس.

3-5-1-9 مراجعة البرنامج التعريفي والبرامج التدريبية الموجهة إلى أعضاء مجلس الإدارة.

3-5-1-10 مراجعة خطة التعاقب الوظيفي بالبنك قبل العرض على مجلس الإدارة للاعتماد.

3-5-2 في حالة أن رئيس المجلس عضو باللجنة، يتعين عدم حضوره اجتماع اللجنة الذي يتم فيه تسمية المرشح المقترح أن يخلفه في حالة تركه لمنصبه لأي سبب من الأسباب تجنباً لأي تعارض في المصالح.

3-5-3 يجوز دعوة مسئول الحوكمة بالبنك لحضور اللجنة دون أن يكون له صوت معدود.

4- الإدارة العليا

4-1 تتمثل الإدارة العليا في مسئولي القطاعات الرئيسية بالبنك، ويقع على عاتقهم مسئولية الإشراف اليومي على أعمال البنك، وتنفيذ الاستراتيجيات والسياسات.

4-2 يجب أن يعكس الهيكل التنظيمي للبنك وإجراءات العمل مبدأ الشفافية والإفصاح لضمان فاعلية الإدارة بالبنك، وينبغي تحديد سلطات ومسئوليات توزيع المهام المختلفة الخاصة بمسئولي الإدارة العليا بشكل واضح وتجنب تعارض المصالح والتأكيد على استقلالية الوظائف الرقابية.

4-3 يجب أن يتمتع مسئولو الإدارة العليا بالخبرة والمعرفة والقدرات والمهارات الضرورية لممارسة أعمالهم وقيادة العاملين بكفاءة، حيث تعتبر الإدارة العليا هي المسئول الأول عن أداء البنك أمام المجلس.

4-4 يجب أن يتابع مسئولو الإدارة العليا، كلٌّ في حدود اختصاصه، أداء مديري الإدارات والأقسام فيما يتعلق بأنشطة البنك وعملياته مع التأكد من حُسن أداء العاملين والتزامهم بالسياسات الداخلية وإجراءات العمل وكذا التعليمات الصادرة عن البنك المركزي.

4-5 تكون الإدارة العليا مسئولة عن إعداد وصف وظيفي لكافة وظائف وأنشطة وأعمال البنك والتأكد من مشاركة أكثر من فرد في اتخاذ القرارات الهامة بما يضمن الموضوعية في اتخاذ القرار وتجنب تعارض المصالح.

5- الإفصاح والشفافية

5-1 يتعين على البنك الالتزام بالإفصاح في الوقت المناسب عن البنود الواردة أدناه، وفقاً للقواعد والتعليمات الرقابية الصادرة عن البنك المركزي، وذلك من خلال قنوات الاتصال المختلفة:

5-1-1 أعضاء مجلس إدارة البنك وخبراتهم ومؤهلاتهم وجهات تمثيلهم، ولجان المجلس.

5-1-2 مسئوليات مجلس الإدارة ولجانه.

5-1-3 هيكل الملكية الخاص بالبنك.

5-1-4 الهيكل التنظيمي للبنك بما يشمل شركاته التابعة وذات المصلحة المشتركة.

5-1-5 ميثاق سلوك العمل المصرفي للبنك.

5-1-6 نبذة عن سياسات البنك الداخلية المتعلقة بممارسات الحوكمة على سبيل المثال لا الحصر: سياسة المسئولية المجتمعية، سياسة الإبلاغ عن الممارسات غير المشروعة، سياسة تعارض المصالح (كما هو موضح بالمرفق رقم 1).

5-1-7 نبذة عن سياسات البنك الخاصة بالمرتبات والمكافآت، متضمنة الإفصاح عن القيمة الإجمالية لما يتقاضاه العشرون أصحاب المكافآت والمرتبات الأكبر في البنك مجتمعين، وعلى أن يشمل ذلك المرتبات والبدلات والمزايا العينية وأسهم التحفيز وأية عناصر أخرى ذات طبيعة مالية أو عينية.

5-1-8 القوائم المالية المعتمدة والإيضاحات المتممة لها.

6- علاقة مجلس إدارة البنك بالمساهمين

6-1 يقع على عاتق المجلس مسئولية التأكد من فتح قنوات اتصال مع مساهمي البنك للتأكد من وصول وجهات نظرهم لكل أعضاء المجلس خاصة فيما يتعلق باستراتيجية البنك ونظم الحوكمة والرقابة الداخلية، مع التأكيد على المحافظة على حقوق المساهمين الأخرين غير الرئيسيين.

6-2 ينبغي أن يقوم المجلس بالاستفادة القصوى من اجتماعات الجمعية العامة عن طريق دعم التواصل مع المساهمين وتشجيعهم على المشاركة الفعالة في الاجتماعات.

6-3 يتعين تزويد المساهمين قبل اجتماع الجمعية العامة بفترة زمنية مناسبة بتاريخ ومكان وجدول أعمال الاجتماع وكذلك الموضوعات التي سيتم مناقشتها في الاجتماع بما يتسق مع ما ورد بقانون البنك المركزي.

6-4 ينبغي على رئيس مجلس الإدارة التأكد من استعداد رؤساء كل من لجنة المراجعة ولجنة المخاطر ولجنة المرتبات والمكافآت ولجنة الحوكمة والترشيحات للرد على استفسارات المساهمين، كما يجب على المجلس إتاحة الفرصة للمساهمين لتوجيه أسئلتهم سواء شفهياً أو كتابياً.

6-5 ضرورة الإفصاح للجمعية العامة عن عمليات البنك الهامة مثل المعاملات مع الأطراف المرتبطة وذلك للإحاطة أو الموافقة بحسب الأحوال.

6-6 يتعين إرساء قواعد خاصة بتفويض المساهمين لدى حضور اجتماعات الجمعية العامة، على أن يتم استيفاء التفويض من الناحية القانونية والشكلية وتضمينه تصويت كل مساهم / مساهمين على كل بند من الموضوعات المعروضة على حده، ومراعاة ألا يتم اصدار أي تفويض من المساهمين لأي من أعضاء مجلس الإدارة أو الإدارة العليا أو العاملين بالبنك.

7- إحكام الرقابة على الهياكل والعمليات المعقدة

7-1 يتعين الحد من قيام البنك بعمليات تتخذ أشكالاً قانونية معقدة غير مبررة أو إجراء معاملات من خلال هياكل تنظيمية غير واضحة بما قد يؤثر سلباً على الالتزام بالشفافية، وبما يُحد من قدرة كل من الإدارة العليا للبنك ومجلس الإدارة والبنك المركزي على الإشراف الفعال على البنك أو المجموعة المصرفية بحسب الأحوال.

7-2 ينبغي أن يكون كل من مجلس الإدارة والإدارة العليا على فهم ودراية كاملة لهيكل البنك وكياناته التابعة والمخاطر المصاحبة له وكذلك أية عمليات أو منتجات مُعقدة متوقع طرحها والمخاطر الناتجة عنها، ويتعين على مجلس الإدارة التأكد من وضع سياسات وإجراءات في هذا الشأن بما يشمل أسلوب إدارة تلك المخاطر ووضع حدود ملائمة لها، ويشمل ذلك فهم أثر الروابط بين الكيانات التابعة والمركز الرئيسي للبنك على كافة أنواع المخاطر التي يتعرض لها البنك وتأثيرها على مصادر التمويل ورأس المال ومستوى المخاطر وكذا سمعة البنك والمجموعة المصرفية ككل، مع ضرورة الالتزام بما يأتي:

7-2-1 ضرورة توافر المعلومات الكافية المتعلقة بتلك الهياكل أو العمليات والغرض منها وحجمها والهدف منها والمخاطر المصاحبة لها وآليات الرقابة عليها، مع ضرورة الإفصاح الملائم عنها من خلال رفع تقارير لمجلس إدارة البنك وكذا الإفصاح عنها للبنك المركزي.

7-2-2 المتابعة الدورية لمدى سلامة تطبيق السياسات والإجراءات والحدود الموضوعة.

7-2-3 التأكد من اتساق طبيعة تلك الهياكل أو العمليات وتوافقها مع القوانين والضوابط الرقابية السارية.

7-3 ضرورة قيام مسئولي قطاع المخاطر لكل كيان تابع برفع تقارير دورية للجنة المخاطر بالبنك وذلك بهدف الوقوف على المخاطر التي تتعرض لها المجموعة بما يدعم متابعة والرقابة على تلك الهياكل أو العمليات، مع ضرورة رفع تقارير دورية لمجلس إدارة البنك في هذا الشأن.

7-4 ضرورة قيام مسئولي قطاعي المراجعة الداخلية والالتزام لكل كيان تابع برفع تقارير دورية للجنة المراجعة بالبنك وذلك بما يدعم المتابعة والرقابة على تلك الهياكل أو العمليات، مع ضرورة رفع تقارير دورية لمجلس إدارة البنك في هذا الشأن تشمل أهم الملاحظات أو التجاوزات وكذا الإجراءات التصحيحية المقترحة.

8- هيكل المجموعة

8-1 يجب أن يكون كل من مجلس الإدارة والإدارة العليا على دراية كاملة بالهيكل التنظيمي للبنك أو المجموعة بما في ذلك وحدات العمل المختلفة والشركات التابعة والمخاطر المحيطة بها، والتأكد من تماشي المجموعة ككل مع سياسات المخاطر واستراتيجية العمل المقررة.

8-2 يتعين على مجلس الإدارة والإدارة العليا معرفة تأثير تعاملات المجموعة وهيكلها على رأس المال والسيولة في ظروف العمل الاعتيادية أو الاستثنائية.

8-3 يتعين إرساء سياسات وإجراءات عمل تضمن التواصل الفعال وتبادل المعلومات بين شركات المجموعة (البنك وشركاته التابعة)، وذلك حتى يتسنى الإحاطة بكافة المخاطر المحيطة بها وإحكام الرقابة عليها، كما يتعين على الإدارة العليا رفع التقارير إلى مجلس الإدارة بما يضمن إحاطة المجلس بهيكل المجموعة على أن تتضمن أية مستجدات ذات صلة قد يترتب عليها تغير في المخاطر أو الإيرادات.

8-4 يتعين التأكد من إحاطة مجلس الإدارة بكافة المخاطر المصاحبة للمنتجات والخدمات التي تقدمها الشركات التابعة والمجموعة ككل.

8-5 التأكد من وجود سياسة لإدارة تعارض المصالح بهدف إدارة وتنظيم المعاملات بين كيانات المجموعة المختلفة.

8-6 يجب أن يتوافر لدى البنك استراتيجية واضحة لهيكل المجموعة، ويتعين على الإدارة العليا التأكد مما يأتي:

8-6-1 وضع هيكل فعال للمجموعة يخدم أهداف البنك ولا يحتوي على أشكال معقدة غير مبررة اقتصادياً أو قانونياً، على أن يتم موافاة البنك المركزي بأية تعديلات جوهرية تطرأ عليه خلال السنة.

8-6-2 وجود آلية مركزية لمراجعة الاستراتيجية والسياسات والإجراءات، وكذا وجود سياسة للموافقة على إنشاء الكيانات التابعة أو تصفيتها ومراقبة أعمالها للتحقق من التزامها بالغرض الذي أنشئت من أجله.

8-6-3 القدرة على توفير معلومات دقيقة تتعلق بهيكل البنك أو المجموعة ككل، وهيكل الملكية، وطبيعة الأنشطة وذلك بالنسبة لكل كيان قانوني تابع على حده.

8-6-4 إدارة كافة المخاطر الناشئة عن الهيكل التنظيمي للمجموعة بما يتضمن المخاطر الناتجة عن التعاملات المالية بين كيانات المجموعة، وعدم موافقة المجلس على إنشاء تلك الكيانات إلا بعد التأكد من إمكانية تحديد وإدارة المخاطر الناشئة جراء ذلك.

8-6-5 التأكد من وجود الخبرات اللازمة والموارد الكافية لإجراء رقابة دورية (داخلية وخارجية) على كافة الكيانات من قبل المجموعة بهدف موافاة مجلس الإدارة بتقارير دورية بشأن أداء تلك الكيانات والتزامها بالمتطلبات القانونية والرقابية، وكذا مدى التزامها بسياسات وحدود المخاطر الخاصة بالمجموعة، كما يجب وضع سياسات تضمن إبلاغ الإدارة العليا ومجلس الإدارة ولجنة المراجعة بأي مخالفات يتم تحديدها لاتخاذ الإجراءات والتوصيات اللازمة في هذا الشأن.

9- الرقابة على الفروع الخارجية

9-1 يتعين على البنوك إحكام الرقابة على فروعها خارج جمهورية مصر العربية من خلال الالتزام بالتالي كحد أدنى:

9-1-1 أن يكون عمل الفروع الخارجية للبنك متماشياً مع أهداف البنك وإستراتيجيته.

9-1-2 التأكد من أن الفرع الخارجي ملتزم بالقوانين والتعليمات الخاصة بالجهات الرقابية بالدولة المضيفة، وكذا القوانين والتعليمات الصادرة عن البنك المركزي المصري بالقدر الذي لا يتعارض مع القوانين السارية في البلد المضيف، كما يتعين على مسئول الالتزام بالبنك إخطار البنك المركزي حال وجود تباين بين القوانين والتعليمات والنظم المحاسبية المطبقة في الدولة المضيفة وتلك الصادرة عن البنك المركزي أو في حالة وجود ما يمنع تبادل المعلومات بين الفرع ومركزه الرئيسي في مصر لاتخاذ اللازم في هذا الشأن، وذلك خلال فترة زمنية مناسبة.

9-1-3 تفويض القدر المناسب من المهام للعاملين بالفرع الخارجي للبنك، مع التأكد من الفصل بين المهام التنفيذية والرقابية لديه، وتطبيق مبدأ الرقابة المشتركة.

9-1-4 التأكد من قيام الفرع الخارجي بأعمال الرقابة الداخلية، وموافاة المركز الرئيسي بتقارير بنتائج هذه الأعمال بشكل دوري.

9-1-5 اعداد تقارير منفصلة عن أداء الفروع الخارجية للعرض على مجلس الإدارة.

9-1-6 ضرورة أن تتضمن خطة المراجعة الداخلية السنوية للبنك للمراجعة على فروع البنك الخارجية بالقدر الذي لا يتعارض مع القوانين السارية في البلد المضيف.

9-1-7 أهمية الاطلاع على ملاحظات تقرير التفتيش الذي تقوم به السلطة الرقابية بالدولة المضيفة مع اخطار البنك المركزي بأهم الملاحظات والإجراءات التصويبية في هذا الشأن.

9-1-8 يتعين ان يعكس الهيكل التنظيمي للفرع تبعية الوظائف الرقابية للمدير المسئول بالمركز الرئيسي.

