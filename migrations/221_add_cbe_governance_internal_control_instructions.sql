تقييم أداء مجلس الإدارة

1- يتعين على البنوك موافاة البنك المركزي في موعد أقصاه نهاية الربع الأول من كل سنة مالية بما يأتي:

1-1 التقييم الذاتي السنوي لأداء مجلس الإدارة ولجانه كوحدة واحدة (على النحو الموضح بالجدول الاسترشادي رقم 1).

1-2 تقييم مستوى أداء كل عضو من أعضاء المجلس على حده على أن يتضمن التقييم عناصر ومعايير محددة، يتم الإفصاح عنها والالتزام بها كحد أدنى ضمن العناصر والمعايير المستخدمة بنماذج التقييم (على النحو الموضح بالجدول الاسترشادي رقم 2).

2- الهدف من التقييم:

التأكد من حسن أداء المجلس وقيامه بالدور المنوط به بصورة فعالة، وتحديد مجالات التغيير التي يمكن أن تؤدى إلى نتائج أفضل، بما ينعكس إيجاباً على القرارات الصادرة عنه بالإضافة إلى تقييم مدى التزام أعضاء مجلس الإدارة بواجباتهم والمتطلبات اللازمة لرفع كفاءتهم.

3- العناصر الرئيسية لتقييم أداء مجلس الإدارة ولجانه، ومستوى أداء كل عضو:

3-1 موافقة مجلس إدارة البنك على النماذج المستخدمة في التقييم الذاتي على مستوى المجلس ولجانه كوحدة واحدة وعلى مستوى أداء كل عضو من الأعضاء على حده.

3-2 تحديد الأهداف الرئيسية المقصود تحقيقها من خلال عملية تقييم الأداء.

3-3 أن يكون التقييم موضوعياً ومستقلاً.

3-4 أن يشجع التقييم المناقشة المفتوحة وإبداء الرأي حول الأداء.

3-5 يتم استيفاء التقييم بواسطة كل عضو منفرداً، وبطريقة تضمن سرية التقييم المقدم من كل عضو.

3-6 أن يشمل التقييم أسئلة لابداء الرأي مع إعطاء درجات مختلفة من الموافقة، مع إضافة أسئلة مفتوحة تتيح الحرية لإبداء الآراء.

4- الإجراءات الواجب اتباعها لدى اعداد تقييم أداء مجلس الإدارة ولجانه، ومستوى أداء كل عضو:

يتم اعداد نماذج التقييم، مع مراعاة تطوير وتحديث تلك النماذج بصفة دورية، كما يمكن تعيين استشاري خارجي لإجراء التقييم إذا رأى مجلس الإدارة ضرورة لذلك، أخذاً في الاعتبار ما يأتي:

1. يتم توزيع التقييم على كافة أعضاء مجلس الإدارة ليقوموا باستيفائه وتقييم بعضهم البعض.

2. تقوم أمانة سر المجلس بتجميع نتائج التقييم وإعداد ملخص بها وعرضها على مجلس الإدارة.

3. يقوم مجلس الإدارة بمناقشة أي إجراءات تصحيحية مطلوبة.

الجدول الاسترشادي رقم (1)

تقييم مجلس الإدارة ولجانه كوحدة واحدة

1- تشكيل مجلس الإدارة

1-1 التمثيل الملائم للمساهمين في البنك.

1-2 دراية أعضاء المجلس بمهمة / إستراتيجية / رؤية البنك.

1-3 توافق تشكيل المجلس مع القوانين والتعليمات الرقابية الصادرة.

1-4 توافر الخبرات والمؤهلات في تشكيل المجلس واللجان.

1-5 عدد أعضاء مجلس الإدارة متوافق مع احتياجات البنك.

1-6 تشكيل اللجان المنبثقة عن المجلس.

1-7 توافر التوازن والاستقلالية في الآراء بالمجلس.

2- توجيه أعضاء مجلس الإدارة الجدد/التطوير المهني للأعضاء

2-1 وضع ميثاق عمل لمجلس الإدارة ولجانه المنبثقة.

2-2 توعية الأعضاء بشأن دورهم بالمجلس، الالتزام الزمني بالمهام والمسئوليات، واستعراض عام للمنظومة وأهدافها الإستراتيجية.

2-3 تنمية المهارات الفنية لأعضاء المجلس بصفة مستمرة خاصةٌ الأعضاء من خارج القطاع المالي أو المصرفي (على سبيل المثال لا الحصر الدورات التدريبية).

2-4 توافر برامج تعريف للأعضاء الجدد في المجلس ومستوى المعلومات المقدمة في هذا البرنامج عن البنك.

3- كفاءة المجلس في وضع الإستراتيجيات والتخطيط وأخذ القرارات

3-1 فعالية مجلس الإدارة في توجيه ووضع الإستراتيجية وتحديد الاهداف طويلة الأجل.

3-2 لجان مجلس الإدارة تتمتع بالكفاءة وتقدم توصيات مفيدة تتيح اتخاذ قرارات أفضل وتجعل اجتماعات مجلس الإدارة أكثر فعالية وكفاءة.

3-3 توزيع وقت اجتماعات مجلس الإدارة بشكل ملائم بين مناقشات مجلس الإدارة وعروض الإدارة التنفيذية.

3-4 تحديد ووضع أولويات وجدولة الموضوعات التي يجب مراجعتها بشكل دوري.

3-5 وجود مناقشات وتفاعل وتبادل في الآراء عند اتخاذ القرارات.

3-6 التطوير والتجديد في أنشطة الأعمال بالبنك، تعيين / الاستعانة بجهات خارجية / خبراء خارجيين للتنفيذ الملائم لبعض المهام.

3-7 انعقاد اجتماعات المجلس ولجانه بصفة دورية منتظمة.

3-8 مدى اطلاع غير الأعضاء باللجان على قرارات اللجان.

3-9 جدول الأعمال المقدم قبل اجتماعات مجلس الإدارة يتيح الاستعداد للاجتماع بشكل مناسب.

4- التزام مجلس الإدارة بدوره الإشرافي على سير أعمال الإدارة العليا

4-1 وضع القيم الأساسية للبنك وقواعد الالتزام بها، تطوير ثقافة العاملين بالبنك، والمعايير الأخلاقية / المجتمعية والمهنية (على سبيل المثال لا الحصر وضع ميثاق سلوك العمل المصرفي وسياسة الابلاغ عن الممارسات غير المشروعة).

4-2 فاعلية التبعية المباشرة للقطاعات الرقابية للجان المجلس.

4-3 تقييم نظم وسير عمل التنظيم الإداري، والموارد البشرية، ومستوى الأجور والمكافآت، وخطط التعاقب الوظيفي، والتعهيد.

4-4 مدى التوجيه من الإدارة التنفيذية لاتخاذ قرار لصالحهم.

4-5 كفاءة العروض المقدمة من الإدارة التنفيذية اثناء اجتماعات مجلس الإدارة بشكل واضح ويكفي لاتخاذ قرارات مناسبة.

4-6 قيام المجلس بتحديد المؤشرات الرئيسية للأداء لمتابعة أداء الإدارة التنفيذية.

4-7 امتلاك مجلس الإدارة الأدوات اللازمة للرقابة والإشراف على الأداء التشغيلي والمالي للبنك بشكل مناسب.

5- وظائف الرقابة الداخلية

5-1 المراجعة الدورية للهيكل التنظيمي الخاص بتلك الوظائف والتأكد المستمر من استقلاليتهم.

5-2 تطبيق سياسة المخاطر للبنك، وثقافة المخاطر، ومستوى المخاطر المقبول، واختبارات التحمل، ونظم المعلومات والتقارير الدورية.

5-3 فاعلية وظيفة الالتزام، وسياسة الالتزام والإجراءات الناتجة عنها.

5-4 فاعلية وظيفة المراجعة الداخلية، وإعداد ومتابعة الخطة السنوية للمراجعة الداخلية.

6- قنوات الاتصال الداخلية والخارجية

6-1 الاجتماع دورياً بالإدارة العليا وقطاع المراجعة الداخلية بالبنك، والاجتماع سنوياً على الأقل بأعضاء المجلس غير التنفيذيين بحضور رئيس المجلس.

6-2 اجتماع الأعضاء غير التنفيذيين مع مراقبي الحسابات بدون الإدارة العليا، بحضور رئيسي إدارة المراجعة الداخلية والالتزام.

6-3 الاجتماع بين أعضاء مجلس الإدارة غير التنفيذيين ورئيس قطاع المخاطر بدون الأعضاء التنفيذيين على الأقل مرة سنوياً.

6-4 وجود آليات فعالة لتطبيق ومتابعة قرارات المجلس.

6-5 اتاحة الاتصال بكبار المسئولين التنفيذيين خارج اجتماعات مجلس الإدارة.

6-6 حصول أعضاء المجلس على معلومات مناسبة في الوقت المناسب لاتخاذ القرار.

6-7 جودة المستندات المقدمة لأعضاء المجلس.

6-8 وجود قنوات اتصال خارجية فعالة وشفافة مع أصحاب المصالح وكافة الأطراف ذات العلاقة.

6-9 قنوات التواصل بين مساهمي البنك وأعضاء المجلس خاصة فيما يتعلق باستراتيجية البنك والتطبيق الأمثل لقواعد الحوكمة.

الجدول الاسترشادي رقم (2)

تقييم أعضاء مجلس الإدارة لبعضهم البعض

1. الاستقلالية في إبداء الرأي.

2. مدى مشاركة وتفاعل الأعضاء في اجتماعات المجلس.

3. الأخذ في الاعتبار ما يتوافق مع حماية مصالح المساهمين وكافة الأطراف ذات الصلة.

4. مدى إفصاح ومعالجة الإفصاح والمعالجة للوقائع والمعاملات التي يبين بها تعارض في المصالح.

5. معرفة كل الأعضاء بالرؤية والرسالة والاستراتيجية الخاصة بالبنك.

6. تعاون أعضاء مجلس الإدارة مع بعضهم البعض بشكل فعال كفريق عمل ومدى تشجيع الأعضاء على التعبير عن آراء مخالفة.

7. مدى فعالية قيادة رئيس المجلس على مستوى مجلس الإدارة وعلى مستوى اللجان.

8. مستوى النقاش في المجالات المختلفة (المصرفية والمالية والاقتصادية والقانونية والتكنولوجية).

9. انتظام الأعضاء في حضور الاجتماعات.

10. خبرات ومؤهلات الاعضاء.

11. تكرار الامتناع عن التصويت من أعضاء المجلس.

12. طرح أسئلة ملائمة وناقدة على الإدارة من أعضاء مجلس الإدارة.

