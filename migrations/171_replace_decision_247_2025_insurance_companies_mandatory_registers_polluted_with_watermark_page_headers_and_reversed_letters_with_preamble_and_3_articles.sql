1- نوع العملية المرفوضة (إصدار - تجديد - تعويض).
2- بيانات المؤمن له وتشمل : الاسم - الرقم القومى أو رقم جواز السفر أو رقم السجل التجارى أو سند الإنشاء ، بحسب الأحوال - رقم الهاتف - البريد الإلكترونى (إن وجد).
