يقيد به جميع عمليات إعادة التأمين الاختيارية التى تبرمها الشركة ، ويجب أن يتضمن - بحد أدنى - البيانات الآتية :
1- اسم العميل.
2- رقم الوثيقة/ الملحق.
3- تاريخ بدء السريان وتاريخ الانتهاء .
4- إجمالى مبلغ التأمين وعدد الأخطار.
5- مبلغ الاحتفاظ وحصص إعادة التأمين موزعة على شركات أو فروع شركات إعادة التأمين والدولة التابع لها.
6- إجمالى وصافى قسط الإصدار ونوع العملة.
7- عمولة إعادة التأمين وفقًا لكل معيد اتفاقى أو اختياري.
8- وسيط إعادة التأمين والدولة التابع لها (إن وجد).
ثامنًا - سجل وسطاء إعادة التأمين :
يقيد به جميع وسطاء إعادة التأمين سواء المقيمين أو غير المقيمين ، الذين تتعامل معهم الشركة ، ويجب أن يتضمن - بحد أدنى - البيانات الآتية :
1- اسم وسيط إعادة التأمين والدولة التابع لها.
2- رقم وتاريخ قيده لدى الهيئة.
3- تاريخ آخر تجديد لقيده لدى الهيئة.
4- إجمالى العمولات المستحقة للوسيط .
تاسعًا - سجل الاستثمارات :
يقيد به جميع استثمارات الشركة ، سواء التى تدار من قبل الشركة أو من خلال إحدى شركات إدارة المحافظ الاستثمارية المرخص لها من الهيئة ، ويتضمن بحسب الأحوال ما يلي :
1- الأموال المخصصة.
2- الأموال الحرة.
3- استثمار الأموال المقابلة للجزء الاستثمارى من وثائق التأمين المرتبطة بالوحدات الاستثمارية .
4- استثمار الأموال المقابلة للعقود التى تصدرها الشركة لعمليات تكوين الأموال.
ويجب أن يتضمن السجل - بحد أدنى - البيانات الآتية :
1- بيان الأرصدة التى تبين الأصول المملوكة للشركة لدى البنوك المودع لديها الأرصدة النقدية ، أو المستثمرة فى شهادات الإيداع أو الاستثمار الصادرة عنها ، وأمناء الحفظ المودع لديهم الأوراق المالية الخاصة بالشركة ، وشركات خدمات الإدارة فى مجال صناديق الاستثمار التى تستثمر الشركة فى وثائقها ، على أن تتضمن بيانات تلك الجهات تفصيلاً .
2- قيمة وعدد جميع الأدوات والأوراق المالية المستثمر فيها.
3- معدلات الفائدة لكل نوع من أنواع الاستثمارات.
4- التعديلات التى طرأت على أى من تلك الأموال مع بيان أى إضافات أو استبعادات على تلك الاستثمارات.
5- قيم الاستثمارات (الاسمية - الدفترية - العادلة) وفقًا للتصنيف المحاسبى طبقًا لنموذج الأعمال المعتمد للشركة ، ومقسمة بحسب عملة الاستثمار.
6- خصم الإصدار وعلاوة الإصدار والاستهلاكات (بالنسبة للأوراق المالية الحكومية).
7- الإهلاك الخاص بالعقارات المستثمر فيها.
8- تاريخ شراء ، وتاريخ الاستحقاق.
9- التصنيف الائتمانى للأوراق أو الأدوات المالية المستثمر فيها «إن وجد».
عاشرًا - سجل العقود :
يقيد به جميع العقود المبرمة بين شركة التأمين وأى من الشركات التى تباشر أيًا من المهن أو الأنشطة المرتبطة بالتأمين ، أو مع أى من الجهات الخارجية ذات الصلة بالعملية التأمينية ، ويجب أن يتضمن - بحد أدنى - البيانات الآتية :
1- بيانات الجهة المتعاقد معها ، وتشمل : (الاسم - العنوان).
2- تاريخ إبرام العقد ومدته.
3- المبالغ المستحقة لأطراف العقد.
4- الغرض من العقد.
5- تاريخ إخطار الهيئة أو الحصول على موافقتها بشأن العقد (إن وجد).
حادى عشر - سجل شكاوى العملاء :
يقيد به جميع الشكاوى التى ترد إلى الشركة من العملاء ، ويجب أن يتضمن - بحد أدنى - البيانات الآتية :
1- بيانات مقدم الشكوى وتشمل :
الاسم - العنوان - الرقم القومى أو رقم جواز السفر أو رقم السجل التجارى أو سند الإنشاء بحسب الأحوال - رقم الهاتف - البريد الإلكترونى (إن وجد).
2- الرقم المرجعى للشكوى .
3- طريقة تقديم الشكوى.
4- تاريخ تقديم الشكوى.
5- موضوع الشكوى.
6- المنتج أو الإدارة المعنية بالشكوى.
7- بيان بالمستندات المرفقة مع الشكوى أو المقدمة تأييدا لها.
8- تاريخ الانتهاء من فحص الشكوى.
9- ما انتهت إليه الشركة بشأن الشكوى (أحقية - عدم أحقية - تمت تسويتها وديًا).
