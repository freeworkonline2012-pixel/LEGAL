-- ⚠️ تصحيح جوهرى اكتُشف أثناء بناء هذه الهجرة (لا فى التدقيق السابق نفسه):
-- من بين الـ21، قانونان لهما صف مقالة واحد فقط (article_count=1) وهو نص OCR
-- تالف فعلياً وغير قابل للقراءة ("حساء حروف") — تحقَّقتُ من محتوى كليهما
-- مباشرة قبل كتابة هذه الهجرة:
--   • 951/2003 (اللائحة التنفيذية لقانون 80/2002) — كان مذكوراً فى تقرير
--     التدقيق كـ"مشكلة معروفة" لكن بلا حسم صريح لحالته؛ التحقق المباشر الآن
--     يُثبت أنه **لا يزال تالفاً**، لم يُصلَح فى أى دفعة سابقة رغم انطباع
--     مغاير محتمل من إشارات سابقة — يُستبعَد من هذا الوسم.
--   • 205/2021 (معايير Fit & Proper) — موثَّق بالفعل صراحة فى تقرير التدقيق
--     كنص مفقود/تالف — يُستبعَد كذلك، متسقاً مع ذلك التوثيق.
-- وسم قانون بمحتوى تالف كـ"ضمن نطاق الحوكمة" كان سيسمح لمحرك استرجاع
-- الخدمة الجديدة بإرجاع مقتطف غير مقروء كـ"أساس قانونى" لحكم حوكمة — ضرر
-- مباشر لجودة الخدمة، لا تحسين هامشى يمكن تأجيله. الاستبعاد هنا جذرى (يمنع
-- المشكلة من مصدرها فى الاسترجاع نفسه) لا حل مؤقت لاحق (مثل فلترة العرض
-- فقط) — إعادة الوسم لهذين القانونين تنتظر نصاً نظيفاً فعلياً أولاً.
--
-- النتيجة: 19 (وليس 21) قانون/قرار يُوسَمان governance_scope=true فى هذه
-- الهجرة. القائمة الكاملة أدناه مع فئة كل واحد (aml_cft / insurance /
-- non_bank_finance) للتوثيق فقط — العمود الفعلى بلا تصنيف فرعى، الفلترة على
-- مستوى "ضمن نطاق الحوكمة/الالتزام/المخاطر" أم لا فقط (Service 3 تحتاج نطاقاً
-- واحداً مُقيَّداً، لا تصنيفاً فرعياً إضافياً فى هذه المرحلة).
--
-- الهجرة قابلة لإعادة التشغيل بأمان (idempotent): ADD COLUMN IF NOT EXISTS +
-- UPDATE بقيمة صريحة (لا تراكمية) — تشغيلها مرتين ينتج نفس الحالة النهائية.
--
-- ⚠️ تصحيح جذرى إضافى (2026-09-11، أثناء دفعة تدقيق نطاق سوق المال):
-- اكتُشف عبر اختبار إعادة تشغيل (idempotency test) للسلسلة الكاملة على
-- قاعدة اختبار محلية أن شرط `WHERE (law_no, law_year) IN (...)` أدناه لم
-- يكن مقيَّداً بـ`category` أو `country_code` — أى أنه يطابق **أى** صف فى
-- جدول laws يحمل نفس زوج (law_no, law_year) بصرف النظر عن فئته. هذا لم
-- يظهر أثره وقت كتابة هذه الهجرة أصلاً (2026-09-04) لأن كل الأزواج
-- الثمانية عشر كانت وقتها فريدة فعلياً فى القاعدة. لكن migrations/043
-- (2026-09-11) أضاف قانون التكنولوجيا المالية (5/2022، فئة
-- non_bank_finance) الذى يتشارك (law_no, law_year) بالصدفة مع قرار
-- اختبارات الوظائف الرئيسية (5/2022، فئة insurance) المُدرَج أصلاً هنا —
-- فأصبح الشرط غير المقيَّد يَسِم قانون التكنولوجيا المالية أيضاً
-- **خطأً** بمجرد إعادة تشغيل هذه الهجرة (وهى تُعاد تلقائياً فى **كل نشر**
-- عبر scripts/run-migration.js، إذ لا يوجد جدول تتبع migrations مُطبَّقة).
-- هذا عيب بنيوى فى الاستعلام نفسه لا فى قرار المحتوى (القرار الموثَّق
-- أعلاه "non_bank_finance (1)" كان ولا يزال صحيحاً) — فالإصلاح هنا هو
-- تقييد الاستعلام ليطابق فعلاً ما وثَّقته التعليقات دائماً: فئة وبلداً
-- محدَّدين، لا رقم/سنة مجرَّدين عرضة للتصادم مع أى قانون مستقبلى. راجع
-- migrations/046 للتصحيح التعويضى الصريح لأى صف تأثر فعلياً بهذا العيب.

BEGIN;

ALTER TABLE laws ADD COLUMN IF NOT EXISTS governance_scope boolean NOT NULL DEFAULT false;

-- aml_cft (8): مكافحة غسل الأموال وتمويل الإرهاب
UPDATE laws SET governance_scope = true
WHERE country_code = 'EG' AND category = 'aml_cft'
  AND (law_no, law_year) IN (
    (80, 2002),
    (94, 2015),
    (11, 2017),
    (22, 2018),
    (53, 2018),
    (1, 2024),
    (161, 2024)
  );

-- insurance (10): حوكمة/التزام/مخاطر شركات التأمين وإعادة التأمين (هيئة الرقابة المالية)
UPDATE laws SET governance_scope = true
WHERE country_code = 'EG' AND category = 'insurance'
  AND (law_no, law_year) IN (
    (100, 2020),
    (17, 2021),
    (59, 2021),
    (5, 2022),
    (48, 2022),
    (3, 2023),
    (4, 2023),
    (89, 2025),
    (148, 2025),
    (200, 2025),
    (2036, 2026)
  );

-- non_bank_finance (1): حوكمة التمويل غير المصرفى (هيئة الرقابة المالية)
-- استُبعِد: 951/2003 و205/2021 (نص تالف — راجع الشرح أعلاه)
UPDATE laws SET governance_scope = true
WHERE country_code = 'EG' AND category = 'non_bank_finance'
  AND (law_no, law_year) IN (
    (101, 2020)
  );

DO $verify$
DECLARE
  v_count int;
  v_expected int := 19;
BEGIN
  SELECT count(*) INTO v_count FROM laws WHERE governance_scope = true;
  IF v_count <> v_expected THEN
    RAISE WARNING 'governance_scope: tagged % laws, expected % — تحقّق يدوياً (بعض القوانين قد تكون غير موجودة بعد فى هذه القاعدة)', v_count, v_expected;
  ELSE
    RAISE NOTICE 'governance_scope: tagged % laws as expected', v_count;
  END IF;
END;
$verify$;

COMMIT;
