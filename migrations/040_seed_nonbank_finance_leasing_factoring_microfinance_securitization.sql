قـرر

(المادة الأولى)
يجوز لشركات التوريق إصدار سندات قابلة للتداول توجه حصيلتها لتمويل الأشخاص الاعتبارية العامة أو الخاصة بعد موافقة السلطة المختصة بها مقابل ما ينشأ لصالح هذه الجهات من تدفقات نقدية متوقع دخولها فى المستقبل فى ذمة المحيل طبقاً للمجرى العادى للأمور، ويشترط فى تلك التدفقات الآتى:
1- أن تكون ناشئة لصالح الأشخاص الاعتبارية العامة أو الخاصة.
2- ألا تكون مقيدة أو مشروطة.
3- أن تكون خالية من أى حقوق حالية أو مستقبلية للغير.

(المادة الثانية)
يتم حوالة نسبة من التدفقات النقدية المستقبلية لمشروع أو مشروعات محددة ناتجة عن أصل أو أكثر للمحيل، خلال فترة محددة، وذلك بموجب اتفاق بين المحيل وشركة التوريق.
وعلى المحيل إعداد دراسة معتمدة من مراقب الحسابات توضح معدلات التشغيل والإيرادات السابقة الخاصة بالمشروع (إن وجدت)، وكذلك التدفقات النقدية المستقبلية المتوقعة للمشروع طوال عمر الإصدار، كما يجب أن تتضمن الدراسة ما يفيد كفاية التدفقات النقدية المستقبلية المقابلة لمحفظة التوريق لسداد مستحقات حملة السندات فى مواعيد استحقاقها.

(المادة الثالثة)
يكون لحملة سندات التوريق حق امتياز على محفظة التوريق بما يضمن الوفاء بحقوقهم ومستحقاتهم فى هذه السندات من أصل وعائد.
ويجوز تقديم ضمانات إضافية يتم الرجوع عليها لسداد مستحقات حملة السندات، ويجوز رهن هذه الضمانات وفقاً للأحكام القانونية المنظمة لذلك.

(المادة الرابعة)
يلتزم محيل محفظة توريق التدفقات النقدية المستقبلية عند إصدار السندات بما يلى:
1- الحصول على درجة تصنيف ائتمانى من إحدى الشركات المرخص لها بذلك أو إحدى الجهات المعتمدة لدى الهيئة، والذى ينبغى ألا تقل درجته عن (-BBB)، مع مراعاة أن يتم تجديده سنوياً طوال عمر الإصدار.
2- الإفصاح فى نشرة الاكتتاب أو مذكرة المعلومات الخاصة بالإصدار عن موجز القوائم والبيانات المالية المعدة وفقاً لمعايير المحاسبة المصرية عن الثلاث سنوات السابقة على الإصدار أو عن المدة من تاريخ التأسيس وحتى الإصدار حال عدم تحقق مدة الثلاث سنوات المشار إليها (إن وجدت)، على أن يرفق به تقرير مراقب الحسابات عن تلك القوائم معداً وفقاً لمعايير المراجعة المصرية.
3- تقديم بيان بصافى القيمة الحالية للتدفقات النقدية المستقبلية، وأسس تقييمها، والضمانات الإضافية إن وجدت معتمداً من مراقب حسابات المحيل.
4- تحديد التدفقات النقدية المستقبلية المراد توريقها بشكل تفصيلى، وتقديم ما يفيد استمرارية تلك التدفقات طوال فترة الإصدار.
5- تحديد الضمانات المقدمة لحملة السندات بشكل محدد للرجوع عليها حال وجود عجز أو إخلال.

(المادة الخامسة)
يجب أن تتضمن نشرة الاكتتاب فى سندات التوريق أو مذكرة المعلومات، فضلاً عن البيانات المنصوص عليها بالمادة (304) من اللائحة التنفيذية لقانون سوق رأس المال، البيانات الآتية:
1- البيانات الخاصة بالمحيل: وعلى وجه الأخص ما يلى:
- الشكل القانونى.
- رأس المال المصدر والمدفوع للشركة المحيلة.
- هيكل المساهمين المالكين لنسبة (%50) أو أكثر من رأس المال أو حقوق التصويت للشركة المحيلة.
- الموقف من القضايا والنزاعات التحكيمية التى تتعلق بنشاطه أو تؤثر على مركزه المالى أو بإحدى مساهماته أو بغيرها من الأصول المملوكة له وإذا كان المحيل شركة فيجب أن يتضمن البيان المشار إليه القضايا والنزاعات التحكيمية التى تتجاوز قيمتها (%2) من حقوق الملكية للشركة وفقاً لآخر قوائم مالية سنوية مجمعة أو منفردة بحسب الأحوال.
- الموقف الضريبى وأى مستحقات أخرى عليه لدى الدولة، وكذا بيان بما إذا كان هناك أى رهونات أو امتيازات على أصوله أو أى قروض أو تسهيلات ائتمانية ممنوحة له (حال وجود ذلك).
2- ملخص لاتفاق الحوالة المبرم بين المحيل وشركة التوريق متضمناً - على الأقل - بياناً بقيمة محفظة التوريق والمعايير والسمات الخاصة بها ومدى تنوعها.
3- موجز القوائم والبيانات المالية للمحيل معدة وفقاً لمعايير المحاسبة المصرية عن الثلاث سنوات السابقة على الإصدار أو عن المدة من تاريخ التأسيس وحتى الإصدار حال عدم تحقق مدة الثلاث سنوات المشار إليها (إن وجدت).
4- قائمة التدفقات النقدية التقديرية لمحفظة التوريق طوال عمر الإصدار، وأسس إعدادها، مرفقاً بها تقرير مراقب الحسابات برأيه فى الافتراضات التى تم الاعتماد عليها فى إعداد قائمة التدفقات النقدية المشار إليها.
5- التزامات وتعهدات الأطراف الخاصة بعملية التوريق طوال عمر الإصدار، وحالات الإخلال بتلك الالتزامات والتعهدات، والإجراءات المتخذة لمواجهتها فى حال حدوثها.
6- التصنيف الائتمانى لكل من المحيل وسندات التوريق والذى ينبغى ألا يقل عن (-BBB) أو ما يعادلها، مع مراعاة أن يتم تجديدهما سنوياً طوال عمر الإصدار.
7- المخاطر التى قد يتحملها حملة السندات وما تم اتخاذه من تدابير أو ضمانات للحد من تلك المخاطر.
وفى جميع الأحوال، يجب اعتماد بيانات نشرة الاكتتاب أو مذكرة المعلومات من رئيس مجلس الإدارة أو العضو المنتدب بشركة التوريق، والمحيل وشركة الترويج والتغطية، وكذا من مراقب حسابات المحيل، والمستشار القانونى لعملية التوريق، وذلك بحسب الأحوال.

(المادة السادسة)
تلتزم شركة التوريق بأن تودع لدى أمين الحفظ خلال ثلاثة أيام عمل من تاريخ تغطية الاكتتاب فى سندات التوريق - على الأقل - ما يلى:
1- نسخة أصلية من نشرة الاكتتاب أو مذكرة المعلومات الخاصة بإصدار السندات والمعتمدة من الهيئة.
2- نسخة من موافقة الهيئة على إصدار السندات.
3- نسخة أصلية من اتفاق الحوالة المبرم بين المحيل وشركة التوريق.
4- نسخة أصلية من اتفاق التحصيل المبرم بين المحيل وشركة التوريق أو الطرف الذى تم الاتفاق معه على تحصيل التدفقات النقدية المستقبلية (حال وجوده)، على أن يتضمن التكليف بتوريد الحصيلة إلى أمين الحفظ فور تحصيلها.
5- المستندات الخاصة بمحفظة التوريق وما يرتبط بها من ضمانات.

(المادة السابعة)
يلتزم المحيل أو المحصل بحسب الأحوال بتوريد التدفقات النقدية المستقبلية محل محفظة التوريق، ويتم إيداعها فى حساب خاص لدى أمين الحفظ فور تحويلها له لصالح حملة السندات.
كما يلتزم أمين الحفظ بسداد أصل وعائد سندات التوريق المصدرة فى مواعيد استحقاقها، وذلك من التدفقات النقدية المستقبلية محل محفظة التوريق، وذلك وفقاً للعقد المبرم بينه وبين شركة التوريق.

(المادة الثامنة)
يتعين على أمين الحفظ أن يفرد حسابات مستقلة لكل عملية توريق، ولا يجوز له الخلط أو الدمج أو المزج بين حساباته الخاصة وبين حسابات عمليات التوريق أو بين بعضها البعض أو أى حسابات أخرى.
ويجب أن يفرد أمين الحفظ لكل عملية توريق الحسابات الآتية:
1- حساب لحصيلة محفظة التوريق.
2- حساب لسداد أصل قيمة سندات التوريق.
3- حساب لسداد العائد المستحق على سندات التوريق.
4- حساب لإدارة استثمار الفائض من حصيلة محفظة التوريق.
