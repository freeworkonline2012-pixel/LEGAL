-- التحقق: قابلة لإعادة التشغيل بأمان (idempotent) — WHERE governance_scope
-- IS DISTINCT FROM true يمنع أى تأثير عند إعادة التشغيل.

BEGIN;

UPDATE laws SET governance_scope = true
WHERE country_code = 'EG'
  AND (law_no, law_year) IN ((42, 2019), (58, 2018), (9, 2021), (61, 2017))
  AND category = 'capital_markets'
  AND governance_scope IS DISTINCT FROM true;

DO $verify$
DECLARE
  v_count int;
  v_expected int := 22;
  v_cm_count int;
BEGIN
  SELECT count(*) INTO v_count FROM laws WHERE governance_scope = true;
  SELECT count(*) INTO v_cm_count FROM laws WHERE governance_scope = true AND category = 'capital_markets';
  IF v_count <> v_expected THEN
    RAISE WARNING 'governance_scope: % قانوناً موسوماً بعد هذه الهجرة، المتوقَّع % — تحقّق يدوياً', v_count, v_expected;
  ELSE
    RAISE NOTICE 'governance_scope: % قانوناً موسوماً كما هو متوقَّع (منها % من فئة capital_markets، كانت 0 قبل هذه الهجرة)', v_count, v_cm_count;
  END IF;
END;
$verify$;

COMMIT;
