===================================================
مواد الإصدار (قبل القانون المرافق)
===================================================

المادة الأولى
يعمل بأحكام القانون المرافق في شأن حماية المستهلك. ولا تخل أحكامه بأحكام قانون حماية المنافسة ومنع الممارسات الاحتكارية الصادر بالقانون رقم 3 لسنة 2005، وقانون الهيئة القومية لسلامة الغذاء الصادر بالقانون رقم 1 لسنة 2017.

المادة الثانية
تختص المحاكم الاقتصادية بالفصل في المنازعات المدنية والتجارية التي تنشأ عن تطبيق أحكام القانون المرافق، وتختص محكمة القضاء الإداري بالفصل في المنازعات الإدارية التي تنشأ عن تطبيق أحكامه.

المادة الثالثة
تصدر اللائحة التنفيذية للقانون المرافق بقرار من رئيس مجلس الوزراء خلال ثلاثة أشهر من تاريخ العمل به، وإلى أن تصدر هذه اللائحة يستمر العمل باللوائح والقرارات السارية، وبما لا يتعارض مع أحكامه.

المادة الرابعة
يلغى قانون حماية المستهلك الصادر بالقانون رقم 67 لسنة 2006.

المادة الخامسة
ينشر هذا القانون في الجريدة الرسمية، ويعمل به اعتبارا من مرور ثلاثة أشهر على تاريخ نشره.
يبصم هذا القانون بخاتم الدولة، وينفذ كقانون من قوانينها.

