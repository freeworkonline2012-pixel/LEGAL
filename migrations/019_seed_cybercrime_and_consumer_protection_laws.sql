القانون المرافق (نص قانون حماية المستهلك)
===================================================

الباب الأول: التعريفات

المادة 1
في تطبيق أحكام هذا القانون، يقصد بالكلمات والعبارات التالية المعنى المبين قرين كل منها:

1- المستهلك: كل شخص طبيعي أو اعتباري يقدم إليه أحد المنتجات لإشباع حاجاته غير المهنية أو غير الحرفية أو غير التجارية، أو يجرى التعامل أو التعاقد معه بهذا الخصوص.

2- الجهاز: جهاز حماية المستهلك.

3- الأشخاص: الأشخاص الطبيعيون، والأشخاص الاعتبارية ومنها الشركات بجميع أشكالها، والكيانات الاقتصادية، والجمعيات والاتحادات والمؤسسات والمنشآت والروابط والتجمعات المالية، وتجمعات الأشخاص على اختلاف طرق تأسيسها المقررة قانونا المعنية بحماية المستهلك، وغير ذلك من الأطراف المرتبطة على النحو الذي تحدده اللائحة التنفيذية لهذا القانون.

4- المنتجات: السلع والخدمات المقدمة من أشخاص القانون العام أو الخاص، وتشمل السلع المستعملة التي يتم التعاقد عليها من خلال مورد، عدا الخدمات المالية والمصرفية المنظمة بأحكام قانون البنك المركزي والجهاز المصرفي، وقانون تنظيم الرقابة على الأسواق والأدوات المالية غير المصرفية.

5- المورد: كل شخص يمارس نشاطا تجاريا أو صناعيا أو مهنيا أو حرفيا يقدم خدمة للمستهلك، أو ينتج سلعة أو يصنعها أو يستوردها، أو يصدرها أو يبيعها أو يؤجرها أو يعرضها أو يتداولها أو يوزعها أو يسوقها، وذلك بهدف تقديمها إلى المستهلك أو التعامل أو التعاقد معه عليها بأي طريقة من الطرق بما في ذلك الوسائل الإلكترونية وغيرها من الوسائل التقنية الحديثة.

6- المعلن: كل شخص يقوم بالإعلان عن سلعة أو خدمة أو الترويج لها بذاته أو بواسطة غيره باستخدام أي وسيلة من الوسائل الإعلامية أو الإعلانية، بما في ذلك الوسائل الرقمية.

ويعد معلنا، طالب الإعلان والوسيط الإعلاني والوكالة الإعلانية ووسيلة الإعلان، وذلك كله وفقا للمواصفات القياسية المصرية الخاصة باشتراطات الإعلان عن السلع والخدمات.

7- العيب: كل نقص في قيمة أو منفعة أي من المنتجات بحسب الغاية المقصودة منها، ويؤدي بالضرورة إلى حرمان المستهلك كليا أو جزئيا من الاستفادة بها فيما أعدت من أجله، بما في ذلك النقص الذي ينتج من خطأ في مناولة السلعة أو تخزينها، وذلك كله ما لم يكن المستهلك قد تسبب في وقوع هذا النقص.

8- التعاقد عن بعد: عمليات عرض المنتجات أو بيعها أو شرائها باستخدام شبكة المعلومات الدولية (الإنترنت)، أو أي وسيلة من وسائل الاتصال المرئية والمسموعة والمقروءة، أو عن طريق الهاتف أو أي وسيلة أخرى.

9- المسابقات: كل عمل يعرض على الجمهور مباشرة أو بواسطة وسيلة إعلامية أو أي وسيلة أخرى، تحت أي مسمى، بما يبعث لدى الجمهور أمل الحصول على جوائز مالية أو عينية مقابل تحملهم أعباء مالية أيا كانت قيمتها.

10- السلوك الخادع: كل فعل أو امتناع عن فعل من جانب المنتج أو المعلن يؤدي إلى خلق انطباع غير حقيقي أو مضلل لدى المستهلك، أو يؤدي إلى وقوعه في خلط أو غلط.

11- الوزير المختص: رئيس مجلس الوزراء.

المادة 2
حرية ممارسة النشاط الاقتصادي مكفولة للجميع، ويحظر على أي شخص إبرام أي اتفاق أو ممارسة أي نشاط يكون من شأنه الإخلال بحقوق المستهلك الأساسية، وعلى الأخص:

1- الحق في الصحة والسلامة عند استعماله العادي للمنتجات.

2- الحق في الحصول على جميع المعلومات والبيانات الصحيحة عن الخدمات أو المنتجات التي يشتريها أو يستخدمها أو تقدم إليه.

3- الحق في الاختيار الحر لمنتجات تتوافر فيها شروط الجودة المطابقة للمواصفات والسعر العادل التنافسي الذي تحدده آليات السوق.

4- الحق في الحفاظ على الكرامة الشخصية واحترام العادات والتقاليد المجتمعية.

5- الحق في المشاركة في المؤسسات والمجالس واللجان التي يتصل عملها بحماية المستهلك.

6- الحق في رفع الدعاوى القضائية عن كل ما من شأنه الإخلال بحقوق المستهلك أو الإضرار بها أو تقييدها، وذلك بإجراءات سريعة وميسرة.

7- الحق في الحصول على تعويض عادل عن الأضرار التي تلحق بالمستهلك أو بأمواله جراء شراء المنتجات أو استخدامها أو تلقي الخدمات.

وذلك كله دون الإخلال بما تقضى به المعاهدات والاتفاقيات الدولية النافذة في جمهورية مصر العربية.

الباب الثاني: التزامات المورد والمعلن

الفصل الأول: الالتزامات العامة

المادة 3
يلتزم المورد بقواعد الصحة والسلامة ومعايير الجودة وضمانها للمستهلك في منتجاته وفقا للمواصفات القياسية المصرية، أو وفقا للمواصفات الدولية المعتمدة في مصر في حال عدم وجودها.

المادة 4
يلتزم المورد بإعلام المستهلك بجميع البيانات الجوهرية عن المنتجات، وعلى الأخص مصدر المنتج وثمنه وصفاته وخصائصه الأساسية، وأي بيانات أخرى تحددها اللائحة التنفيذية لهذا القانون بحسب طبيعة المنتج.

المادة 5
يلتزم المورد بأن تكون جميع الإعلانات والبيانات والمعلومات والمستندات والفواتير والإيصالات والعقود بما في ذلك المحررات والمستندات الإلكترونية وغير ذلك مما يصدر عنه في تعامله مع المستهلك، مدونا باللغة العربية وبخط واضح تسهل قراءته.

كما يلتزم بأن يضع عليها البيانات التي من شأنها تحديد شخصيته، وعلى الأخص عنوانه وطرق الاتصال به، وبيانات قيده في السجل الخاص بنشاطه، وعلامته التجارية إن وجدت.

ويجوز أن تكون تلك البيانات مدونة بلغتين أو أكثر على أن تكون إحداها باللغة العربية.

المادة 6
يلتزم المورد بأن يضع على السلع البيانات التي توجبها المواصفات القياسية المصرية أو القانون أو اللائحة التنفيذية لهذا القانون باللغة العربية بشكل واضح تسهل قراءته، وذلك على النحو الذي يتحقق به الغرض من تلك البيانات حسب طبيعة كل منتج وطريقة الإعلان عنه أو عرضه أو التعاقد عليه.

ويلتزم مقدم الخدمة بأن يحدد بطريقة واضحة بيانات الخدمة التي يقدمها، ومميزاتها، وخصائصها، وأماكن تقديمها ومواعيدها.

المادة 7
يلتزم المورد بأن يعلن أسعار السلع أو الخدمات التي يعرضها أو يقدمها، بشكل واضح على أن يتضمن السعر ما يفرضه القانون من ضرائب أو أي فرائض مالية أخرى، وذلك وفقا للضوابط التي تحددها اللائحة التنفيذية لهذا القانون.

المادة 8
يحظر حبس المنتجات الإستراتيجية المعدة للبيع عن التداول بإخفائها، أو عدم طرحها للبيع، أو الامتناع عن بيعها، أو بأي صورة أخرى.

ويصدر قرار من رئيس مجلس الوزراء بتحديد المنتجات الإستراتيجية لفترة زمنية محددة وضوابط تداولها والجهة المختصة بذلك، وينشر القرار في جريدتين يوميتين واسعتي الانتشار.

ويلتزم حائزو المنتجات الإستراتيجية لغير الاستعمال الشخصي بإخطار الجهة المختصة بالسلع المخزنة لديهم وكمياتها.

المادة 9
يلتزم المورد أو المعلن بتجنب أي سلوك خادع، وذلك متى انصب هذا السلوك على أي عنصر من العناصر الآتية:

1- طبيعة السلعة أو صفاتها الجوهرية أو العناصر التي تتكون منها أو كميتها.

2- مصدر السلعة أو وزنها أو حجمها أو طريقة صنعها أو تاريخ إنتاجها أو تاريخ صلاحيتها أو شروط استعمالها أو محاذيره.

3- خصائص المنتج والنتائج المتوقعة من استخدامه.

4- السعر أو كيفية أدائه، ويدخل في ذلك أي مبالغ يتم إضافتها للسعر وعلى وجه الخصوص قيمة الضرائب المضافة.

5- جهة إنتاج السلعة أو تقديم الخدمة.

6- نوع الخدمة ومكان تقديمها ومحاذير استخدامها وصفاتها الجوهرية سواء انصبت على نوعيتها أو الفوائد من استخدامها.

7- شروط التعاقد وإجراءاته، وخدمة ما بعد البيع، والضمان.

8- الجوائز أو الشهادات أو علامات الجودة التي حصل عليها المنتج أو السلعة أو الخدمة.

9- العلامات التجارية أو البيانات أو الشعارات.

10- وجود تخفيضات على السعر على خلاف الحقيقة.

11- الكميات المتاحة من المنتجات.

ويجوز للائحة التنفيذية لهذا القانون إضافة عناصر أخرى.

المادة 10
يلتزم المورد بأن يسلم المستهلك فاتورة تثبت التعامل أو التعاقد معه على المنتج، متضمنة بصفة خاصة رقم تسجيله الضريبي، وتاريخ التعامل أو التعاقد، وثمن المنتج ومواصفاته، وطبيعته ونوعيته وكميته، وأي بيانات أخرى تحددها اللائحة التنفيذية لهذا القانون، وتبين هذه اللائحة الأحوال التي يكتفي فيها ببيان أو أكثر مما ذكر.

المادة 11
إذا لم يسلم المورد الفاتورة على النحو المبين في المادة (10) من هذا القانون، يكون للمستهلك الحق في إثبات مواصفات المنتج وسائر عناصر التعاقد بجميع طرق الإثبات.

المادة 12
يلتزم المورد في حالة الاتفاق على حجز منتج بأن يسلم المستهلك إيصالا يفيد الحجز، موضحا به خصائص المنتج وصفاته وأي بيانات جوهرية أخرى تحددها اللائحة التنفيذية لهذا القانون بحسب طبيعة المنتج والتعاقد.

المادة 13
يحظر استيراد منتجات أو إنتاجها أو تداولها أو الإعلان عنها على نحو يكون من شأنه التمييز بين المواطنين أو الإساءة إليهم، أو الإخلال بقواعد النظام العام أو الآداب العامة.

المادة 14
لا يجوز الإعلان عن المسابقات بأي وسيلة إلا بعد إخطار الجهاز بالبيانات التي تحددها اللائحة التنفيذية لهذا القانون قبل موعد الإعلان بثلاثة أيام على الأقل وللجهاز أن يوقف المسابقة وأي إعلانات في شأنها إذا تبين له عدم جدية المسابقة، أو أنها خادعة، أو كان الإعلان عنها مخالفا لنص المادة (13) من هذا القانون. ويصدر قرار الوقف وفقا للقواعد [تصحيح تحريرى: "القواعس" فى المصدر، خطأ طباعى واضح] والإجراءات المنصوص عليها في المادة (57) منه.

المادة 15
لا يجوز الإعلان عن حجز وحدات عقارية، أو التعاقد على بيعها، أو بيع الأراضي المعدة للبناء، أو تقسيمها، إلا بعد الحصول على ترخيص بالبناء وفقا لأحكام قانون البناء الصادر بالقانون رقم 119 لسنة 2008 ولا يجوز أن يتضمن التعاقد أي شرط بتقاضي البائع أو خلفه نسبة أو رسوما أو عمولة من ثمن تصرف المشتري في الوحدة العقارية، أو مقابل هذا التصرف. ويقع باطلا كل شرط يخالف ذلك.

المادة 16
يحظر على الموردين التردد على الوحدات السكنية لعرض المنتجات أو بيعها دون طلب مسبق وصريح من المستهلك وفقا للإجراءات التي تحددها اللائحة التنفيذية لهذا القانون.

المادة 17
للمستهلك الحق في استبدال السلعة أو إعادتها مع استرداد قيمتها النقدية، دون إبداء أي أسباب ودون تحمل أي نفقات خلال أربعة عشر يوما من تسلمها، وذلك دون الإخلال بأي ضمانات أو شروط قانونية أو اتفاقية أفضل للمستهلك، وللجهاز أن يحدد مددا أقل بالنظر إلى طبيعة بعض السلع.
واستثناء من أحكام الفقرة الأولى من هذه المادة، لا يجوز للمستهلك مباشرة حق الاستبدال أو الإعادة في الأحوال الآتية:
1- إذا كانت طبيعة السلعة أو خصائصها أو طريقة تعبئتها أو تغليفها تحول دون استبدالها أو ردها، أو يستحيل معه إعادتها إلى الحالة التي كانت عليها عند التعاقد.
2- إذا كانت السلعة من السلع الاستهلاكية القابلة للتلف السريع.
3- إذا لم تكن السلعة بذات الحالة التي كانت عليها وقت البيع لسبب يرجع إلى المستهلك.
4- إذا كانت من السلع التي تصنع بناء على مواصفات خاصة حددها المستهلك، وكانت السلعة مطابقة لهذه المواصفات.
5- الكتب والصحف والمجلات، والبرامج المعلوماتية وما يماثلها.
ويجوز للائحة التنفيذية لهذا القانون إضافة حالات أخرى.

المادة 18
يلتزم المورد بوضع بيان يتضمن حقوق المستهلك في الاستبدال والاسترجاع المعتمدة من الجهاز، والمنصوص عليها في هذا القانون ولائحته التنفيذية في مكان ظاهر داخل أماكن عرض المنتجات أو بيعها. ويحظر على المورد تعليق بيع المنتجات على شرط مخالف للعرف التجاري، أو شرط بيع كمية معينة، أو ربط البيع بشراء منتجات أخرى، أو غير ذلك من الشروط.

المادة 19
يلتزم المورد خلال مدة أقصاها سبعة أيام من اكتشافه أو علمه بوجود عيب في المنتج أن يبلغ الجهاز بهذا العيب وبأضراره المحتملة. فإذا كان من شأن العيب الإضرار بصحة المستهلك أو سلامته، التزم المورد بأن يبلغ الجهاز بهذا العيب فور اكتشافه أو علمه به، وأن يعلن توقفه عن إنتاج المنتج أو التعامل عليه، وأن يحذر المستهلكين من استخدامه بالنشر في وسائل الإعلام المختلفة. ويلتزم المورد في أي من الأحوال المشار إليها، بإصلاح العيب أو باستبدال المنتج أو استرجاعه مع رد قيمته دون أي تكلفة إضافية على المستهلك. ولا يتم استئناف الإنتاج أو التعامل على المنتج من جانب المورد إلا بعد موافقة الجهاز. وتحدد اللائحة التنفيذية لهذا القانون الإجراءات اللازمة لذلك.

المادة 20
يضمن المورد جودة المنتج محل التعاقد وسلامته طوال فترة الضمان، كما يضمن توافر المواصفات التي تم التعاقد بناء عليها.

المادة 21
للمستهلك الحق خلال ثلاثين يوما من تسلم السلعة في استبدالها أو إعادتها مع استرداد قيمتها النقدية، إذا شابها عيب أو كانت غير مطابقة للمواصفات أو للغرض الذي تم التعاقد عليها من أجله. ويلتزم المورد في هذه الأحوال بناء على طلب المستهلك باستبدال السلعة أو استردادها مع رد قيمتها دون أي تكلفة إضافية على المستهلك، وكل ذلك دون الإخلال بأي ضمانات أو شروط قانونية أو اتفاقية أفضل للمستهلك أو ما يحدده الجهاز من مدد أقل بالنظر إلى طبيعة السلعة. وتحدد اللائحة التنفيذية لهذا القانون الأحكام والإجراءات اللازمة لذلك.

المادة 22
يلتزم المورد بضمان السلع المعمرة ضد عيوب الصناعة لمدة عامين على الأقل من تاريخ استلام المستهلك للسلعة، وذلك مع عدم الإخلال بأي ضمانات أو شروط قانونية أو اتفاقية أفضل للمستهلك. ويصدر رئيس مجلس الوزراء بناء على عرض الوزير المختص بشئون الصناعة، قرارا بتحديد السلع المعمرة وفقا للمعايير التي تحددها اللائحة التنفيذية لهذا القانون. وفي حالة المنتجات التي تحتاج إلى تركيب أو تشغيل من جانب المورد تحسب مدة الضمان من تاريخ التركيب أو التشغيل الفعلي، بحد أقصى شهران من تاريخ استلام المستهلك للمنتج، ويجب أن يسلم المورد إلى المستهلك إيصالا مبينا به تاريخ التشغيل الفعلي.

المادة 23
يشمل الضمان أعمال الكشف والفحص والإصلاح وقطع الغيار الأصلية بالإضافة إلى تحمل نفقات انتقال الفنيين ونفقات نقل المنتج عند الحاجة إلى الإصلاح من مقر المستهلك إلى مقر الشركة أو مركز الصيانة وإعادته إلى مقر المستهلك بعد الإصلاح، بما في ذلك نفقات التركيب والتشغيل. ويلتزم المورد خلال فترة الضمان بإعلام المستهلك بفترات الصيانة الدورية، وبأن يسلم المستهلك إيصالا موضحا به ما تم من أعمال إصلاح وصيانة، وإذا لم يقم المورد بإصلاح المنتج التزم بأن يستبدل بالسلعة أخرى جديدة من ذات النوع والمواصفات، أو رد قيمتها، وذلك كله وفقا للمدد والأحوال التي تحددها اللائحة التنفيذية لهذا القانون.

المادة 24
يلتزم المورد إذا تكرر في السلعة العيب ذاته أكثر من مرتين خلال العام الأول من تاريخ استلام المستهلك لها بما يؤثر جوهريا على جودة الأداء الوظيفي للسلعة بأن يستبدل بها أخرى جديدة من ذات النوع والمواصفات دون أي تكلفة على المستهلك أو استردادها مع رد قيمتها، ما لم يحدد الجهاز مدة أقل من المدة المشار إليها بالنظر إلى طبيعة السلعة، وذلك طبقا لما تحدده اللائحة التنفيذية لهذا القانون.

المادة 25
يلتزم مورد الخدمة برد مقابل الخدمة أو مقابل ما يجبر النقص فيها أو إعادة تقديمها إلى المستهلك في حالة وجود عيب أو نقص بها وفقا لطبيعتها وشروط التعاقد عليها والعرف التجاري، أو تنفيذ ما يقرره الجهاز عند الخلاف.

المادة 26
يضمن مورد خدمات التشطيبات والصيانة والتركيبات المنزلية صلاحية ما قام بتنفيذه من أعمال وما تم توريده من منتجات لمدة سنة على الأقل، ما لم يحدد الجهاز مدة أقل بالنظر إلى طبيعة الأعمال أو المنتجات، ويكون الضمان ثلاث سنوات على الأقل إذا كان العيب راجعا لغش أو إهمال جسيم. ويلتزم المورد عند تحقق شروط المسئولية عن عدم الصلاحية بإعادة تقديم الخدمة أو برد مقابلها أو ما يجبر النقص فيها، وباستبدال ما تم توريده من المنتجات أو رد قيمتها، أو تنفيذ ما يقرره الجهاز عند الخلاف. ويلتزم مورد خدمات التشطيبات والصيانة والتركيبات المنزلية بأن يسلم المستهلك وقت التعاقد وقبل مباشرة الأعمال المتعاقد عليها، إيصالا يثبت التعامل ومواصفاته والتكلفة المتوقعة، وأي بيانات أخرى تحددها اللائحة التنفيذية لهذا القانون. وتبين اللائحة التنفيذية لهذا القانون الأحوال التي يكتفي فيها ببيان أو أكثر مما ذكر، وذلك بحسب طبيعة المنتج والعرف التجاري، فإذا لم يسلم المورد الإيصال على النحو المبين بالفقرة السابقة، يكون للمستهلك إثبات سائر عناصر التعاقد بكل طرق الإثبات.

المادة 27
يكون المنتج مسئولا عن كل ضرر يلحقه المنتج أو يحدثه إذا ثبت أن الضرر نشأ بسبب عيب في المنتج يرجع إلى تصميمه أو صنعه أو تركيبه. ويكون المورد مسئولا عن كل ضرر يلحقه أو يحدثه المنتج يرجع إلى طريقة استعماله استعمالا خاطئا إذا ثبت أن الضرر بسبب تقصير المورد في اتخاذ الحيطة الكافية لمنع وقوع الضرر أو التنبيه إلى احتمال وقوعه. ويكون الموزع أو البائع مسئولا عن كل ضرر يلحقه أو يحدثه المنتج إذا ثبت أن الضرر نشأ بسبب عيب يرجع إلى طريقة إعداده للاستهلاك أو حفظه أو تعبئته أو تداوله أو عرضه. وفي جميع الأحوال تكون مسئولية الموردين تضامنية.

المادة 28
يقع باطلا كل شرط يرد في عقد أو وثيقة أو مستند أو غير ذلك مما يتعلق بالتعاقد مع المستهلك، إذا كان من شأنه خفض أي من التزامات المورد الواردة بهذا القانون أو لائحته التنفيذية أو إعفاؤه منها.

المادة 29
يلتزم المورد الذي أبرم العقد بالحفاظ على المعلومات والبيانات الخاصة بالمستهلك، وألا يتداولها أو يفشيها بما يخالف أحكام هذا القانون أو القوانين المتعلقة بهذا الشأن، ما لم يثبت قبول المستهلك صراحة بذلك، كما يلتزم باتخاذ جميع الاحتياطيات الضرورية للحفاظ على سرية وخصوصية هذه البيانات والمعلومات. وللنائب العام أو من يفوضه من المحامين العموم على الأقل، سواء من تلقاء نفسه أو بناء على طلب جهة رسمية أو أحد ذوي الشأن، أن يأمر بالاطلاع أو بالحصول على أي بيانات أو معلومات خاصة بالمستهلك إذا اقتضى ذلك كشف الحقيقة في جناية أو جنحة قامت دلائل جدية على وقوعها. وفي جميع الأحوال، للمحكمة المختصة الاطلاع على تلك البيانات أو المعلومات بمناسبة نظر نزاع معروض عليها.

الفصل الثاني

المادة 30
يلتزم المورد في حالة البيع بالتقسيط بتسليم المستهلك فاتورة أو محررا يشمل البيانات الآتية:
1- السعر الإجمالي للبيع.
2- ثمن البيع للمنتج نقدا.
3- العائد السنوي، ومجموع العائد المستحق عن فترة التقسيط.
4- المبلغ الذي يتعين على المستهلك دفعه مقدما، إن وجد.
5- الجهة المقدمة للمنتج بالتقسيط، ومدته، وعدد الأقساط، وقيمة كل قسط.
6- حقوق والتزامات كل من المستهلك والمورد في حالة إخلال أي منهما بشروط الاتفاق.

المادة 31
للمستهلك الحق في أي وقت في سداد كل الأقساط قبل موعد استحقاقها، على أن يخفض من قيمة ما يتم سداده مقدار العائد المستحق عن باقي المدة، ما لم يتفق على غير ذلك.

المادة 32
في حالة التعاقد بنظام اقتسام الوقت (التايم شير)، أو المشاركة الجزئية في الملكية، يكون للمستهلك الحق في الرجوع في العقد خلال أربعة عشر يوما من تاريخ توقيعه دون إبداء أسباب، ودون تحمل أي نفقات، وذلك دون الإخلال بالقوانين أو القرارات المنظمة لهذه التعاقدات.
وتسري أحكام هذا القانون على التعاقد بنظام الملكية الجزئية أو أي أنظمة أخرى مشابهة لنظام اقتسام الوقت.

المادة 33
تلتزم مراكز الخدمة والصيانة بإبلاغ المستهلك ببيان بأعمال الصيانة والإصلاح اللازمة للمنتج، ومدة الإصلاح وتكلفته، ويجب عليها الحصول على موافقته الصريحة على هذه الأعمال قبل إجرائها.
كما تلتزم بإصدار فاتورة للمستهلك توضح بها ما تم من أعمال الصيانة وما تم استبداله من أجزاء للمنتج محل الخدمة.
وتضمن المراكز المشار إليها سلامة المنتج في حدود خدمة الإصلاح وفقا لطبيعة الخدمة وشروط التعاقد أو الحدود الدنيا للضمان التي تحددها اللائحة التنفيذية لهذا القانون.
كما تلتزم عند تحقق شروط المسئولية عن سلامة الإصلاح إما برد ما حصلته من مقابل للخدمة أو بإعادة تقديم الخدمة بغير أي تكلفة إضافية على المستهلك، وذلك ما لم يكن العيب قد نشأ لسبب أجنبي أو لخطأ المستهلك.

المادة 34
يلتزم المورد بتوفير مراكز الخدمة والصيانة والإصلاح وقطع الغيار الأصلية أو المعتمدة للسلع المستوردة أو المنتجة محليا.
ويلتزم المورد بإخطار الجهاز بمراكز الخدمة والصيانة المعتمدة، وبأي تغيير يطرأ عليها على النحو الذي تحدده اللائحة التنفيذية لهذا القانون.
ويحدد مجلس إدارة الجهاز بقرار منه يصدر بعد أخذ رأي اتحادات الأعمال المعنية، مدة تنفيذ الالتزام الوارد بالفقرة الأولى من هذه المادة والسلع التي تعفى منه بسبب طبيعتها أو بسبب العادات التجارية.

المادة 35
في حالة بيع السلع المستعملة، يلتزم المورد بأن يبين للمستهلك حالة السلعة وما بها من عيوب، وذلك على النحو الذي تبينه اللائحة التنفيذية لهذا القانون.
وفي حالة بيع المركبات المستعملة، يلتزم المورد بأن يقدم إلى المستهلك تقريرا فنيا بحالة المركبة وما بها من عيوب صادرا من مركز خدمة مرخص له بمزاولة هذا النشاط، ما لم يتفق على خلاف ذلك.
وتكون مسئولية المورد ومركز الخدمة مصدر التقرير تضامنية إذا ثبت تعمد أي منهما إخفاء بيانات جوهرية تؤثر على ثمن الشراء أو على إتمام عملية البيع، أو كان عدم تضمن تقرير الفحص تلك البيانات راجعا إلى إهمال جسيم من جانب أي منهما.

الفصل الثالث: التعاقد عن بعد

المادة 36
لا تسري أحكام هذا الفصل على العقود المبرمة بين المستهلك والمورد أو المعلن بحسب الأحوال، في الحالتين الآتيتين:
1- الخدمات المصرفية والمالية والخدمات المرتبطة بالتداول في سوق رأس المال.
2- التعاقد للاشتراك في الصحف وغيرها من المطبوعات الدورية.
ويجوز للائحة التنفيذية لهذا القانون إضافة حالات أخرى تستثنى من تطبيق أحكام هذا الفصل.

المادة 37
يلتزم المورد قبل إبرام العقد عن بعد بأن يمد المستهلك بشكل جلي وصريح، بالمعلومات والبيانات التي تمكنه من اتخاذ قراره بالتعاقد، وعلى الأخص ما يأتي:
1- بيانات المورد، وتشمل الاسم والعنوان ورقم الهاتف والبريد الإلكتروني إن وجد، ورقم السجل التجاري والبطاقة الضريبية، وما إذا كان المورد منتميا لمهنة منظمة قانونا، وصفته المهنية واسم الهيئة أو التنظيم المهني المسجل أو المقيد فيه، بالإضافة إلى أي معلومات تتيح التعرف على المصنع أو المستورد بحسب الأحوال.
2- بيانات المنتج محل العرض، بما فيها مصدره وصفاته وخصائصه الجوهرية، وكيفية استعماله، والمخاطر التي قد تنتج عن هذا الاستعمال إن وجدت.
3- ثمن المنتج وجميع المبالغ التي قد تضاف إلى الثمن، وعلى الأخص الرسوم والضرائب ومصاريف الشحن.
4- مدة العرض.
5- الضمان الذي يقدمه المورد.
6- الخدمات التي يقدمها بعد التعاقد إن وجدت.
7- مدة العرض الذي يتناول خدمات تقدم بشكل دوري.
8- تاريخ التسليم ومكانه، والمصاريف المستحقة عند التسليم.
9- أحكام الرجوع في العقد، وخاصة المدة التي يجوز خلالها للمستهلك الرجوع فيه.
10- بيانات مركز الصيانة وأسلوب إجراء الصيانة للسلع التي حددها هذا القانون.
11- بيانات التعاقد التي سترسل إلى المستهلك في حالة إتمام عملية التعاقد.
وأي بيانات أخرى تكفل حقوق المستهلك وتحددها اللائحة التنفيذية لهذا القانون.

المادة 38
إذا أبدى المستهلك قبوله للتعاقد عن بعد، وجب أن يتم تأكيد موافقته، وأن يتاح له الحق في تصحيح طلبه أو تعديله خلال سبعة أيام عمل من القبول، ما لم يتفق الطرفان على مدة أطول، وذلك في الأحوال وبالكيفية التي تبينها اللائحة التنفيذية لهذا القانون.
وفي غير الأحوال المستثناة التي يصدر بها قرار من مجلس إدارة الجهاز بحسب طبيعة التعاقد أو العادات التجارية المعمول بها، يتعين على المورد أن يرسل إلى المستهلك إخطارا كتابيا فور التعاقد متضمنا بيانات العرض المشار إليها في المادة (37) من هذا القانون، وسائر شروط التعاقد، ويجوز إرسال هذا الإخطار بالبريد الإلكتروني أو بأي وسيط إلكتروني آخر قابل للحفظ والتخزين، ولا يجوز أن يشتمل الإخطار على بيانات مغايرة لتلك التي تضمنها عرض المورد.

المادة 39
يلتزم المورد في التعاقد عن بعد، وفيما لم يرد في شأنه نص خاص في هذا الفصل، بجميع أحكام هذا القانون.

المادة 40
مع عدم الإخلال بأي ضمانات أو شروط قانونية أو اتفاقية أفضل للمستهلك، يحق للمستهلك الذي يتعاقد عن بعد الرجوع في العقد خلال أربعة عشر يوما من استلامه السلعة.
وفي هذه الحالة يلتزم المورد برد المبلغ المدفوع من المستهلك بذات طريقة دفعه، ما لم يتفق على طريقة أخرى للرد، وذلك خلال مدة لا تجاوز سبعة أيام من تاريخ إعادة المنتج بالنسبة للسلع، أو من تاريخ التعاقد بالنسبة للخدمات، ويتحمل المستهلك نفقات الشحن وإعادة المنتج، ما لم ينص العقد على غير ذلك.
وإذا تأخر المورد في تسليم المنتج عن التاريخ المتفق عليه، أو لم يسلمه خلال ثلاثين يوما إذا لم يكن قد اتفق على تاريخ التسليم، يكون للمستهلك الرجوع في التعاقد، دون أي نفقات، خلال أربعة عشر يوما من تاريخ التأخر أو من تاريخ الاستلام أيهما أطول على أن يخطر المورد بذلك، وفي هذه الحالة يلتزم المورد برد المبلغ المدفوع من المستهلك فور إخطاره بالرجوع عن التعاقد وفقا للكيفية والمدد المنصوص عليهما في الفقرتين السابقتين بحسب الأحوال، ويتحمل المورد جميع نفقات إعادة الشحن ومصاريف التسليم.
وذلك كله وفقا للإجراءات التي تحددها اللائحة التنفيذية لهذا القانون.

المادة 41
يسقط حق المستهلك في العدول عن التعاقد المنصوص عليه في المادة (40) من هذا القانون في الحالات الآتية:
1- إذا انتفع كليا بالخدمة قبل انقضاء المهلة المقررة للحق في العدول.
2- إذا كان الاتفاق يتناول سلعا صنعت بناء على طلبه، أو وفقا لمواصفات حددها.
3- إذا كان الاتفاق يتناول أشرطة فيديو أو أسطوانات أو أقراصا مدمجة أو برامج معلوماتية أو مطبوعات أزال المستهلك غلافها.
4- إذا حدث عيب في السلعة نتيجة سوء حيازتها من قبل المستهلك.
5- في الأحوال التي يعد فيها طلب العدول متعارضا مع طبيعة المنتج، أو يخالف العرف التجاري، أو يعد تعسفا من جانب المستهلك في ممارسة الحق في العدول، وذلك كله على النحو الذي تحدده اللائحة التنفيذية لهذا القانون.

الباب الثالث: جهاز حماية المستهلك

المادة 42
جهاز حماية المستهلك هو الجهاز المختص بتطبيق أحكام هذا القانون، ويتمتع بالشخصية الاعتبارية العامة، ويتبع الوزير المختص، ومقره الرئيسي مدينة القاهرة، وله أن ينشئ فروعا بجميع المحافظات، وتجوز له الاستعانة بجمعيات حماية المستهلك في المحافظات في ممارسة اختصاصاته.

المادة 43
يهدف الجهاز إلى حماية المستهلك وصون مصالحه، وله في سبيل تحقيق كل ذلك ما يأتي:
1- وضع الخطط وبرامج العمل لحماية حقوق المستهلك، وتعزيزها وتنميتها، ووسائل تحقيق كل ذلك.
2- نشر ثقافة حماية المستهلك، وإتاحتها للمواطنين.
3- تلقي الشكاوى والبلاغات بجميع أنواعها في مجال حماية المستهلك من المستهلكين والجمعيات، والتحقيق فيها، وتحدد اللائحة التنفيذية لهذا القانون المدة اللازمة للرد على الشكوى طبقا للمجموعات السلعية المختلفة بحد أقصى ثلاثون يوما.
4- التنسيق مع أجهزة الدولة المختلفة لتطبيق أحكام هذا القانون وعلى الأخص جهاز حماية المنافسة ومنع الممارسات الاحتكارية، وتلتزم هذه الأجهزة بتقديم البيانات والمشورة الفنية التي يطلبها الجهاز وذلك فيما يتعلق بالموضوعات المتصلة بأحكام هذا القانون، وبما لا يخل بالقوانين الأخرى، وذلك على النحو الذي تحدده اللائحة التنفيذية لهذا القانون.
5- دراسة الاقتراحات والتوصيات التي ترد إلى الجهاز فيما يتصل بحقوق المستهلك، وإعداد البحوث والدراسات الخاصة بها.
6- التنسيق والتعاون وتقديم الدعم الفني مع الإدارات والقطاعات المعنية بشكاوى المستهلكين والمستخدمين والمواطنين والعملاء في الهيئات والمصالح والأجهزة والوزارات المختلفة، وتبادل الدراسات والبحوث ذات الصلة بمجال تطبيق أحكام هذا القانون.
7- دعم أنشطة الجمعيات الأهلية المختصة بحماية المستهلك فنيا وقانونيا.
8- التعاون مع الأجهزة الرقابية في ضبط الأسواق، والتصدي لأي مخالفة لأحكام هذا القانون.
9- وضع برامج تدريبية لتأهيل المعنيين بمجال حماية المستهلك.
10- تعزيز التعاون في مجال حماية المستهلك في الداخل والخارج واتخاذ الإجراءات الاستباقية والإنذار المبكر للكشف عن أي ضرر محتمل قد يصيب المستهلك.
11- إبداء الرأي في التشريعات والسياسات والقرارات التي من شأنها المساس بحقوق المستهلكين وذلك من تلقاء ذاته أو بناء على طلب الجهات المعنية، وتلتزم الجهات المعنية بأخذ رأي الجهاز في مشروعات القوانين واللوائح المتعلقة بحقوق المستهلك.
12- إقامة الدعاوى المدنية التي تتعلق بمصالح جموع المستهلكين، أو التدخل فيها، وفقا لأحكام القوانين المنظمة لمباشرة إجراءات التقاضي أمام المحاكم.

المادة 44
تتكون موارد الجهاز مما يأتي:
1- الاعتمادات التي تخصص له في الموازنة العامة للدولة.
2- الهبات والمنح والإعانات التي يقبلها وفقا للقانون وبما لا يتعارض مع أهدافه.
3- ما تخصصه الدولة للجهاز من الهبات والمنح والإعانات الدولية الموجهة إلى مجالات حقوق المستهلك.
4- ما يعادل (25%) من الحصيلة النقدية للمصالحات في قضايا مخالفة هذا القانون.
5- حصيلة الرسوم المقررة بمقتضى هذا القانون.
6- مقابل أداء الأعمال والدراسات والخدمات التي يؤديها مع مراعاة حكم المادة (45) من هذا القانون.

المادة 45
يكون للجهاز موازنة سنوية مستقلة، تبدأ مع بداية السنة المالية للدولة، وتنتهي بنهايتها، ويؤول الفائض من موارده إلى الخزانة العامة للدولة.
ومع مراعاة نص المادة (53) من هذا القانون، لا يجوز أن يتقاضى الجهاز مقابلا عن الشكاوى التي يتلقاها من المستهلكين ولا عما يتخذه من إجراءات حيالها، ولا يجوز للعاملين بالجهاز الحصول على حوافز أو مكافآت من حصيلة الغرامات أو حصيلة الهبات والمنح التي يحصل عليها الجهاز.

المادة 46
يعين رئيس الجهاز بقرار من رئيس الجمهورية أو من يفوضه بناء على عرض الوزير المختص، يتضمن تحديد مرتبه وبدلاته.
ويكون للجهاز مجلس إدارة، يشكل برئاسة رئيس الجهاز، وعضوية كل من:
- نائب متفرغ لرئيس الجهاز من ذوي الخبرة
- أحد نواب رئيس مجلس الدولة، يختاره رئيس المجلس
- ممثل للوزارة المختصة بالتجارة الخارجية
- ممثل للوزارة المختصة بالتموين والتجارة الداخلية
- ممثل للوزارة المختصة بالمالية
- ممثل للوزارة المختصة بالصناعة
- ممثل للإدارة العامة لشرطة التموين والتجارة الداخلية
- ممثل للهيئة القومية لسلامة الغذاء
- عضو عن جمعيات الصعيد والقاهرة الكبرى والوجه البحري والقناة والبحر الأحمر وسيناء
- ممثل للاتحاد النوعي لحماية المستهلك
- ممثل للاتحاد التعاوني الاستهلاكي المركزي
- ممثل للاتحاد العام للغرف التجارية واتحاد الصناعات المصرية
مدة المجلس أربع سنوات قابلة للتجديد لمرة واحدة.

المادة 47
مجلس إدارة الجهاز هو السلطة العليا المهيمنة على شئونه، وله أن يتخذ ما يراه من القرارات لتحقيق أهدافه، ويباشر اختصاصاته على الوجه المبين في هذا القانون، وله على وجه الخصوص ما يأتي:
1- وضع لوائح تنظيم العمل به وتنظيم أمانته الفنية وشئونه المالية والإدارية وذلك دون التقيد بالنظم الحكومية، وتصدر هذه اللوائح بقرار من الوزير المختص.
2- قبول الهبات والمنح والإعانات والتبرعات التي تقدم للجهاز وفقا للقانون وبما لا يتعارض مع اختصاصاته.
3- الموافقة على مشروع الموازنة السنوية والحساب الختامي للجهاز.
4- اقتراح أسماء العاملين بالجهاز المطلوب منحهم صفة الضبطية القضائية اللازمة لتطبيق أحكام هذا القانون.
5- النظر في التقارير التي يقدمها رئيس الجهاز عن سير العمل به، وما يتطلبه العمل من قرارات وإجراءات.

المادة 48
يجتمع مجلس الإدارة بدعوة من رئيسه مرة على الأقل كل شهر، وكلما دعت الحاجة لذلك، وتجوز دعوة المجلس للانعقاد بناء على طلب ثلثي أعضائه، وتكون اجتماعاته صحيحة بحضور عشرة أعضاء وتصدر قراراته بأغلبية أصوات الحاضرين، وإذا تساوت الأصوات يرجح الجانب الذي منه الرئيس.
وتكون قرارات المجلس نافذة دون الحاجة إلى اعتماد أو تصديق، وللمجلس أن يدعو إلى حضور جلساته من يرى الاستعانة بهم من ذوي الخبرة دون أن يكون لهم صوت معدود في التصويت.
ولا يجوز لرئيس المجلس أو لأي عضو من أعضائه الاشتراك في المداولات أو التصويت في أي حالة تعرض على المجلس يكون له أو لمن يمثله مصلحة فيها، أو خصومة بينه وبين أحد أطرافها، أو أحد أقربائه حتى الدرجة الرابعة، أو يكون قد مثل أو يمثل أحد الأطراف المعنية.
وتنظم اللائحة التنفيذية لهذا القانون الإجراءات اللازمة في حالة وجود تعارض في المصالح.

المادة 49
يكون للجهاز مدير تنفيذي متفرغ، يصدر بتعيينه وبتحديد معاملته المالية قرار من الوزير المختص بناء على ترشيح مجلس إدارة الجهاز، وتحدد اللائحة التنفيذية لهذا القانون اختصاصاته، وتكون مدة تعيينه سنتين قابلة للتجديد، ويحضر المدير التنفيذي اجتماعات مجلس الإدارة دون أن يكون له صوت معدود.

المادة 50
يمثل رئيس مجلس الإدارة الجهاز أمام القضاء وفي صلاته بالغير، ويتولى تنفيذ قرارات المجلس وتصريف شئون الجهاز وتطوير نظم العمل به، وله تفويض نائبه أو المدير التنفيذي أو من يراه في بعض اختصاصاته، وعند غيابه أو خلو منصبه يحل محله نائب الرئيس بصفة مؤقتة.

المادة 51
يكون للعاملين بالجهاز وغيرهم من العاملين المدنيين بالدولة الذين يصدر بتحديدهم قرار من وزير العدل بناء على اقتراح مجلس إدارة الجهاز صفة الضبطية القضائية في تطبيق أحكام هذا القانون وقانون قمع التدليس والغش رقم 48 لسنة 1941 والمرسوم بقانون رقم 95 لسنة 1945 الخاص بشئون التموين.
ويكون لمأموري الضبط القضائي الحق في الاطلاع لدى أي جهة حكومية أو غير حكومية على جميع الدفاتر والمستندات والحصول على جميع المعلومات والبيانات اللازمة لفحص الحالات المعروضة على الجهاز.
ويكون لهم لهذا الغرض دخول جميع الأماكن المخصصة للبيع أو المودع بها المنتجات الخاضعة لأحكام هذا القانون، ولهم أخذ عينات من تلك المنتجات، وفحصها وتحليلها في المعامل التي تحددها اللوائح والقرارات الصادرة تنفيذا لأحكام هذا القانون، ووفقا للإجراءات المقررة بها.

المادة 52
في الأحوال التي ينشأ فيها خلاف بين المورد والمستهلك والمعلن حول تطبيق أحكام هذا القانون، أو في حق المستهلك في استبدال السلعة، أو رد قيمتها في الأحوال المنصوص عليها في هذا القانون، يحال الأمر إلى الجهاز ليصدر قرارا ملزما في هذا الشأن.
وللجهاز أن يصدر قرارا باستبدال السلعة، أو برد قيمتها بسعر شرائها من تاريخ تقديم المستهلك الشكوى مضافا إليه العائد المقرر وفقا للسعر المعلن من البنك المركزي، أو برد القيمة السوقية للسلعة، وذلك كله وفقا للضوابط والإجراءات التي تحددها اللائحة التنفيذية لهذا القانون.
ولمجلس إدارة الجهاز أن يشكل لجانا تتولى فحص المنازعات التي تقع بين المستهلكين وبين الموردين أو المعلنين والناتجة عن تطبيق أحكام هذا القانون، وتصدر التوصيات اللازمة في شأنها للجهاز، وللجنة أن تستعين في أداء عملها بمن ترى الاستعانة بهم دون أن يكون لهم صوت معدود عند التصويت.

المادة 53
للجهاز الحق في توجيه أطراف الشكوى لفحص المنتج محل الشكوى فنيا بأحد المعامل أو الهيئات المعتمدة عند الحاجة لذلك، ويحدد الجهاز الطرف المتحمل لمصروفات الفحص الفني أو المعاينات.

المادة 54
يلتزم المورد والمعلن بموافاة الجهاز بما يطلبه من البيانات أو الأوراق أو المستندات اللازمة لممارسة اختصاصاته، وذلك خلال المواعيد التي تحددها اللائحة التنفيذية لهذا القانون.

المادة 55
يحظر الإفصاح عن المعلومات والبيانات المتعلقة بحالات تطبيق القانون التي يتم تقديمها أثناء الفحص. كما يحظر استخدام هذه المعلومات لغير أغراضها الأصلية، وعلى العاملين بالجهاز عدم العمل لدى الأشخاص الخاضعين للفحص لمدة عامين من تاريخ الفحص.

المادة 56
على الجهاز عند ثبوت مخالفة أحكام هذا القانون إلزام المخالف بتعديل أوضاعه وإزالة المخالفة خلال فترة زمنية يحددها مجلس إدارته، وذلك دون الإخلال بأحكام المسئولية الناشئة عن هذه المخالفات. وإذا ترتب على المخالفة أو كان من شأنها وقوع أي ضرر بصحة المستهلك أو سلامته، يكون لمجلس إدارة الجهاز وفقا للقواعد التي تبينها اللائحة التنفيذية لهذا القانون إصدار قرار بوقف تقديم الخدمة، أو التحفظ على السلع محل المخالفة إلى حين انتهاء التحقيقات أو قرار قضائي أو صدور حكم في شأنها، ويجب أن يتخذ الجهاز التدابير اللازمة لإعلام المستهلكين بالمخالفة.

المادة 57
في أحوال مخالفة المادتين (9) و(14) من هذا القانون، للجهاز أن يطلب من المورد والمعلن تصحيح أو تعديل الإعلان الخادع أو المضلل، فإذا امتنع عن إجراء التصحيح خلال ثلاثة أيام من تاريخ الطلب، أو كان محل الإعلان منتجا يشكل ضررا على صحة المستهلك وسلامته، أو كان الإعلان مخالفا لأحكام المادة (13) من هذا القانون، كان للجهاز أن يتخذ الإجراءات الكفيلة بوقف الإعلان مؤقتا لمدة لا تجاوز سبعة أيام، وعليه في هذه الحالة أن يحرر محضرا يثبت فيه ما تم من إجراءات ومبرراتها ويعرضه على النيابة العامة المختصة، وذلك خلال ثمان وأربعين ساعة من تاريخ وقف الإعلان. وعلى النيابة عرض المحضر على محكمة الجنح المستأنفة المختصة منعقدة في غرفة المشورة خلال أربع وعشرين ساعة مشفوعا بمذكرة برأيها، وتصدر المحكمة قرارا وقتيا في شأن المحضر، في مدة لا تجاوز اثنتين وسبعين ساعة من تاريخ عرضه عليها، إما بتأييد ما تم من إجراءات لوقف الإعلان، أو بإلغائها، وتفصل المحكمة في مدى استمرار العمل بالإجراءات الصادرة من الجهاز بوقف الإعلان كلما رأت وجها لتأجيل نظر المحضر. فإذا لم يعرض الجهاز المحضر المشار إليه في الفقرة السابقة في الموعد المحدد يعد قراره بوقف الإعلان كأن لم يكن. ويسقط الأمر الوقتي الصادر من المحكمة في المحضر بصدور أمر من النيابة العامة بألا وجه لإقامة الدعوى الجنائية، أو بصدور حكم نهائي بالبراءة.

المادة 58
مع مراعاة ما ورد في شأنه نص خاص في هذا القانون، تكون القرارات التي يصدرها الجهاز تطبيقا لأحكام هذا القانون نهائية ويكون الطعن عليها أمام محكمة القضاء الإداري. ويستثنى الطعن على القرارات المشار إليها من تطبيق أحكام القانون رقم 7 لسنة 2000 بإنشاء لجان التوفيق في بعض المنازعات التي تكون الوزارات والأشخاص الاعتبارية العامة طرفا فيها.

المادة 59
يجوز لمجلس إدارة الجهاز، بناء على موافقة أغلبية أعضائه، التصالح مع المتهم في الجرائم المنصوص عليها في هذا القانون، ما لم ينتج عنها أية إصابات أو حالات وفاة للمستهلكين، وبشرط إزالة أسباب المخالفة، وذلك على النحو الآتي:
1- يجوز التصالح قبل إحالة الدعوى الجنائية إلى المحكمة المختصة مقابل أداء مبلغ لا يقل عن الحد الأدنى ولا يجاوز ثلث الحد الأقصى للغرامة المقررة.
2- يجوز التصالح بعد إحالة الدعوى الجنائية إلى المحكمة المختصة وحتى صدور حكم نهائي فيها مقابل أداء مبلغ لا يقل عن ثلاثة أمثال الحد الأدنى للغرامة المقررة، ولا يجاوز نصف حدها الأقصى.
ويترتب على التصالح انقضاء الدعوى الجنائية.

المادة 60
يلتزم الجهاز بوضع برنامج يسمى ((صديق المستهلك)) يشترك فيه المورد بناء على طلبه، ويمنح شهادة تسمى ((شهادة صديق المستهلك)) عن سنة واحدة سابقة لتقديم الطلب شريطة التزامه بأحكام هذا القانون ولائحته التنفيذية. وللجهاز الحق في سحب هذه الشهادة فور علمه بثبوت إخلال المورد بأي شرط من شروط منحها. وتحدد اللائحة التنفيذية لهذا القانون شروط وضوابط منح هذه الشهادة، ورسوم إصدارها بما يتناسب مع حجم وطبيعة نشاط المنشأة محل التقييم وبما لا يجاوز عشرين ألف جنيه عن كل وحدة بيع خاصة بالمورد.

المادة 61
لذوي الشأن من أطراف الشكوى الحصول على شهادة رسمية بما انتهت إليه إجراءات الشكوى، وكذا صور التقارير الفنية ذات الصلة، وتحدد اللائحة التنفيذية لهذا القانون ضوابط استخراج تلك الشهادة ورسوم إصدارها بما لا يجاوز مائتي جنيه.

