المادة 63
مع عدم الإخلال بأية عقوبة أشد من المنصوص عليها في أي قانون آخر ودون الإخلال بالحق في التعويض، يعاقب على الأفعال المبينة في المواد التالية بالعقوبات المنصوص عليها فيها.

المادة 64
يعاقب بغرامة لا تقل عن عشرة آلاف جنيه ولا تجاوز خمسمائة ألف جنيه أو مثل قيمة المنتج محل المخالفة أيهما أكبر، كل مورد خالف أحكام أي من المواد: (3، 4، 5، 6، 7، 12، 14، 16، 18، 21، 35، 38، 40/ فقرة أولى وثانية، 55، 56/ فقرة أولى، 62/ فقرة أخيرة) من هذا القانون.
ويعاقب بذات العقوبة كل من خالف القرارات الصادرة نفاذا لحكم المادة (33/ فقرة أولى) من هذا القانون، وللمحكمة أن تحكم بغلق مركز الخدمة والصيانة المخالف لمدة لا تجاوز ستة أشهر.

المادة 65
يعاقب بغرامة لا تقل عن ثلاثين ألف جنيه ولا تجاوز مليون جنيه أو مثلي قيمة المنتج محل المخالفة أيهما أكبر، كل مورد خالف أحكام أي من المواد: (10، 20، 22، 24، 25، 26، 29، 30، 31، 33/ فقرة ثانية وثالثة، 40/ فقرة ثالثة) من هذا القانون.

المادة 66
يعاقب بغرامة لا تقل عن خمسين ألف جنيه ولا تجاوز مليوني جنيه، أو مثلي قيمة المنتج محل المخالفة أيهما أكبر، كل مورد خالف أحكام أي من المواد: (9، 13، 15/ فقرة أولى، 32، 34، 56/ فقرة ثانية) من هذا القانون.

المادة 67
يعاقب بغرامة لا تقل عن عشرين ألف جنيه ولا تجاوز خمسمائة ألف جنيه، كل من ارتكب أيا من الأفعال الآتية:
1- حال دون أداء مأموري الضبط القضائي المخولين بتنفيذ أحكام هذا القانون لأعمال وظائفهم.
2- امتنع عن موافاة الجهاز بالبيانات أو الأوراق أو المستندات المنصوص عليها في المادة (54) من هذا القانون.
3- قام بإمداد الجهاز ببيانات أو بأوراق أو مستندات غير صحيحة مع العلم بذلك.

المادة 68
يعاقب بغرامة لا تقل عن خمسين ألف جنيه ولا تجاوز مليون جنيه، أو مثلي القيمة المتفق عليها مع الوسيلة الإعلانية نظير الإعلان المخالف أيهما أكبر، كل من امتنع عن تنفيذ القرار الصادر بوقف الإعلان وفقا لأحكام المادة (57) من هذا القانون.

المادة 69
في حالة العود لأي من الجرائم المعاقب عليها في المواد السابقة من هذا القانون تضاعف عقوبة الغرامة بحديها.

المادة 70
يعاقب بالغرامة التي لا تقل عن خمسين ألف جنيه ولا تجاوز مليوني جنيه، أو ما يعادل قيمة البضاعة محل الجريمة أيهما أكبر، كل من خالف حكم المادة (19) من هذا القانون.
فإذا ترتب على مخالفة حكم المادة المشار إليها تعريض حياة المستهلك للخطر، أو تعريضه للإصابة بمرض مدمن أو مستعص، تكون العقوبة الحبس والغرامة التي لا تقل عن مائة ألف جنيه ولا تجاوز مليوني جنيه، أو بإحدى هاتين العقوبتين.

المادة 71
يعاقب بالحبس مدة لا تقل عن سنة، وغرامة لا تقل عن مائة ألف جنيه ولا تجاوز مليوني جنيه أو ما يعادل قيمة البضاعة موضوع الجريمة أيهما أكبر، كل من خالف حكم المادة (8) من هذا القانون.

المادة 72
إذا نشأت عن مخالفة أي حكم من أحكام هذا القانون إصابة شخص بعاهة مستديمة أو بمرض مدمن أو مستعص، تكون العقوبة السجن وغرامة لا تقل عن مائة ألف جنيه ولا تجاوز مليون جنيه أو ما يعادل قيمة السلعة محل الجريمة أيهما أكبر.
وإذا رأت المحكمة تطبيق حكم المادة (17) من قانون العقوبات فلا يجوز في هذه الحالة النزول بالعقوبة المقيدة للحرية عن الحبس مدة سنة واحدة.
وإذا نشأت عن المخالفة وفاة شخص أو أكثر، تكون العقوبة السجن المؤبد وغرامة لا تقل عن مائتي ألف جنيه ولا تجاوز مليوني جنيه، أو ما يعادل قيمة السلعة محل الجريمة أيهما أكبر.

المادة 73
فضلا عن العقوبات المقررة في هذا القانون، يجب الحكم على المورد برد قيمة المنتج محل المخالفة للمستهلك في كل حالة يكون للمستهلك الحق في استرداد القيمة، ما لم يكن قد استردها قبل صدور الحكم.
ولا يحول تطبيق الفقرة الأولى من المادة (32) من قانون العقوبات دون تطبيق عقوبة الرد المنصوص عليها بالفقرة السابقة.

المادة 74
يعاقب المسئول عن الإدارة الفعلية للشخص الاعتباري المخالف بذات العقوبات المنصوص عليها في هذا القانون إذا ثبت علمه بالمخالفة، وكان إخلاله بالواجبات التي تفرضها عليه تلك الإدارة قد أسهم في وقوع الجريمة.
ويكون الشخص الاعتباري مسئولا بالتضامن عن الوفاء بما يحكم به من عقوبات مالية وتعويضات إذا كانت المخالفة قد ارتكبت من أحد العاملين به باسمه أو لصالحه.

المادة 75
تقضى المحكمة بنشر الحكم الصادر بالإدانة على نفقة المحكوم عليه في جريدة يومية واحدة والمواقع الإلكترونية واسعة الانتشار، ويلتزم الجهاز بالإعلان تفصيليا في موقعه الإلكتروني عن الأحكام النهائية الصادرة بالإدانة وفقا لأحكام هذا القانون، على أن يستمر الإعلان لمدة ثلاث سنوات من تاريخ صدور الحكم وعلى قلم كتاب المحكمة المختصة موافاة الجهاز بصور رسمية من تلك الأحكام دون أي إجراءات أو سداد رسوم قضائية أو غيرها من الرسوم.

المادة 76
لا يجوز تحريك الدعوى الجنائية أو اتخاذ إجراءات فيها بالنسبة إلى الجريمة المنصوص عليها في المادة (13) من هذا القانون إلا بطلب كتابي من الوزير المختص أو من يفوضه.

