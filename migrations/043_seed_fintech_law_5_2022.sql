قانون تنظيم وتنمية استخدام التكنولوجيا المالية
فى الأنشطة المالية غير المصرفية

(الباب الأول)
تعريفات وأهداف القانون

مادة (1):

فى تطبيق أحكام هذا القانون يُقصد بالكلمات والعبارات التالية المعنى المبين قرين كل منها :

1- الهيئة: الهيئة العامة للرقابة المالية .
2- مجلس إدارة الهيئة: مجلس إدارة الهيئة العامة للرقابة المالية .
3- رئيس الهيئة: رئيس مجلس إدارة الهيئة العامة للرقابة المالية .
4- الأنشطة المالية غير المصرفية: الأسواق والأدوات المالية غير المصرفية الخاضعة لإشراف ورقابة الهيئة بما فيها أسواق أوراق المال ، والتمويل العقارى ، والتأمين ، والتأجير التمويلى ، والتخصيم ، وتمويل المشروعات المتوسطة والصغيرة والمتناهية الصغر ، والتمويل الاستهلاكى .
5- التكنولوجيا المالية: آلية تستخدم التقنية التكنولوجية الحديثة والمبتكرة فى القطاع المالى غير المصرفى لدعم وتيسير الأنشطة والخدمات المالية والتمويلية والتأمينية من خلال البرامج أو المنصات الرقمية أو الذكاء الاصطناعى أو السجلات الإلكترونية .
6- التكنولوجيا المالية الرقابية: استخدام الهيئة للتطبيقات التكنولوجية للرقابة على الالتزام بالقوانين والقواعد المقررة .
7- التكنولوجيا المالية الإشرافية: آلية تعنى بجمع البيانات رقميًا والتحقق منها وتحليل مؤشراتها من خلال برامج معدة لهذا الغرض .
8- المنصة الرقمية: نموذج أعمال قائم على استخدام الوسائل التكنولوجية فى مزاولة الأنشطة المالية غير المصرفية وفى عرض المنتجات والخدمات المرتبطة بها على الأشخاص الراغبين فى الحصول عليها ، ويسمح بتبادل البيانات والمعلومات اللازمة لإتمام هذه التعاملات .
9- أمن البيانات (الأمن السيبرانى): إجراءات وعمليات تقنية وتنظيمية من شأنها الحفاظ على خصوصية البيانات وسريتها وسلامتها ووحدتها وتكاملها فيما بينها .
10- الهوية الرقمية: أى بيانات معالجة تقنيًا تتعلق بشخص طبيعى أو اعتبارى محدد أو يمكن تحديده بشكل مباشر أو غير مباشر عن طريق الربط بين هذه البيانات وأى بيانات أخرى كالاسم ، أو الصورة ، أو الصوت ، أو رقم تعريفى ، أو محدد للهوية عبر الإنترنت ، على أن تسمح هذه البيانات بالتقييم والمصادقة على المعاملات التى تتم من خلال المنصات الرقمية .
11- السجل الرقمى: سجل إلكترونى يتضمن البيانات المتعلقة بالمعاملات التى يجريها الأشخاص الطبيعيون أو الاعتباريون التى تتم وفقًا لأحكام هذا القانون ، بما يسمح بتتبع هذه البيانات من خلال شبكة آمنة .
12- العقد الرقمى: عقد يتضمن حقوق والتزامات المتعاقدين بشكل إلكترونى ، ويمكن تسجيله فى سجل رقمى ، كما يجوز أن يكون العقد الرقمى «عقدًا ذكيًا» من خلال برنامج يهدف إلى تنفيذ أحكام العقد والتحكم فيها أو توثيقها تلقائيًا .
13- خدمات التعهيد: الخدمات التى تسندها الشركات والجهات تزاول أنشطة مالية غير مصرفية باستخدام بعض مجالات التكنولوجيا المالية إلى طرف ثالث للقيام بأى مهام أو أنشطة نيابة عنها .
14- التطبيقات الإلكترونية لبرامج المستشار المالى: نظام آلى مبتكر تستخدمه الجهات المرخص لها بمزاولة الأنشطة المالية غير المصرفية فى تحليل بيانات المالية الحالية وأهدافهم المالية المستقبلية لتقديم المشورة الفنية لهم فيما يتعلق بالأنشطة المالية غير المصرفية ، وذلك من خلال استخدام تطبيقات الذكاء الاصطناعى .
15- التطبيقات الإلكترونية للتمويل الأصغر: أحد منتجات التمويل متناهى الصغر يتم منحه للأفراد بغرض تمويل نشاط اقتصادى باستخدام التطبيقات الإلكترونية من خلال الوسائط الرقمية المتعددة لتبادل البيانات أو المعلومات أو لتشغيل وإدارة محفظة التمويل .
16- التطبيقات الإلكترونية للتأمين: نموذج أعمال قائم على استخدام التقنيات التكنولوجية الحديثة مثل الذكاء الاصطناعى وأدوات تحليل البيانات الضخمة لإنشاء نماذج أو منتجات تأمين جديدة .
17- التطبيقات الإلكترونية للتمويل الاستهلاكى: نموذج أعمال قائم على استخدام التقنيات التكنولوجية من خلال الوسائط الرقمية المتعددة لتبادل البيانات أو المعلومات أو تشغيل وإدارة محفظة التمويل الاستهلاكى .
18- الشمول المالى: إتاحة مختلف الخدمات المالية للاستخدام من قبل جميع فئات المجتمع من خلال القنوات الرسمية بجودة وتكلفة مناسبة مع حماية حقوق المستفيدين بما يمكنهم من إدارة أموالهم بشكل سليم .

مادة (2):

تهدف الهيئة من تطبيق أحكام هذا القانون إلى تعزيز الشمول المالى ، والعمل على توسيع قاعدة المستفيدين من الأنشطة المالية غير المصرفية ، ورفع كفاءتها ، وخفض التكاليف اللازمة للاستفادة من هذه الأنشطة والخدمات .

وتكون الهيئة هى الجهة الإدارية المختصة بتطبيق أحكام هذا القانون دون غيرها ، ولها كافة الإجراءات اللازمة لتعزيز وتنمية استخدام نظم التكنولوجيا المالية الحديثة والمبتكرة فى أى من مجالات الأنشطة المالية غير المصرفية وتقديم الاستشارات المالية المرتبطة بها ، ويكون لها فى سبيل تحقيق أغراض هذا القانون على وجه الأخص ما يلى :

1- اتخاذ إجراءات تأسيس الشركات الخاضعة لأحكام هذا القانون .
2- منح التراخيص والموافقات اللازمة لمزاولة الأنشطة المنصوص عليها فى هذا القانون .
3- استخدام التطبيقات التكنولوجية للتأكد من الالتزام بالقوانين والقواعد المقررة بما يعمل على تيسير قيام الهيئة بدورها الرقابى على الجهات الخاضعة لهذا الالتزام بمعايير الشفافية والحوكمة ، وحماية المتعاملين فى الأسواق المالية غير المصرفية واعتماد أدوات تكنولوجية حديثة ومبتكرة لتيسير التعامل مع القطاع المالى غير المصرفى فى مجال استخدام التكنولوجيا المالية .
4- استخدام التطبيقات التكنولوجية بهدف جمع البيانات رقميًا والتحقق منها وتحليل مؤشراتها من خلال برامج معدة لهذا الغرض ، واستخدام آليات الذكاء الاصطناعى وغيرها من النماذج الرقمية للكشف عن الوقائع التى تشكل مخالفات للقوانين المنظمة للأنشطة المالية غير المصرفية ، والاشتباه فى غسل الأموال ، إضافة إلى الإنذار المبكر بالمخاطر المتعلقة بالسيولة أو التمويل أو غيرها من الأمور المتعلقة بالاستقرار المالى .
5- إنشاء بيئة اختبار رقابية لتطبيقات التكنولوجيا المالية سواء بنفسها أو بالمشاركة مع الغير .
6- وضع ضوابط أمن البيانات والأجهزة .
7- الإشراف والرقابة على الشركات والجهات الخاضعة لأحكام هذا القانون .
8- تلقى الشكاوى التى يقدمها ذوو الشأن من المتعاملين مع شركات مزاولات الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية ، عن مخالفة أحكام هذا القانون أو القرارات الصادرة تنفيذًا له .
9- إعداد ونشر الدراسات والإحصاءات اللازمة لتعزيز مزاولة الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية .
10- نشر الوعى بالأنشطة المالية غير المصرفية التى يتم مزاولتها باستخدام التكنولوجيا المالية ، وحماية حقوق المتعاملين فى هذه الأنشطة والحفاظ على المناخ التنافسى الذى يساعد على نموها .

(الباب الثانى)
مزاولة الأنشطة المالية
غير المصرفية باستخدام التكنولوجيا المالية

مادة (3):

تقدم طلبات تأسيس الشركات الراغبة فى مزاولة الأنشطة المالية غير المصرفية من خلال تقنيات التكنولوجيا المالية إلى الهيئة على النموذج المعد لذلك ، مرفقًا بها الأوراق التى تحددها الهيئة ، ومن بينها على الأخص ما يلى :

1- شهادة الإيداع البنكية بما يفيد سداد رأس المال المصدر مدفوعًا بالكامل بحسب طبيعة النشاط التى تزاوله الشركة .
2- ثلاث نسخ من العقد الابتدائى والنظام الأساسى للشركة .
3- طلب وكيل المؤسسين متضمنًا على وجه الخصوص اسم الشركة وبيانًا بأسماء المؤسسين ورأس المال المصدر والمدفوع .
4- إقرار مراقب حسابات الشركة بقبول التعيين .

وتعد الهيئة سجلاً تدون به طلبات تأسيس الشركات المشار إليها بأرقام متتابعة وفقًا لتاريخ ورود كل منها ، ويكون لكل طلب ملف خاص تودع فيه أوراق التأسيس وكل ما يتعلق بذلك من إجراءات . وتشكل بقرار من رئيس الهيئة لجنة تضم عناصر فنية وقانونية لإبداء الرأى والعرض على رئيس الهيئة لإصدار قرار فى شأن تأسيس تلك الشركات خلال ثلاثين يومًا ويعتبر عدم إصدار القرار خلال هذه المدة بمثابة رفض لطلب التأسيس .

ويحظر على هذه الشركات مزاولة نشاطها داخل جمهورية مصر العربية أو من خارجها للمقيمين فيها أو للشركات التى تزاول نشاطها فى مصر إلا بعد الحصول على ترخيص بذلك وفقًا للشروط والضوابط المنصوص عليها فى هذا القانون والقرارات الصادرة تنفيذًا له ، والقيد لدى الهيئة فى سجل خاص لهذا الغرض وفقًا للضوابط والإجراءات التى يصدر بها قرار من مجلس إدارة الهيئة .

مادة (4):

يُشترط للحصول على ترخيص بمزاولة الأنشطة المالية غير المصرفية من خلال تقنيات التكنولوجيا المالية ، توافر الشروط الآتية على الأخص :

1- أن يقتصر عمل الشركة على مزاولة الأنشطة المرخص لها بها .
2- تحديد هيكل الملكية المباشر وغير المباشر والأطراف المرتبطة بشكل محدد .
3- أن يتوافر لدى الشركة التجهيزات والبنية التحتية وأنظمة المعلومات ووسائل الحماية والتأمين اللازمة لمباشرة النشاط وفقًا للمتطلبات التى يصدر بها قرار من مجلس إدارة الهيئة .

ويصدر مجلس إدارة الهيئة قرارًا بالشروط الأخرى اللازمة للحصول على الترخيص المتعلقة بتحديد هيكل الملكية وتشكيل مجلس الإدارة وضوابط عدم تعارض المصالح .

ويحدد مجلس إدارة الهيئة رسم الترخيص بمزاولة النشاط للشركة بما لا يجاوز خمسين ألف جنيه ، على أن يسدد بإحدى وسائل الدفع غير النقدى وفقًا لأحكام قانون تنظيم استخدام وسائل الدفع غير النقدى بالقانون رقم 18 لسنة 2019 .

مادة (5):

يجوز للشركات والجهات الحاصلة على ترخيص من الهيئة بمزاولة أى من الأنشطة المالية غير المصرفية بعد الحصول على موافقة الهيئة مباشرة لهذه الأنشطة باستخدام بعض مجالات التكنولوجيا المالية ، أو من خلال إحدى الجهات المقيدة بسجل الهيئة المنصوص عليه بالمادة (6) من هذا القانون ، وذلك بموجب اتفاق تعهيد مبرم بينهما موضحًا به جميع حقوق والتزامات الطرفين .

ويجب على الشركات والجهات التى ترغب فى الحصول على موافقة الهيئة لمزاولة الأنشطة المالية غير المصرفية المرخص لها بمزاولتها باستخدام بعض مجالات التكنولوجيا المالية استيفاء الشروط الآتية :

1- أن يتوافر لدى الشركة التجهيزات والبنية والأنظمة والمعلومات ووسائل الحماية والتأمين اللازمة لمباشرة النشاط وفقًا للمتطلبات التى يصدر بها قرار من مجلس إدارة الهيئة .
2- ألا تكون الشركة أو الجهة مخالفة لأحكام القانون المنظم لنشاطها أو القرارات الصادرة تنفيذًا له وقت تقديم طلب الموافقة .
3- سداد رسم الموافقة بما يعادل نصف رسم الترخيص المشار إليه بالمادة (4) من هذا القانون ، يسدد بإحدى وسائل الدفع غير النقدى وفقًا لأحكام قانون تنظيم استخدام وسائل الدفع غير النقدى بالقانون رقم 18 لسنة 2019 .

ويصدر مجلس إدارة الهيئة قرارًا بالشروط والإجراءات الأخرى اللازمة للحصول على موافقة الهيئة على مزاولة الأنشطة المالية غير المصرفية المرخص لها بمزاولتها باستخدام بعض مجالات التكنولوجيا المالية المتعلقة بتحديد هيكل الملكية وتشكيل مجلس الإدارة وضوابط عدم تعارض المصالح .

مادة (6):

ينشأ بالهيئة سجل يقيد به الجهات الراغبة فى تقديم خدمات التعهيد يحددها مجلس إدارة الهيئة للشركات والجهات المرخص لها من الهيئة بمزاولة الأنشطة المالية غير المصرفية حال رغبتها فى استخدام بعض مجالات التكنولوجيا المالية لمزاولة الأنشطة المالية غير المصرفية .

ويضع مجلس إدارة الهيئة ضوابط القيد والشطب بالسجل ، على أن تتضمن على الأخص ما يلى :

1- الخبرة المتطلبة فى الجهات الراغبة فى القيد بالسجل .
2- الالتزامات التى يجب أن تلتزم بها الجهات الراغبة فى القيد بالسجل .
3- حالات الشطب من السجل .

مادة (7):

على الشركات أو الجهات الحاصلة على ترخيص أو موافقة من الهيئة بحسب الأحوال ، لمزاولة الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية ، الالتزام بالقواعد والضوابط والمتطلبات التى يصدر بها قرار من مجلس إدارة الهيئة والتى يجب أن تتضمن على وجه الأخص ما يلى :

1- الشروط الواجب توافرها فى الهيكل التنظيمى للشركة ومتطلبات الخبرة العملية والكفاءة المهنية فى القائمين على إدارة النشاط .
2- معايير وصلاحيات التطبيقات الإلكترونية المستخدمة فى مزاولة النشاط .
3- التجهيزات والبنية التكنولوجية وأنظمة المعلومات ووسائل الحماية والتأمين اللازمة لمباشرة النشاط .
4- متطلبات الحوكمة من حيث تشكيل مجلس الإدارة واللجان المنبثقة عنه والإفصاحات المطلوبة وتوقيتاتها .
5- ضوابط مكافحة غسل الأموال وتمويل الإرهاب ، بمراعاة التعليمات الصادرة من وحدة مكافحة غسل الأموال وتمويل الإرهاب وبعد التنسيق مع الجهات المعنية ذات الصلة .
6- الإجراءات والوسائل اللازمة للحفاظ على استقرار السوق وحماية المتعاملين .

مادة (8):

يجوز للشركات والجهات الراغبة فى مزاولة الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية ، الحصول على ترخيص أو موافقة الهيئة بحسب الأحوال ، استخدام أحد التطبيقات الآتية :

1- التطبيقات الإلكترونية لبرامج المستشار المالى .
2- التطبيقات الإلكترونية للتمويل الأصغر .
3- التطبيقات الإلكترونية للتأمين .
4- التطبيقات الإلكترونية للتمويل الاستهلاكى .

ويجوز لمجلس إدارة الهيئة اعتماد تطبيقات إلكترونية أخرى على أن يتوافر فيها ما يلى :

1- الصلاحية لأداء مهام الأنشطة المالية غير المصرفية الصادرة بشأنها الترخيص أو الموافقة بحسب الأحوال .
2- نظم لحماية البيانات الخاصة بالمتعاملين من الاختراق الإلكترونى والهجمات السيبرانية .
3- التوافق مع الضوابط التى تصدرها الهيئة بشأن التحقق من الهوية الرقمية والعقود الرقمية فى مزاولة الأنشطة المالية غير المصرفية وضوابط مكافحة غسل الأموال .

(الباب الثالث)
أحكام عامة

مادة (9):

تقوم الهيئة بنفسها أو بالمشاركة مع الغير أو أن تعهد بذلك إلى إحدى الجهات ذات الاختصاص ، إنشاء ، مختبر تنظيمى للتطبيقات يسمح لمزاولى الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية ، أو للجهات الراغبة فى القيد أو المقيدة بسجل الهيئة المشار إليه بالمادة (6) من هذا القانون ، باختبار تطبيقات التكنولوجيا المالية المبتكرة بما فى ذلك نماذج الأعمال والآليات ذات العلاقة المطبقة على عملاء حقيقيين تمهيدًا لتقديمها للعملاء ، وذلك تحت إشراف ورقابة الهيئة .

وللهيئة إصدار ترخيص مؤقت للشركات الناشئة فى التكنولوجيا المالية لفترة لا تزيد على سنتين ، لدعم الشركات الناشئة المبتكرة فى مجال التكنولوجيا المالية فى تقديمها للأنشطة والمنتجات المالية غير المصرفية .

ويحدد مجلس إدارة الهيئة شروط وضوابط وإجراءات الترخيص للشركات المشار إليها وقواعد الإشراف والرقابة عليها ، والحد الأدنى لرأسمالها المصدر بما لا يقل عن مائتين وخمسين ألف جنيه ، وتعفى الشركات الناشئة من رسم الترخيص .

مادة (10):

مع مراعاة الأحكام الواردة بالقوانين المنظمة للأنشطة المالية غير المصرفية فى شأن الأحكام التى يجب أن تتضمنها العقود المبرمة بين الشركات أو الجهات التى تزاول أنشطة مالية غير مصرفية وعملائها ، يتعين على الشركات أو الجهات الحاصلة على ترخيص أو موافقة من الهيئة ، لمزاولة الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية ، تضمين العقود بينها وبين عملائها ما يلى :

1- الأحكام والبيانات التفصيلية لأطراف العقد .
2- تحديد مبلغ التمويل الممنوح ، والمدة الزمنية للسداد ، وعدد أقساط السداد وشروطه ، وقيمة كل منها .
3- سعر العائد المتخذ أساسًا لحساب قيمة التمويل ، وبيان ما إذا كان ثابتًا أو متغيرًا ، وذلك دون التقيد بالحدود المنصوص عليها فى الحدود المنصوص عليها فى أى تشريع آخر .
4- بيان الضمانات التى حصل عليها الممول .

مادة (11):

مع عدم الإخلال بأحكام القانون رقم 15 لسنة 2004 بتنظيم التوقيع الإلكترونى وبإنشاء هيئة تنمية صناعة تكنولوجيا المعلومات ، يصدر مجلس إدارة الهيئة ضوابط التحقق من الهوية الرقمية وضوابط العقود الرقمية للجهات التى تستخدم التكنولوجيا المالية فى مزاولة الأنشطة المالية غير المصرفية .

كما يصدر مجلس إدارة الهيئة معايير إنشاء وترخيص وضوابط عمل السجل الرقمى والتكنولوجيا الخاصة بتأمين البيانات المسجلة به والتحقق من صحتها .

ويكون للبيانات المدرجة على الوسائط والوسائل الإلكترونية التى تستخدمها الشركات أو الجهات الخاضعة لأحكام هذا القانون ، حجية المحررات الرسمية فى الإثبات .

مادة (12):

تتلقى الهيئة الشكاوى التى يقدمها ذوو الشأن من المتعاملين مع مزاولى الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية ، عن مخالفة أحكامه أو القرارات الصادرة تنفيذًا له ، وتلتزم الهيئة بالرد على هذه الشكاوى خلال موعد لا يجاوز شهرًا من تاريخ استيفاء المستندات التى تحددها الهيئة فى هذا الشأن .

ويصدر قرار من رئيس الهيئة بتنظيم إجراءات تقديم الشكاوى والبت فيها وطريقة إخطار مقدميها بالرد ، على أن تتضمن هذه الإجراءات إمكانية تقديم الشكوى للهيئة مباشرة أو بخطاب مسجل بعلم الوصول أو بإحدى الوسائل الإلكترونية التى تقررها الهيئة فى هذا الشأن .

مادة (13):

مع عدم الإخلال بأحكام قانون حماية البيانات الشخصية الصادر بالقانون رقم 151 لسنة 2020 ، يلتزم مزاولو الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية الخاضعة لأحكام هذا القانون ومدير ومستشارو هذه الجهات والعاملون لدى أى منها بالمحافظة على السرية التامة لعملائهم ، وعدم إفشاء أى معلومات عنهم أو عن معاملاتهم إلى الغير بدون موافقتهم المسبقة كتابيًا أو بإحدى الوسائل الإلكترونية وفى حدود هذه الموافقة .

مادة (14):

لمجلس إدارة الهيئة حال مخالفة الشركات القائمة على تقنيات التكنولوجيا المالية فى مزاولة الأنشطة المالية غير المصرفية لأحكام هذا القانون أو القرارات الصادرة تنفيذًا له ، أو إذا فقدت شرطًا من شروط الترخيص أو إذا قامت بما من شأنه تهديد استقرار السوق أو مصالح المساهمين فيها أو المتعاملين معها ، أن يتخذ معها واحدًا أو أكثر من التدابير الآتية :

1- توجيه تنبيه إلى الشركة بإزالة المخالفة خلال المدة وبالشروط المحددة فى التنبيه .
2- دعوة مجلس إدارة الشركة أو جمعيتها العامة للانعقاد ، بحضور أحد ممثلى الهيئة ، للنظر فى أمر المخالفات المنسوبة إليها واتخاذ اللازم نحو إزالتها .
3- حل مجلس إدارة الشركة وتعيين مفوض لتسيير أعمال الشركة لمدة مؤقتًا لا تجاوز ستة أشهر ويجوز مدها لمدة أخرى ، ويعرض المفوض خلال مدة تعيينه الأمر على الجمعية العامة لتعيين مجلس إدارة جديد بالأداة القانونية المقررة .
4- المنع من مزاولة عقود أو إبرام عقود جديدة لمدة لا تزيد على ستة أشهر .
5- إلغاء الترخيص بمزاولة النشاط .

ويجوز أن تصدر التدابير المنصوص عليها بالبندين (1، 2) من هذه المادة من رئيس الهيئة ، كما يجوز له اتخاذ التدبير المنصوص عليه فى البند (4) من هذه المادة إذا كان الخطر شديدًا ومن شأنه أن يترتب عليه ضرر يتعذر تداركه ، وذلك لمدة أقصاها أشهر أو إلى حين العرض على مجلس إدارة الهيئة أيهما أقرب .

وتسرى التدابير المنصوص عليها فى القوانين المنظمة للأنشطة المالية غير المصرفية فى شأن الشركات والجهات الحاصلة على موافقة الهيئة على مزاولة هذه الأنشطة باستخدام بعض مجالات التكنولوجيا المالية ، حال مخالفتها لأحكام هذا القانون أو القرارات الصادرة تنفيذًا له ، وذلك دون الإخلال بسلطة مجلس إدارة الهيئة فى إلغاء الموافقة الحاصل عليها هذه الشركات أو الجهات حال مخالفتها الأحكام المشار إليها .

مادة (15):

تنشأ لجنة أو أكثر لنظر التظلمات التى يقدمها أصحاب الشأن من القرارات الإدارية الصادرة تطبيقًا لأحكام هذا القانون ، ويصدر بتشكيل كل لجنة قرار من مجلس إدارة الهيئة ، وتكون برئاسة أحد نواب رئيس مجلس الدولة وعضوية اثنين من أعضائه بدرجة مستشار على الأقل يرشحهم رئيس مجلس الدولة ، وممثل عن الهيئة يرشحه رئيس الهيئة ، وعضو من ذوى الخبرة يرشحه رئيس الهيئة بنفسه أو من يمثله .

ويصدر بتشكيل اللجنة واختصاصاتها والمعاملة المالية لأعضائها وإجراءات نظر التظلمات المقدمة إليها قرار من مجلس إدارة الهيئة .

ويكون تقديم التظلم إما بتسليمه باليد بتسلمه إما مسجل بخطاب الوصول أو بإحدى الوسائل الإلكترونية التى يقررها مجلس إدارة الهيئة .

ويكون التظلم أمام هذه اللجنة وجوبيًا قبل رفع الدعوى أمام المحكمة المختصة خلال ستين يومًا من تاريخ الإخطار أو العلم اليقينى به ، على أن تصدر اللجنة قرارها فى التظلم خلال ثلاثين يومًا من تاريخ تقديمه ، ويكون قرار اللجنة نهائيًا ومسببًا .

ويترتب على تقديم التظلم إلى اللجنة وقف المدة المقررة قانونًا لسقوط أو تقادم الحقوق أو لرفع الدعوى ، وذلك حتى انقضاء ميعاد البت فى التظلم .

مادة (16):

يكون للعاملين الذين يصدر بتحديدهم قرار من وزير العدل بناءً على طلب رئيس الهيئة صفة مأمورى الضبط القضائى فى إثبات الجرائم التى تقع بالمخالفة لأحكام هذا القانون أو القرارات الصادرة تنفيذًا له ، ويكون لهم فى سبيل ذلك الاطلاع على السجلات والدفاتر والمستندات والبيانات والوسائط الإلكترونية والمستندات الحاصلة على ترخيص أو موافقة بحسب الأحوال ، وفروعها والأماكن التى توجد بها هذه السجلات والدفاتر والمستندات والبيانات والوسائط ، وعلى المسئولين فى الجهات المذكورة أن يقدموا إلى العاملين المذكورين البيانات وصور المستندات التى يطلبونها لهذا الغرض ، وعدم حجبها إلا على سند من هذا القانون .

(الباب الرابع)
العقوبات

مادة (17):

مع عدم الإخلال بأى عقوبة أشد منصوص عليها فى قانون العقوبات أو فى قانون آخر ، يعاقب على الجرائم المنصوص عليها فى المواد التالية بالعقوبات المقررة بالعقوبات فيها .

مادة (18):

يعاقب بالحبس مدة لا تقل عن ستة أشهر وبغرامة لا تقل عن مائتى ألف جنيه ولا تزيد على مليون جنيه ، أو بإحدى هاتين العقوبتين ، كل من زاول أو أنشأ أو أدار أحد الأنشطة الواردة بهذا القانون دون الحصول على ترخيص أو موافقة على النحو المنصوص عليه بهذا القانون .

وفى حالة العود ، تكون عقوبة الحبس والغرامة معًا .

مادة (19):

يعاقب بغرامة لا تقل عن خمسين ألف جنيه ولا تزيد على خمسمائة ألف جنيه ، كل من خالف أحكام المادة (7) من هذا القانون .

مادة (20):

يعاقب بالحبس مدة لا تجاوز شهرًا وبغرامة لا تقل عن عشرين ألف جنيه ولا تجاوز مائة ألف جنيه ، أو بإحدى هاتين العقوبتين ، كل من تعمد منع أحد العاملين بالهيئة الذين يتمتعون بصفة الضبطية القضائية عن أداء أى من الأعمال المكلف بها بموجب هذا القانون ، وكذا كل من تعمد حجب البيانات أو المستندات أو الوسائط الإلكترونية المطلوبة فى هذا الشأن دون سند من هذا القانون .

مادة (21):

