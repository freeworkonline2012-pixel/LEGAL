(المادة الأولى)

مع عدم الإخلال بأحكام قانون البنك المركزى والجهاز المصرفى الصادر بالقانون رقم 194 لسنة 2020 ، تسرى أحكام القانون المرافق على مزاولى الأنشطة المالية غير المصرفية باستخدام التكنولوجيا المالية .

(المادة الثانية)

يسرى فيما لم يرد بشأنه نص خاص فى القانون المرافق ، أحكام قانون شركات المساهمة وشركات التوصية بالأسهم والشركات ذات المسئولية المحدودة وشركات الشخص الواحد الصادر بالقانون رقم 159 لسنة 1981 ، وأحكام القوانين المنظمة للأنشطة المالية غير المصرفية بحسب الأحوال .

(المادة الثالثة)

فيما عدا المنازعات والدعاوى التى يختص بنظرها مجلس الدولة ، تختص المحاكم الاقتصادية بالفصل فى المنازعات والدعاوى الناشئة عن تطبيق أحكام القانون المرافق .

(المادة الرابعة)

يلتزم المخاطبون بأحكام القانون المرافق بتوفيق أوضاعهم وفقًا لأحكامه خلال ستة أشهر من تاريخ صدور القرارات المنفذة له .

ولمجلس إدارة الهيئة العامة للرقابة المالية ، بقرار منه مد فترة توفيق الأوضاع المنصوص عليها فى الفقرة السابقة لمدد أخرى مماثلة لا تتجاوز فى مجموعها سنتين .

ويجوز بقرار من رئيس مجلس الوزراء ، بناءً على عرض رئيس الهيئة العامة للرقابة المالية مد فترة توفيق الأوضاع المالية لمدة سنتين أخريين .

(المادة الخامسة)

