يكون الشخص الطبيعي أو المدير المسئول لدى الشخص الاعتباري المقيدين بالسجل مسئولين عن أعمال التقييم الصادرة عنهما، ويلتزمان بالتوقيع على تقارير التقييم ودراسات القيمة العادلة الصادرة عنهم ولا يجوز الإنابة فى ذلك، كما يكونا مسئولين عن التحقق من التزام كافة الأطراف ذوي العلاقة والمجموعات المرتبطة بهم بالمعايير الاساسية للأداء المهني ومعايير التقييم الصادرة عن الهيئة.

