إنشاء السجل
يُنشأ بالهيئة سجل لقيد الأشخاص الراغبين فى القيام بأعمال التقييم، يسمى «سجل خبراء إعادة تقييم الأصول».
ويجب أن يتضمن السجل البيانات الرئيسية لخبراء التقييم الذين يتم قيدهم به، وذلك على النحو الذي تحدده الهيئة.
ولا يجوز لغير المقيدين بالسجل القيام بأي من أعمال التقييم لأغراض إعادة تقييم الأصول وفقاً لمعايير المحاسبة المصرية.
ويُقسم السجل إلى عدة أقسام بحسب الأصول المراد تقييمها على النحو الآتي:
القسم الأول: شركات الاستشارات المالية والجهات المرخص لهما من الهيئة للقيام بأعمال التقييم المالي وإعداد دراسات القيمة العادلة.
القسم الثاني: خبراء تقييم الأصول العقارية.
القسم الثالث: خبراء تقييم الآلات والمعدات ووسائل النقل والانتقال.

(المادة الثانية)
شروط قيد الأشخاص الطبيعيين بالسجل
يشترط فى راغب القيد من الأشخاص الطبيعيين استيفاء الشروط الآتية:
1- أن يكون مقيداً بجدول خبراء التقييم لدى الهيئة أو أن يكون مرخصاً له بأن يكون خبير تقييم من الجهة المختصة فى الدولة التي اكتسب خبرته فيها بالنسبة لطالبى القيد من الأجانب.
2- أن يتوافر لديه الكفاءة المهنية وأن يجتاز الاختبارات التي تحددها الهيئة لهذا الغرض.
3- أن يتعهد بتقديم وثيقة تأمين ضد الأخطار المهنية طوال مدة القيد، وفقاً للشروط التي تضعها الهيئة بما يتلاءم مع حجم ونطاق المسئوليات المترتبة على أعمال التقييم التي يقوم بها.
4- ألا يكون قد صدر بشأنه خلال الثلاث سنوات السابقة على تقديم طلب القيد أي أحكام نهائية في جناية، أو جنحة في إحدى الجرائم الماسة بالشرف، أو في إحدى الجرائم المنصوص عليها في القوانين المالية غير المصرفية، أو قانون البنك المركزي والجهاز المصرفي، أو قانون غسل الأموال، أو صدر ضده إحدى التدابير الإدارية عدا التنبيه.
5- سداد مقابل الخدمات المشار إليه بالمادة السابعة من هذا القرار.

(المادة الثالثة)
شروط قيد الأشخاص الاعتباريين بالسجل
يشترط فى راغب القيد من الأشخاص الاعتباريين استيفاء الشروط الآتية:
1- أن يكون مقيداً بسجل قيد شركات الاستشارات المالية والجهات المرخص لهما من الهيئة للقيام بأعمال التقييم المالي وإعداد دراسات القيمة العادلة أو بجدول خبراء التقييم لدى الهيئة أو بسجل بيوت خبرة لدى البنك المركزي المصري.
2- أن يتوافر فى المسئولين الرئيسيين الذين تحددهم الهيئة لدى الشخص الاعتباري ممن لهم حق اعتماد تقارير التقييم الصادرة عنهم حسن السمعة والكفاءة المهنية واجتياز الاختبارات التي تحددها الهيئة لهذا الغرض.
3- أن يتعهد بتقديم وثيقة تأمين ضد الأخطار المهنية طوال مدة القيد، وفقاً للشروط التي تضعها الهيئة وبما يتلاءم مع حجم ونطاق المسئوليات المترتبة على أعمال التقييم التي يتم القيام بها.
4- سداد مقابل الخدمات المشار إليه بالمادة السابعة من هذا القرار.

(المادة الرابعة)
إجراءات تقديم طلب القيد بالسجل
يُقدم طلب القيد بالسجل من الأشخاص الطبيعيين أو الاعتباريين على النموذج المُعد من الهيئة لهذا الغرض مرفقاً به المستندات الدالة على استيفاء الشروط الواردة بالمادتين الثانية أو الثالثة من هذا القرار بحسب الأحوال، وأي مستندات أخرى ترى الهيئة ضرورة تقديمها.
تشكل لجنة بالهيئة للبت فى طلب القيد خلال ثلاثين يوماً من تاريخ تقديمه مستوفياً المستندات المؤيدة له.

