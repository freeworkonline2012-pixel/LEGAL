مفهوم وسائل الدفع غير النقدي:
المقصود بها كل وسيلة دفع ينتج عنها إضافة فى أحد الحسابات المصرفية للمستفيد، مثل أوامر الإيداع والتحويل والخصم وبطاقات الائتمان والخصم، والدفع باستخدام الهاتف المحمول، أو غيرها من الوسائل التي يُقرها محافظ البنك المركزي المصري. ولا يُعد من بينها القيام بالإيداع النقدي المباشر لدى البنك الذي يحتفظ لديه بحساب الشركة أو الجهة المالية غير المصرفية التي سيتم التعامل معها.

الحساب المصرفي:
عقد يتفق بمقتضاه شخص طبيعي أو اعتباري مع أحد البنوك المسجلة لدى البنك المركزي أو إحدى الجهات المصرح لها بمباشرة نشاط الإيداع أو الائتمان فى جمهورية مصر العربية على فتح حساب يستخدم فى قيد جميع العمليات لسداد واستلام وتسوية المدفوعات المتبادلة نقداً أو عن طريق الوحدات النقدية الإلكترونية، مثل: الحساب الجاري، وحساب التوفير، وحساب الوديعة لأجل، وحساب الدفع باستخدام الهاتف المحمول، والحسابات المرتبطة ببطاقات الائتمان، والبطاقات مسبقة الدفع.

