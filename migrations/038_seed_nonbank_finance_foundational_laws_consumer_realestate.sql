عبد الفتاح السيسى

---

قانون تنظيم نشاط التمويل الاستهلاكى

المادة 1:

فى تطبيق أحكام هذا القانون ، يقصد بالكلمات والعبارات التالية المعنى المبين قرين كل منها :

1- الهيئة: الهيئة العامة للرقابة المالية .
2- مجلس إدارة الهيئة: مجلس إدارة الهيئة العامة للرقابة المالية .
3- التمويل الاستهلاكى: كل نشاط يهدف إلى توفير التمويل المخصص لشراء السلع والخدمات لأغراض استهلاكية متى تمت مزاولته على وجه الاعتياد ، ويشمل التمويل من خلال بطاقات المدفوعات التجارية أو إحدى وسائل الدفع التى يقررها البنك المركزى . ولا يعتبر تمويلاً استهلاكيًا فى تطبيق أحكام هذا القانون الذى تقل المدة الزمنية لسداد أقساطه عن الحد الذى يصدر به قرار من مجلس إدارة الهيئة على ألا يقل فى كل الأحوال عن ستة أشهر .
4- شركة التمويل الاستهلاكى: كل شركة مرخص لها بممارسة نشاط التمويل الاستهلاكى وتكون خاضعة لرقابة الهيئة العامة للرقابة المالية ، بما فى ذلك الشركات التى تقدم تمويلاً استهلاكيًا باستخدام بطاقات مدفوعات تجارية أو إحدى وسائل الدفع التى يقررها البنك المركزى بناء على تعاقدها مع شبكة من بائعى ومقدمى السلع والخدمات الاستهلاكية .
5- مقدمو التمويل الاستهلاكى: متجر السلع أو موزعوه الذين يزاولون نشاط التمويل الاستهلاكى .
6- بطاقات المدفوعات التجارية: البطاقات التجارية غير المصرفية الصادرة وفقًا للقواعد التى يضعها البنك المركزى ، والتى تستخدم فى منح تمويل استهلاكى .
7- عملاء التمويل الاستهلاكى: كل شخص يحصل على تمويل بموجب المعاملات التى تشملها الضوابط الواردة بهذا القانون لأغراض خارج نطاق تجارته أو مهنته .
8- الكفالة بأجر: عقد بمقتضاه يكفل شخص الوفاء بالتزام عميل التمويل الاستهلاكى بأن يتعهد لشركة التمويل الاستهلاكى أو لمقدم التمويل الاستهلاكى بأن يفى بهذا الالتزام إذا لم يف به العميل نفسه ، وذلك نظير أجر .

المادة 2:

تسرى أحكام هذا القانون على نشاط التمويل الاستهلاكى الذى تقدمه شركات التمويل الاستهلاكى فى شأن السلع والخدمات الآتية :

- المركبات وسيارات الركوب بجميع أنواعها .
- السلع المعمرة ومن بينها الأجهزة الكهربائية والإلكترونية .
- الخدمات التعليمية .
- الخدمات الطبية .
- خدمات السفر والسياحة .
- أي سلع أو خدمات أخرى يوافق عليها مجلس إدارة الهيئة .

كما تسرى أحكام هذا القانون على نشاط التمويل الاستهلاكى الذى يمارسه مقدمو التمويل الاستهلاكى فى شأن السلع الآتية :

- المركبات وسيارات الركوب بجميع أنواعها .
- السلع المعمرة ومن بينها الأجهزة الكهربائية والإلكترونية .

المادة 3:

تكون ممارسة نشاط التمويل الاستهلاكى وفقًا للأحكام الواردة بهذا القانون والشروط والضوابط والمعايير التى يصدر بها قرار من مجلس إدارة الهيئة .

فى جميع الأحوال ، يحظر على الشركات المرخص لها بمزاولة نشاط التمويل الاستهلاكى ومقدمى التمويل الاستهلاكى تلقى الودائع .

المادة 4:

يجوز لشركة التمويل الاستهلاكى أو مقدمى التمويل الاستهلاكى إشهار الحقوق المنشأة لصالح أى منهم على المنقولات محل عقود التمويل الاستهلاكى بسجل الضمانات المنقولة وفقًا لأحكام قانون تنظيم الضمانات المنقولة الصادر بالقانون رقم 115 لسنة 2015 .

المادة 5:

تلتزم شركات التمويل الاستهلاكى ومديروها ومستشاروها ومقدمو التمويل الاستهلاكى والعاملون لدى أى منهم بالمحافظة على السرية التامة لعملائهم ، وعدم إفشاء أى معلومات عنهم أو عن معاملاتهم إلى الغير بدون موافقتهم الكتابية المسبقة وفى حدود هذه الموافقة ، وذلك باستثناء الحالات التى يلزم فيها تقديم معلومات محددة وفقًا لما تفرضه القوانين المعمول بها .

المادة 6:

تلتزم شركات التمويل الاستهلاكى ومقدمو التمويل الاستهلاكى بضوابط التسويق والإعلان التى تصدرها الهيئة ، وعلى الأخص ما يتعلق بالإفصاح عن كيفية حساب سعر العائد وتحديده ، وبإخطار الهيئة بحجم النشاط وطبيعته والعوائق التى تعترضه على النحو الذى تطلبه الهيئة .

المادة 6 مكرر:

لا يجوز ممارسة نشاط الكفالة بأجر فى نشاط التمويل الاستهلاكى إلا بعد القيد بالسجل الذى تعده الهيئة لهذا الغرض ، ويستثنى من ذلك البنوك وشركات ضمان الائتمان المرخص لها بموجب قانون البنك المركزى والجهاز المصرفى الصادر بالقانون رقم 194 لسنة 2020 .

ويضع مجلس إدارة الهيئة قواعد وشروط وإجراءات القيد والشطب فى السجل المشار إليه بالفقرة الأولى من هذه المادة ، ويكون القيد فى هذا السجل بغير مقابل .

كما يضع مجلس إدارة الهيئة الضوابط الخاصة بشروط ممارسة النشاط المشار إليه فى هذه المادة وعلى الأخص ما يلى :

(أ) بالنسبة للأشخاص الاعتبارية: مراعاة أحكام المادتين (5، 12) من هذا القانون .
(ب) بالنسبة للأشخاص الطبيعية: الالتزام بإبرام عقد مع العميل يتضمن على الأقل ما يلى :
- تحديد الالتزام الذى يتم كفالته بموجب عقد الكفالة تحديدًا واضحًا .
- جميع الضمانات التى يحصل عليها الكفيل طبقًا لعقد الكفالة .
- قيمة الأجر الذى يحصل عليه الكفيل بموجب عقد الكفالة .
*مضافة بموجب قانون رقم 158 لسنة 2022.

المادة 7:

تقدم طلبات تأسيس شركات التمويل الاستهلاكى إلى الهيئة على النموذج المعد لذلك مرفقًا بها الأوراق التى تحددها الهيئة ، ومن بينها على الأخص ما يأتى :

- شهادة إيداع بنكية بما يفيد سداد رأس المال المصدر مدفوعًا بالكامل .
- ثلاث نسخ من العقد الابتدائى والنظام الأساسى للشركة .
- طلب من وكيل المؤسسين متضمنًا على وجه الخصوص اسم الشركة وبيانًا بأسماء المؤسسين وبيان رأس المال المصدر والمدفوع .
- إقرار من مراقب حسابات الشركة بقبول التعيين .

وتعد الهيئة سجلاً تدون به طلبات تأسيس الشركات المشار إليها بأرقام متتابعة وفقًا لتاريخ ورود كل منها ، ويكون لكل طلب ملف خاص تودع فيه أوراق التأسيس وكل ما يتعلق بذلك من إجراءات . وتشكل بقرار من رئيس الهيئة لجنة تضم عناصر فنية وقانونية للنظر فى تأسيس تلك الشركات .

المادة 8:

لا تجوز مزاولة نشاط التمويل الاستهلاكى إلا للشركات المرخص لها من الهيئة وفقًا للشروط والضوابط المنصوص عليها فى هذا القانون والقرارات الصادرة تنفيذًا له ، وبعد القيد لدى الهيئة فى سجل خاص لهذا الغرض وفقًا للضوابط والإجراءات التى يصدر بها قرار من مجلس إدارة الهيئة .

ويحدد مجلس إدارة الهيئة رسم الترخيص لمزاولة النشاط للشركة بما لا يجاوز مائة ألف جنيه ، ويسدد وفقًا لطرق السداد المقررة قانونًا .

ويجوز للهيئة الترخيص لشركة التمويل الاستهلاكى بممارسة أنشطة مالية غير مصرفية أخرى ، وذلك وفقًا للضوابط التى يضعها مجلس إدارة الهيئة فى هذا الشأن ، ومن بينها على الأخص وجوب إمساك حسابات وقوائم مالية مستقلة لكل نشاط ، واستيفاء متطلبات الحد الأدنى لرأس المال المصدر مدفوعًا بالكامل لجميع الأنشطة المالية غير المصرفية المرخص لها بمزاولتها .

ويقدم طلب الترخيص مرفقًا به عقد الشركة والنظام الأساسى والسجل التجارى والبطاقة الضريبية ، بالإضافة إلى ما يفيد استيفاء الشروط الواردة بالمادة (9) من هذا القانون وغيرها من المستندات التى يحددها مجلس إدارة الهيئة ، وفى حالة رفض الطلب يكون قرار الرفض مسببًا ، ويجب إصدار قرار بالرفض خلال ثلاثين يومًا من تاريخ تقديم الطلب مستوفيًا جميع المستندات المطلوبة . ويكون لصاحب الشأن الحق فى اللجوء للجنة التظلمات المنصوص عليها فى المادة (23) من هذا القانون فى حالتى رفض الطلب أو عدم الرد عليه .

ويتم قيد الشركة التى يصدر لها الترخيص بمزاولة النشاط فى السجل المعد لذلك لدى الهيئة .

المادة 9:

يشترط للحصول على ترخيص مزاولة نشاط التمويل الاستهلاكى توافر الشروط الآتية :

1- أن تتخذ الشركة شكل شركة مساهمة ، وألا يقل رأسمالها المصدر عن الحد الذى يقرره مجلس إدارة الهيئة ، على ألا يقل فى جميع الأحوال عن عشرة ملايين جنيه .
2- أن يقتصر عمل الشركة على نشاط التمويل الاستهلاكى ، ما لم يرخص لها بمزاولة أنشطة مالية غير مصرفية أخرى .
3- أن يكون من ضمن مؤسسى الشركة أشخاص اعتبارية بنسبة لا تقل عن (50%) من رأسمال الشركة ، وألا تقل نسبة مساهمة المؤسسات المالية عن (25%) من رأسمال الشركة ، ويستثنى من ذلك الشركات التى تزاول نشاط التمويل الاستهلاكى قبل العمل بهذا القانون إلا إذا تم الاستحواذ عليها أو تغيير هيكل ملكيتها بما يجاوز ثلث رأسمالها المصدر .
4- أن يتوافر لدى شاغلى مناصب العضو المنتدب والمدير المالى فى الشركة الشروط والخبرة المهنية التى يصدر بها قرار من مجلس إدارة الهيئة .
5- أن يتوافر لدى الشركة التجهيزات والبنية التكنولوجية وأنظمة المعلومات اللازمة لمباشرة النشاط وفقًا للمتطلبات التى تحددها الهيئة .
6- أن يتوافر لدى الشركة لائحة داخلية تنظم ضوابط وإجراءات منح التمويل وتحديد نسبة التمويل حسب قدرة العملاء على السداد ، والالتزام بالاستعلام عن إعلانها لدى إحدى شركات الاستعلام الائتمانى ، وآليات إدارة المخاطر والملاءة المالية ، والتعامل مع شكاوى العملاء التى يلتزم بها المديرون والعاملون .
7- أى شروط أخرى يضعها مجلس إدارة الهيئة .

المادة 10:

على شركات التمويل الاستهلاكى أن تبرم عقدًا بينها وبين عملائها وفقًا للنموذج الذى تضعه الهيئة ، على أن يتضمن على وجه الخصوص ما يأتى :

1- تحديد السلع أو الخدمات محل التمويل تحديدًا نافيًا للجهالة .
2- بيان سعر السلع أو الخدمات عند الشراء ، وما يدفعه عميل التمويل منه وقت إبرام التعاقد .
3- تحديد مبلغ التمويل المقدم من الشركة ، والمدة الزمنية للسداد ، وعدد أقساط السداد وشروطه وقيمة كل منها ، وسعر العائد المتخذ أساسًا لحساب قيمة التمويل ، وما إذا كان ثابتًا أو متغيرًا ، وذلك دون التقيد بالحدود المنصوص عليها فى أى تشريع آخر .
4- بيان الضمانات التى حصلت عليها شركة التمويل ، بما فى ذلك المنع من التصرف لحين الوفاء وفقًا للسياسة الائتمانية التى تضعها الهيئة بموافقتها .
5- تصريح العميل للشركة بالإفصاح عن بيانات التمويل إلى الهيئة وشركات الاستعلام الائتمانى .
6- حق عميل التمويل فى التعجيل بالوفاء والشروط المرتبطة بذلك .
7- حق الشركة فى بيع الديون المستحقة لها أو خصمها .
8- أن يتضمن العقد رقم الترخيص الصادر للشركة وما يفيد خضوعها لرقابة الهيئة وإشرافها .

ولشركات التمويل الاستهلاكى تقديم التمويل من خلال بطاقات المدفوعات التجارية أو إحدى وسائل الدفع التى يقررها البنك المركزى بناء على تعاقدها مع شبكة من بائعى ومقدمى السلع والخدمات الاستهلاكية ، وفى هذه الحالة تلتزم الشركات بإبرام عقد بينها وبين عملائها وفقًا للنموذج الذى تضعه الهيئة ، على أن يتضمن على الأخص ما يتضمنه من البنود (4) حتى (8) من الفقرة السابقة ، بالإضافة إلى ما يلى :

1- بيان بأسماء بائعى ومقدمى السلع والخدمات وقت إبرام العقد ، وأسلوب تحديثه والإضافة بالحذف طوال فترة سريانه .
2- تحديد الحد الأقصى للتمويل المقدم من الشركة ، وشروط سداده ، وسعر العائد المتخذ أساسًا لحساب التحويل ، وما إن كان ثابتًا أو متغيرًا .

المادة 11:

تلتزم شركة التمويل الاستهلاكى بإعداد القوائم المالية الدورية والسنوية وفقًا لمعايير المحاسبة المصرية ، ويصدر مجلس إدارة الهيئة قرارًا بالقواعد الأخرى لإعداد القوائم المالية ومواعيد إعدادها وإرسالها إلى الهيئة ومواعيد عرضها على الجمعية العامة للشركة .

ويتولى مراجعة حسابات الشركة مراقب حسابات أو أكثر من بين المقيدين بالسجل المعد لهذا الغرض لدى الهيئة وفقًا لمعايير المراجعة المصرية .

المادة 12:

على الشركات المرخص لها بمزاولة نشاط التمويل الاستهلاكى الالتزام بالقواعد والمعايير التى يضعها مجلس إدارة الهيئة ، ويجب أن تتضمن كحد أدنى ما يأتى :

1- متطلبات الحوكمة من حيث تشكيل مجلس الإدارة ، واللجان المنبثقة عنه ، والإفصاحات المطلوبة وتوقيتاتها .
2- معايير الملاءة المالية .
3- ضوابط تحديد نسب التمويل بحسب قدرة العملاء على السداد .
4- الحد الأدنى لاحتساب الاضمحلال والمخصصات للتمويل المشكوك فى تحصيله .
5- ضوابط فتح الفروع ونقلها وغلقها .
6- ضوابط مكافحة غسل الأموال وتمويل الإرهاب ، بمراعاة التعليمات الصادرة من وحدة مكافحة غسل الأموال وتمويل الإرهاب وبعد التنسيق مع الجهات المعنية .

المادة 13:

تلتزم شركات التمويل الاستهلاكى المرخص لها بمزاولة هذا النشاط بتقديم تقرير ربع سنوى إلى الهيئة وفقًا للنموذج المعد من الهيئة ، على أن يتضمن على الأقل ما يأتى :

1- نتائج أعمال الشركة .
2- حجم التمويل وتوزيعه وفقًا للسلع والخدمات محل التمويل .
3- حجم التمويل المتعثر ونسبته إلى إجمالى نشاط الشركة .
4- مدى الالتزام بتطبيق نسب التمويل بحسب قدرة العملاء على السداد .

المادة 14:

على مقدمى التمويل الاستهلاكى الذى يكون نشاطهم الرئيسى توزيع السلع محل التمويل أو بيعها الحصول على ترخيص بذلك من الهيئة والقيد فى سجل خاص لديها متى تجاوز حجم التمويل المقدم منها الحد الذى يقرره مجلس إدارة الهيئة سنويًا ، بشرط ألا يقل عن خمسة وعشرين مليون جنيه مصرى ، كما يشترط على الأخص ما يأتى :

1- أن يتخذ مقدم التمويل الاستهلاكى شكل إحدى شركات الأموال كشركة مساهمة ، أو شركة توصية بالأسهم ، أو شركة ذات مسئولية محدودة .
2- أن يخصص مبلغًا لا يقل عن الحد الأدنى الذى يقرره مجلس إدارة الهيئة الذى لا يقل عن عشرة ملايين جنيه مصرى لمزاولة نشاط التمويل الاستهلاكى .
3- أن يتوافر لدى المدير التنفيذى المسئول عن نشاط التمويل الاستهلاكى الشروط والخبرة المهنية التى يصدر بها قرار من مجلس إدارة الهيئة .
4- أن يتوافر لدى الشركة التجهيزات والبنية التكنولوجية وأنظمة المعلومات اللازمة لمباشرة نشاط التمويل الاستهلاكى وفقًا للمتطلبات التى تحددها الهيئة .
5- أن يتوافر لدى الشركة لائحة داخلية تنظم ضوابط وإجراءات منح التمويل وتحديد نسب التمويل حسب قدرة العملاء على السداد ، والالتزام بالاستعلام عن عملائها لدى إحدى شركات الاستعلام الائتمانى ، وآليات إدارة المخاطر والملاءة المالية ، والتعامل مع شكاوى العملاء التى يلتزم بها المديرون والعاملون .
6- أن تمسك الشركة حسابات وقوائم مالية مستقلة لنشاط التمويل الاستهلاكى ، وأن تلتزم بأحكام المادة (11) من هذا القانون .
7- أن تبرم عقدًا بينها وبين عملائها وفقًا لأحكام المادة (10) من هذا القانون .
8- أى شروط أخرى يضعها مجلس إدارة الهيئة .

المادة 15:

يقدم طلب الترخيص من مقدمى التمويل الاستهلاكى مرفقًا به عقد الشركة والنظام الأساسى والسجل التجارى والبطاقة الضريبية ، بالإضافة إلى ما يفيد استيفاء الشروط المنصوص عليها بالمادة (14) من هذا القانون وغيرها من المستندات التى تحددها الهيئة .

وعلى الهيئة البت فى طلب الترخيص بالقبول أو بالرفض وذلك بقرار مسبب خلال ثلاثين يومًا من تاريخ تقديم الطلب مستوفيًا جميع المستندات المطلوبة ، وفى حالة رفضه يجب أن يكون قرارها مسببًا .

وتقيد الشركة التى يصدر لها الترخيص بمزاولة النشاط فى السجل المعد لذلك لدى الهيئة . ويحدد مجلس إدارة الهيئة رسم الترخيص بمزاولة النشاط للشركة بما لا يجاوز مائة ألف جنيه ، ويسدد وفقًا لطرق السداد المقررة قانونًا .

المادة 16:

على مقدمى التمويل الاستهلاكى المرخص لهم بمزاولة نشاط التمويل الاستهلاكى ، الالتزام بالقواعد والمعايير التى يضعها مجلس إدارة الهيئة والتى تتضمن على الأخص ما يأتى :

1- معايير الملاءة المالية .
2- ضوابط تحديد نسب التمويل بحسب قدرة العملاء على السداد .
3- الحد الأدنى لاحتساب الاضمحلال والمخصصات للتمويل المشكوك فى تحصيله .
4- ضوابط مكافحة غسل الأموال وتمويل الإرهاب ، بمراعاة التعليمات الصادرة من وحدة مكافحة غسل الأموال وتمويل الإرهاب وبعد التنسيق مع الجهات المعنية فى هذا الشأن .

المادة 17:

ينشأ اتحاد يضم شركات التمويل الاستهلاكى ومقدمى التمويل الاستهلاكى فى مجال التمويل الاستهلاكى يسمى الاتحاد المصرى للجهات العاملة فى مجال التمويل الاستهلاكى ، يتمتع بالشخصية الاعتبارية الخاصة المستقلة ، ويخضع إشرافًا ورقابيًا للهيئة .

ويتولى الاتحاد تقديم التوصيات فى شأن تنمية النشاط وزيادة الوعى به ، وتبنى المبادرات الداعمة له ، وإبداء الرأى بشأن التشريعات المنظمة له ، وتنمية مهارات العاملين وتدريبهم ، والتنسيق وتمثيل الأنشطة بين الأعضاء .

ويصدر بالنظام الأساسى للاتحاد قرار من مجلس إدارة الهيئة ، شريطة أن يتضمن تحديد موارد الاتحاد ونسب تمثيل الأنشطة فى مجلس إدارته .

المادة 18:

يسجل الاتحاد فى سجل خاص بالهيئة ، بعد أداء رسم مقداره خمسة آلاف جنيه ، وينشر قرار إنشائه ونظامه الأساسى فى الوقائع المصرية على نفقة الاتحاد .

وتلتزم جميع الجهات المرخص لها بالعمل فى مجال التمويل الاستهلاكى بالانضمام إلى الاتحاد ومراعاة نظامه الأساسى .

ومع عدم الإخلال بالتدابير التى يختص بها مجلس إدارة الهيئة أو رئيسه وفق أحكام هذا القانون ، يجوز للاتحاد أن يتخذ ضد أعضائه التدابير الإدارية التى ينص عليها نظامه الأساسى عند مخالفة نظامه أو القواعد المهنية السليمة .

المادة 19:

تعمل الهيئة على نشر الوعى بنشاط التمويل الاستهلاكى وحماية المتعاملين فيه والحفاظ على المناخ التنافسى الذى يساعد على نموه .

وتقوم الهيئة بإعداد ونشر الدراسات والإحصاءات اللازمة للتعريف بنشاط التمويل الاستهلاكى .

المادة 20:

يكون للعاملين الذين يصدر بتحديدهم قرار من وزير العدل بناء على طلب رئيس مجلس إدارة الهيئة صفة مأمورى الضبط القضائى فى إثبات الجرائم التى تقع بالمخالفة لأحكام هذا القانون أو القرارات الصادرة تنفيذًا له ، ويكون لهم فى سبيل ذلك الاطلاع على السجلات والدفاتر والمستندات والبيانات والوسائط الإلكترونية فى مقار الشركات ومقدمى التمويل الاستهلاكى وفروعها والأماكن التى توجد بها ، وعلى المسئولين فى الجهات المذكورة أن يقدموا إلى الموظفين المذكورين البيانات وصور المستندات التى يطلبونها لهذا الغرض .

المادة 21:

تتلقى الهيئة الشكاوى التى يقدمها أصحاب الشأن من المتعاملين مع شركات ومقدمى التمويل الاستهلاكى عن مخالفة أحكام هذا القانون أو القرارات الصادرة تنفيذًا له ، وتلتزم الهيئة بالرد على هذه الشكاوى خلال موعد لا يجاوز شهرًا من تاريخ استيفاء المستندات التى تحددها الهيئة ، ويصدر قرار من رئيس الهيئة بتنظيم إجراءات تقديم الشكاوى والبت فيها وطريقة إخطار مقدميها بالرد .

المادة 22:

لمجلس إدارة الهيئة فى حالة مخالفة الشركة لأحكام هذا القانون أو القرارات الصادرة تنفيذًا له ، أو إذا فقدت شرطًا من شروط الترخيص ، أو إذا قامت بما من شأنه تهديد استقرار السوق أو مصالح المساهمين فيها أو المتعاملين معها ، أن يتخذ تدبيرًا أو أكثر من التدابير الآتية :

1- توجيه تنبيه إلى الشركة بإزالة المخالفة خلال المدة وبالشروط المحددة فى التنبيه .
2- دعوة مجلس إدارة الشركة أو جمعيتها العامة للانعقاد ، بحضور أحد ممثلى الهيئة ، للنظر فى أمر المخالفات المنسوبة إليها واتخاذ اللازم نحو إزالتها .
3- دعوة الجمعية العمومية للشركة للنظر فى تنحية رئيس مجلس إدارة الشركة أو العضو المنتدب أو كليهما .
4- حل مجلس إدارة الشركة وتعيين مفوض لتسيير أعمال الشركة مؤقتًا لمدة لا تجاوز ستة أشهر ويجوز مدها لمدة أخرى ستة أشهر ، ويعرض المفوض خلال مدة تعيينه الأمر على الجمعية العمومية لتعيين مجلس إدارة جديد بالأداة القانونية المقررة .
5- المنع من إبرام عقود تمويل جديدة لمدة لا تزيد على ستة أشهر .
6- إلغاء ترخيص الخاص بالتمويل الاستهلاكى أو تقديم التمويل الاستهلاكى .

ويجوز اتخاذ التدابير المنصوص عليها فى البنود (1، 5، 6) من هذه المادة ضد مقدمى التمويل الاستهلاكى حال تحقق أى من الحالات المنصوص عليها فى الفقرة الأولى من هذه المادة ، بما فيها فى عزل المدير التنفيذى المسئول عن نشاط التمويل الاستهلاكى .

ويجوز لرئيس مجلس إدارة الهيئة حال مخالفة شركة التمويل الاستهلاكى لأحكام هذا القانون أن يأمر مؤقتًا بغلق مقارها بالطريق الإدارى .

ويجوز أن تصدر التدابير المنصوص عليها بالبندين (1،2) من هذه المادة من رئيس الهيئة ، كما يجوز له اتخاذ أى من التدابير المنصوص عليها فى البندين (4، 5) من هذه المادة إذا كان الخطر شديدًا ومن شأنه أن يترتب عليه ضرر يتعذر تداركه ، وذلك لمدة أقصاها شهر أو لحين العرض على مجلس إدارة الهيئة أيهما أقرب .

ويجوز للمجلس تحقيقًا لاستقرار السوق ، أو حماية لحقوق المتعاملين مع شركات ومقدمى التمويل الاستهلاكى ، وفى حالة تعرض أى منهم لمشكلات مالية تؤثر على مراكزهما المالى ، إلزامهما بتعزيز ملاءتهما المالية وفقًا لجدول زمنى محدد .

المادة 23:

تنشأ لجنة أو أكثر لنظر التظلمات التى يقدمها أصحاب الشأن من القرارات الإدارية الصادرة تطبيقًا لأحكام هذا القانون ، ويصدر بتشكيل كل لجنة قرار من مجلس إدارة الهيئة ، وتكون برئاسة أحد نواب رئيس مجلس الدولة وعضوية اثنين من مستشارى مجلس الدولة يتم اختيارهم وفقًا لأحكام القانون المنظم لمجلس الدولة ، وممثل عن الهيئة يختاره رئيسها ، وعضو من ذوى الخبرة . ويكون للمتظلم الحضور أمام اللجنة بنفسه أو بنائب عنه أو من يمثله .

ويحدد قرار مجلس إدارة الهيئة تشكيل اللجنة واختصاصاتها ومكافآت أعضائها وإجراءات النظر فى التظلم والبت فيه ومواعيد تلك الإجراءات . ويكون التظلم أمام هذه اللجنة وجوبيًا خلال ستين يومًا من تاريخ الإخطار أو العلم اليقينى به ، على أن تصدر اللجنة قرارها فى الميعاد الذى يجاوز ثلاثين يومًا من تاريخ استيفاء المستندات والبيانات المطلوبة ، ويكون قرارها نهائيًا ونافذًا .

ولا تقبل الدعوى التى ترفع إلى المحكمة المختصة إلا بعد اللجوء إلى اللجنة المشار إليها بعد ميعاد التقدم بالتظلم ومواعيد البت فيه .

ويترتب على تقديم التظلم إلى اللجنة وقف المدد المقررة قانونًا لسقوط أو تقادم الحقوق أو لرفع الدعوى ، وذلك حتى انقضاء ميعاد البت فى التظلم .

المادة 24:

مع عدم الإخلال بأى عقوبة أشد منصوص عليها فى قانون العقوبات أو فى أى قانون آخر ، يعاقب على الجرائم المنصوص عليها فى المواد التالية بالعقوبات المقررة فيها .

المادة 25:

يعاقب بالحبس وبغرامة لا تقل عن مائتى ألف جنيه ولا تزيد على مليون جنيه ، أو بإحدى هاتين العقوبتين ، كل من زاول نشاط التمويل الاستهلاكى الخاضع لأحكام هذا القانون دون الحصول على ترخيص بذلك .

ويعاقب بذات العقوبة كل من خالف أيًا من أحكام المادة (5) من هذا القانون ، وتتعدد الغرامات بتعدد المجنى عليهم .

المادة 26:

يعاقب بغرامة لا تقل عن عشرة آلاف جنيه ولا تزيد على مائة ألف جنيه ، كل من خالف أيًا من ضوابط التعاقد مع عملاء التمويل المنصوص عليها فى المادتين (10، 14) من هذا القانون أو ضوابط التسويق والإعلان لنشاط التمويل الاستهلاكى المنصوص عليها فى المادة (6) من هذا القانون .

المادة 27:

يعاقب بغرامة لا تقل عن خمسمائة جنيه ولا تزيد على ألف جنيه عن كل يوم تأخير فى تسليم القوائم المالية والتقارير الدورية التى يحددها مجلس إدارة الهيئة .

وتضاعف الغرامة بحديها الأدنى والأقصى فى حال تكرار التأخير عن كل يوم تأخير فى حال زيادة التأخير على شهر .

المادة 28:

يعاقب بالحبس لمدة لا تجاوز شهرًا وبغرامة لا تقل عن عشرين ألف جنيه ولا تجاوز مائتى ألف جنيه ، أو بإحدى هاتين العقوبتين ، كل من تعمد منع أحد العاملين بالهيئة الذين يتمتعون بصفة الضبطية القضائية من أداء أى من الأعمال المكلف بها بموجب هذا القانون ، وكذا كل من تعمد حجب البيانات أو المستندات أو الوسائط الإلكترونية المطلوبة فى هذا الشأن دون سند من هذا القانون .

المادة 28 مكرر:

يعاقب بالحبس وبغرامة لا تقل عن خمسة آلاف جنيه ولا تزيد على ضعفى المتبقى من قيمة التمويل محل عقد التمويل ، أو بإحدى هاتين العقوبتين ، كل من استخدم الغش أو التدليس للامتناع عن تنفيذ كل أو بعض التزاماته المالية المقررة بموجب عقد التمويل المبرم وفقًا لأحكام هذا القانون .

وتستثنى الجرائم المبينة فى هذه المادة من الأحكام المشار إليها بالمادة (32) من هذا القانون .

ويجوز الصلح فى هذه الجرائم سواء أمام النيابة العامة أو المحكمة المختصة ، بحسب الأحوال ، وذلك فى أية حالة تكون عليها الدعوى ، ويترتب على الصلح انقضاء الدعوى الجنائية بالنسبة للجريمة التى تم الصلح بشأنها ، وتأمر النيابة العامة بوقف تنفيذ العقوبة إذا تم الصلح أثناء تنفيذها ولو بعد صيرورة الحكم باتًا .
*مضافة بموجب قانون رقم 158 لسنة 2022.

المادة 28 مكرر 1:

يُعاقب بالحبس وبغرامة لا تقل عن خمسين ألف جنيه ولا تزيد على خمسمائة ألف جنيه ، أو بإحدى هاتين العقوبتين ، كل من مارس نشاط الكفالة بأجر فى نشاط التمويل الاستهلاكى دون أن يكون مقيدًا بالسجل المعد لهذا الغرض .
*مضافة بموجب قانون رقم 158 لسنة 2022.

