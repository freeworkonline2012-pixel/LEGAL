مادة 42 مكرر:

لمجلس إدارة الهيئة عند إخلال أى من الوكلاء العقاريين أو خبراء التقييم العقارى أو وسطاء التمويل العقارى بأى من التزاماتهم الواردة بهذا القانون ولائحته التنفيذية والمعايير والضوابط التى يضعها مجلس إدارتها عند مخالفة ما يراه مناسبًا اتخاذ التدابير الآتية :

1- توجيه إنذار بإزالة المخالفة .
2- وقف مزاولة النشاط لمدة لا تجاوز سنة .
3- الشطب من سجلات الهيئة .

