مادة 7:

يجوز للمستثمر التصرف فى العقار الضامن بالبيع أو غيره أو ترتيب أى حق عينى عليه وذلك بعد موافقة الممول وبشرط أن يقبل المتصرف إليه الحلول محل المستثمر فى التزاماته المترتبة على اتفاق التمويل .

ويجوز للمستثمر تأجير العقار الضامن لتمكين غيره من الانتفاع بشغله بدلًا منه وذلك بعد الحصول على موافقة الممول وللمستثمر أن يشترط حوالة الحق للممول فى أجرة العقار أو مقابل شغله وذلك وفاء لمستحقاته .

ولا يجوز للممول رفض الموافقة على التصرف فى العقار الضامن أو تأجيره أو تمكين الغير من الانفراد بشغله أو تأجيره إلا لأسباب جدية تتعرض معها مصالحه بالخطر ويجب عليه إخطار المستثمر بهذه الأسباب كتابة خلال ثلاثين يومًا من تاريخ إخطاره برغبته فى التصرف أو التأجير وإلا اعتبر موافقًا على ذلك .

وللممول أن يشترط تضامن المستثمر مع من يتصرف إليه بالوفاء بالالتزامات المترتبة على اتفاق التمويل . وتحدد اللائحة التنفيذية القواعد والإجراءات التى تتبع فى الأحوال المشار إليها .

مادة 8:

إذا تصرف المستثمر فى العقار الضامن أو أجره أو مكن أحدًا أو أجره بالمخالفة لأحكام المادة السابقة كان للممول أن يطالب المتصرف إليه بشغله باقى أقساط الثمن أو قيمة اتفاق التمويل بحسب الأحوال بإنذار على يد محضر خلال مهلة لا تقل عن ثلاثين يومًا .

فإذا لم يقم هذا المستثمر بهذا الوفاء كان للممول أن يتخذ فى مواجهته الإجراءات المنصوص عليها فى الباب الرابع من هذا القانون .

مادة 9:

يجوز للمستثمر أن يعجل بالوفاء بأقساط الثمن أو بالتمويل كله أو بعضه .

وفى هذه الحالة يتم خفض الأقساط المستحقة عليه بما يتناسب مع تعجيل الوفاء وفقًا للقواعد التى تحددها اللائحة التنفيذية لهذا القانون .

(الباب الثالث)
قيد الضمان العقارى وحوالة الحقوق الناشئة عن اتفاق التمويل

مادة 10:

يقدم طلب قيد الضمان العقارى إلى مكتب الشهر العقارى الكائن فى دائرته العقار من الممول أو المستثمر متضمنًا البيانات التى تحددها اللائحة التنفيذية مرفقًا به سند ملكية العقار .

ويجب البت فى طلب القيد بعد التحقق من صحة حدود العقار على النحو الوارد بالطلب وبسند الملكية وبتكليف أو تقديمه أن يستوفيه بما يستوفيه خلال أسبوع من تاريخ تقديم الطلب .

ويخطر مقدم الطلب خلال الموعد المشار إليه بالقرار الصادر بشأنه بموجب كتاب موصى عليه مسجل بعلم الوصول ويجب أن يكون القرار برفض الطلب مسببًا .

مادة 11:

يجوز للممول أن يحيل حقوقه الناشئة عن اتفاق التمويل سواء على سبيل التمليك أو الرهن إلى الشركة أو إلى إحدى الجهات المرخص لها بمباشرة نشاط التوريق ، وذلك كله وفقًا للقواعد التى تحددها اللائحة التنفيذية لهذا القانون ، على أن ترهن أو ترتهن الإتفاقيات الضامنة رهنًا حيازيًا وفقًا لذلك طبقًا للقواعد التى يحددها مجلس إدارتها .

ويقيد عقد الرهن أو إحدى الجهات الهيئة تمسكه بسجل يحدده أحد الجهات التى يحددها مجلس إدارتها .

ويجب أن يتضمن إتفاق التمويل قبول المستثمر بحوالة حقوق الممول المشار إليها فى الفقرة الأولى ، ويترتب إخطار المستثمر بالحوالة وحدد إخطار التمويل العقارى طريقة الإخطار .

