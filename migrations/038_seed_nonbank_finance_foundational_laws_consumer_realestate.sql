مادة 42 مكرر 1:

تنشأ لجنة أو أكثر لنظر تظلمات الشركات ووكلاء العقارى وخبراء التقييم العقارى ووسطاء التمويل العقارى من القرارات الإدارية الصادرة تطبيقًا لأحكام هذا القانون ولائحته التنفيذية .

ويصدر بتشكيل كل لجنة قرار من الوزير المختص ، تكون برئاسة أحد نواب رئيس مجلس الدولة وعضوية اثنين من مستشارى الدولة يختارهم رئيسها وممثل عن الهيئة وعضو من ذوى الخبرة يختاره الوزير المختص .

ويكون للمتظلم أمام هذه اللجنة خلال خمسة عشر يومًا من تاريخ الإخطار أو العلم به ، على أن تصدر اللجنة قراراها فى التظلم خلال ثلاثين يومًا ويكون قرارها نهائيًا .

ولا تقبل الدعوى التى ترفع إلى المحكمة المختصة إلا بعد اللجوء إلى اللجنة المشار إليها بعد فوات ميعاد التظلم أو صدور قرار فيه .

ويترتب على تقديم التظلم إلى اللجنة وقف المدة المقررة قانونًا لسقوط أو تقادم الحقوق أو رفع الدعوى ، وذلك حتى انقضاء ميعاد البت فى التظلم .

ويصدر بإجراءات نظر التظلم والبت فيه والرسوم واجبة السداد بما لا يجاوز عشرين ألف جنيه بالنسبة لشركات التمويل العقارى أو إعادة التمويل العقارى وعشرة آلاف جنيه بالنسبة للوكلاء العقاريين وخبراء التقييم العقارى ووسطاء التمويل العقارى قرار من الوزير المختص .

ويتم رد الرسوم للمتظلم فى حالة قبول تظلمه أو صدور حكم بإلغاء القرار .

