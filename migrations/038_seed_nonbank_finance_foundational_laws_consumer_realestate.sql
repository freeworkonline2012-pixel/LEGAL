مادة 33:

تلتزم الشركة بإعداد القوائم المالية وتقديمها للهيئة وفقًا للمعايير وفى المواعيد التى يحددها مجلس إدارتها .

ويتولى مراجعة حسابات الشركة مراقبى حسابات من بين المقيدين فى السجل المعد لهذا الغرض بالهيئة وفقًا لمعايير المراجعة التى يحددها مجلس إدارتها .

