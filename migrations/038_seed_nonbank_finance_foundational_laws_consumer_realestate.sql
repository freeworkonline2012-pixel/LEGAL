بإصدار قانون تنظيم نشاط التمويل الاستهلاكى
(نسخة محدثة تتضمن التعديلات المدخلة بموجب القانون رقم 158 لسنة 2022)

المادة 1 إصدار:
يعمل بأحكام القانون المرافق فى شأن تنظيم نشاط التمويل الاستهلاكى .

المادة 2 إصدار:
تعد الشركات المرخص لها من الهيئة العامة للرقابة المالية بممارسة نشاط التمويل الاستهلاكى طبقا لأحكام القانون المرافق من الشركات التى تؤدى خدمات فى مجال الأسواق المالية غير المصرفية وفقًا لأحكام قانون تنظيم الرقابة على الأسواق والأدوات المالية غير المصرفية رقم 10 لسنة 2009 .

المادة 3 إصدار:
لا تسرى أحكام القانون المرافق التى تجريها البنوك الخاضعة لرقابة البنك المركزى المصرى ولو كانت بغرض تمويل شراء سلع أو خدمات استهلاكية .
كما لا تسرى أحكامه على الأنشطة المنظمة بموجب قوانين التمويل العقارى والتأجير التمويلى والتخصيم والتمويل متناهى الصغر أو شراء العقارات من خلال المطورين العقاريين .

المادة 4 إصدار:
تسرى على شركات التمويل الاستهلاكى فيما لم يرد فى شأنه نص فى القانون المرافق الأحكام الواردة فى قانون شركات المساهمة وشركات التوصية بالأسهم والشركات ذات المسئولية المحدودة الصادر بالقانون رقم 159 لسنة 1981 ، والقانون رقم 10 لسنة 2009 بشأن تنظيم الأسواق والأدوات المالية غير المصرفية .
ولا تسرى أحكام القانون التجارى الصادر بالقانون رقم 17 لسنة 1999 والقانون رقم 100 لسنة 1957 فى شأن بعض البيوع التجارية على شركات التمويل الاستهلاكى ومقدمى التمويل الاستهلاكى الخاضعين لأحكام القانون المرافق .

المادة 5 إصدار:
فيما عدا المنازعات والدعاوى التى يختص بنظرها مجلس الدولة ، تختص المحاكم الاقتصادية بالفصل فى المنازعات والدعاوى الناشئة عن تطبيق أحكام القانون المرافق بما فيها منازعات التنفيذ الوقتية والموضوعية وكذا الدعاوى الجنائية عن الجرائم المنصوص عليها فيه .

المادة 6 إصدار:
على كل من يزاول نشاط التمويل الاستهلاكى المنظم بموجب القانون المرافق توفيق أوضاعه وفقًا لأحكامه خلال ستة أشهر من تاريخ العمل به .
ولمجلس إدارة الهيئة العامة للرقابة المالية بقرار منه مد فترة توفيق الأوضاع المنصوص عليها فى الفقرة السابقة لمدد أخرى مماثلة لا تجاوز فى مجموعها سنتين .

المادة 7 إصدار:
ينشر هذا القانون فى الجريدة الرسمية ، ويعمل به من اليوم التالى لتاريخ نشره .
يبصم هذا القانون بختم الدولة ، وينفذ كقانون من قوانينها .
