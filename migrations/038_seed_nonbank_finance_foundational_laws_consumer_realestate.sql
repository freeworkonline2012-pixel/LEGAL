قانون التمويل العقارى

(الباب الأول)
أحكام عامة

مادة 1:

تسرى أحكام هذا القانون على أنشطة التمويل العقارى وهى :

(أ) تمويل شراء أو بناء أو ترميم أو تحسين العقارات لأغراض السكن والوحدات الإدارية والمنشآت الخدمية ومبانى المحال المخصصة للنشاط التجارى .
(ب) الإجارة مع مراعاة أحكام القانون رقم 95 لسنة 1995 فى شأن التأجير التمويلى .
(ج) تمويل شراء حق الإنتفاع بالعقارات .
(د) تمويل شراء العقارات بنظامى المشاركة والمرابحة .
(هـ) إعادة التمويل العقارى .

ويجوز للوزير المختص بموافقة مجلس إدارة الهيئة إضافة أنشطة أخرى فى مجال التمويل العقارى .

ويكون ذلك التمويل بضمان حق الإمتياز على العقار أو رهنه رهنًا رسميًا ، أو غير ذلك من الضمانات التى يقبلها الممول طبقًا للقواعد والإجراءات والشروط التى تحددها اللائحة التنفيذية لهذا القانون .

* معدله بقرار رئيس جمهورية مصر العربية بالقانون رقم 55 لسنة 2014

مادة 1 مكرر:

يعتد بتاريخ إثبات إتفاق التمويل العقارى وشهره وكذا قيد الضمان وتجديده وشطبه ، من جميع الرسوم والتكاليف المساحية . ويستثنى من أحكام الضمان قيد الضمانتين (43، 44) من القانون رقم 114 لسنة 1946 بتنظيم الشهر العقارى لحين سداد كامل الدين والمادة (42) من قانون الضريبة على الدخل الصادر بالقانون رقم 91 لسنة 2005 وذلك عند منح التمويل العقارى .

كما تعفى العقارات الممولة وفقًا لأحكام هذا القانون من رسوم التنازل التى تفرضها الجهات المصدرة لقرارات تخصيص الأراضى لجهات التمويل .

* مضافة بقرار رئيس جمهورية مصر العربية بالقانون رقم 55 لسنة 2014

مادة 2:

مع عدم الإخلال باختصاصات جهاز حماية المنافسة ومنع الممارسات الإحتكارية ، تختص الهيئة بالتنظيم والرقابة والإشراف على جميع أنشطة التمويل العقارى المبينة فى هذا القانون .

* معدله بقرار رئيس جمهورية مصر العربية بالقانون رقم 55 لسنة 2014
[النص قبل التعديل كان ينشئ هيئة عامة تتبع وزير الاقتصاد والتجارة الخارجية تختص بشئون التمويل العقارى ويصدر بشأنها وتشكيلها قرار من رئيس الجمهورية .]

مادة 3:

تكون للجهات التالية غير ملزمة بمزاولة نشاط التمويل العقارى المنصوص عليه فى هذا القانون بشرط قيدها فى سجل تعده الجهة الإدارية لهذا الغرض :

(1) الأشخاص الاعتبارية العامة التى يدخل نشاط التمويل العقارى ضمن أغراضها .
(2) شركات التمويل العقارى المنصوص عليها فى الباب الخامس من هذا القانون .

ويجوز للبنوك المسجلة لدى البنك المركزى المصرى وفقًا للقواعد التى يقررها أن تزول نشاط التمويل العقارى دون قيدها لدى الجهة الإدارية ولا تسرى عليها أحكام الفقرة الثانية من المادة (4) والباب السابع من هذا القانون .

مادة 4:

تكون مزاولة أنشطة التمويل العقارى ومجالاته المنصوص عليها فى هذا القانون وفقًا للقواعد والمعايير التى يحددها مجلس إدارة الهيئة التى تتناسب مع القدرة المالية لطالب التمويل وذلك فى ضوء الحالة العامة للسوق .

وتصدر الهيئة قواعد وإجراءات قواعد وشروط التمويل ووحدوده والحدود الائتمانية ونسبة التمويل إلى قيمة العقار أو الضمان أو حسب الأحوال .

ويكون لجهات التمويل وإعادة التمويل المرخص لها الحق فى تحديد تكاليف التمويل دون التقيد بالحدود القصوى المقررة بالتقيد فى قانون آخر .

وتقدر قيمة العقار الضامن بمعرفة خبراء التقييم المقيدة أسماءهم فى الجداول التى تعدها الهيئة لهذا الغرض بشرط ألا يكون لهذا الغرض من بين العاملين لدى الممول .

وتحدد اللائحة التنفيذية قواعد وإجراءات وشروط القيد فى هذه الجداول .

* معدله بقرار رئيس جمهورية مصر العربية بالقانون رقم 55 لسنة 2014

مادة 5: [ملغاة — أُلغيت بموجب قانون رقم 93 لسنة 2018]

(كانت تنص قبل الإلغاء على إنشاء صندوق ضمان ودعم نشاط التمويل العقارى المنصوص عليه فى هذا القانون تلتزم الدولة بتوفير أراضٍ مخفضة الدخول لدعم إسكان ذوى الدخول المنخفض من خلال هذا الصندوق ، ويصدر قرار من مجلس إدارة الصندوق بتحديد شروط وقواعد استحقاق هذه المساكن ومعايير توصيف مشروعات إسكان ذوى الدخل المنخفض .)

