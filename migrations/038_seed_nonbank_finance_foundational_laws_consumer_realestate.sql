مادة 41:

ينشأ لدى الجهة الإدارية مكتب لتلقى الشكاوى وفحص الشكاوى التى تقدم بشأن مخالفة أحكام هذا القانون أو القرارات الصادرة تنفيذًا له وتحدد اللائحة التنفيذية لماذا تحدده اللائحة التنفيذية نظام وإجراءات عمل هذا المكتب .

مادة 42:

لمجلس إدارة الهيئة فى حال مخالفة الشركة أيًا من أحكام هذا القانون أو القرارات الصادرة تنفيذًا له أو إذا فقدت شرطًا من شروط الترخيص أو إذا قامت بما من شأنه تهديد استقرار السوق أو مصالح المساهمين فيها أو المتعاملين معها أن يتخذ تدبيرًا أو أكثر من التدابير الآتية :

(أ) توجيه تنبيه إلى الشركة بإزالة المخالفة خلال المدة وبالشروط المحددة فى التنبيه .
(ب) مطالبة مجلس إدارة الشركة بدعوة مجلس إدارتها أو الجمعية العامة للنظر فى أمر المخالفات المنسوبة إليها واتخاذ اللازم نحو إزالتها .
(ج) حل مجلس إدارة الشركة وتعيين مفوض لحين تعيين مجلس إدارة جديد بالأداة القانونية المقررة .
(د) المنع من مزاولة كل أو بعض الأنشطة المرخص بمزاولتها لفترة محددة أو منع التعامل مع عملاء جدد .
(هـ) إلغاء ترخيص مزاولة بعض أو كل الأنشطة المرخص بمزاولتها .

ويجوز أن تصدر التدابير المنصوص عليها بالبندين (أ، ب) من رئيس الهيئة ، كما يجوز له اتخاذ أى من التدابير المنصوص عليها فى البند (د) من هذه المادة إذا كان الخطر شديدًا ومن شأنه أن يترتب عليه ضرر يتعذر تداركه ، وذلك لمدة أقصاها شهر أو لحين العرض على مجلس إدارة الهيئة أيهما أقرب .

كما للمجلس تقرير ما يراه مناسبًا من تدابير أخرى للحفاظ على حقوق المتعاملين مع هذه الشركة .

ويجوز للمجلس تحقيقًا لاستقرار السوق أو حماية لحقوق المتعاملين أو المساهمين إذا اقتضم خطر يهدد استقرار نشاط التمويل العقارى فيها المشاركين اتخاذ التدابير الآتية :

(1) توجيه إنذار بإزالة المخالفة خلال مدة محددة .
(2) وقف مزاولة النشاط لفترة لا تجاوز تسعين يومًا .
(3) المنع من مزاولة النشاط مع تحديد الإجراءات اللازمة لمواجهة الآثار المترتبة على هذا المنع .

ويكون للجهة الإدارية أن تتخذ التدابير التالية بالنسبة لشركات التمويل العقارى المخالفة بهذا القانون واللائحته التنفيذية :

(1) إلزام الشركة باتخاذ إجراءات إدماجها فى شركة أخرى أو فى إحدى الجهات الأخرى التى تزاول هذا النشاط خلال مدة لا تجاوز ثلاثة أشهر يجوز مدها بقرار من الوزير المختص .
(2) إلزام الشركة بزيادة رأس مالها المدفوع أو حجم السيولة النقدية معًا أو الأمرين وفقًا لجدول زمنى محدد .

