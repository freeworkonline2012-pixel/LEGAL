مادة 29:

يقدم طلب الترخيص إلى الجهة الإدارية على النموذج الذى تعده لهذا الغرض وتحدد اللائحة التنفيذية قواعد وإجراءات الترخيص ورسومه بما لا يجاوز عشرة آلاف جنيه .

مادة 30:

على الجهة الإدارية إعطاء طالب الترخيص شهادة باستلام المستندات المقدمة منه أو بيانًا بما يلزم تقديمه من مستندات أخرى وعليه استيفاء هذه المستندات خلال الثلاثة أشهر التالية وإلا سقط طلبه .

مادة 31:

تقوم الجهة الإدارية بالبت فى طلب الترخيص وإخطار الطالب بقرارها كتابة بشأنه خلال ثلاثين يومًا من تاريخ استيفاء المستندات اللازمة .

ولا يجوز للجهة الإدارية أن ترفض الترخيص إلا فى الحالات الآتية :

(1) عدم استيفاء الشروط المبينة فى هذا القانون أو القرارات الصادرة تنفيذًا له .
(2) عدم توافر المعايير التى تحددها اللائحة التنفيذية بشأن الخبرة والكفاءة المهنية فى مديرى الشركة .
(3) صدور حكم بشهر إفلاس أى من مؤسسيها أو مديريها خلال السنوات الخمس السابقة على تقديم الطلب ما لم يكن قد رد إليه اعتباره .
(4) أن يكون قد سبق الحكم على أحد مؤسسى الشركة أو مديرها أو أحد أعضاء مجلس الإدارة خلال السنوات الخمس السابقة على تقديم طلب الترخيص بعقوبة جناية أو جنحة ماسة بالشرف أو الأمانة ما لم يكن قد رد إليه اعتباره .

مادة 32:

تبين اللائحة التنفيذية المعايير المالية التى يتعين على الشركة الالتزام بها بما يتضمن ما يأتى :

(1) الأسلوب الذى يتبع فى تقييم أصول الشركة .
(2) تحديد الحد الأدنى لنسب حقوق المساهمين إلى كل من أصول الشركة وخصومها وحجم محفظة التمويل .
(3) تحديد الحد الأدنى للأصول المتداولة إلى الخصوم المتداولة .
(4) القواعد اللازمة لضمان حسن سير أعمال الشركة وضمان حقوق الدائنين والعملاء .

مادة 32 مكرر:

تعد العوائد المدينة التى تدفعها الشركة على القروض ووسائل التمويل من غيرها ومصروفاتها المحتسبة على التمويل المشكوك فى تحصيله وفقًا للمعايير التى تضعها الهيئة ولما يقرره مراقبو حسابات الشركة من مقابل التكاليف الواجبة الخصم عند تحديد صافى الدخل الخاضع للضريبة وفقًا لأحكام قانون الضريبة على الدخل بالقانون رقم 91 لسنة 2005 .

كما تعد من ضريبة الديون المشكوك الخصم المخصصات التى تعتمدها إدارة الشركة بناءً على تقرير مراقبى الحسابات لزيادة على المخصصات المشار إليها وذلك بعد اتخاذ الإجراءات الجادة لاستيفائها وفقًا للضوابط والإجراءات التى يضعها مجلس إدارة الهيئة فى هذا الخصوص .

وتعفى من ضريبة الدمغة والرسوم وغيرها من الضرائب والرسوم أرصدة القروض وأية صورة من صور التمويل التى تقدمها الشركة لعملائها وفقًا لأحكام هذا القانون .

