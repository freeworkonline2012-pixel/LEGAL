(الباب الرابع)
التنفيذ على العقار

مادة 12:

للممول فى حالة عدم وفاء المستثمر بالمبالغ المستحقة عليه أو مضى ثلاثين يومًا على استحقاقها أو عند ثبوت نقص مخل بضمان قيمة العقار بفعل المستثمر أو إهمال المستثمر أو شاغل العقار واجب النفاذ بحكم قضائى واجب النفاذ أن ينذر المستثمر بالوفاء أو بتقديم ضمان كافٍ بحسب الأحوال وذلك خلال ستين يومًا على الأقل من تاريخ الإنذار .

مادة 13:

مع عدم الإخلال بأحكام المادتين (35) و(37) من هذا القانون إذا انقضت المدة المحددة بالإنذار دون قيام المستثمر بالوفاء أو بتقديم الضمان كان الممول ملتزمًا بالوفاء بكامل المبالغ المتبقية طبقًا لاتفاق التمويل العقارى .

ويكون للممول فى هذه الحالة أن يطلب من قاضى التنفيذ الذى يقع العقار فى دائرة اختصاصه وضع الصيغة التنفيذية على اتفاق التمويل والأمر بالحجز على العقار الضامن لبيعه تمهيدًا بعد إعلان قانونًا المستثمر لسماع أقواله .

مادة 14:

يقوم الممول بعد وضع الصيغة التنفيذية على اتفاق التمويل بإعلانها إلى المستثمر مع تكليفه بالوفاء خلال مدة لا تقل عن ثلاثين يومًا كما يقوم بإعلانها إلى مكتب الشهر العقارى المختص للتأشير به بغير رسوم خلال أسبوع من تاريخ إعلان ذلك إلى الضمان العقارى مع إعلان جميع الدائنين المقيدة حقوقهم وإلا كان التكليف بالوفاء غير نافذ فى حقهم .

مادة 15:

يقوم التأشير بالسند التنفيذى فى مكتب الشهر العقارى مقام تسجيل تنبيه نزع الملكية .

مادة 16:

إذا لم يقم المستثمر بالوفاء خلال المدة المحددة له فى الإعلان بالسند التنفيذى صدر قاضى التنفيذ بناءً على طلب الممول أمرًا بتعيين وكيل عقارى من بين الوكلاء المقيدة أسماؤهم بسجل تعده الجهة الإدارية لهذا الغرض لمباشرة إجراءات بيع العقار بالمزاد العلنى المنصوص عليها فى المواد التالية تحت الإشراف المباشر لقاضى التنفيذ .

وتحدد اللائحة التنفيذية الشروط الواجب توافرها فى الوكلاء العقاريين وقواعد تحديد أتعابهم وإجراءات القيد فى السجل .

مادة 17:

لكل ذى مصلحة أن يطلب استبدال الوكيل العقارى بطلب مسبب يقدمه إلى قاضى التنفيذ ولا يترتب على مجرد تقديم الطلب وقف إجراءات التنفيذ إلا إذا قرر ذلك القاضى للقاضى أن يأمر بالاستبدال إذا تبين له جدية أسباب الطلب .

مادة 18:

يحدد أثمان الخبراء من الوكلاء عن إليهم المشار إليهم فى الفقرة الثانية من المادة (4) الثمن الأساسى للعقار .

ويحدد الوكيل العقارى شروط بيع العقار بالمزاد العلنى على أن تتضمن تاريخ وساعة ومكان إجراء البيع والثمن الأساسى للعقار وتأمين الاشتراك فى المزاد وتحدد اللائحة التنفيذية قواعد حساب هذا التأمين .

مادة 19:

على الوكيل العقارى أن يعلن كلا من المستثمر وحائز العقار والدائنين المقيدة حقوقهم بشروط الميعاد المحدد لإجراء المزايدة بمدة لا تقل عن ثلاثين يومًا ولا تجاوز خمسة وأربعين يومًا وذلك بلصق الإعلان على العقار وعلى اللوحة المعدة للإعلانات بالمحكمة الكائن فى دائرتها العقار مع نشره فى جريدتين يوميتين واسعتى الانتشار للمستثمر وللممول أن يطلبا الإعلان أو النشر أكثر من مرة على نفقته .

مادة 20:

يتولى الوكيل العقارى إجراء المزايدة فى اليوم المحدد للبيع ويبدأ المزايدة بالنداء على الثمن الأساسى وتنتهى بإيقاع البيع على من يقدم أكبر عرض ، فإذا كان هذا العرض أقل من الثمن الأساسى ولم يبلغ عدد المزايدين ثلاثة أشخاص وجب على الوكيل تأجيل البيع إلى يوم آخر خلال الثلاثين يومًا التالية وما يعلن عنه بذات الإجراءات المنصوص عليها فى المادة (19) من هذا القانون ولا يجوز للممول أن يشترك فى المزايدة إلا إذا كان أكبر مبلغ العرض السابق كان أقل من أكبر مقدار مستحقاته قبل المستثمر مقابل إبراء ذمة الممول منها فى جميع الأحوال ويعتبر العرض الذى لا يزاد عليه خلال خمس دقائق نهائيًا للمزايدة .

مادة 21:

إذا قام المستثمر بالوفاء بما عليه من أقساط فى وقت سابق على إيقاع البيع وجب على الوكيل العقارى أن يوقف الإجراءات ويلتزم المستثمر بأن يؤدى إلى الممول المصروفات التى يصدر بها أمر من قاضى التنفيذ بتقديره .

مادة 22:

يصدر القاضى حكمًا بإيقاع البيع بناءً على متن من إجراءات وسداد كامل الثمن وما يتبع من شروطه ويجب أن يتضمن منطوق الحكم إلزام شاغلى العقار المبيع عليه ما لم يكن الممول قد سبقت موافقته على شغلهم العقار تطبيقًا لأحكام المادة (7) من هذا القانون أو كانوا مستأجرين بعقود ثابتة تاريخها قبل اتفاق التمويل .

ويجب إيداع نسخة الحكم الأصلية ملف التنفيذ فى اليوم التالى لصدوره .

مادة 23:

لمن يقع عليه البيع أن يسجل هذا الحكم ويترتب على هذا التسجيل تطهير العقار من جميع الحقوق العينية التبعية التى أعلن أصحابها بالسند التنفيذى وبإجراءات البيع طبقًا للمادة (19) من هذا القانون .

مادة 24:

لا يجوز استئناف حكم إيقاع البيع إلا لعيبى الإجراءات أو لبطلان الحكم ومع ذلك يجوز لشاغل العقار استئناف الحكم إذا تضمن إخلاءه ، ويرفع الاستئناف إلى المحكمة الاستئنافية المختصة خلال الخمسة عشر يومًا التالية لتاريخ النطق بالحكم بالنسبة له عدا شاغل العقار فيبدأ الميعاد له من تاريخ إعلانه بالحكم .

مادة 25:

لا يترتب على رفع دعوى الاستحقاق من الغير وقف إجراءات التنفيذ على العقار ما لم تقض المحكمة بغير ذلك .

مادة 26:

يقوم الوكيل العقارى بإيداع حصيلة البيع خزينة المحكمة ويتولى قاضى التنفيذ ما لم يتم الطعن على حكم إيقاع البيع من أحد الأطراف توزيع هذه الحصيلة على الدائنين حسب مراتبهم فى اليوم التالى لفوات مواعيد الطعن أو صدور حكم برفضه وذلك بعد سداد جميع مصاريف التنفيذ وذلك بمحضر يحرر بذلك ويودع بملف التنفيذ .

مادة 27:

تسرى أحكام قانون المرافعات المدنية والتجارية فيما لم يرد بشأنه نص خاص فى هذا الباب .

(الباب الخامس)
شركات التمويل وإعادة التمويل العقارى

مادة 28:

يجب أن تتخذ الشركة شكل شركة مساهمة مصرية ، وألا يقل رأس مالها المصدر والمدفوع منه عن الحد الذى تبينه اللائحة التنفيذية .

واستثناءً من أحكام المادة الأولى من مواد إصدار هذا القانون لا تسرى أحكام القانون رقم 230 لسنة 1996 بتنظيم تملك غير المصريين للعقارات المبنية والأراضى الفضاء على الشركات الخاضعة لأحكام هذا القانون أيًا كانت نسبة رأس المال غير المصرى فيها عدا نص بند (الثانية، الثالثة، الرابعة) من القانون المشار إليه .

ويكون الترخيص بمزاولة أنشطة التمويل وإعادة التمويل العقارى وفقًا لأحكام القانون وما تحدده اللائحة التنفيذية لهذا القانون .

