الرقابة

مادة 37:

للممول أن يشترط على المستثمر التأمين لمصلحة الممول بقيمة حقوقه لدى إحدى شركات التأمين المصرية ضد مخاطر عدم الوفاء بسبب وفاة أو عجز المستثمر .

وتحدد اللائحة التنفيذية قواعد وشروط هذا التأمين .

مادة 38:

لا يجوز لغير الوسطاء المقيدة أسماؤهم فى جدول تعده الجهة الإدارية لهذا الغرض مباشرة أعمال الوساطة بين الممول والمستثمر فى اتفاق التمويل .

وتحدد اللائحة التنفيذية قواعد وشروط وإجراءات القيد فى هذا الجدول .

مادة 39:

تعد الجهة الإدارية نموذجًا بالشروط الأساسية للتمويل العقارى وعلى الممول والوسيط أن يسلم طالب التمويل صورة من هذا النموذج ويجب أن يرفق باتفاق التمويل إقرار من المستثمر بأنه تسلم تلك الصورة واطلع عليها قبل التوقيع على اتفاق التمويل .

مادة 40:

يلتزم الممول بإبلاغ المستثمر مرتين سنويًا على الأقل بجميع البيانات المتعلقة باتفاق التمويل وكذلك عند حدوث أى تعديل فى هذه البيانات وذلك وفقًا لما تحدده الهيئة .

