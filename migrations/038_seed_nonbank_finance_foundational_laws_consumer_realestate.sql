اتفاق التمويل

مادة 6:

يكون التمويل العقارى بموجب إتفاق إتفاقى بين أطراف التمويل وفقًا للنماذج المعتمدة من الهيئة ، ويتضمن هذا الاتفاق على الأخص ما يأتى :

(أ) بيان العقار وثمنه .
(ب) مقدار المبلغ المعجل الذى يتم سداده من ثمن العقار .
(ج) عدد وقيمة أقساط باقى الثمن وشروط الوفاء بها ، على أن تكون محددة أو قابلة للتحديد سلفًا باستخدام معادلة ثابتة مربوطة بأحد المؤشرات الرسمية التى تحددها الهيئة لحساب التغيير فى تكلفة التمويل زيادة أو نقصًا وذلك لحين استيفائها بالكامل .
(د) قبول البائع حوالة حقوقه والضمانات المرتبطة بأقساط الثمن المحالة إلى الممول ، وذلك ضمانًا لوفاء الممول .
(هـ) التزام المستثمر بقيد حق امتياز الثمن المحالة إلى الممول .
(و) إلتزام أطراف الاتفاق باثبات تاريخ إتفاق التمويل وتوثيق إتفاق التمويل بالشهر العقارى بالشكل الرسمى المعمول عليه أو التصديق عليه فى جميع الأحوال ، وتعفى جميع الإجراءات الواردة فى هذه الفقرة من كافة الرسوم والضرائب والمصروفات .

وتحدد اللائحة التنفيذية الشروط والبيانات الأخرى الواجب تضمينها فى اتفاقات التمويل العقارى المنصوص عليها فى هذا القانون طبقًا لطبيعة كل اتفاق .

