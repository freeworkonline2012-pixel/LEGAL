بشأن إصدار قانون التمويل العقاري
(نسخة محدثة وفقاً لآخر تعديل)

المادة الأولى إصدار:

مع عدم الإخلال بأحكام القرار بقانون رقم 15 لسنة 1963 بحظر تملك الأجانب للأراضى الزراعية وما فى حكمها ، والقانون رقم 230 لسنة 1996 بتنظيم تملك غير المصريين للعقارات المبنية والأراضى الفضاء ، يعمل بأحكام القانون التمويل العقارى المرافق ويلغى كل حكم يخالف أحكامه .

المادة الثانية إصدار:

فى تطبيق أحكام القانون المرافق والقرارات الصادرة تنفيذًا له ، يقصد بالكلمات والعبارات التالية المعنى المبين قرين كل منها :

(أ) الوزير المختص: الوزير المختص بتطبيق أحكام قانون تنظيم الرقابة على الأسواق والأدوات المالية غير المصرفية الصادر بالقانون رقم 10 لسنة 2009 .
(ب) الهيئة أو الجهة الإدارية: الهيئة العامة للرقابة المالية .
(ج) التمويل العقارى: التمويل فى أى من الأنشطة المنصوص عليها فى المادة (1) من القانون المرافق أو التى يتم إضافتها بقرار من الوزير المختص بعد موافقة مجلس إدارة الهيئة .
(د) إعادة التمويل العقارى: إعادة تمويل الجهات التى تزاول نشاط التمويل العقارى .
(هـ) الإجارة: تأجير العقارات الذى ينتهى بالتمليك .
(و) الضمان العقارى: العقار المقدم عن التمويل العقارى .
(ز) العقار الضامن: العقار المحل بحق إمتياز أو بالرهن الرسمى أو بغير ذلك من الضمانات .
(ح) المستثمر: المشترى أو من حصل على التمويل فى غير حالة الشراء .
(ط) الشركة: كل شركة تمارس نشاطًا أو أكثر من أنشطة التمويل العقارى المنصوص عليها فى المادة (1) من القانون المرافق .

* معدلة بقرار رئيس جمهورية مصر العربية بالقانون رقم 55 لسنة 2014
[النص قبل التعديل كان يقصد بعبارة الوزير المختص وزير الاقتصاد والتجارة الخارجية ، وبعبارة الجهة الإدارية الهيئة العامة الإدارية المختصة بشئون التمويل العقارى وتتبع وزير الاقتصاد والتجارة الخارجية .]

المادة الثالثة إصدار:

يصدر مجلس الوزراء اللائحة التنفيذية للقانون المرافق فى تاريخ العمل به .

المادة الرابعة إصدار:

ينشر هذا القانون فى الجريدة الرسمية ويعمل به من اعتبار اليوم التالى لمضى ثلاثة أشهر على تاريخ نشره .

يبصم هذا القانون بخاتم الدولة وينفذ كقانون من قوانينها .

