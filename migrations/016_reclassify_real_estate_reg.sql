-- 016_reclassify_real_estate_reg.sql — نقل اللائحة التنفيذية لقانون التمويل
-- العقارى إلى تصنيف "اللوائح التنفيذية" (2026-08-28)
--
-- قرار مجلس الوزراء رقم 1 لسنة 2001 (المُدرج فى migrations/014) بإصدار اللائحة
-- التنفيذية لقانون التمويل العقارى رقم 148 لسنة 2001 كان مُصنَّفاً kind=
-- pm_decision (قرار رئيس مجلس الوزراء) — تصنيف دقيق شكلياً (الأداة نفسها
-- صادرة عن مجلس الوزراء) لكنه غير صحيح وظيفياً: يضع المستند تحت صفحة
-- «القرارات» (DECISION_KINDS تشمل pm_decision) بينما هو فعلياً «لائحة
-- تنفيذية» بحكم موضوعه ومحتواه، ومكانه الصحيح صفحة «اللوائح التنفيذية»
-- (kind=regulation)، والتى كانت بلا أى محتوى مُدخَل حتى الآن (حالة فارغة
-- متعمَّدة موثّقة فى law-kind.ts). طلب صريح من رجل الأعمال لتصحيح التصنيف.

BEGIN;

UPDATE laws
SET kind = 'regulation', updated_at = now()
WHERE law_no = 1 AND law_year = 2001 AND country_code = 'EG';

COMMIT;
