  SELECT count(*) INTO v_version_count FROM article_versions av
    JOIN articles a ON a.id = av.article_id WHERE a.law_id = v_law_id;

  IF v_article_count < 30 THEN
    RAISE WARNING '[060] law 5/2022: بعد الهجرة % مادة فقط (متوقَّع 30) — راجع يدوياً.', v_article_count;
  ELSE
    RAISE NOTICE '[060] law 5/2022: % مادة و% نسخة بعد الهجرة.', v_article_count, v_version_count;
  END IF;

  UPDATE laws SET governance_scope = true, enacted_at = COALESCE(enacted_at, '2022-02-08')
  WHERE id = v_law_id;

  SELECT count(*) INTO v_scope_count FROM laws WHERE governance_scope = true;
  RAISE NOTICE '[060] law 5/2022: governance_scope=true مؤكَّد. إجمالى governance_scope=true الآن: %.', v_scope_count;
END;
