الأصول الافتراضية: هى التمثيل الرقمى للقيمة المالية التى يمكن تداولها أو تحويلها رقمياً، ويمكن استخدامها لأغراض الدفع أو الاستثمار، بما لا يشمل التمثيل الرقمى للعملات الورقية والأوراق المالية وغيرها من الأصول المالية.

