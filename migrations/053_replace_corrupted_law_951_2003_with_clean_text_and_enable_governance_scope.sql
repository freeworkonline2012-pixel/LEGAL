وحدة مكافحة غسل الأموال وتمويل الإرهاب: وتراقب المؤسسات المالية والأعمال غير المالية وأصحاب المهن غير الخاضعين لرقابة السلطات الرقابية المشار إليها فى هذه المادة.

السلطات الرقابية: تراقب المؤسسات المالية أو الأعمال غير المالية وأصحاب المهن التى يصدر بتحديدها قرار من رئيس مجلس الوزراء يحددها ويحدد التزاماتها.

جهات إنفاذ القانون: هى الجهات التى يدخل ضمن اختصاصها القيام بأعمال المكافحة والتحرى وجمع الاستدلالات فى جميع الجرائم بما فيها جرائم غسل الأموال وجرائم تمويل الإرهاب والجرائم الأصلية.

تجميد الأموال: الحظر المؤقت الذى يفرض على نقل الأموال أو الأصول أو تبديلها أو تحريكها أو التصرف فيها أو تحويلها.

المعنيون بالتنفيذ: السلطات الرقابية والمؤسسات المالية والأعمال غير المالية وأصحاب المهن، ومصلحة السجل التجارى، ومصلحة الشهر العقارى والتوثيق، ومصلحة الجمارك، والإدارة العامة للمرور بوزارة الداخلية، وأى شخص طبيعى أو اعتبارى قد يوفر خدمات مالية أو غير مالية لأشخاص أو كيانات مدرجة على قوائم مجلس الأمن أو قائمتى الكيانات الإرهابية والإرهابيين المحلية أو يمكن أن تكون بحوزته أموال أو أصول أخرى ذات صلة بالأشخاص والكيانات المدرجة على هذه القوائم، دون تأخير، فوراً وفى غضون ساعات من صدور القرار بتحديث قوائم مجلس الأمن أو إدراجها ونشره على الموقع الإلكترونى لمجلس الأمن، أو نشر القرار بتحديث قائمتى الكيانات الإرهابية والإرهابيين المحلية بالجريدة الرسمية أو التعديل.

الجهات المعنية بمكافحة غسل الأموال والجرائم الأصلية المرتبطة بها أو تمويل الإرهاب: هى كافة الجهات التى تتمتع بمسئوليات محددة لمكافحة غسل الأموال أو تمويل الإرهاب، وما يرتبط بها من جرائم أصلية، ويشمل ذلك الوحدة والسلطات المنوط بها التحرى والتحقيق فى ملاحقة جرائم غسل الأموال والجرائم الأصلية المرتبطة بها وجرائم تمويل الإرهاب، وحجز الأصول الإجرامية وتجميدها ومصادرتها، والسلطات القضائية والجمركية، والجهات المعنية بإنشاء الأشخاص الاعتبارية، وغيرها من جهات الرقابة فى الدولة.

العميل الذى لا تربطه علاقة دائمة: العميل الذى لا تربطه علاقة دائمة مع المؤسسة المالية أو الأعمال غير المالية وأصحاب المهن من أى مؤسسة مالية يطلب تنفيذ عملية ما، دون أن يكون لديه إقامة دائمة أو علاقة عمل مستمرة، وتعد العملية المطلوب تنفيذها من العميل عملية عارضة.

اللجنة الوطنية التنسيقية: اللجنة الوطنية التنسيقية فى مجال مكافحة غسل الأموال وتمويل الإرهاب المنشأة بقرار رئيس مجلس الوزراء رقم 63 لسنة 2005 أو أية جهة أخرى تقوم بدلاً عنها.

