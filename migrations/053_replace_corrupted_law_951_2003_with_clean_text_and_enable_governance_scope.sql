6- الجهات التى تمارس نشاطها وفقاً لأحكام قانون صناديق التأمين الخاصة الصادر بالقانون رقم 54 لسنة 1975.
7- الجهات التى تمارس نشاطها وفقاً لأحكام قانون الإشراف والرقابة على التأمين فى مصر الصادر بالقانون رقم 10 لسنة 1981 ولائحته التنفيذية.
8- الجهات التى تمارس نشاطها وفقاً لأحكام قانون سوق رأس المال الصادر بالقانون رقم 95 لسنة 1992 ولائحته التنفيذية.
9- الجهات التى تمارس نشاطها وفقاً لأحكام قانون الإيداع والقيد المركزى للأوراق والأدوات المالية الصادر بالقانون رقم 93 لسنة 2000 ولائحته التنفيذية.
10- الجهات التى تمارس نشاطها وفقاً لأحكام قانون التمويل العقارى الصادر بالقانون رقم 148 لسنة 2001.
11- الجهات التى تمارس نشاط تمويل المشروعات المتوسطة والصغيرة ومتناهية الصغر وفقاً لأحكام القانون رقم 141 لسنة 2014.
