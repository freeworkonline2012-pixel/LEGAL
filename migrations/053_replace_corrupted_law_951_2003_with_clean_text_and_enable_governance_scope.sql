1- التبادل بين الأصول الافتراضية والعملات الرسمية بكافة صورها.
2- التبادل بين نوع أو عدة أنواع من الأصول الافتراضية.
3- تحويل الأصول الافتراضية.
4- حفظ و/أو إدارة الأصول الافتراضية أو الأدوات التى تمكن من التحكم فى الأصول الافتراضية.
