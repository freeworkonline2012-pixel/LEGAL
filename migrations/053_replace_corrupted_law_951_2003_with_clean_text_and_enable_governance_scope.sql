-- ===== خطأ حرج اكتُشِف وأُصلِح أثناء الاختبار المحلى (قبل أى تنفيذ فعلى) =====
-- الصياغة الأولى لهذه الهجرة استخدمت نمطاً لتفادى تكرار متن كل مادة مرتين
-- (مرة فى articles ومرة فى article_versions): `WITH insX AS (INSERT INTO
