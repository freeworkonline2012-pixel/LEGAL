-- articles.id, ..., articles.body FROM articles, insX WHERE articles.id =
-- insX.id;`. عند التشغيل الفعلى المحلى تبيَّن أن هذا النمط **يُدرِج صفراً من
-- الصفوف فى article_versions** لكل مادة عدا الماديتين الإصداريتين (اللتين
-- كانتا تقرآن من الـCTE مباشرة). السبب الجذرى: فى PostgreSQL، الاستعلامات
-- الفرعية العادية (table scan) داخل نفس العبارة (statement) التى تحوى CTE
-- مُعدِّل للبيانات (data-modifying CTE) لا "ترى" الصفوف التى أدرجها ذلك الـCTE
-- — لأن كل أجزاء العبارة تستخدم نفس اللقطة (snapshot) الزمنية لبداية العبارة.
-- أى إعادة قراءة لجدول articles ضمن نفس العبارة لا يجد الصف المُدرَج للتو.
-- **الإصلاح الجذرى المُطبَّق**: تغيير `RETURNING id` إلى `RETURNING id, body`
-- فى كل CTE، وقراءة body مباشرة من مخرجات الـCTE نفسه (`FROM insX` بدلاً من
-- `FROM articles, insX WHERE articles.id = insX.id`) — هذا لا يصطدم بقيد
-- اللقطة لأنه لا يُعيد قراءة الجدول، بل يقرأ فقط ما أرجعته RETURNING. أُعيد
-- الاختبار المحلى الكامل (3 تشغيلات متتالية) بعد الإصلاح وتأكَّد أن
-- article_versions يحوى بالضبط 100 صفاً (99 نشط + 1 ملغاة) مطابقاً لعدد
-- articles، بلا أى فجوة أو تكرار. لولا هذا الاختبار المحلى قبل الدفع، كانت
