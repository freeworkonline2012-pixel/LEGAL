جهات الرقابة: هى الجهات المختصة بالرقابة على المؤسسات المالية والأعمال غير المالية وأصحاب المهن وفقاً لنص الفقرتين الأولى والثانية من المادة (7) من القانون، وتتمثل فيما يلى:
وزارة الاتصالات والمعلومات، وتراقب الهيئة القومية للبريد فيما تقدمه من خدمات مالية فيما عدا نظم الدفع وخدمات الدفع التى تختص بالإشراف عليها البنك المركزى.
البنك المركزى المصرى، ويراقب البنوك العاملة فى مصر وفروعها فى الخارج وفروع البنوك الأجنبية العاملة فى مصر، وشركات الصرافة والجهات الأخرى المرخص لها بالتعامل فى النقد الأجنبى، وما رخصت له هذه الجهات الأخرى على سبيل الاحتراف - لصالح عميل أو نيابة عنه - من نشاط أو أكثر من الأنشطة المالية للمؤسسات المالية، ومشغلى نظم الدفع ومقدمى خدمات الدفع الواردة بهذه المادة.
الهيئة العامة للرقابة المالية، وتراقب المؤسسات المالية التى تمارس أنشطة التأمين أو إعادة التأمين وصناديق التأمين الخاصة وأعمال الوساطة فى التأمين، والمؤسسات المالية التى تمارس أياً من أنشطة سوق رأس المال أو التمويل العقارى، والمؤسسات المالية العاملة فى مجال تلقى الأموال بغرض استثمارها، والجهات التى تمارس نشاطها وفقاً لقانون الإيداع والقيد المركزى للأوراق والأدوات المالية، والمؤسسات المالية التى تمارس أياً من أنشطة التأجير التمويلى والتخصيم، والمؤسسات المالية التى تمارس نشاط التمويل الاستهلاكى ومتناهى الصغر.
وزارة التجارة والصناعة المختصة بالإشراف على سماسرة العقارات، وتراقب سماسرة العقارات الوارد ذكرهم بهذه المادة.
