14- أية جهة أخرى تمارس على سبيل الاحتراف - لصالح عميل أو نيابة عنه - نشاطاً أو أكثر من الأنشطة المرخص بها للمؤسسات المالية، يصدر بتحديدها قرار من رئيس مجلس الوزراء.

الأعمال والمهن غير المالية: أصحاب المهن:
1- سماسرة العقارات، عند تنفيذهم عمليات لصالح عملائهم بشراء أو بيع عقارات.
2- تجار المعادن النفيسة وتجار الأحجار الكريمة، عند تنفيذهم لعملائهم أية عمليات نقدية تساوى أو تجاوز خمسة عشر ألف دولار أمريكى أو ما يعادلها بالجنيه المصرى أو بعملة أجنبية أخرى، ويشمل ذلك العمليات المرتبطة التى يساوى أو يجاوز إجماليها الحد المذكور.
3- المحامون والمحاسبون، سواء كانوا يزاولون المهنة بشكل منفرد أو كشركاء أو مهنيين فى شركة تمارس هذه المهنة، عند قيامهم بإعداد أو تنفيذ عمليات لصالح عملائهم تتعلق بالأنشطة الآتية:
(أ) شراء وبيع العقارات.
(ب) إدارة الأموال والأوراق المالية أو غيرها من الأصول.
(ج) إدارة الحسابات المصرفية أو حسابات التوفير أو حسابات الأوراق المالية.
(د) تنظيم المساهمات بغرض إنشاء أو تشغيل أو إدارة الشركات.
(ه) إنشاء الشخصيات الاعتبارية أو الترتيبات القانونية أو تشغيلها أو إدارتها، وشراء أو بيع الكيانات التجارية.
4- أندية القمار، بما فى ذلك التى تباشر أنشطتها من خلال شبكة الإنترنت وعلى متن السفن، عند قيام عملائها بعمليات مالية تساوى أو تجاوز ثلاثة آلاف دولار أمريكى أو ما يعادلها بالجنيه المصرى أو بعملة أجنبية أخرى، ويشمل ذلك العمليات المرتبطة التى يساوى أو تجاوز إجماليها ذلك الحد المذكور.
5- مقدمو خدمات الشركات والصناديق الاستئمانية، وذلك عند قيامهم، على سبيل الاحتراف، بتقديم أى من الخدمات التالية لعملائهم:
(أ) العمل بصفة مؤسس أو وكيل مؤسس للأشخاص الاعتبارية.
(ب) العمل أو الترتيب لشخص آخر ليكون بصفة مدير مفوض أو عضو مجلس إدارة أو شريك فى شركة أو موقع مشابه يتعلق بأشخاص اعتبارية أخرى.
(ج) توفير مكتب مسجل أو عنوان بريد أو عنوان مراسلة أو عنوان إدارى لأى شركات أو لأى شخص معنوى أو لأى ترتيب قانونى.
(د) التصرف أو الترتيب لشخص آخر ليتصرف كوصى لصندوق استئمانى صريح أو لأى ترتيب قانونى آخر مماثل.
6- المهن والأعمال الأخرى التى يصدر بتحديدها وبالتزاماتها وبالجهات التى تتولى الرقابة عليها قرار من رئيس مجلس الوزراء.

