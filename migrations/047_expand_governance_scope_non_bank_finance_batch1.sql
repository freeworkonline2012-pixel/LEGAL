-- كان نطاق non_bank_finance = 1 (101/2020 فقط). يصبح 8 (+7). إجمالى
-- governance_scope الكلى كان 25 (بعد 045/046)، يصبح 32.
--
-- التحقق: قابلة لإعادة التشغيل بأمان (idempotent).

BEGIN;

UPDATE laws SET governance_scope = true
WHERE country_code = 'EG'
  AND category = 'non_bank_finance'
  AND (law_no, law_year) IN ((1, 2001), (5, 2022), (18, 2020), (141, 2014), (148, 2001), (176, 2018), (177, 2024))
  AND governance_scope IS DISTINCT FROM true;

DO $verify$
DECLARE
  v_count int;
  v_expected int := 32;
  v_nbf_count int;
  v_nbf_expected int := 8;
BEGIN
  SELECT count(*) INTO v_count FROM laws WHERE governance_scope = true;
  SELECT count(*) INTO v_nbf_count FROM laws WHERE governance_scope = true AND category = 'non_bank_finance';
  IF v_count <> v_expected OR v_nbf_count <> v_nbf_expected THEN
    RAISE WARNING 'governance_scope: % قانوناً موسوماً (منها % من non_bank_finance)، المتوقَّع % (منها %) — تحقّق يدوياً', v_count, v_nbf_count, v_expected, v_nbf_expected;
  ELSE
    RAISE NOTICE 'governance_scope: % قانوناً موسوماً كما هو متوقَّع (منها % من non_bank_finance — اكتملت مراجعة الفئة: 8 من 19+1 مُدرَجة)', v_count, v_nbf_count;
  END IF;
END;
$verify$;

COMMIT;
