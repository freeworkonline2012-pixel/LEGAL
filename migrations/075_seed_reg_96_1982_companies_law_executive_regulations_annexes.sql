ثانياً. أحكام خاصة بالأسهم العينية:
في حالة إصدار أسهم عينية سواء عند التأسيس أو عند زيادة رأس المال فيجب أن تتضمن نشرة الاكتتاب ما يلي:
1- ملخص الموجودات المالية والمعنوية المقدمة في مقابل الأسهم العينية، وأسماء مقدميها وشروط تقديمها، مع ذكر ما إذا كانوا من المؤسسين أو أعضاء مجلس الإدارة، وملخص لإفادة مدى هذه الموجودات من ملكية مقدميها لكل نوع منها أصلاً.
2- جميع عقود المعاوضة التي وردت على العقارات المقدمة للشركة خلال السنوات الخمس السابقة على تقديمها، وملخص أهم الشروط التي تمت على أساسها هذه العقود وما كانت تغله تلك العقارات من ريع في هذه المدة.
3- جميع حقوق الرهن والامتياز المترتبة على الحصص العينية غير النقدية.
4- الشروط التي يعلق عليها استيفاء الحصص العينية نقداً عند التخيير في ذلك.
5- تاريخ صدور قرار اللجنة التي تشكلها الهيئة العامة للاستثمار للتحقق من أن تقدير الحصص العينية والمناطق الحرة للاستثمار صحيح، وملخص عن تعليقات اللجنة الوافي على الموجودات والقيمة التي قدرتها لكل منها.
6- عدد الأسهم المسددة القيمة المصدرة في مقابل هذه الأسهم العينية حسب تقدير الخبراء.

ثالثاً. أحكام خاصة بزيادة رأس المال:
عند إصدار أسهم لزيادة رأس المال فيجب أن تتضمن نشرة الاكتتاب ما يلي:
1- الإشارة إلى اجتماع الجمعية العامة غير العادية أو مجلس الإدارة التي قررت الزيادة، ومواد القانون النظامي التي استند إليها، وتقرير أن الأسهم الأصلية سددت بالكامل، أو أن الإصدار الجديد مستثنى بالكامل من هذا الشرط، مع إيضاح وجه هذا الاستثناء.
2- مقدار الزيادة، وعدد الأسهم وعلاوة الإصدار وأسبابها، وإذا كانت الأسهم ذات فئات مختلفة فيلزم بيان واف عن خصائص كل نوع، والحقوق المتعلقة بها، سواء بالنسبة لتوزيع الأرباح أو عند التصفية.
3- إذا كان جزء من الزيادة في مقابل أسهم عينية فتتضمن نشرة الاكتتاب الأحكام المبينة في الفقرة "ثانياً".
4- ملخص كاف عن المركز المالي للشركة، وبيان مفصل بالأسباب التي دعت إلى زيادة رأس المال ومدى إفادة الشركة من توقع إفادة هذه الزيادة.

