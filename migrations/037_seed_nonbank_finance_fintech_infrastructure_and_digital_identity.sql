المنصة الرقمية: نموذج أعمال قائم على استخدام الوسائل التكنولوجية فى مزاولة الأنشطة المالية غير المصرفية، وفى عرض المنتجات والخدمات المرتبطة بها على الأشخاص الراغبين فى الحصول عليها، ويسمح بتبادل البيانات والمعلومات اللازمة لإتمام هذه التعاملات.

الهوية الرقمية: أى بيانات معالجة تقنيًا تتعلق بشخص طبيعى أو اعتبارى محدد يمكن تحديده بشكل مباشر أو غير مباشر عن طريق الربط بين هذه البيانات وأى بيانات أخرى كالاسم، أو الصورة، أو الصوت، أو رقم تعريفى، أو محدد للهوية عبر شبكة الاتصالات العالمية (الإنترنت)، على أن تسمح هذه البيانات بالتقييم والمصادقة على المعاملات التى تتم من خلال المنصات الرقمية والمرتبطة بالأنشطة المالية غير المصرفية.

العقد الرقمى: أى عقـد يتضمن حقـوق والتزامات المتعـاقدين بشكل رقمى، ويمكن تسجيله فى سجل رقمى، كما يجوز أن يكون العقد الرقمى "عقـدًا ذكـيًا" من خلال برنامج يهدف إلى تنفيذ أحكام العقد والتحكم فيها أو توثيقها تلقائيًا.

المعاملة الرقمية: أى معاملة رقمية تتم بين متعامل له هوية رقمية محددة وبين مقدم الخدمة من خلال منصته الرقمية.

السجل الرقمى: سجل إلكترونى يتضمن البيانات المتعلقة بالمعاملات التى يجريها المتعاملين من خلال المنصة الرقمية والتى تتم وفقًا لأحكام القانون، بما يسمح بتتبع هذه البيانات من خلال شبكة آمنة.

الكتابة الإلكترونية: كل حروف أو أرقام أو رموز أو أى علامات أخرى تثبت على دعامة إلكترونية أو ضوئية أو رقمية أو أى وسيلة أخرى مشابهة وتعطى دلالة قابلة للإدراك.

المحرر الإلكترونى: رسالة بيانات تتضمن معلومات تُنشأ أو تُدمج أو تُخزن، أو تُرسل، أو تُستقبل، كليًا، أو جزئيًا، بوسيلة إلكترونية، أو رقمية، أو ضوئية، أو بأى وسيلة أخرى مشابهة.

التوقيع الإلكترونى: ما يوضع على محرر إلكترونى ويتخذ شكل حروف، أو أرقام، أو رموز، أو إشارات، أو غيرها، ويكون له طابع منفرد يسمح بتحديد شخص الموقع ويميزه عن غيره.

عمليات التعرف على العميل إلكترونيًا: عمليات التعرف على المعلومات الأساسية ومتطلبات العميل واحتياجاته لتحليل وتحديد مدى ملاءمة المنتجات والخدمات المالية غير المصرفية المطروحة، ويكون ذلك بغرض إنشاء حساب عميل رقمى يمكنه من استعراض وطلب خدمات ومنتجات مالية غير مصرفية من خلال المنصات الرقمية.

عمليات التعاقد مع العميل إلكترونيًا: عمليات التعاقد على منتج مالى غير مصرفى بغرض إنشاء حساب رقمى للمنتج المالى غير المصرفى المرتبط بحساب العميل الرقمى وتتضمن تسجيل بيانات العقد الرقمى فى سجلات رقمية للحفظ من خلال المنصات الرقمية.

الجهات المخاطبة:

1- الشركات الراغبة فى الحصول على تراخيص لمزاولة الأنشطة المالية غير المصرفية من خلال تقنيات التكنولوجيا المالية تحت مظلة القانون رقم 5 لسنة 2022 .

2- الشركات والجهات الحاصلة على ترخيص من مزاولة الأنشطة المالية غير المصرفية بمزاولة أى من الأنشطة المالية غير المصرفية تحت مظلة أى من قوانين أخرى، والراغبة فى الحصول على موافقة الهيئة لتباشر هذه الأنشطة باستخدام بعض مجالات التكنولوجيا المالية بنفسها، أو من خلال إحدى جهات التعهيد تحت مظلة القانون رقم 5 لسنة 2022 .

3- الشركات الراغبة فى تقديم خدمات التعهيد فى مجالات التكنولوجيا المالية التى يمكن استخدامها فى مزاولة الأنشطة المالية غير المصرفية تحت مظلة القانون رقم 5 لسنة 2022 .

ثانياً - ضوابط الهوية الرقمية

1- يتم ضبط الهوية الرقمية من خلال ثلاث عمليات فرعية وهى التحديد والتحقق والمصادقة .

2- يتم إنشاء الهوية الرقمية أو تجديدها من خلال استيفاء عمليات التحديد والتحقق والمصادقة على الهوية المادية، ولتمكين المتعامل من الدخول على المنصة الرقمية يتم استيفاء عمليات التحديد والتحقق والمصادقة على الهوية الرقمية.

3- يجب أن تعتمد العمليات الفرعية على أكثر من مجموعة نوعية من عوامل التحديد والتحقق والمصادقة.

4- تنقسم المجموعات النوعية إلى ثلاث مجموعات، وهى :

(أ) مجموعة عامل المعرفة: وتشمل عدة عناصر منها اسم المستخدم، وكلمة مرور، وإجابات على أسئلة شخصية.

(ب) مجموعة عامل الحيازة: وتشمل عدة عناصر منها إثبات الشخصية، وصندوق البريد الإلكترونى، ورقم التليفون المحمول أو رقم الشريحة المرتبطين برقم التليفون المحمول، وحساب دفع غير نقدى إلكترونى معتمد.

(ج) مجموعة عامل الوجود والحيوية: وتشمل عدة عناصر منها الخصائص البيومترية لبصمة الوجه، ولبصمة الصوت، ولبصمة الأصابع، ولهندسة الكف، ولبصمة العين، وحيوية رد الفعل، ومحددات الموقع الجغرافى، ومحددات الموقع السيبرانى، ومحددات وقت المعاملة.

(د) فى تطبيق أحكام البندين السابقين يجب على مُقدم الخدمة استيفاء المتطلبات الواردة بالملحق رقم (1) .

(ه) فى عمليات التحديد والتحقق والمصادقة بغرض إنشاء هوية رقمية أو عند التجديد، يجب أن يتم الآتى :

(أ) استخدام أربعة عناصر من مجموعة عامل الحيازة على الأقل على أن يكون بينهم مستند إثبات الشخصية، وصندوق البريد الإلكترونى، ورقم التليفون المحمول، ورقم الجهاز المستخدم، بالإضافة إلى ثلاثة عناصر من مجموعة عامل الوجود والحيوية على الأقل أن يكون بينهم الخصائص البيومترية لبصمة الوجه، وحيوية رد الفعل، ومحددات الموقع الجغرافى.

(ب) تحديد الموقع السيبرانى ووقت المعاملة.

(ج) إنشاء أو تحديث ثلاثة عناصر من مجموعة عامل المعرفة وهم اسم المستخدم، وكلمة المرور، وإجابات على الأسئلة الشخصية.

(د) الربط الإلكترونى مع أى أنظمة تعدها الهيئة أو تقررها تنفيذًا لأحكام القانون رقم 5 لسنة 2022 بشأن تنظيم وتنمية استخدام التكنولوجيا المالية فى الأنشطة المالية غير المصرفية.

5- فى عمليات التحديد والتحقق والمصادقة اللاحقة لإنشاء أو تجديد الهوية الرقمية، يجب أن يتم الآتى:

(أ) استخدام عنصرين من عناصر مجموعة عامل المعرفة وهما اسم المستخدم، وكلمة المرور، بالإضافة إلى عنصر على الأقل من عناصر عامل الحيازة من بين رقم الجهاز المستخدم، أو رقم التليفون المحمول، أو صندوق البريد الإلكترونى، بالإضافة إلى عنصر على الأقل من عامل الوجود والحيوية من أحد الخصائص البيومترية، أو حيوية رد الفعل، أو محددات الموقع الجغرافى.

(ب) تحديد الموقع السيبرانى ووقت المعاملة.

(ج) مراجعة التغيرات على أى من العناصر من خلال السجل الإلكترونى، واتخاذ الإجراءات المناسبة والتى تتضمن الربط الإلكترونى مع أى أنظمة تعدها الهيئة أو تقررها تنفيذًا لأحكام القانون رقم 5 لسنة 2022 بشأن تنظيم وتنمية استخدام التكنولوجيا المالية فى الأنشطة المالية غير المصرفية.

6- للهوية الرقمية ثلاث درجات من الثقة وهى :

(أ) درجة الثقة الأساسية والمتضمنة بحد أدنى عنصرين من مجموعة عامل المعرفة، بالإضافة إلى عنصر واحد من عناصر مجموعة عامل الحيازة، بالإضافة إلى أربعة عناصر من مجموعة عامل الوجود والحيوية، وتكون تلك الدرجة مطلوبة فى العمليات ذات المخاطر المنخفضة.

(ب) درجة الثقة العامة والمتضمنة بحد أدنى العوامل المطلوبة فى درجة الثقة الأساسية بالإضافة إلى حيازة حساب دفع غير نقدى، وتكون تلك الدرجة مطلوبة فى العمليات ذات المخاطر المتوسطة.

(ج) درجة الثقة المرتفعة والمتضمنة بحد أدنى العوامل المطلوبة فى درجة الثقة العامة بالإضافة إلى حيازة توقيع إلكترونى معتمد، وتكون تلك الدرجة مطلوبة فى العمليات ذات المخاطر المرتفعة.

ويحدد مقدمو الخدمات نوع العملية من حيث الخطورة وفقًا لما تقرره الهيئة فى هذا الشأن.

ثالثاً - ضوابط العقود الرقمية

1- يلتزم مُقدم الخدمة بالتحقق من هوية المتعامل، ورضائه، كما يلتزم بحفظ العقد الإلكترونى، وفقًا للمتطلبات الآتية :

(أ) التحقق من هوية المُتعامل :

يتم التحقق من هوية المُتعامل من خلال ضوابط ذات ضوابط الهوية الرقمية المشترطة للدخول على المنصة الرقمية، والواردة فى البند ثانيًا من هذه القواعد.

(ب) التحقق من رضاء المتعامل:

يجب على مقدم الخدمة بالقدر اللازم، التحقق من رضاء المتعامل، والذى يستلزم توافر عناصر الأهلية والإرادة، وأحكام الإيجاب والقبول، وبخاصة إثبات اطلاع المُتعامل على كافة شروط العقد، مع عدم الإخلال بالطبيعة الخاصة للعقود الرقمية.

(ج) الحفظ الإلكترونى للعقد:

يتعين بعد إبرام العقد حفظه بكافة المراحل السابقة على إبرامه وتوقيتاتها فى السجل الرقمى باستخدام تقنية التشفير المناسبة التى توافق عليها الهيئة.

2- فى حالة التعاقدات الرقمية المرتبطة بتنفيذ معاملات ذات درجة المخاطر المنخفضة أو المتوسطة والتى تحددها الشركة وفقًا لما تقرره الهيئة، يتم استخدام تقنية التشفير المناسبة مع تضمين بيانات حساب الدفع الإلكترونى التى تم التحقق من حيازتها من قبل المتعاقد، ويتضمن العقد الرقمى فى هذه الحالة موافقة المتعاقد على استخدام الحساب لإتمام المعاملات المرتبطة بالتدفقات النقدية المتفق عليها من خلال مقدمى خدمات الدفع الالكترونى المعتمدين من البنك المركزى.

3- فى حالة التعاقدات الرقمية المرتبطة بتنفيذ معاملات ذات درجة المخاطر المرتفعة والتى تحددها الشركة وفقًا لما تقرره الهيئة، يُستخدم تقنية التوقيع الإلكترونى المقرون بشفرة المفتاحين العام والخاص (المعروفة باسم تقنية شفرة المفتاح العام) من أحد مقدمى خدمات التصديق على التوقيع الإلكترونى المصرح لهم من هيئة تنمية صناعة تكنولوجيا المعلومات، وتحدد الهيئة قيمة المعاملات الإلكترونية التى لا تتطلب التوقيع الإلكترونى المقرون بشفرة المفتاحين العام والخاص.

رابعاً - السجل الرقمي

1- يكون لكل منصة رقمية سجل رقمى، والذى يكون قابل للتجزئة لسجلات رقمية فرعية يكون كل منها مخصص لنوع واحد من العمليات والمعاملات المرتبطة بخدمة المنصة الرقمية، وعلى سبيل المثال:

(أ) "السجل الرقمى" لعمليات "الهوية الرقمية" والمتضمن معاملات إنشاء وتحديث وتجديد وإلغاء هوية رقمية.

(ب) "السجل الرقمى" لعمليات "التعرف على العميل" والمتضمن معاملات إنشاء وتحديث وتعديل وإلغاء حساب عميل رقمى.

(ج) "السجل الرقمى" لعمليات "التعاقد الالكترونى" والمتضمن معاملات إنشاء وتحديث وتعديل وإلغاء حساب مالى غير مصرفى منتج رقمى.

(د) "السجل الرقمى" لعمليات "المعاملات المرتبطة بالمنتج المالى غير المصرفى" والمتضمن معاملات إنشاء وتحديث وتعديل وإلغاء معاملة على حساب منتج مالى غير مصرفى، وتكون مرتبطة بطبيعته.

2- يكون "السجل الرقمى" قابل لحفظ واسترجاع الآتى:

(أ) بيانات وتفاصيل المعاملة وتسجيل الأحداث المرتبطة بالعمليات المختلفة مع بيان أطرافها وتوقيتاتها ومضمونها كلما تغيرت الحالة للأصل الرقمى.

(ب) المستندات الرقمية المرتبطة كمدخل أو مرفق أو مخرج للمعاملة.

3- يتم استخدام تقنية التشفير المناسبة التى توافق عليها الهيئة لضمان سرية محتويات السجل الرقمى واستخدام آليات لضمان عدم تعديل المحتوى بعد تسجيله وتخزينه.

4- يتم توفير وسائل تخزين ذات سعة تخزينية مناسبة للاحتفاظ بالسجلات والمستندات الرقمية وأرشفتها لمدة خمس سنوات على الأقل من بعد انتهاء صلاحية الأصل الرقمى موضوع التسجيل، بعد إخطار الجهات المالكة والمستفيدة من الأصل، ما لم يكن هناك دعوى قضائية أو تحكيمية يخطر بها مقدم الخدمة، فيتم الاحتفاظ لحين الفصل فى النزاع، ويجوز حفظ وأرشفة السجلات والمستندات بعد هذه المدة فى وسائل تخزين خارج البيئة التشغيلية الحية، أو التخلص منها بعد الحصول على الموافقة المسبقة على الهيئة.

5- يتم استخدام نظم إدارة قواعد بيانات وملفات مناسبة مع التأكد من توفيرها درجات الاعتمادية القصوى، والتأكد من تطبيق آليات إدارة حالات فشل التسجيل المناسبة، والتأكد من تطبيق آليات مناسبة لاستمرارية الأعمال والتعافى من الكوارث.

6- يتم التأكد من وجود آليات للتحقق والبحث والتلخيص وإصدار التقارير عن محتوى السجلات دون المساس بمتطلبات التأمين والحماية، مع وجود آليات التسجيل عمليات التحقق والبحث مع بيان توقيتاتها دون المساس بتوقيتات الأحداث الأصلية.

7- يتم الالتزام بنموذج تنسيق واسع النطاق للتسجيل المستخدم على النظام وهو "سجل النظام"، المحدد فى (RFC 5424) الصادر من "مجموعة عمل هندسة الإنترنت" (IETF)، ويجوز استخدام نموذج تنسيق بديل بعد الحصول على موافقة الهيئة.

8- فى جميع الأحوال يجب أن يتضمن السجل الرقمى الخصائص التى تمكن من التحليل الجنائى الرقمى للأحداث من خلال سلسلة منهجية من الأساليب والإجراءات الخاصة بجمع الأدلة، من مكونات البنية التكنولوجية والمتضمنة أجهزة الحاسبات ووسائل التخزين وأنظمة إدارة قواعد البيانات وأنظمة التشغيل وأنظمة التحكم فى السماح بالدخول، ومن مكونات نظم المعلومات والمطبقات والقواعد البيانات المرتبطة بالمكونات المختلفة فى متناول أصحاب صلاحية التعامل على السجل، والذين يشملوا على سبيل المثال مسئول النظام، والمحقق الجنائى، والمطور.

9- فى حال الاعتماد على نماذج عمل الحوسبة الحسابية العامة أو الخاصة والتى تقدم خدمات متنوعة على نفس البيئة التكنولوجية المشتركة لأكثر من عميل، يجب الحصول على موافقة الهيئة، والتأكد من الفصل التام بين البيئة الافتراضية لكل عميل.

10- يجب أن يتضمن السجل الرقمى إثبات وتوثيق التسلسل على الحيازة فى المخرجات من السجل الرقمى باستخدام تقنيات التشفير أو أى تكنولوجيا أخرى توافق عليها الهيئة وبما يحافظ على:

(أ) خصوصية البيانات.

(ب) عدم التعديل بالحذف أو بالإضافة أو بالتغيير (من مسئول المنصة الرقمية أو من مستخدم المنصة الرقمية أو من المحقق الجنائي أو من أى طرف خارجى).

(ج) ما يمنع إنكار محتوى السجل من مسئول المنصة الرقمية.

(د) ما يمنع إنكار محتوى السجل من مستخدم المنصة الرقمية.

11- تعتبر عمليات التسجيل الإلكترونى والتوقيع الإلكترونى وإنفاذ شروط العقد الذكية المؤمنة من خلال تقنية "سلسلة الكتل" (BLOCK CHAIN)، أو تقنية مجموعة القيود الموزعة المسموح بها الأعمال من نماذج بها فى مزاولة الأنشطة المالية غير المصرفية المبنية على الهوية الرقمية، والعقود الرقمية، والسجلات الرقمية، ويكون العقد الذكى الذى فى هذه الحالة برنامج يتبع الحالة التعاقدية والتى تتغير بوقوع أحداث متفق عليها مسبقًا، وقد يعمل من خلال تقنية "سلسلة الكتل".

12- يجوز تطبيق السجل الرقمى على تقنيات مركزية أو موزعة وفقًا للمتطلبات الواردة بالملحق رقم (2) .

13- تحوز البيانات سابق الإشارة إليها حجية المحررات الرسمية فى الإثبات، من تاريخ حفظها فى السجل الرقمى.

خامساً - مجالات استخدام التكنولوجيا المالية لمزاولة الأنشطة المالية غير المصرفية

1- تُحدد الهيئة المجالات الأساسية اللازمة لاستخدام التكنولوجيا المالية فى مزاولة الأنشطة المالية غير المصرفية التى تلتزم بها الجهات المخاطبة بأحكام هذا القرار، ومنها:

(أ) مجال عمليات التحديد والتحقق والمصادقة إلكترونيًا.

(ب) مجال عمليات التعرف على العميل إلكترونيًا.

(ج) مجال عمليات إبرام عقود على منتجات مالية غير مصرفية إلكترونيًا.

(د) مجال عمليات التسجيل والحفظ والاسترجاع من السجلات الرقمية إلكترونيًا.

2- تُحدد الهيئة المجالات الأخرى التى يجوز فيها استخدام التكنولوجيا المالية فى مزاولة الأنشطة المالية غير المصرفية.

سادساً - متطلبات الامتثال

يجب إعداد تقرير نصف سنوى بشأن "نتائج أعمال المراجعة ونسب الخطأ"، أخذًا فى الاعتبار طبيعة وحجم النشاط الذى يزاوله مقدم الخدمة، ويجب موافاة الهيئة بهذا التقرير معتمدًا من مجلس إدارة مقدم الخدمة خلال أربعة أسابيع من تاريخ انتهاء المدة المقدم عنها التقرير، وذلك لكل من عمليات ومجالات التكنولوجيا المالية غير المصرفية التى يمكن استخدامها فى مزاولة الأنشطة المالية غير المصرفية، طبقًا للنموذج الوارد بالملحق رقم (3) .

