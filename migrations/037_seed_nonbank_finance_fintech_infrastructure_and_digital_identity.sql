ملحق (3): إطار عمل إدارة الأمن السيبرانى
(CSM-F: Cybersecurity Management Framework)

وهو إطار العمل المنظم لإدارة الأمن السيبرانى (Cybersecurity Management) كعنصر أساسى ومتمم لإدارة أمن المؤسسات (ESM: Enterprise Security Management)، ويتكون إطار العمل من العمليات الاستراتيجية على المستوى الاستراتيجى، والعمليات التخطيطية على المستوى التنفيذى، والإجراءات التطبيقية على المستوى التشغيلى، وتتبنى الهيئة بين مبدأ "إدارة الأمن السيبرانى" و"إدارة المخاطر التكنولوجية"، حيث تكون المخاطر السيبرانية أحد أنواع المخاطر التكنولوجية . وعلى هذا تكون دورة حياة إدارة المخاطر السيبرانية على المستوى الاستراتيجى مماثلة لدورة حياة إدارة المخاطر التكنولوجية ("الهيكلة" و"التقييم" و"المجابهة" و"المراقبة" للمخاطر التكنولوجية) .

ومن خلال فهم درجة تحمل المخاطر، يمكن للشركات أو الجهات المالية غير المصرفية تحديد الأولوية لأنشطة الأمن السيبرانى، مما يمكّن من اتخاذ قرارات مستنيرة بشأن نفقات إدارة المخاطر السيبرانية . ويوفر تنفيذ مبادرات إدارة المخاطر السيبرانية القدرة على التعامل مع التعديلات عنها والإبلاغ عن المخاطر السيبرانية بطرق مختلفة، بما فى ذلك تخفيف المخاطر، أو تجنب المخاطر، أو قبول المخاطر، أو تحويل المخاطر، اعتمادًا على التأثير المحتمل على تقديم الخدمات الهامة .

وتعمل الضوابط المنصوص عليها كدليل للممارسات السليمة لإدارة الأمن السيبرانى والمخاطر السيبرانية .

ويتبنى هذا العرض لإطار عمل "إدارة الأمن السيبرانى" منهجية "دورة الحياة لتحسين الأمن السيبرانى" من المعهد الوطنى للمعايير والتكنولوجيا (NIST: National Institute for Standards & Technology) لكل من التجهيزات، والبنية التكنولوجية، وأنظمة المعلومات، ووسائل الحماية والتأمين .

ويجب على مجلس الإدارة وضع واعتماد "استراتيجية إدارة الأمن السيبرانى" والتى تكون مرتبطة وممتاشية مع "استراتيجية تكنولوجيا المعلومات" ومع البنية الهيكلية لأعمال الأنشطة المالية غير المصرفية، ويكون ذلك من خلال "إطار عمل إدارة الأمن السيبرانى" والذى يكون معتمدًا من مجلس الإدارة وحاكمًا للإدارة التنفيذية وللإدارة التشغيلية . كما يجب على مجلس الإدارة أيضًا مراجعته بشكل دورى مرة واحدة على الأقل كل ثلاث سنوات . ويكون لمجلس الإدارة تشكيل "لجنة إدارة الأمن السيبرانى" التابعة لمجلس الإدارة تكون مسئولة عن الإشراف على تنفيذ إطار عمل إدارة الأمن السيبرانى والتأكد من ملاءمة دورة العمل والمسئولين عن تنفيذها، والتأكد من الالتزام بالإجراءات المطلوب اتباعها .

ويشتمل هذا الإطار على 5: عمليات استراتيجية لدورة الحياة للأمن السيبرانى (Cybersecurity Process)، تشمل "التحديد" (Identify) و"الحماية" (Protect) و"الرصد" (Detect) و"الاستجابة" (Respond) و"الاستعادة" (Recover) للأمن السيبرانى، وما تتضمنه من 23 عملية استراتيجية فرعية، وما يرتبط بهم من 108 عملية تخطيطية على المستوى التنفيذى .

1- العمليات الاستراتيجية :

العمليات الاستراتيجية لدورة حياة الأمن السيبرانى (Cybersecurity Process)، وتشمل :

1- التحديد (Identify): ويقصد به تطوير الفهم التنظيمى لإدارة مخاطر الأمن السيبرانى للأنظمة والأصول والبيانات والقدرات :
● إدارة الأصول (Asset Management): ويقصد به تحديد وإدارة البيانات والموظفين والأجهزة والأنظمة والمرافق التى تمكن الشركة أو الجهة المالية غير المصرفية من تحقيق أغراض العمل بما يتوافق مع أهميتها النسبية للأهداف التنظيمية واستراتيجية المخاطر لها .
● بيئة الأعمال (Business Environment): ويقصد به فهم رسالة الشركة أو الجهة المالية غير المصرفية وأهدافها وأصحاب المصلحة وأنشطتها؛ وتُستخدم هذه المعلومات لإبلاغ أدوار ومسؤوليات وقرارات إدارة المخاطر فى مجال الأمن السيبرانى .
● الحوكمة (Governance): ويقصد بها فهم السياسات والإجراءات والعمليات لإدارة ومراقبة المتطلبات التنظيمية والقانونية والمتعلقة بالمخاطر البيئية والتشغيلية وإبلاغ إدارة مخاطر الأمن السيبرانى .
● تقييم المخاطر (Risk Assessment): ويقصد به فهم الشركة أو الجهة المالية غير المصرفية مخاطر الأمن السيبرانى التنظيمية للعمليات (بما فى ذلك الرسالة أو الوظائف أو الانطباع أو السمعة) والأصول التنظيمية والأفراد .
● استراتيجية إدارة المخاطر (Risk Management Strategy): ويقصد به وضع أولويات الشركة أو الجهة المالية غير المصرفية والقيود وتحمل المخاطر والافتراضات واستخدامها لدعم قرارات المخاطر التشغيلية .
● إدارة مخاطر سلسلة التوريد (Supply Chain Risk Management): يقصد به وضع أولويات الشركة أو الجهة المالية غير المصرفية والقيود وتحمل المخاطر والافتراضات واستخدامها لدعم قرارات المخاطر المرتبطة بإدارة مخاطر سلسلة التوريد . ويتم تخطيط وتنفيذ وتقييم عمليات تحديد وإدارة مخاطر سلسلة التوريد .
2- الحماية (Protect): ويقصد بها تطوير وتنفيذ الضمانات المناسبة لضمان تقديم خدمات البنية التحتية الحيوية :
● إدارة الهوية والمصادقة والتحكم فى الوصول (Authentication & Access Control): ويقصد به الوصول إلى الأصول المادية والمنطقية والملحقات المرتبطة بها على المستخدمين المعتمدين والعمليات والأجهزة، ويتم إدارتها بما يتفق مع المخاطر المقدرة للوصول غير المصرح به إلى الأنشطة والمعاملات المصرح بها .
● الوعى والتدريب (Awareness & Training): ويقصد به تزويد موظفى الشركة أو الجهة المالية غير المصرفية وشركائها بالتثقيف التوعوى للأمن السيبرانى ويتم تدريبهم على أداء واجباتهم ومسؤولياتهم المتعلقة بالأمن السيبرانى بما يتفق مع السياسات والإجراءات والاتفاقيات ذات الصلة .
● أمن البيانات (Data Security): ويقصد به إدارة المعلومات والسجلات (البيانات) بما يتوافق مع استراتيجية المخاطر لحماية سرية المعلومات وسلامتها وتوافرها .
● عمليات وإجراءات حماية المعلومات (Information Protection Processes & Procedures): ويقصد به الحفاظ على السياسات الأمنية (التى تتناول الغرض والنطاق والأدوار والمسؤوليات والالتزام الإدارى والتنسيق بين الكيانات التنظيمية) والعمليات والإجراءات وتستخدم لإدارة حماية أنظمة المعلومات والأصول .
● الصيانة (Maintenance): ويقصد به إجراء عمليات الصيانة والإصلاح لمكونات التحكم الصناعية والمعلومات النظمة بما يتفق مع السياسات والإجراءات .
● التكنولوجيا الوقائية (Protective Technology): ويقصد به أن تدار الحلول التكنولوجية الأمنية لضمان أمن ومرونة الأنظمة والأصول، بما يتوافق مع السياسات والإجراءات والاتفاقيات ذات الصلة .
3- الرصد (Detect): ويقصد به تطوير وتنفيذ الإجراءات المناسبة لاكتشاف وتحديد وقوع حدث الأمن السيبرانى :
● الأحداث غير المألوفة والنمطية (Anomalies & Events): ويقصد به الكشف عن الأنشطة غير المألوفة وفهم التأثير المحتمل للأحداث .
● المراقبة الأمنية المستمرة (Security Continuous Monitoring): ويقصد به مراقبة نظام المعلومات والأصول لتحديد أحداث الأمن السيبرانى والتحقق من فعالية تدابير الحماية .
● تحسين عملية الرصد (Detection Process Improvement): ويقصد به تحديث عملية الرصد وإجراءاتها واختباراتها بما يتناسب مع ما يطرأ من أحداث غير متوقعة .
4- الاستجابة (Respond): ويقصد بها تطوير وتنفيذ الاجراءات المناسبة لاتخاذ التدابير المتعلقة بحدث الأمن السيبرانى المكتشف :
● تخطيط الاستجابة (Response Planning): ويقصد به التحقق من تنفيذ خطة الاستجابة والحفاظ عليها أثناء أو بعد وقوع حادث .
● التواصل بخصوص الاستجابة (Response Communications): ويقصد به التحقق من أن يعرف الموظفون أدوارهم وترتيب العمليات عند الحاجة إلى الاستجابة .
● التحليل (Response Analysis): ويقصد به إجراء التحقيق فى الإخطارات من أنظمة الرصد .
● تدابير التخفيف (Mitigation): ويقصد به اتخاذ التدابير التى من شأنها منع تفاقم الحدث، والتخفيف من آثاره، وحل مسبباته .
● تحسين عملية الاستجابة (Respond Process Improvement): ويقصد به أن يتم تحسين إجراءات الاستجابة من خلال دمج الدروس المستفادة من الرصد أو الاستجابة الحالية والسابقة .
5- الاستعادة (Recover): ويقصد بها تطوير وتنفيذ الإجراءات المناسبة للحفاظ على خطط المرونة واستعادة أى قدرات أو خدمات تعرضت للضرر بسبب حدث للأمن السيبرانى :
● تخطيط الاستعادة (Recovery Planning): ويقصد به تنفيذ خطة الاستداد أثناء أو بعد حادث الأمن السيبرانى .
● تحسين عملية الاستعادة (Recover Process Improvement): ويقصد به تحسين تخطيط الاستداد وعملياته من خلال دمج الدروس المستفادة فى الأنشطة المستقبلية .
● التواصل بخصوص الاستعادة (Recovery Communications): ويقصد به تنسيق أنشطة الاستعادة مع أطراف داخلية وخارجية (مثل مراكز التنسيق والاتحادات والهيئة ومقدمى خدمة الإنترنت ومسئولى الأنظمة المتعرضة للهجوم ومسئولى الأنظمة المتعرضة للهجوم وفرق مجابهة أحداث الأمن السيبرانى الأخرى مثل وزارة الاتصالات والموردين والمتأثرين) .

2- العمليات التخطيطية :

العمليات التخطيطية لدورة الحياة للأمن السيبرانى (Cybersecurity Process) :

1- التحديد (Identify) :
إدارة الأصول (Asset Management) وتشتمل على :
● جرد الأجهزة والأنظمة المادية للشركة أو الجهة المالية غير المصرفية .
● جرد منصات البرامج والتطبيقات للشركة أو الجهة المالية غير المصرفية .
● تحديد آليات ومسارات التواصل وتدفق البيانات على المستوى التنظيمى .
● فهرسة أنظمة المعلومات الخارجية .
● تحديد أولويات الموارد (على سبيل المثال، الأصول الملموسة، والأجهزة، والبيانات، والوقت، والموظفين، والبرامج) بناءً على تصنيفها وأهميتها وقيمة الأعمال .
● إنشاء أدوار ومسؤوليات الأمن السيبرانى لجميع القوى العاملة وأصحاب المصلحة من الأطراف الثالثة (مثل الموردين والعملاء والشركاء) .
بيئة الأعمال (Business Environment) وتشتمل على :
● تحديد دور الشركة أو الجهة المالية غير المصرفية فى سلسلة التوريد والإفصاح عنه .
● تحديد مكان الشركة أو الجهة المالية غير المصرفية فى البنية التحتية الحيوية وقطاعاتها السوقية والإفصاح عنها .
● تحديد أولويات الرسالة والأهداف والأنشطة التنظيمية والإفصاح عنها .
