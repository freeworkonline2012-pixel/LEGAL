القواعد المرفقة

أولاً - تعريفات

في تطبيق أحكام القواعد الآتية يُقصد بالمصطلحات التالية المعنى المبين قرين كل منها :

1- التجهيزات التحتية (Facilities Infrastructure): البنية التحتية من مرافق وتجهيزات لازمة لمراكز المعلومات (الأساسية والبديلة) والتي تشمل التجهيزات اللازمة للوصول للمرافق العامة من الكهرباء والاتصالات والمياه والصرف، والأنظمة الداخلية للكهرباء والتهوية والتبريد وكابلات الشبكات واكتشاف ومكافحة الحريق والأمن المادي والتحكم فى الدخول والمراقبة من خلال الدوائر التليفزيونية المغلقة .

2- البنية التكنولوجية (Technology Infrastructure): البنية التحتية من أجهزة ونظم لازمة لمراكز المعلومات (الأساسية والبديلة) والتى تشمل التجهيزات اللازمة لنقل البيانات ووسائل التخزين والأجهزة الطرفية المخصصة، وأجهزة الحاسبات وأجهزة الشبكات، وأنظمة البنية التحتية لقواعد البيانات .

3- أنظمة المعلومات (Information Systems): الأنظمة المكونة من تطبيقات (Applications) وقواعد بيانات (Databases) يتم تطويرها لتؤدى مهام محددة دعماً لعمليات ودورات العمل المستهدفة، وتساهم فى التنسيق بين المستخدمين الداخليين أو الخارجيين، وقد تشمل تطبيقات "ذكاء اصطناعي" (Artificial Intelligence) لتوفير درجات أعلى من التشغيل الآلى (automation) والدقة والسرعة فى أداء المهام .

4- وسائل الحماية والتأمين (Protection & Security Mechanisms): الآليات والمنهجيات المستخدمة لتوفير الآتي:
1- القدرة على منع وقوع المخاطر التكنولوجية (Technology Risk Prevention) التى من شأنها فقد الخصوصية والسرية (Confidentiality)، أو السلامة والتكامل (Integrity)، أو التوافر والإتاحة (Availability)، للبنية التحتية للتجهيزات أو للبنية التحتية التكنولوجية أو لأنظمة المعلومات شاملة التطبيقات والبيانات .
2- القدرة على التحمل والمرونة والتعافى لاستعادة الإمكانيات والوظائف والبيانات بعد وقوع المخاطر (After-Risk Recovery & Resiliency) .
5- المخاطر التكنولوجية (Technology Risk): أى من التهديدات (Threats) أو نقاط الضعف (Vulnerabilities) الناشئة عن الاعتماد على البنية التكنولوجية وعلى أنظمة المعلومات فى أداء الأعمال والتى من شأنها حال وقوعها التأثير سلبًا على القدرة على استمرار أداء تلك الأعمال .

6- مرونة التحمل التكنولوجية (Technology Resiliency): قدرة البنية التكنولوجية وأنظمة المعلومات على التحمل واستعادة الإمكانات والوظائف المستهدفة بعد وقوع خطر تكنولوجى .

7- المخاطر السيبرانية (Cyber Risk): أى من التهديدات (Threats) أو نقاط الضعف (Vulnerabilities) الناشئة عن اتصال البنية التحتية التكنولوجية الداخلية بالشبكات الخارجية أو الشبكة العالمية للتواصل (الإنترنت) .

8- مرونة التحمل السيبرانية (Cyber Resiliency): قدرة البنية التكنولوجية وأنظمة المعلومات على التحمل واستعادة الإمكانات والوظائف المستهدفة بعد وقوع خطر سيبرانى .

9- أمن البيانات (NBFS-Cybersecurity) في مزاولة الأنشطة المالية غير المصرفية: إجراءات وعمليات تقنية وتنظيمية من شأنها الحفاظ على خصوصية البيانات وسريتها وسلامتها ووحدتها وتكاملها فيما بينها .

10- المنصة الرقمية المستخدمة في مزاولة الأنشطة المالية غير المصرفية (NBFS-Digital Platform): نموذج أعمال قائم على استخدام الوسائل التكنولوجية فى مزاولة الأنشطة المالية غير المصرفية وفى عرض المنتجات والخدمات المرتبطة بها على الأشخاص الراغبين فى الحصول عليها، ويسمح بتبادل البيانات والمعلومات اللازمة لإتمام هذه التعاملات .

11- الجهات الراغبة في تقديم خدمات التعهيد (Outsourcing Service Provider): جهة تقدم خدمات تكنولوجية عن طريق اتفاقية تعهيد (Outsourcing Agreement) يكون الطرف العاهد (Outsourcing Party) هو المستفيد من الخدمة ويكون الطرف المعهد إليه (Outsourcee) هو مقدم الخدمة .

12- أنظمة التكنولوجيا الحرجة (NB-Critical-System): نظام أو تطبيق يؤدى فشله إلى إضعاف قدرة الشركات والجهات العاملة فى الأنشطة المالية غير المصرفية فى الوفاء بالتزاماتها بالتعاملين أو للهيئة العامة للرقابة المالية .

13- بيانات العميل (Client Data): بيانات تتعلق بالعميل أو حساباته أو الحسابات المرتبطة بالمنتجات المالية غير المصرفية أو المعاملات المالية المرتبطة بتلك المنتجات المالية غير المصرفية .

14- معلومات التعرف الشخصية (Personally Identifiable Information): أى بيانات للعميل يمكن استخدامها لتمييز أو تتبع هوية الشخص .

15- الإدارة التنفيذية للشركة (Executive Management): وتشمل الوحدات التنظيمية المسئولة عن العمليات التخطيطية على المستوى التنفيذى (Planning – Executive Level)، والإشراف والرقابة الداخلية على الإجراءات التطبيقية على المستوى التشغيلى (Internal Auditing on Applied Procedures – Operational Level) لوظائف وخدمات أعمال الأنشطة المالية غير المصرفية أو لوظائف وخدمات تكنولوجيا المعلومات الممكنة .

16- الإدارة التشغيلية للشركة (Operational Management): وتشمل الوحدات التنظيمية المسئولة عن الإجراءات التطبيقية على المستوى التشغيلى (Applied Procedures – Operational Level)، لوظائف وخدمات أعمال الأنشطة المالية غير المصرفية أو لوظائف وخدمات تكنولوجيا المعلومات الممكنة .

17- العمليات الاستراتيجية (Strategy Processes): وتشمل العمليات المحققة لاستراتيجية مستهدفة من خلال دورة حياة معينة (Intended Life Cycle)، وتكون لكل عملية مجموعة من المدخلات (Inputs) ومجموعة من المخرجات (Outputs)، وعلى أن تكون المخرجات من كل عملية مدخلات لعملية أخرى (أو لعمليات أخريات)، ويكون للمجموعة من خصائص دورية التكرار (Cyclical Iterations) تتطور مع كل تكرار للدورة "أغراض وقيم مضافة" (Purpose & Value-add) . وعلى أن يتحقق من دورة حياة العمليات الاستراتيجية "أغراض وقيم مضافة" مع كل تكرار للدورة، وتمثل "العمليات الاستراتيجية" المستوى الاستراتيجى لإطار العمل المستهدف (Intended Framework) .

18- العمليات التخطيطية (Planning Processes): وتشمل مجموعة العمليات (Processes) المحققة لخطط مستهدفة، تنفيذاً لاستراتيجية معينة، وتكون لكل عملية مجموعة من المدخلات (Inputs) ومجموعة من المخرجات (Outputs)، وعلى أن تكون المخرجات من كل عملية مدخلات لعملية أخرى (أو لعمليات أخريات)، وعلى أن يتحقق من مجموعة العمليات التخطيطية "الأغراض والقيم المضافة" للاستراتيجية المعينة . وتمثل "العمليات التخطيطية" المستوى التنفيذى لإطار العمل المستهدف (Intended Framework) .

19- الإجراءات التطبيقية (Applied Procedures): مجموعة الإجراءات المطبقة لعمليات تخطيطية معينة، ويكون لكل إجراء "حادث مشغل" (trigger events) كما يكون له "حالات ناتجة" (resulting state) والتى قد تكون "مشغلة" لإجراء آخر أو لإجراءات أخرى، وعلى أن يتحقق من مجموعة الإجراءات التطبيقية للعمليات التخطيطية المعينة "الأغراض والقيم المضافة" . وتمثل الإجراءات التطبيقية "المستوى التشغيلي" لإطار العمل المستهدف (Intended Framework) .

20- الجهات المخاطبة :
● الشركات والجهات الراغبة في الحصول على ترخيص لمزاولة الأنشطة المالية غير المصرفية من خلال تقنيات التكنولوجيا المالية تحت مظلة القانون رقم 5 لسنة 2022 .
● الشركات والجهات الحاصلة على ترخيص من الهيئة بمزاولة أي من الأنشطة المالية غير المصرفية تحت مظلة أي قوانين أخرى، والراغبة في الحصول على موافقة الهيئة لتباشر هذه الأنشطة باستخدام بعض مجالات التكنولوجيا المالية بنفسها، أو من خلال إحدى جهات التعهيد تحت مظلة القانون رقم 5 لسنة 2022 .
● الشركات الراغبة في تقديم خدمات التعهيد في مجالات التكنولوجيا المالية التي يمكن استخدامها في مزاولة الأنشطة المالية غير المصرفية تحت مظلة القانون رقم 5 لسنة 2022 .

ثانيًا - التجهيزات والبنية التكنولوجية وأنظمة المعلومات ووسائل الحماية والتأمين :

1- تلتزم الشركات والجهات المخاطبة بأحكام هذا القرار بتوفير التجهيزات التى تحددها الهيئة للربط الآلى معها .

2- تلتزم الشركات والجهات المخاطبة بأحكام هذا القرار بتوفير أجهزة الخوادم الأساسية كحد أدنى لمتطلبات البنية التكنولوجية وأنظمة المعلومات :
● حاسبات تعمل كخوادم لقواعد البيانات Database Servers .
● حاسبات تعمل كخوادم للتطبيقات Application Servers .
● حاسبات تعمل كخوادم للويب Web Server .
على أن يتم مراعاة التالى :
● توفير نظم تشغيل حديثة ومرخصة .
● توفير الأنظمة والتطبيقات والبرمجيات – المُرخصة – اللازمة لتشغيل الخدمات المختلفة .
● الإتاحة الدائمة للخدمات دون توقف (High Availability) .

3- تلتزم الشركات والجهات المخاطبة بأحكام هذا القرار بضوابط أمن المعلومات التالية كحد أدنى :
● نظام جدار نارى (Next Generation Firewall) لتأمين الشبكات والمعلومات .
● نظام حماية لأنظمة الويب (Web Application Firewall) .
● نظم أمن المعلومات لكافة الأصول .
● نظام رصد ومراقبة كافة الأحداث المرتبطة بالأصول بما يتيح الرصد اللحظى وإصدار التقارير المجمعة للأحداث المرتبطة .
● استخدام خاصية تشفير البيانات بما يتوافق مع المعايير العالمية فى تشفير قواعد البيانات .
● إجراء الصيانة الدورية للأجهزة والأنظمة وتأمين الشبكات والمعلومات مع مراعاة قواعد الضبط المناسبة لها وتحديثها بصفة مستمرة .
● تزويد جميع أجهزة الحاسب المتصلة بشبكة الشركة (حاسبات مكتبية، محمولة، خوادم) ببرامج محدثة ومرخصة لمكافحة الفيروسات والبرمجيات الضارة مثل نظام (Endpoint Detection & Response) وAntivirus .
● عمل التحديث الدورى لأنظمة التشغيل والتطبيقات والبرمجيات المختلفة .
● الفصل المؤمن (Security Isolation) بين أنظمة الخدمات المختلفة وفقًا للمستوى الأمنى لها .
● عمل اختبارات معتمدة (Penetration Test) لقياس مدى تأمين الشبكات والتطبيقات والبرمجيات مرة واحدة سنويًا على الأقل وتسليم نسخة من هذه الاختبارات للهيئة، ويجوز للهيئة طلب إعادة الاختبارات إذا تبين وجود نقاط ضعف تستدعى ذلك .
● إبلاغ الهيئة عند حدوث اختراقات لأمن المعلومات (Security Incidents) التى تحدث على مستوى البنية الأساسية للمعلومات والأنظمة العاملة عليها .
● تأمين الموقع الإلكترونى بشهادة تأمين إلكترونية سارية مخصصة للتعريف وتشفير البيانات (SSL Certificate)، بحيث تظهر للعملاء عند تصفحهم الموقع الالكترونى بشهادة تأمين إلكترونية .
● إصدار رقم فريد إليه (Unique Session ID)، مضافًا إليه خَتم التوقيت (Time Stamp) لكل اتصال حال فتح الاتصال من التحقق عند الدخول .
● تسجيل الأنشطة (Logging Activities) التى تحدث على جميع الأجهزة والأنظمة (System Logs, Security Logs, Application Logs) وما يعتمد عليه من أجهزة مساعدة مثل (الحاسبات، وأجهزة شبكات، وأجهزة تأمين معلومات) لمدة لا تقل عن خمس سنوات من تاريخ حدوث النشاط .
● الاحتفاظ بسجلات التعاملات على الحساب كاملة (Transactions Logs) بما فى ذلك جميع عمليات تسجيل الدخول والخروج وغيرها ولمدة لا تقل عن خمس سنوات .

4- تلتزم الشركات والجهات المخاطبة بأحكام هذا القرار بالضوابط التالية :
● أن تكون قاعدة بيانات عملاء الشركة داخل الحدود الجغرافية لجمهورية مصر العربية .
● إبلاغ الهيئة فى حالة اتخاذ أى إجراءات لنقل مقرها أو مركز بياناتها (Data Center) بمدة لا تزيد على 30 يومًا من تاريخ البدء فى اتخاذ الإجراءات .
● توفير مركز لخدمة العملاء يعمل 24 ساعة يوميًا على الرد على استفسارات العملاء وحل المشاكل محل الاستفسار فور حدوثها .
● توقيع اتفاقية مستوى الخدمات (Service Level Agreement) بين كل من الشركة وعملائها .

5- تعتبر الأطر العامة (إطار عمل حوكمة تكنولوجيا المعلومات وإطار عمل إدارة مخاطر التكنولوجيا وإطار عمل إدارة الأمن السيبرانى) الواردة بالملاحق المرفقة أدلة استرشادية للممارسات الصحيحة، وتحدد الهيئة الحد الأدنى اللازم اتباعه منها فى كل حالة على حدة .

