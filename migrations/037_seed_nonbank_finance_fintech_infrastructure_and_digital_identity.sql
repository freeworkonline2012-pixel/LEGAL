ملحق (1): إطار عمل حوكمة تكنولوجيا المعلومات
(ITG-F: Information Technology Governance Framework)

يُقصد بالمصطلحات التالية المعنى قرين كل منها :

إطار عمل حوكمة تكنولوجيا المعلومات: هو عنصر أساسى ومتمم لحوكمة المؤسسات، وما يستتبعه من حوكمة لإدارة خدمات تكنولوجيا المعلومات (ITSM: Information Technology Service Management) . ويكون إطار العمل من العمليات الاستراتيجية على المستوى الاستراتيجى، والعمليات التخطيطية على المستوى التنفيذى، والإجراءات التطبيقية على المستوى التشغيلى، ويتبنى هذا العرض لإطار عمل "حوكمة تكنولوجيا المعلومات" منهجية التوجه الخدمى لتقديم خدمات تكنولوجيا المعلومات (ITSM) لكل من التجهيزات، والبنية التكنولوجية، وأنظمة معلومات، ووسائل الحماية والتأمين، ويجوز استخدام أفضل الممارسات وأطر العمل العالمية الأخرى، أو تبنى إطار عمل بديل بعد العرض والموافقة من الهيئة .

ويجب على مجلس إدارة الشركة وضع واعتماد "استراتيجية تكنولوجيا المعلومات" ويكون ذلك من خلال "إطار عمل حوكمة تكنولوجيا المعلومات" والذى يكون معتمدًا من مجلس الإدارة وحاكمًا للإدارة التنفيذية وللإدارة التشغيلية . كما يجب على مجلس الإدارة أيضًا مراجعته بشكل دورى مرة واحدة على الأقل كل ثلاث سنوات، ويكون لمجلس الإدارة تشكيل لجنة تُسمى "لجنة حوكمة تكنولوجيا المعلومات" التابعة لمجلس الإدارة وتكون مسئولة عن الإشراف على تنفيذ إطار عمل خدمات حوكمة تكنولوجيا المعلومات والمسئولين والتأكد من ملاءمة دورة العمل والتأكد من الالتزام بالإجراءات المطلوب اتباعها .

ويشمل إطار عمل تكنولوجيا المعلومات خمس عمليات استراتيجية أساسية لدورة الحياة (LP)، تتضمن 40 عملية تخطيطية على المستوى التنفيذى، بالإضافة إلى 12 عملية استراتيجية مساندة لدورة الحياة (SP)، تتضمن 62 عملية تخطيطية على المستوى التنفيذى، بإجمالى 17 عملية استراتيجية و102 عملية تخطيطية .

1- العمليات الاستراتيجية : هى العمليات التى تهدف إلى تحويل موارد مقدم خدمات تكنولوجيا المعلومات إلى خدمات ذات قيمة للعملاء، ويجب توفير هذه الخدمات بمستويات متفق عليها من الجودة والتكلفة والمخاطر، وتنقسم إلى :

أولاً - العمليات الاستراتيجية الأساسية لدورة الحياة، وتشمل :
1- تحديد الاتجاه الاستراتيجى : ويقصد به اتخاذ قرارات استراتيجية لخدمة العملاء باستخدام تكنولوجيا المعلومات، بدءًا من تقييم احتياجات العملاء وبيئة الأعمال وتحديد الخدمات التى يجب أن تقدم والقدرات المطلوبة لتقديمها .
2- تصميم الخدمات الجديدة أو المعدلة : ويقصد به تحديد النتائج المتوقعة والخصائص المطلوبة لخدمة جديدة أو معدلة، وتحديد البنية التحتية والقدرات الأخرى اللازمة لتقديم الخدمة، وتطوير نهج تنفيذها .
3- بناء الخدمات الجديدة أو المعدلة : ويقصد به بناء ونشر خدمات جديدة أو معدلة، ويشمل تنسيق تطوير واقتناء وتطوير واختبار جميع مكونات الخدمة المطلوبة .
4- تشغيل الخدمات : ويقصد به ضمان تقديم الخدمات بفعالية وكفاءة، ويشمل تلبية طلبات الخدمة، وحل الحوادث والمشكلات، وكذلك تنفيذ المهام التشغيلية الروتينية .
5- تحسين الخدمات : ويقصد به التحقق باستمرار مما إذا كانت الخدمات تقدم النتائج المطلوبة، وتحديد إمكانات التحسين فى طريقة إنتاج الخدمات .

ثانيًا - العمليات الاستراتيجية المساندة لدورة الحياة، وتشمل :
1- إعداد وصيانة نظام إدارة الخدمة : ويقصد به إنشاء نظام إدارة الخدمة وتشغيله وتحسينه باستمرار، وتكون هذه العملية مسئولة عن إدارة سياسات وعمليات إدارة الخدمة كمكونات رئيسية فى نظام إدارة الخدمة .
2- الحفاظ على محفظة الخدمات : ويقصد به ضمان احتواء محفظة الخدمات على معلومات متسقة ومحدثة حول الخدمات التى يديرها مقدم الخدمة، ويتحقق ذلك من خلال التحكم فى التغييرات فى محفظة الخدمات وتعريفات الخدمة، بالإضافة إلى إجراء مراجعات منتظمة لمحفظة الخدمات .
3- إدارة علاقات العملاء : وتكون هذه العملية مسئولة عن الحفاظ على علاقة إيجابية مع العملاء، وتحديد العملاء الجدد المحتملين، وضمان الحصول على تعليقات منتظمة من العملاء الحاليين من خلال اجتماعات واستطلاعات الرأى، وتوقيع اتفاقيات خدمة العملاء مع عملاء مقدم الخدمة .
4- إدارة معلومات مكونات التهيئة : ويقصد به الاحتفاظ بمعلومات حول عناصر مكونات التهيئة المطلوبة لتقديم الخدمات، بما فى ذلك العلاقات بينهم .
5- تقييم التغييرات والتنسيق لها : ويقصد به التحكم فى دورة حياة جميع التغييرات ويكون غرضها الرئيسى هو التمكين من إجراء تغييرات مفيدة، مع الحد الأدنى من تعطيل الخدمات .
6- إدارة المشاريع : ويقصد به تخطيط وتنسيق الموارد لإكمال مشروع فى الوقت والتكلفة والنطاق المستهدفين .
7- ضمان الأمن : ويقصد به ضمان أمن مجموعة خدمات مقدم الخدمة، ومواءمة الاحتياجات الأمنية لعملاء مقدم الخدمة، وضمان حماية الأنظمة والبيانات من التطفل، وألا يتم الوصول إليها إلا من الأطراف المصرح لها .
8- الاستعداد لأحداث الكوارث : ويقصد به التأكد من أن مقدم الخدمة يمكنه توفير الحد الأدنى من مستويات الخدمة المتفق عليها فى حالة الأحداث التى تعتبر كوارث، ويتم تحقيق ذلك فى المقام الأول من خلال تنفيذ آليات لمنع حدوث كوارث، ومن خلال وضع خطط وترتيبات للاستمرارية لاستعادة الخدمات بمجرد وقوع كارثة .
9- ضمان الامتثال : ويقصد به ضمان امتثال الخدمات والعمليات والأنظمة للمتطلبات القانونية ذات الصلة والمعايير وسياسات المؤسسة .
10- إدارة الموارد البشرية : ويقصد به توفير المهارات ومستويات الموظفين المطلوبة من قبل مقدم الخدمة لتحقيق أهدافه .
11- إدارة الموردين : ويقصد به التأكد من أن جميع الاتفاقيات مع الموردين تدعم احتياجات العمل، وأن جميع الموردين يفون بالتزاماتهم التعاقدية .
12- إدارة الشئون المالية للخدمة : ويقصد به إدارة متطلبات الميزانية والمحاسبة والرسوم الخاصة بمقدم الخدمة .

2- العمليات التخطيطية، وتشمل :

أولاً - العمليات التخطيطية الأساسية لدورة الحياة، وتشمل :
1- تحديد الاتجاه الاستراتيجى :
● تقييم الوضع الاستراتيجى الحالى : ويقصد به تقييم الوضع القائم لمقدم خدمات تكنولوجيا المعلومات والقدرات اللازمة لأدائها واحتياجات عملائها، والبدائل المتاحة لتلك الخدمات ومكوناتها .
● تحديد توجيهات الاستخدام الاستراتيجى للتكنولوجيا : ويقصد به الموائمة مع الأهداف الاستراتيجية للأعمال .
● تحديد المبادرات الاستراتيجية : ويقصد به دراسة وتحديد المبادرات وأنسب الطرق لتنفيذها .
● البدء فى مشروعات تطوير الخدمات : ويقصد به تحديد مسئول الخدمة وتحديد وضمان الموازنة اللازمة، وتحديد جدول زمنى .
● مراقبة المبادرات الاستراتيجية : ويقصد به التحقق من سيرها وفقًا للمخطط، واتخاذ تدابير تصحيحية عند الضرورة .
2- تصميم الخدمات الجديدة أو المعدلة :
● تحديد خصائص الخدمة المطلوبة : ويقصد به تحديد النتيجة المتوقعة والخصائص المطلوبة لخدمة جديدة أو معدلة، ويتضمن ذلك تحديد خصائص أى خدمات داعمة يجب إعدادها أو تعديلها حتى تتمكن من تقديم الخدمة الجديدة .
● تصميم البنية التحتية المطلوبة والإمكانيات الأخرى التى يجب إنشاؤها قبل تقديم خدمة جديدة أو معدلة .
● تحديد منهجية التنفيذ : ويقصد به وصف كيفية إنشاء البنية التحتية والقدرات الأخرى المطلوبة لتقديم خدمة جديدة أو معدلة .
● الإعداد لتنفيذ الخدمة : ويقصد به تقديم مستندات تصميم الخدمة للمراجعة النهائية وتحديد ما إذا كانت الخدمة جاهزة للتنفيذ .
3- بناء الخدمات الجديدة أو المعدلة :
● التنسيق بين عمليات التطوير والشراء : ويقصد به بدء وتنسيق الأنشطة لتطوير أو شراء مكونات البنية التحتية والقدرات الأخرى المطلوبة لخدمة جديدة أو متغيرة .
● تطوير التطبيقات والأنظمة : ويقصد به تطوير أو تهيئة مكونات التطبيقات والأنظمة التى توفر الوظائف المطلوبة للخدمات، ويتضمن هذه العملية تطوير تطبيقات وأنظمة مخصصة بالإضافة إلى تخصيص وتهيئة مكونات المنتجات التى تم شراؤها .
● قبول تسليم مكونات الخدمة : ويقصد به تلقى مكونات الخدمة المطلوبة وتقديمها للتقييم الأولى، وتتضمن هذه العملية التأكد أن هذه المكونات تفى بمعايير الجودة الصارمة التى يسمح لها بالدخول إلى مرحلة اختبار الخدمة الرئيسية .
● إنشاء أو تحديث الوثائق التشغيلية : ويقصد به تقديم إرشادات لتشغيل الخدمة الجديدة .
● اختبار مكونات الخدمة : ويقصد به اختبار جميع مكونات الخدمة وكذلك جميع الأدوات والآليات المطلوبة لنشر مكونات الخدمة التى تلبى معايير الجودة الصارمة فقط التى يسمح لها بالدخول إلى بيئة الإنتاج الحية .
● نشر مكونات الخدمة فى البيئة الإنتاجية : ويقصد به نشر مكونات الخدمة فى بيئة الإنتاج الحية .
● الإعداد لتفعيل الخدمة : ويقصد به تقييم ما إذا كانت جميع مكونات البنية التحتية والقدرات الأخرى موجودة قبل السماح بتفعيل الخدمات الجديدة .
4- تشغيل الخدمة :
● دعم عملية تشغيل الخدمة : ويقصد به تقديم الدعم لعملية تشغيل الخدمة، من خلال ضمان توفر الموارد المطلوبة لتشغيل الخدمات، وعن طريق تكوين أنظمة الدعم التشغيلى وصيانتها وغيرها .
● تنظيم عملية تشغيل الخدمة : ويقصد به تقديم إرشادات للإجراءات التى سيتم تنفيذها بواسطة طاقم التشغيل .
● مراقبة الخدمات : ويقصد به التأكد من مراقبة البنية التحتية للخدمة واستخدام الخدمة باستمرار، ولتحديد الاستجابات المناسبة إذا تم اكتشاف أى مخالفات .
● إصدار تقارير جودة الخدمة : ويقصد به قياس جودة الخدمة المحققة على أساس منتظم وتحديد المجالات التى يجب تحسين جودة الخدمة فيها .
● أداء المهام التشغيلية الروتينية : ويقصد به تنفيذ المهام التشغيلية الروتينية المطلوبة لتقديم جودة الخدمة المتفق عليها على أساس مستدام .
● حل حوادث وطلبات الخدمة : ويقصد به حل حوادث وطلبات الخدمة هو إعادة المستخدمين إلى أسرع وقت ممكن .
● دعم حل الحوادث وطلبات الخدمة : ويقصد به تقديم الدعم لحل الحوادث وطلبات الخدمة، على سبيل المثال عن طريق تكوين الأنظمة لإدارة الحوادث وطلبات الخدمة، وعن طريق الحفاظ على مجموعة من نماذج طلب الخدمة والحوادث .
● تسجيل الحوادث وطلبات الخدمة : ويقصد به تسجيل جميع التفاصيل ذات الصلة بالحوادث وطلبات الخدمة، والتحقق من إعطاء جميع التراخيص المطلوبة، وتحديد أولويات الحوادث أو الطلبات .
● تلبية طلبات الخدمة : وتكون عادة إما طلبات للحصول على معلومات أو طلبات لتنفيذ تغييرات طفيفة (قياسية) مثل إعادة تعيين كلمة المرور .
● إبلاغ المستخدمين والعملاء بشكل استباقى : ويقصد به إبلاغ بإخفاقات الخدمة الفعلية أو الوشيكة بمجرد أن تصبح معروفة لدعم المستوى الأول، بحيث يكون المستخدمون والعملاء فى وضع يمكنهم من التكيف مع الانقطاعات، وتكون هذه العملية مسئولة أيضًا عن توزيع معلومات مهمة أخرى، مثل تنبيهات الأمان الحالية .
● حل الحوادث الكبرى : ويقصد به حل حادث كبير يتسبب فى انقطاعات خطيرة فى الأنشطة التجارية ويجب حلها على وجه السرعة، بهدف استرداد سريع للخدمة، ربما عن طريق حل بديل .
● حل الحوادث فى دعم المستوى الأول : ويقصد به حل حادث (انقطاع الخدمة) ضمن الإطار الزمنى المتفق عليه، ويهدف إلى الاسترداد السريع للخدمة، ربما من خلال تطبيق حل بديل، وبمجرد أن يتضح أن دعم المستوى الأول غير قادر على حل الحادث نفسه عندما يتم تجاوز الأوقات المستهدفة لحل المستوى الأول، يتم نقل الحادث إلى دعم المستوى الثانى .
● حل الحوادث فى دعم المستوى الثانى : ويقصد به حل حادث (انقطاع الخدمة) ضمن الإطار الزمنى المتفق عليه، ويهدف إلى الاسترداد السريع للخدمة، ربما عن طريق حل بديل، وإذا لزم الأمر، قد تشارك دعم مجموعات متخصصة فى هذا الشأن .
● مراقبة الحوادث وطلبات الخدمة المعلقة : ويقصد به المراقبة المستمرة لحالة معالجة الحوادث وطلبات الخدمة، بحيث يمكن التصعيد فى حال كان من المحتمل انتهاك أوقات الحل المتفق عليها .
● إغلاق الحوادث وطلبات الخدمة : ويقصد به تقديم سجلات طلب الخدمة والحادث إلى الرقابة الجودة النهائية قبل الإغلاق، ويهدف إلى التأكد من أن تاريخ الحادث أو طلب الخدمة موصوف بتفاصيل كافية، ويجب تسجيل النتائج المستخلصة من حل الحوادث لاستخدامها فى المستقبل .
● حل المشكلات : ويقصد به إدارة دورة حياة جميع المشكلات، حيث تكون المشكلة هى السبب الكامن وراء واحد أو عدة حوادث (محتملة) . وتهدف هذه العملية إلى منع وقوع حوادث الخدمة وتقليل تأثير حوادث الخدمة التى لا يمكن منعها .
● تحديد المشكلات بشكل استباقى : ويقصد به تحسين التوافر العام للخدمات من خلال تحديد المشكلات بشكل استباقى وتوفير حلول بديلة مناسبة قبل حدوث مزيد من حوادث الخدمة .
● تصنيف المشكلات وترتيبها حسب الأولوية : ويقصد به تسجيل المشاكل وترتيبها حسب الأولوية مع العناية المناسبة، من أجل تسهيل حل سريع وفعال .
● تحليل المشكلات وحلها : ويقصد به تحديد الأسباب الكامنة وراء المشكلات وتحديد أنسب حل للمشكلات وتوفير حل مؤقت إذا لم يتوفر حل كامل .
● مراقبة المشكلات المعلقة : ويقصد به المراقبة المستمرة للمشكلات المعلقة فيما يتعلق بحالة المعالجة الخاصة بها، واتخاذ الإجراءات التصحيحية كما هو مطلوب .
● إغلاق المشاكل : ويقصد به التأكد من أن حل المشكلة كان ناجحًا وأن جميع المعلومات ذات الصلة محدثة .
5- تحسين الخدمات :
● أداء مراجعات تحسين الخدمة : ويقصد به تحديد إمكانيات تحسين الخدمة، ويتضمن ذلك ما إذا كانت جودة الخدمة المقدمة تتماشى مع الالتزامات التعاقدية، وكذلك اكتشاف نقاط الضعف فى طريقة تقديم الخدمة .
● تحديد تحسينات الخدمة : ويقصد به تحديد أهداف مبادرات تحسين الخدمة ونهج تنفيذها، وهذا يشمل إعداد دراسات الجدوى للمبادرات .
● بدء مبادرات تحسين الخدمة : ويقصد به إطلاق مبادرات تحسين الخدمة، ويتضمن ذلك الحصول على إذن من خلال طلب ميزانية وتقديم طلب للتغيير .
● تنفيذ تحسينات الخدمة : ويقصد به تنفيذ واختبار ونشر تحسينات الخدمة، ويتضمن ذلك تحديث تعريفات الخدمة واتفاقيات ذات الصلة .
● مراقبة مبادرات تحسين الخدمة : ويقصد به تقييم ما إذا كانت مبادرات تحسين الخدمة تسير وفقًا للخطة، وإدخال تدابير تصحيحية عند الضرورة .

ثانيًا - العمليات التخطيطية المساندة لدورة الحياة، وتشمل :
1- إعداد وصيانة نظام إدارة الخدمة :
● عمليات التصميم والسياسات : ويقصد به إنتاج تصميمات جديدة أو محدثة لعمليات إدارة الخدمة، والتى يتم تنفيذها عادةً من خلال مبادرات تحسين الخدمة كجزء من مشاريع تطوير الخدمة .
● تنفيذ تحسينات العملية : ويقصد به تنفيذ واختبار ونشر عمليات إدارة خدمة جديدة أو تحسينات على العمليات الحالية، وهذا يشمل تحديث وثائق العملية ذات الصلة .
● مراقبة مبادرات تحسين العملية : ويقصد به تقييم ما إذا كانت مبادرات تحسين العملية تسير وفقًا للخطة، وإدخال تدابير تصحيحية عند الضرورة .
● تشغيل العمليات : ويقصد به ضمان تشغيل العمليات بفعالية وكفاءة، بما يتماشى مع أهداف مقدم الخدمة، ويتضمن ذلك إدارة الموارد اللازمة لتشغيل العملية، بالإضافة إلى إعداد التقارير عن أداء العملية .
● أداء مراجعات العملية : ويقصد به تقديم عمليات إدارة الخدمة إلى مراجعات تدقيق منتظمة، وتحديد إمكانيات التحسين التى يجب معالجتها من خلال مبادرات تحسين العملية .
2- الحفاظ على محفظة الخدمات :
● إضافة خدمات جديدة أو متغيرة إلى محفظة الخدمات : ويقصد به إضافة معلومات حول (مخطط) الخدمات الجديدة أو التى تم تغييرها بشكل ملحوظ إلى مجموعة الخدمات .
● تحديث محفظة الخدمات : ويقصد به تحديث المعلومات فى محفظة الخدمات .
● تنشيط الخدمات الجديدة أو المتغيرة : ويقصد به التحقق من أن الخدمات الجديدة أو التى تم تغييرها بشكل كبير للتشغيل، وللحصول على موافقة رسمية لتنشيط الخدمة .
● مراجعة محفظة الخدمات : ويقصد به إرسال محفظة الخدمات إلى المراجعات المنتظمة، من أجل اكتشاف الأخطاء فى محفظة الخدمة أو التناقضات بين تعريفات الخدمة أو اتفاقيات الخدمة .
3- إدارة علاقات العملاء :
● البحث عن عملاء جدد : ويقصد به تحديد العملاء الجدد المحتملين وتقديم عروض مقدم الخدمة إلى هؤلاء العملاء المحتملين .
● توقيع اتفاقيات خدمة العملاء أو إنهائها : ويقصد به توقيع اتفاقيات خدمة العملاء مع العملاء الذين يرغبون فى استخدام خدمات مقدم خدمة، وتكون هذه العملية مسئولة أيضًا عن إنهاء اتفاقيات خدمة العملاء التى لم تعد مطلوبة .
● معالجة شكاوى العملاء : ويقصد به تسجيل شكاوى العملاء وتقييم ما إذا كانت الشكاوى مبررة وتحديد الخطوات المطلوبة للتعامل مع الشكاوى .
● مراقبة شكاوى العملاء : ويقصد به المراقبة المستمرة لحالة معالجة شكاوى العملاء المعلقة واتخاذ الإجراءات التصحيحية إذا لزم الأمر .
● عقد اجتماعات العملاء : ويقصد به التواصل مع العملاء بشكل منتظم للتعرف على احتياجاتهم وخططهم المستقبلية .
● إجراء استطلاعات رضا العملاء : ويقصد به تخطيط وتنفيذ وتقييم استطلاعات رضا العملاء المنتظمة، ويكون الهدف الرئيسى من هذه العملية هو التعرف على المجالات التى لا يتم فيها تلبية توقعات العملاء قبل فقدان العملاء لمقدمى الخدمات البديلة .
4- إدارة معلومات مكونات التهيئة :
● دعم إدارة معلومات مكونات التهيئة : ويقصد به إعداد وصيانة الأدوات اللازمة لإدارة فعالة لعناصر مكونات التهيئة (Configuration Items) ومعلومات مكونات التهيئة ذات الصلة .
● الحفاظ على نموذج مكونات التهيئة : ويقصد به تحديد الهيكل الأساسى لنموذج مكونات التهيئة (Configuration Model Structure) والحفاظ عليه، بحيث يكون قادرًا على الاحتفاظ بجميع المعلومات حول عناصر مكونات التهيئة، ويتضمن ذلك تحديد سمات أنواعها ومكوناتها الفرعية، بالإضافة إلى أنواع العلاقات المطلوبة بينها .
● التحكم فى عناصر مكونات التهيئة : ويقصد به التأكد من عدم إضافة عناصر مكونات التهيئة أو تعديلها بدون التفويض المطلوب، وأن هذه التعديلات مسجلة بشكل كاف فى نظام إدارة مكونات التهيئة .
● مراجعة التحكم فى عناصر مكونات التهيئة : ويقصد به إجراء فحوصات منتظمة، والتأكد من أن المعلومات الواردة فى نظام إدارة مكونات التهيئة هى تمثيل دقيق لمعلومات عناصر مكونات التهيئة المثبتة بالفعل فى بيئة الإنتاج الحية .
5- تقييم التغييرات والتنسيق لها :
● دعم تقييم التغييرات : ويقصد به إعداد وصيانة الأدوات اللازمة لإدارة التغييرات بفعالية وكفاءة .
● تسجيل ومراجعة "طلبات التغيير" (Request for Changes): ويقصد به تصفية طلبات التغيير التى لا تحتوى على جميع المعلومات المطلوبة للتقييم أو التى لا تعتبر غير عملية .
● تقييم التغييرات الطارئة والتصريح بها : ويقصد به تقييم التغييرات الطارئة والتصريح بها فى أسرع وقت ممكن، ويتم استدعاء هذه العملية إذا كان لا يمكن تطبيق إجراءات تقييم التغيير العادية .
● تقييم التغييرات (مدير التغيير) : ويقصد به تحديد مستوى التفويض المطلوب لتقييم التغيير المقترح، ويتم تمرير تغييرات كبيرة إلى "المجلس الاستشارى للتغيير" (Change Advisory Board) للتقييم، بينما يتم تقييم التغييرات الطفيفة الفور والموافقة عليها من قبل مدير التغيير .
● تقييم التغييرات (المجلس الاستشارى للتغيير) : ويقصد به تقييم التغيير المقترح والتصريح به من خلال المجلس الاستشارى للتغيير، وإذا لزم الأمر، تشارك مستويات أعلى من السلطة (مثل مجلس الإدارة) فى عملية التفويض .
● مراقبة التغييرات المفتوحة : ويقصد به مراقبة التغييرات المعلقة باستمرار فيما يتعلق بحالة تنفيذها واتخاذ الإجراءات التصحيحية حسب الاقتضاء .
● مراجعة وإغلاق التغييرات : ويقصد به تقييم مسار تنفيذ التغيير والنتائج المحققة، من أجل التحقق من وجود تاريخ كامل للأنشطة للرجوع إليها فى المستقبل، وللتأكد من تحليل أى أخطاء والدروس المستفادة .
6- إدارة المشاريع :
● بدء المشاريع : ويقصد به تحديد أصحاب المصلحة والمسؤوليات والموارد المتاحة للمشروع، وتحديد المخاطر والقيود والافتراضات التى تؤثر على المشروع، وينتج عن هذه العملية ميثاق مشروع معتمد .
● تخطيط المشاريع : ويقصد به إنشاء خطة المشروع وتحديثها .
● مراقبة المشاريع : ويقصد به رصد التقدم المحرز فى المشروع واستهلاك الموارد والإبلاغ عنه، وبدء الإجراءات التصحيحية إذا لزم الأمر .
● مراجعة المشاريع وإغلاقها : ويقصد به تقييم مسار المشروع والنتائج المحققة، للتأكد من تحليل أى أخطاء والدروس المستفادة .
7- ضمان الأمن :
● تقييم المخاطر الأمنية : ويقصد به تحديد المخاطر الأمنية التى يجب إدارتها من قبل مقدم الخدمة، وتحديد الاستجابات المناسبة للمخاطر .
● تحديد التحسينات الأمنية : ويقصد به تحديد أهداف مبادرات تحسين الأمن ونهج تنفيذها، ويشمل إعداد دراسات الجدوى للمبادرات .
● بدء مبادرات تحسين الأمان : ويقصد به إطلاق مبادرات تحسين الأمان، ويتضمن ذلك الحصول على إذن من خلال طلب ميزانية وتقديم طلب للتغيير .
● تنفيذ آليات التحكم والضوابط الأمنية : ويقصد به تنفيذ واختبار ونشر آليات تحكم وضوابط أمنية جديدة أو محسنة .
● تشغيل آليات التحكم والضوابط الأمنية : ويقصد به ترتيب تدريب أمنى مناسب لموظفى وعملاء مقدم الخدمة، ولضمان الصيانة والاختبار المنتظمين لآليات التحكم والضوابط الأمنية .
● مراجعة آليات التحكم والضوابط الأمنية : ويقصد به تقديم آليات التحكم والضوابط الأمنية إلى المراجعات المنتظمة، من أجل تحديد إمكانيات التحسين التى يجب معالجتها من خلال مبادرات تحسين الأمن .
8- الاستعداد لأحداث الكوارث :
● تقييم المخاطر المرتبطة بأحداث الكوارث : ويقصد به تحديد أحداث الكوارث التى يجب أن يديرها مقدم الخدمة، وتحديد ترتيبات وآليات الاستمرارية المناسبة .
● تحديد تحسينات الاستمرارية : ويقصد به تحديد أهداف المبادرات لتحسين استمرارية الخدمة ونهج تنفيذها، ويشمل إنشاء دراسات الجدوى للمبادرات .
● بدء مبادرات تحسين الاستمرارية : ويقصد به إطلاق مبادرات تهدف إلى ضمان أو تحسين استمرارية الخدمة، ويتضمن ذلك الحصول على إذن من خلال طلب ميزانية وتقديم طلب للتغيير .
● تنفيذ ترتيبات الاستمرارية : ويقصد به تنفيذ واختبار ونشر آليات وترتيبات استمرارية جديدة أو محسنة .
● تشغيل ترتيبات الاستمرارية : ويقصد به توفير وعى كافٍ لموظفى وعملاء مقدم الخدمة لأحداث الكوارث، ولضمان الصيانة والاختبار المنتظمين لترتيبات وآليات الاستمرارية .
● مراجعة ترتيبات الاستمرارية : ويقصد به تقديم ترتيبات وآليات الاستمرارية للمراجعات المنتظمة، من أجل تحديد إمكانيات التحسين التى يجب معالجتها من خلال مبادرات تحسين الاستمرارية .
9- ضمان الامتثال :
● تحديد متطلبات الامتثال : ويقصد به تحديد متطلبات الامتثال التى يتعين على مزود الخدمة الوفاء بها .
● تحديد ضوابط الامتثال : ويقصد به تحديد تفاصيل الضوابط والآليات التى يجب وضعها للوفاء بمتطلبات الامتثال .
● أداء مراجعات الامتثال : ويقصد به تقديم ضوابط وآليات الامتثال للمراجعات المنتظمة، وتحديد المجالات التى يجب تحسين الامتثال فيها .
10- إدارة الموارد البشرية :
● تحديد المهارات المطلوبة : ويقصد به تحديد المهارات التى تحتاج إلى تطوير، بناءً على تقييم المجموعة الحالية من المهارات والاحتياجات المستقبلية .
● تطوير المهارات المطلوبة : ويقصد به تحديد وتنظيم ومراقبة تدابير التدريب والتعليم .
● تعيين موظفين جدد : ويقصد به اختيار موظفين جدد وتعيينهم بما يتماشى مع متطلبات مهارات مقدم الخدمة .
11- إدارة الموردين :
● إعداد خدمات الدعم الخارجى : ويقصد به إعداد خدمات الدعم الخارجية، ويتم استدعاء هذه العملية أثناء تنفيذ الخدمة إذا كانت هناك حاجة إلى خدمات دعم خارجية لخدمة جديدة أو متغيرة .
● شراء عناصر البنية التحتية : ويتم استدعاء هذه العملية أثناء تنفيذ الخدمة إذا كانت هناك حاجة إلى بنية تحتية جديدة لخدمة جديدة، أو أثناء تشغيل الخدمة إذا كان سيتم شراء قطع الغيار .
● عقد اجتماعات الموردين : ويقصد به التواصل مع الموردين على أساس منتظم من أجل مناقشة أى قضايا تتعلق بأدائهم، لتحديد إمكانيات تحسين التعاون والتعرف على خطط الموردين للمستقبل .
● مراجعة أداء الموردين : ويقصد به مراقبة أداء الموردين، ولا سيما الجهات الراغبة فى تقديم خدمات التعهيد الذين يقدمون أو يقومون بتشغيل الخدمات أو العمليات، ويشمل التحقق ذلك مما إذا كانت أهداف الخدمة والالتزامات التعاقدية الأخرى قد تم الوفاء بها، وكذلك تحديد أسباب عدم المطابقة وفرص التحسين .
● تجديد أو إنهاء اتفاقيات الموردين : ويقصد به التقييم على أساس منتظم ما إذا كانت الاتفاقيات مع الموردين لا تزال ذات صلة قبل تجديد تلك الاتفاقيات، وإنهاء الاتفاقيات التى لم تعد هناك حاجة إليها .
● فحص فواتير الموردين : ويقصد به فحص فواتير الموردين الواردة للتأكد من صحتها قبل إرسالها إلى الإدارة المالية للتسوية .
● التعامل مع نزاعات الموردين : ويقصد به تسجيل نزاعات الموردين وتقييم النزاعات والحجج الأساسية الخاصة بهم، وتحديد الخطوات المطلوبة لحل النزاعات .
● مراقبة نزاعات الموردين : ويقصد به المراقبة المستمرة لحالة معالجة نزاعات الموردين المعلقة واتخاذ الإجراءات التصحيحية إذا لزم الأمر .
12- إدارة الشئون المالية للخدمة :
● الحفاظ على إطار الإدارة المالية : ويقصد به تحديد الأطر اللازمة لإدارة بيانات التخطيط المالى وتكاليفه، وتخصيص التكاليف على الخدمات وعمليات إدارة الخدمة .
● أداء التخطيط المالى : ويقصد به تحديد الموارد المالية المطلوبة خلال فترة التخطيط التالية، وتخصيص تلك الموارد لتحقيق أفضل الفوائد .
● إعداد التقارير المالية : ويقصد به تحليل هيكل تكاليف توفير الخدمة وتقييم ربحية الخدمات، وتعد التقارير المالية الناتجة مدخلاً هامًا لتحسين نطاق خدمات مزود الخدمة .
● إصدار فواتير العميل : ويقصد به إصدار فواتير مقابل الخدمات للعملاء .

---

ملحق (2): إطار عمل إدارة مخاطر التكنولوجيا
(TRM-F: Technology Risk Management Framework)

وهو إطار العمل المنظم لإدارة مخاطر التكنولوجيا (TRM: Technology Risk Management) كعنصر أساسى ومتمم لإدارة مخاطر المؤسسات (ERM: Enterprise Risk Management)، ويتكون إطار عمل المخاطر من العمليات الاستراتيجية على المستوى الاستراتيجى، والعمليات التخطيطية على المستوى التنفيذى، والإجراءات التطبيقية على المستوى التشغيلى، ويتبنى هذا العرض لإطار عمل "إدارة مخاطر التكنولوجيا" مبدأ الرقابة على أساس المخاطر التى تتبناها الهيئة العامة للرقابة المالية، بما يتوافق مع المعايير الدولية لأطر عمل إدارة المخاطر من المعهد الوطنى للمعايير والتكنولوجيا (NIST) لكل من التجهيزات، والبنية التكنولوجية، وأنظمة المعلومات، ووسائل الحماية والتأمين، ويجوز استخدام أفضل الممارسات وأطر العمل العالمية الأخرى، أو تبنى ممارسة بديلة بعد العرض على الهيئة وأخذ موافقة الهيئة على هذه الممارسة البديلة على أن يشمل الضوابط الحاكمة لتوافر التجهيزات والبنية التكنولوجية وأنظمة المعلومات ووسائل الحماية والتأمين من منظور "إدارة مخاطر التكنولوجيا" :

وتنشأ المخاطر الناشئة عن استخدام التكنولوجيا من فشل أو خروقات أنظمة تكنولوجيا المعلومات أو التطبيقات أو المنصات أو البنية التحتية، مما قد يؤدى إلى خسارة مالية أو اضطرابات فى الخدمات أو العمليات المالية غير المصرفية أو الإضرار بسمعة الشركات والجهات المالية غير المصرفية .

وتعزيز قدرتها على الصمود ضد الاضطرابات التكنولوجية للحفاظ على الثقة فى النظام المالى غير المصرفى، ويتطلب التطور المتزايد للتهديدات السيبرانية أيضًا زيادة اليقظة والقدرة على الاستجابة للتهديدات الناشئة . ويجب أن يكون ضمان هذا التوافر المستمر للخدمات الأساسية للعملاء والحماية الكافية لبيانات العملاء، من الأولويات الحرجة للشركات والجهات المالية غير المصرفية .

ويجب على مجلس الإدارة وضع واعتماد "استراتيجية إدارة مخاطر التكنولوجيا" والتى تكون مرتبطة وممتاشية مع "استراتيجية تكنولوجيا المعلومات" ومع البنية الهيكلية لأعمال الأنشطة المالية غير المصرفية، ويكون ذلك من خلال "إطار عمل إدارة مخاطر التكنولوجيا" والذى يكون معتمدًا من مجلس الإدارة وحاكمًا للإدارة التنفيذية وللإدارة التشغيلية . كما يجب على مجلس الإدارة أيضًا مراجعته بشكل دورى مرة واحدة على الأقل كل ثلاث سنوات . ويكون لمجلس الإدارة تشكيل "لجنة إدارة مخاطر التكنولوجيا" التابعة لمجلس الإدارة تكون مسئولة عن الإشراف على تنفيذ إطار عمل إدارة المخاطر والتأكد من ملاءمة دورة العمل والمسئولين عن تنفيذها، والتأكد من الالتزام بالإجراءات المطلوب اتباعها .

ويشمل إطار عمل هذا على 4: عمليات استراتيجية لدورة الحياة للمخاطر (LRP: Life-cycle Risk Process) تشمل "الهيكلة" (Frame) و"التقييم" (Assess) و"المجابهة" (Response) و"المراقبة" (Monitor) للمخاطر، والتى تتكامل مع 7 عمليات استراتيجية لدورة الحياة للأنظمة وآليات التحكم (SCP: Systems & Controls Process) تشمل "التحضير" (Prepare) و"التصنيف" (Categorize) و"الاختيار" (Select) و"التنفيذ" (Implement) و"التقييم" (Assess) و"السماح" (Authorize) و"المراقبة" (Monitor) للأنظمة وآليات التحكم، وتتضمن الأربع عمليات الاستراتيجية لدورة الحياة للمخاطر 12 عملية تخطيطية على المستوى التنفيذى، وتتضمن السبع عمليات الاستراتيجية لدورة الحياة للأنظمة وآليات التحكم 47 عملية تخطيطية على المستوى التنفيذى . وعلى هذا يكون إجمالى العمليات على المستوى الاستراتيجى 11 عملية استراتيجية، كما يكون إجمالى العمليات على المستوى التنفيذى 59 عملية تخطيطية .

1- العمليات الاستراتيجية :

أولاً - العمليات الاستراتيجية لدورة الحياة للمخاطر، وتشمل :
1- الهيكلة للمخاطر (Framing Risk): ويقصد به إصدار استراتيجية إدارة المخاطر التى تتناول كيفية تقييم المخاطر، والاستجابة لها ومراقبتها، وتوضح استراتيجية إدارة المخاطر الافتراضات المحددة ودرجات تحمل المخاطر والأولويات المستخدمين لاتخاذ قرارات الاستثمار والعمليات . وتتضمن إدارة المخاطر أيضًا أى قرارات واعتبارات على المستوى الاستراتيجى حول كيفية إدارة المخاطر التى تتعرض لها العمليات والأصول التنظيمية والأفراد .
2- التقييم للمخاطر (Assessing Risk): ويقصد به تحديد أولويات وتقدير المخاطر على العمليات التنظيمية للأعمال (متضمنة المهمة، والوظائف، والانطباع، والسمعة)، والأصول التنظيمية للأعمال، والأفراد، الناتجة عن تشغيل واستخدام أنظمة المعلومات .
وتتضمن عملية تقييم المخاطر تحديد التهديدات وأوجه الضعف التى يمكن استغلالها، من حيث احتمالية الحدوث والتأثير السلبى المحتمل (أى حجم الضرر) .
3- المجابهة للمخاطر (Responding to Risk): ويقصد به تحديد كيفية مجابهة المخاطر، عن طريق تقييم، وتنفيذ مسارات العمل المناسبة لقبول، أو تجنب، أو تخفيف، أو مشاركة، أو نقل المخاطر على العمليات والأصول التنظيمية والأفراد، والناتجة عن تشغيل واستخدام أنظمة المعلومات .
4- المراقبة للمخاطر (Monitoring of Risk): ويقصد به التحقق من : (1) الامتثال، (2) تحديد الفعالية المستمرة لتدابير الاستجابة للمخاطر، (3) تحديد التغييرات المؤثرة على المخاطر فى أنظمة المعلومات وبيئات التشغيل .
ويعطى تحليل نتائج المراقبة القدرة على الحفاظ على الوعى بالمخاطر التى يتم تكبدها، وتسليط الضوء على الحاجة إلى إعادة النظر فى الخطوات الأخرى فى عملية إدارة المخاطر، وبدء أنشطة العملية تحسين حسب الحاجة .

ثانيًا - العمليات الاستراتيجية لدورة الحياة للأنظمة وآليات التحكم (Systems & Controls Process)، وتشمل :
1- التحضير على المستوى التنفيذى والتشغيلى للأنظمة : ويقصد به تنفيذ عمليات إدارة المخاطر بفعالية وكفاءة، من حيث الجودة والتكلفة، من خلال : (1) تسهيل التواصل بين مجلس الإدارة والإدارة التنفيذية والإدارة التشغيلية، (2) تعزيز تحديد الضوابط المشتركة والحدود الدنيا الأساسية لها على تقليل العبء على الإدارة التنفيذية والإدارة التشغيلية وتكلفة تطوير الأنظمة وحمايتها، (3) تقليل تعقيد البنية التحتية لتكنولوجيا المعلومات من خلال تجميع وتوحيد وتحسين الأنظمة والتطبيقات من خلال هيكلة بنية الأعمال، (4) تحديد وترتيب الأولويات، وتركيز الموارد على الأصول الأعلى قيمة، والتى تتطلب مستويات متزايدة من الحماية .
2- التصنيف للأنظمة (Categorize Systems): ويقصد به إبلاغ عمليات ومهام إدارة المخاطر التنظيمية من خلال تحديد التأثير السلبى على العمليات والأصول والأفراد فيما يتعلق بفقدان السرية والنزاهة وتوافر الأنظمة والمعلومات التى تتم معالجتها وتخزينها ونقلها بواسطة تلك الأنظمة .
3- الاختيار لآليات التحكم (Select Controls): ويقصد به تحديد الضوابط اللازمة لحماية نظام المعلومات والبنية الهيكلية للأعمال، وبما يتناسب مع المخاطر التى تتعرض لها العمليات والأصول التنظيمية والأفراد .
4- التنفيذ لآليات التحكم (Implement Controls): ويقصد به تنفيذ آليات التحكم فى خطط الأمن والخصوصية للنظام والبنية الهيكلية للأعمال وللتوثيق فى ملف إعدادات التهيئة المرجعى .
5- التقييم لآليات التحكم (Assess Controls): ويقصد به تحديد ما إذا كانت آليات التحكم والضوابط المختارة للتنفيذ قد تم تنفيذها بشكل صحيح، وتعمل على النحو المنشود، وتنتج النتيجة المرجوة فيما يتعلق بتلبية متطلبات الأمن والخصوصية للنظام وللبنية الهيكلية للأعمال .
6- السماح للأنظمة (Authorize Systems): ويقصد به توفير المساءلة التنظيمية من خلال مطالبة مسئول الإدارة العليا بتحديد ما إذا كانت مخاطر الأمن والخصوصية (بما فى ذلك مخاطر سلسلة التوريد) للعمليات والأصول التنظيمية أو الأفراد بناءً على تشغيل نظام أو استخدام ضوابط مشتركة، أمر مقبول .
7- المراقبة للأنظمة وآليات التحكم (Monitor Controls): ويقصد به الحفاظ على الوعى المستمر بالحالة الأمنى والخصوصية والنظام المعلومات لدعم قرارات إدارة المخاطر .

2- العمليات التخطيطية :

أولاً - العمليات التخطيطية لدورة الحياة للمخاطر، وتشمل :
1- تحديد الإطار الحاكم للمخاطر (Risk Framing) :
● افتراضات المخاطر : ويقصد به تحديد الافتراضات التى تؤثر على كيفية تقييم المخاطر والاستجابة لها ومراقبتها، متضمنة مصادر التهديد، ونقاط الضعف، والعواقب، والاحتمالات .
● محددات المخاطر : ويقصد به تحديد القيود المفروضة على إجراء تقييم المخاطر والاستجابة وأنشطة مراقبة المخاطر .
● تحمل المخاطر : ويقصد به تحديد مستوى تحمل المخاطر على مستوى البنية الهيكلية للأعمال .
● الأولويات والمفاضلات : ويقصد به تحديد الأولويات والمفاضلات بين البدائل فى إدارة المخاطر .
2- تقييم المخاطر (Risk Assessment) :
● تحديد التهديدات وأوجه الضعف : ويقصد به تحديد التهديدات ونقاط الضعف فى أنظمة المعلومات التنظيمية والبيانات التى تعمل فيها الأنظمة .
● تحديد المخاطر : ويقصد به تحديد المخاطر على العمليات والأصول التنظيمية والأفراد إذا ما تمكنت التهديدات المحددة من استغلال نقاط الضعف المحددة .
3- المجابهة للمخاطر (Responding to Risk) :
● تحديد المجابهة للمخاطر : ويقصد به تحديد مسارات العمل البديلة للاستجابة للمخاطر المحددة أثناء تقييم المخاطر، والتى قد تتضمن قبول المخاطر، وتجنب المخاطر، والتخفيف من حدة المخاطر، وتقاسم المخاطر أو تحويلها .
● تقييم البدائل : ويقصد به تقييم مسارات العمل البديلة للاستجابة للمخاطر .
● اتخاذ قرار الاستجابة للمخاطر : ويقصد به تحديد مسار العمل المناسب للاستجابة للمخاطر .
● تنفيذ الاستجابة للمخاطر : ويقصد به تنفيذ مسار العمل المختار للاستجابة للمخاطر .
4- المراقبة للمخاطر (Monitoring Risk) :
● استراتيجية مراقبة المخاطر : ويقصد به تطوير استراتيجية مراقبة المخاطر والتى تتضمن الغرض من أنشطة المراقبة وأنواعها وتوقيتاتها وتكرارها .
● مراقبة المخاطر : ويقصد به مراقبة أنظمة المعلومات التنظيمية وبيئات التشغيل على أساس مستمر للتحقق من الامتثال، وتحديد فعالية تدابير الاستجابة للمخاطر، وتحديد التغييرات .

ثانيًا - العمليات التخطيطية لدورة الحياة للأنظمة وآليات التحكم، وتشمل :
1- التحضير على المستوى التنفيذى والتشغيلى للأنظمة :
التحضير على المستوى التنفيذى للأنظمة :
● أدوار إدارة المخاطر : ويقصد به تحديد الأفراد وتعيين أدوار رئيسية لتنفيذ إطار عمل إدارة المخاطر .
● استراتيجية إدارة المخاطر : ويقصد به وضع استراتيجية لإدارة المخاطر التنظيمية تتضمن تحديدًا وتعبيرًا عن تحمل المخاطر التنظيمية .
● تقييم المخاطر التنظيمية للأعمال : ويقصد به اكتمال تقييم المخاطر على المستوى التنظيمى للأعمال أو تحديث تقييم المخاطر الحالى .
● الحدود الدنيا الأساسية لآليات التحكم : ويقصد به تحديد وإتاحة الحدود الدنيا الأساسية لآليات التحكم، والتى تكون مخصصة ومتناسقة مع إطار عمل الأمن السيبرانى .
● تحديد آليات التحكم المشتركة : ويقصد به تحديد وتوثيق ونشر آليات التحكم المشتركة المتاحة لأنظمة المعلومات المختلفة .
● تحديد أولويات مستوى التأثير : ويقصد به أن يتم تحديد أولويات أنظمة المعلومات من حيث مستوى التأثير .
● استراتيجية المراقبة المستمرة على المستوى التنفيذى : ويقصد به تطوير وتنفيذ استراتيجية مراقبة لفعالية الرقابة على المستوى التنفيذى للأنظمة .
التحضير على المستوى التشغيلى للأنظمة :
● التركيز على الرسالة والغرض ووظائف الأعمال : ويقصد به تحديد الرسالة والغرض الذى يهدف النظام إلى دعمها .
● أصحاب المصلحة فى النظام : ويقصد به تحديد أصحاب المصلحة الذين لهم مصلحة فى النظام .
● تحديد الأصول : ويقصد به تحديد وترتيب أهمية الأصول لأصحاب المصلحة .
● حدود الحصول على الصلاحية : ويقصد به تحديد الحدود التى يلزم الحصول على صلاحية للدخول من خلالها على النظام .
● أنواع المعلومات : ويقصد به تحديد أنواع المعلومات التى تتم معالجتها وتخزينها ونقلها بواسطة النظام .
● دورة حياة المعلومات : ويقصد به تحديد وفهم جميع مراحل دورة حياة المعلومات لكل نوع من أنواع المعلومات التى يتم معالجتها أو تخزينها أو نقلها بواسطة النظام .
● تقييم المخاطر على المستوى التشغيلى للنظام : ويقصد به اكتمال تقييم المخاطر على مستوى النظام أو تحديث تقييم المخاطر الحالى .
● تعريف المتطلبات : ويقصد به تحديد متطلبات الأمن والخصوصية وتحديد أولوياتها .
● البنية الهيكلية للأعمال : ويقصد به تحديد وضع النظام داخل البنية الهيكلية للأعمال .
● تخصيص المتطلبات : ويقصد به تخصيص متطلبات الأمن والخصوصية للنظام وللبيئة التى يعمل فيها النظام .
● تسجيل النظام : ويقصد به تسجيل النظام لأغراض الإدارة والمساءلة والتنسيق والإشراف .
2- التصنيف للأنظمة (Categorize Systems) :
● وصف نظام : ويقصد به وصف وتوثيق خصائص النظام .
● التصنيف الأمنى : ويقصد به تحديد التصنيف الأمنى للنظام، بما فى ذلك المعلومات التى تتم معالجتها بواسطة النظام، وعلى أن يتم توثيق نتائج التصنيف الأمنى فى خطط الأمن والخصوصية وإدارة مخاطر سلسلة الإمدادات (Supply Chain Risk Management)، وعلى أن تتوافق نتائج التصنيف الأمنى مع البنية الهيكلية للأعمال، وعلى أن تعكس نتائج التصنيف الأمنى استراتيجية إدارة المخاطر المعتمدة .
● مراجعة التصنيف الأمنى والموافقة عليه : ويقصد به مراجعة نتائج التصنيف الأمنى والموافقة على قرار التصنيف من قبل الإدارة العليا .
3- الاختيار لآليات التحكم (Select Controls) :
● اختيار آليات التحكم : ويقصد به اختيار الحدود الدنيا الأساسية لضوابط وآليات التحكم لحماية النظام بما يتناسب مع المخاطر .
● تفصيل آليات التحكم : ويقصد به تفصيل الحدود الدنيا الأساسية لآليات التحكم لحماية النظام بما يتناسب مع المخاطر .
● تخصيص آليات التحكم : ويقصد به وجود منهجية لآليات التحكم المخصصة لنظام، أو مشتركة لمجموعة من الأنظمة، أو مختلطة، وعلى أن يتم تحديد عناصر آليات التحكم (أى عناصر آلية أو فيزيائية أو بشرية) .
● توثيق عمليات تنفيذ التحكم المخطط لها : ويقصد به توثيق آليات التحكم وإجراءات التخصيص المرتبطة بها فى خطط الأمن والخصوصية والمكافحة .
● استراتيجية المراقبة المستمرة للنظام : ويقصد به تطوير استراتيجية مراقبة مستمرة للنظام تعكس استراتيجية إدارة المخاطر .
● مراجعة الخطة والموافقة عليها : ويقصد به مراجعة واعتماد خطط الأمن والخصوصية التى تعكس اختيار آليات التحكم والضوابط اللازمة لحماية النظام وبيئة التشغيل المتناسبة مع المخاطر والموافقة عليها من قبل مسئول إدارة المخاطر التكنولوجية .
4- التنفيذ لآليات التحكم (Implement Controls) :
● تنفيذ آليات التحكم : ويقصد به تنفيذ آليات التحكم والضوابط المحددة فى خطط الأمن والخصوصية النظام .
● تحديث معلومات آليات التحكم : ويقصد به توثيق التغييرات على التنفيذ المخطط لآليات التحكم والضوابط، وعلى أن يتم تحديث خطط الأمن والخصوصية بناءً على المعلومات التى تم الحصول عليها أثناء تنفيذ آليات التحكم والضوابط .
5- التقييم لآليات التحكم (Assess Controls) :
● اختيار المقيم للمهمة : ويقصد به اختيار مقيّم أو فريق تقييم لإجراء تقييمات آليات التحكم، وعلى أن يتم تحقيق المستوى المناسب من الاستقلالية للمقيم أو فريق التقييم المختار .
● خطة التقييم للمهمة : ويقصد به توفير الوثائق اللازمة لإجراء التقييمات للمقيم أو فريق التقييم، وعلى أن يتم تطوير وتوثيق خطط تقييم الأمان والخصوصية، ويتم اعتماد ومراجعة خطط تقييم الأمان والخصوصية لتحديد التوقعات لضمان الرقابة ومستوى الجهد المطلوب .
● تقييمات آليات التحكم : ويقصد به إجراء تقييمات آليات التحكم وفقًا لخطط تقييم الأمن والخصوصية، وعلى أن يتم النظر فى فرص إعادة استخدام نتائج التقييم من التقييمات السابقة لتحسين فعالية عملية إدارة المخاطر من حيث الوقت والتكلفة، وعلى أن يتم تعظيم استخدام التشغيل الآلى automation لإجراء تقييمات آليات التحكم لزيادة سرعة وفعالية وكفاءة التقييمات .
● تقارير تقييم المهام : ويقصد به إصدار تقارير تقييم الأمن والخصوصية التى توفر النتائج والتوصيات .
● إجراءات المعالجة : ويقصد به اتخاذ إجراءات تصحيحية لمعالجة أوجه القصور فى آليات التحكم والضوابط المطبقة وبيئة التشغيل، وعلى أن يتم تحديث خطط الأمن والخصوصية لتعكس آليات التحكم التنفيذ التى تم إجراؤها بناءً على التقييمات وإجراءات العلاج اللاحقة .
● خطة العمل ومخرجات محددة : ويقصد به وضع خطة عمل محددة ومخرجات محددة من خطط العلاج المقترحة للمخاطر غير المقبولة بناءً على تقارير تقييم الأمن والخصوصية .
6- السماح للأنظمة (Authorize Systems) :
● متطلبات ومرفقات السماح : ويقصد به تحديد متطلبات والمرفقات اللازم توفيرها وتقديمها للمسئول للموافقة على السماح للنظام أو لآليات التحكم بالتشغيل فى البيئة الإنتاجية .
● تحليل المخاطر وتحديدها : ويقصد به تقديم تحديد المخاطر للمسئول المفوض المخاطر إدارة استراتيجية يعكس بما ذلك تحمل المخاطر .
● الاستجابة للمخاطر : ويقصد به توفير استجابات للمخاطر، بناءً على المخاطر المحددة .
● قرار السماح : ويقصد به اتخاذ قرار الموافقة على أو رفض طلب السماح الخاص بالنظام أو آليات التحكم العامة .
● تقرير السماح : ويقصد به الإبلاغ عن قرارات السماح ونقاط الضعف الكبيرة والمخاطر للإدارة العليا .
7- المراقبة للأنظمة وآليات التحكم (Monitor Controls) :
● تغييرات النظام والبيئة : ويقصد به مراقبة نظام المعلومات وبيئة التشغيل وفقًا لاستراتيجية المراقبة المستمرة .
● التقييمات الجارية : ويقصد به إجراء التقييمات المستمرة لفعالية الرقابة وفقًا لاستراتيجية المراقبة المستمرة .
● الاستجابة للمخاطر المستمرة : ويقصد به تحليل مخرجات أنشطة المراقبة المستمرة والاستجابة لها بشكل مناسب .
● تحديثات متطلبات ومرفقات السماح : ويقصد به تحديث وثائق إدارة المخاطر بناءً على أنشطة المراقبة المستمرة .
● الإبلاغ عن الأمن والخصوصية : ويقصد به إيجاد عملية للإبلاغ عن وضع الأمن والخصوصية للمسئول المفوض وغيره من الإدارة العليا .
● السماح المستمر : ويقصد به قيام مسئولى السماح للأنظمة وآليات التحكم على استخدام نتائج أنشطة المراقبة المستمرة والإبلاغ عن التغييرات فى تحديد المخاطر وقرارات القبول .
● التخلص من نظام : ويقصد به تطوير وتنفيذ استراتيجية للتخلص من النظام، حسب الحاجة .

