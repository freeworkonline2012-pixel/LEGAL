ملحق رقم (2): تقنيات السجل الرقمي

1- يجوز تطبيق السجل الرقمى بناءً على تقنية "مجموعة القيود الموزعة"، أو "تقنية سلسلة الكتل" فى إدارة سجلات مقدمى الخدمات المالية غير المصرفية، بما فى ذلك سجلات التعرف على العميل، ويكون ذلك بعد الحصول على موافقة الهيئة مع تخصيص "منسق عام" لكل "سجل موزع" وهو المسئول عن إشراك أصحاب صلاحية التعامل التقنى فى المنظومة لتحديد احتياجات كل منهم والعمل بشكل قاطع على حلها والذى قد يتم تنفيذه من خلال "تقنية سلسلة الكتل" كنوع من أنواع السجلات الموزعة.

2- تتطلب تقنية "مجموعة القيود الموزعة" شبكة وحدات حسابية وتخزينية من نظير إلى نظير وخوارزميات لتحقيق الاتفاق أو الإجماع بحيث يتم تكرار نسخ "مجموعة القيود" بشكل موثوق عبر وحدات الشبكة الموزعة.

3- يكون نظام "مجموعة القيود الموزعة" هو قاعدة بيانات رقمية مُستخدم لتخزين المعلومات على وحدات حسابية وتخزينية موزعة ومنتشرة عبر شبكة النظائر. ويكون لكل وحدة مشاركة نسخة فى نظام "مجموعة القيود الموزعة" سلطة متساوية التأثير، ويجب الحصول على موافقة بالإجماع من جميع الوحدات المشاركة. وعندما توافق الوحدات على إجراء التغييرات ويتم إجراء هذه التغييرات، تتلقى كل وحدة فى الشبكة اللامركزية تلقائيًا التحديثات التى تم إجراؤها على قاعدة البيانات.

4- يكون نظام الكتل المسلسلة "قاعدة بيانات" لمعاملات رقمية غير مركزية، ومكررة النسخ للمعاملات الرقمية "متفق عليها" من قبل أعضاء الشبكة النظائر، وتختص تقنية "سلسلة الكتل" بأن هيكل البيانات يتخذ شكل كتل كل كتلة تكون مسلسلة زمنيًا، ومؤمنة رياضيًا باستخدام شفرة مستنبطة من معلومات المعاملة الرقمية السابقة.

5- يكون نظام الكتل المسلسلة عام، أو خاص، أو بدخول بناءً على إذن، أو بدون إذن، وقد يكون مرتبطًا بأصول مشفرة ذات مشاركة مرمزة، أو غير مرمزة.

