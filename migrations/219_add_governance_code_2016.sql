يقوم مركز المديرين المصري منذ إنشاءه عام 2003، بإصدار الأدلة الاسترشادية لتطبيقات حوكمة الشركات طبقاً لأفضل الممارسات الدولية وبما يتماشى مع كافة القوانين المنظمة لعمل الشركات داخل جمهورية مصر العربية.

أصدر المركز عام 2005 أول دليل لحوكمة الشركات يتناول بصفة أساسية الشركات المقيدة لها أوراق مالية بالبورصة لمساعدتها على الالتزام بمتطلبات الحوكمة والإفصاح، بما يعود عليها وعلى كافة مساهميها والمتعاملين معها بالنفع، وبما يساهم أيضاً في تحقيق أعلى معدلات الكفاءة والاستدامة المرجوة لها.

ثم في عام 2006 أصدر المركز دليل حوكمة شركات قطاع الأعمال العام، نظراً لما لهذا القطاع العريض من أهمية كبرى في الاقتصاد القومي المصري، حيث يحتوي على مجموعة شركات كبيرة تعمل في كافة الصناعات الإستراتيجية بالدولة. وجاء هذا الدليل ليعزز من دور الدولة كمالك لهذا القطاع ويدعم نظم رقابته ويضمن كفاءة تشغيله.

وفي عام 2011 قام المركز بتحديث دليل حوكمة الشركات المقيدة لها أوراق مالية بالبورصة بما يتماشى مع معدلات تطبيق الحوكمة في ذلك الوقت حرصاً منه على مواكبة أفضل ممارسات الحوكمة على المستويين الدولي والإقليمي فيما يخص دور مجالس الإدارة. كما أوصى بتفعيل نظم الرقابة المختلفة بالشركات وتطرق لدور الشركات في مجال المسئولية الاجتماعية وحماية البيئة فضلاً عن التوصية بإتباع قاعدة الالتزام أو التفسير.

الجديد في هذا الإصدار من الدليل المصري لحوكمة الشركات

عمل مركز المديرين المصري على تطوير وتحديث الأدلة السابقة ودمجها جميعاً في هذا الدليل تحت عنوان "الدليل المصري لحوكمة الشركات" وذلك على النحو التالي:

أولاً: أضفى صفة العمومية والشمولية على النسخة الأخيرة من الدليل مستوعباً في ذلك أحدث ما توصل إليه العالم على المستويين الدولي والإقليمي في مجال الحوكمة، ومخاطباً كافة أنواع الشركات في مصر كل منها بحسب طبيعتها وحجمها وبطريقة تسمح لها جميعاً بتطبيق ما يتناسب معها من قواعد الحوكمة وكذلك بشكل يمكنها من وضع خطط مستقبلية لاستيعاب ما ينقصها من القواعد على المدى المتوسط والطويل لاستكمال تطبيقها مع معدلات نمو حجمها.

ثانياً: قدمه كدليل استرشادي لكافة الجهات التشريعية والرقابية لأخذه في الاعتبار عند سن وتحديث التشريعات والتعليمات الرقابية ذات الصلة بحوكمة الشركات داخل جمهورية مصر العربية.

وفيما يلي عرض سريع لما تم تحديثه وتطويره بهذا الإصدار من الدليل المصري لحوكمة الشركات:

أ. إرساء منهجية عامة في تقديم دليل الحوكمة، توضح ضرورة وجود دليل متطور لحوكمة الشركات في مصر وأهمية دور الدولة وحكومتها ومؤسساتها في دعم فكر وتطبيقات الحوكمة.

ب. إيضاح أهمية الحوكمة بشكل متفرد وتأكيد المزايا التي تعود على الشركات من تطبيقها.

ج. التحديد بشكل واضح لنطاق تطبيق تلك القواعد ودرجة تماشيها مع طبيعة وحجم كل شركة.

د. إيلاء أهمية خاصة لقاعدة "الالتزام أو التفسير" كقاعدة جوهرية تمهد لفرض القواعد بشكل إلزامي.

ه. التوسع في التعريف بالمفاهيم والمصطلحات المستخدمة في الدليل بما يعزز من زيادة استيعاب وفهم المستخدمين لمحتوياته.

و. التأكيد على دور الجمعية العامة للمساهمين في اختيار مجلس إدارة كفء لتحقيق أهداف الشركة.

ز. إفراد أهمية أكبر لدور مجلس الإدارة باعتباره أهم عنصر من عناصر إدارة وتوجيه الشركة، فضلاً عن مسئوليته الرئيسية في تطبيق الحوكمة، فتعرض الدليل إلى المزيج الأمثل لأعضاء مجلس الإدارة من حيث نوعية الأعضاء ومسئولياتهم، وكذلك استعرض مختلف أنواع اللجان المنبثقة عن مجلس الإدارة لمعاونته في أداء عمله.

ح. تناول دور أمين سر مجلس الإدارة ومسئولياته داخل الشركة بشكل وافي وطبقاً لأفضل الممارسات الدولية.

ط. التركيز بشكل أكبر على مكونات البيئة الرقابية وما لها من أهمية كبيرة داخل أي شركة بداية من نظام الرقابة الداخلية مروراً بإدارة المراجعة الداخلية وإدارة المخاطر وإدارة الالتزام والتوصية بوجود إدارة لحوكمة الشركات داخل كل شركة.

ك. إفراد أهمية خاصة لمراقبي الحسابات في ضوء ما يقومون به من دور هام.

ل. إلقاء المزيد من الضوء على دور نشاط علاقات المستثمرين داخل الشركات المقيدة لها أوراق مالية بالبورصة.

م. تناول سبل وأدوات الإفصاح المختلفة، وعزز من أهمية الإفصاح غير المالي موضحاً المعلومات الجوهرية الواجب الإفصاح عنها عبر التقارير الدورية المختلفة.

ن. وأخيراً استعراض كافة السياسات والمواثيق والأدلة الواجب على كل شركة صياغتها وتطبيقها لتنظيم عملها الداخلي فيما يخص الحوكمة.

ويهدف هذا الدليل إلى دعم كافة الشركات الراغبة في فهم وتطبيق الحوكمة كمنهج متكامل نحو النمو والاستدامة، تحقيقاً لرسالة وإستراتيجية مركز المديرين المصري بما يعود بالنفع على الشركات وعلى الاقتصاد القومي بشكل عام.

1/1 الدليل المصري لحوكمة الشركات
_الموضع: الباب الأول — الإطار العام لحوكمة الشركات_

يعد "الدليل المصري لحوكمة الشركات" بمثابة الإطار العام المتكامل للحوكمة وموضوعاتها ذات الصلة، ويضم مجموعة من القواعد الاسترشادية عن حوكمة الشركات طبقاً لأفضل الممارسات الدولية والإقليمية تستخدم كدليل استرشادي لتطبيق الحوكمة في كافة أنواع الشركات داخل جمهورية مصر العربية، ويسترشد بها كذلك في سن التشريعات والتعليمات الرقابية الخاصة بتطبيقات الحوكمة. ويأتي هذا الدليل بما لا يتعارض مع قانون شركات المساهمة رقم 159 لسنة 1981 ولائحته التنفيذية وقانون سوق رأس المال رقم 95 لسنة 1992 ولائحته التنفيذية وقواعد قيد وشطب الأوراق المالية بالبورصة المصرية التي تصدر عن مجلس إدارة الهيئة العامة للرقابة المالية.

1/2 دور الدولة والجهات التشريعية والرقابية
_الموضع: الباب الأول — الإطار العام لحوكمة الشركات_

للدولة متمثلة في حكومتها والجهات التشريعية والرقابية بها دور رئيسي في اتخاذ توجه واضح لتطوير المنظومة التشريعية لحوكمة الشركات بشكل تدريجي وموضوعي يسمح بتطبيق كافة القواعد الواردة في هذا الدليل على كافة أنواع الشركات بالدولة كلٍ بحسب حجمها وطبيعة عملها، وكذلك مساندة ودعم القائمين على الترويج ونشر الوعي بثقافة وتطبيقات الحوكمة. كل ذلك بهدف الوصول إلى الغاية الأساسية وهي أن تشهد مصر ارتقاءً في مستوى تطبيق قواعد الحوكمة بطرق صحيحة تجني كافة الجهات ثمارها المتمثلة في ترسيخ فكر الإدارة الرشيدة وزيادة معدلات الشفافية والإفصاح والحد من الفساد والمعاملة العادلة لكافة المستثمرين ولاسيما حماية حقوق صغار المستثمرين.

1/3 مفهوم حوكمة الشركات
_الموضع: الباب الأول — الإطار العام لحوكمة الشركات_

حوكمة الشركات بصورة عامة هي مجموعة من الأسس والمبادئ والنظم التي تحكم العلاقة بين مجلس الإدارة من ناحية وبين ملاك الشركة والأطراف الأخرى المتعاملة معها من ناحية أخرى، بهدف تحقيق أفضل حماية وتوازن بين مصالح كل تلك الأطراف.

1/4 أهداف ومزايا تطبيق حوكمة الشركات
_الموضع: الباب الأول — الإطار العام لحوكمة الشركات_

على الشركات المصرية أن تسعى إلى تطبيق قواعد الحوكمة والالتزام بها ليس امتثالاً للقوانين والتعليمات الرقابية فحسب، ولكن أيضاً لما تحققه الحوكمة من منافع عديدة فضلاً عن تطوير مناخ الاستثمار وزيادة النمو الاقتصادي بشكل عام.

وتتسم حوكمة الشركات بالقابلية للتطبيق، ومزاياها عديدة منها على سبيل المثال لا الحصر:

• حماية الحقوق بشكل مطلق، مثل حماية حقوق المساهمين أو ملاك الشركة، وحقوق العاملين بها، وأيضاً حقوق المتعاملين مع الشركة مثل العملاء والدائنين والموردين وأجهزة الدولة، حتى تمتد لحماية المجتمع ككل والبيئة التي تعمل فيها الشركة.

• تحقيق أفضل معدلات استدامة ممكنة للشركات.

• تحسين كفاءة التشغيل ودعم الرقابة على الأداء.

• توفير التمويل وتخفيض تكلفة رأس المال.

• الحد من تأثير المخاطر والأزمات.

• العمل على تجنب تعارض المصالح عند تعاملات الداخليين والأطراف ذوي العلاقة.

• مساعدة الشركات العائلية للتحول للشكل المؤسسي.

ومن خلال تطبيق الحوكمة، فإن شركات المساهمة المغلقة سيصبح من السهل عليها قيد أوراقها المالية بالبورصة، الأمر الذي يستوجب انتباه مساهميها وإداراتها إلى ضرورة متابعة تطبيق الحوكمة تمهيداً واستعداداً للقيد في سوق الأوراق المالية. فالتأهيل السليم للطرح العام أو القيد في البورصة يأتي عن طريق تطبيق مبادئ الحوكمة مقدماً بشكل سليم.

وحوكمة الشركات ثقافة لابد وأن تنبع من الشركة ذاتها، ويجب اتخاذها كرؤية وإستراتيجية طويلة المدى يتم تطبيقها بشكل مستدام وليس فقط في الأجل القصير. وعلى ذلك فإن الدور المنتظر من كافة القائمين على إدارة الشركات والمؤسسات المالية والجمعيات المهنية وجمعيات رجال الأعمال والمستثمرين الأفراد والمؤسسات فضلاً عن الجهات الرقابية والتشريعية هو نشر ثقافة حوكمة الشركات والترويج لها ووضع هذه القواعد موضع التطبيق واعتبار تطبيق الشركات للحوكمة أحد علامات نجاحها وتميزها.

1/5 نطاق التطبيق
_الموضع: الباب الأول — الإطار العام لحوكمة الشركات_

مع عدم الإخلال بكافة التشريعات والتعليمات الرقابية المنظمة لعمل جميع الشركات داخل جمهورية مصر العربية، تنطبق هذه القواعد على الشركات المقيدة وغير المقيدة لها أوراق مالية في البورصة، والمؤسسات المالية المصرفية وغير المصرفية، والشركات الصناعية والتجارية والخدمية بغض النظر عن حجمها وطبيعة نشاطها سواء كانت شركات عائلية أو مملوكة ملكية عامة.

ويرتبط بما سبق أيضاً أن حوكمة الشركات على النحو السليم لا تعنى فقط مجرد الالتزام بمجموعة من القواعد وتفسيرها تفسيراً ضيقاً وحرفياً، وإنما هي ثقافة وأسلوب في ضبط العلاقة بين ملاك الشركة ومجلس إدارتها والمتعاملين معها، ولذلك فكلما اتسع نطاق من يأخذون بتطبيقات الحوكمة كلما كانت المصلحة أكبر للمجتمع بأسره.

1/6 قاعدة "الالتزام أو التفسير" (Comply or Explain)
_الموضع: الباب الأول — الإطار العام لحوكمة الشركات_

بما لا يتعارض مع إلزامية القوانين والتعليمات الرقابية، فإن الأصل أن تقوم الشركة بالعمل على تطبيق كافة القواعد الواردة بهذا الدليل. فإن لم تستطع تطبيق بعض القواعد لأي سبب من الأسباب، فعليها تفسير ذلك بشكل موضوعي ومقبول، إعمالاً لقاعدة "الالتزام أو التفسير". وعلى كل شركة أن تعد جدولاً بكل القواعد الواردة في هذا الدليل وما تلتزم به منها وما لا تلتزم به ومبررات عدم الالتزام، وكذلك خطتها المستقبلية للتطبيق. وتفصح عن هذا التقرير على موقعها الإلكتروني وفي التقرير السنوي المعد لمساهميها.

1/7 مرجعيات إعداد الدليل المصري لحوكمة الشركات
_الموضع: الباب الأول — الإطار العام لحوكمة الشركات_

اعتمد مركز المديرين المصري في إعداد وتطوير هذا الدليل على مرجعيات عديدة، لعل من أبرزها مبادئ منظمة التعاون الاقتصادي والتنمية OECD الصادرة عام 1999، وتعديلاتها الصادرة عام 2004، وكذلك التعديلات الأخيرة لها الصادرة عام 2015 بالمبادئ الستة الأساسية التي تمثل مرجعية عامة لحوكمة الشركات في العالم وهي على سبيل الحصر:

1. الإطار العام: ضرورة التأكد من وجود إطار عام فعال لحوكمة الشركات يضمن كفاءة وشفافية الأسواق والالتزام بالتشريعات والقوانين، وينص بوضوح على ضرورة تحديد المسئوليات ما بين الجهات التشريعية والرقابية المختلفة.

2. الحقوق والمعاملة المتكافئة للمساهمين: يجب أن يكفل إطار حوكمة الشركات حماية كافة حقوق المساهمين والمعاملة المتكافئة بينهم، ومن بينهم صغار المساهمين والمساهمين الأجانب، كما ينبغي أن تتاح لكافة المساهمين فرصة الحصول على تعويض فعلي في حالة انتهاك حقوقهم.

3. دور المستثمر المؤسسي والأطراف المختلفة بأسواق المال: يجب أن يوفر الإطار العام لحوكمة الشركات محفزات اقتصادية للمستثمر المؤسسي والأطراف المختلفة بأسواق المال خلال دورة الاستثمار لضمان كفاءة إدارة أسواق المال والتطبيق الأمثل لحوكمة الشركات.

4. دور أصحاب المصالح: يجب أن يتضمن إطار حوكمة الشركات الاعتراف بحقوق أصحاب المصالح كما يرسيها القانون، وأن يعمل أيضاً على تشجيع التعاون بين الشركات وبين أصحاب المصالح المختلفة بهدف تعظيم الثروات وخلق فرص العمل وتحقيق الاستدامة للمشروعات القائمة على أسس مالية سليمة.

5. الإفصاح والشفافية: ينبغي أن يكفل إطار حوكمة الشركات الإفصاح الدقيق وفي الوقت المناسب بشأن الأمور الهامة التي يترتب عليها أحداث جوهرية، والخاصة بالشركة وموقفها المالي وأدائها وهيكل ملكيتها وكذلك أسلوب ممارسة الإدارة بها.

6. مسئوليات مجلس الإدارة: يجب أن يتيح إطار حوكمة الشركات الخطوط الإرشادية والإستراتيجية لتوجيه الشركات، كما يجب أن يكفل المتابعة الفعالة للإدارة التنفيذية من قبل مجلس الإدارة وأن يضمن مسائلة مجلس الإدارة من قبل الشركة والمساهمين.

كذلك استرشد مركز المديرين المصري ببعض المرجعيات الأساسية لتحديث هذا الدليل منها ما يلي:

• تقرير لجنة كادبوري الصادر بالمملكة المتحدة عام 1992.

• منهجية حوكمة الشركات الصادرة عن مؤسسة التمويل الدولية بمجموعة البنك الدولي.

• تعليمات حوكمة البنوك الصادرة عن البنك المركزي المصري عام 2011.

• المبادئ الصادرة عن المنظمة الدولية لهيئات الأسواق المالية IOSCO.

• قواعد قيد وشطب الأوراق المالية بالبورصة المصرية الصادرة عن الهيئة العامة للرقابة المالية في يناير 2014 وتعديلاتها.

• التعليمات الرقابية المختلفة والخاصة بحوكمة الشركات الصادرة عن الهيئة العامة للرقابة المالية.

كما تم الأخذ في الاعتبار أفضل الممارسات الدولية والإقليمية وتجارب الدول المختلفة في تطبيق حوكمة الشركات كركائز أساسية في تطوير منظومة الحوكمة داخل جمهورية مصر العربية.

1/8 التعريفات
_الموضع: الباب الأول — الإطار العام لحوكمة الشركات_

• الجمعية العامة: هي التجمع الذي يضم كل ملاك الشركة أو حملة أسهمها.

• مساهمو الأقلية وصغار المساهمين: هم حملة الأسهم الذين يمتلكون نسبة غير مؤثرة من رأس مال الشركة.

• الأطراف والمجموعات المرتبطة: هي كل مجموعة تكون خاضعة للسيطرة الفعلية من قبل الأشخاص الطبيعيين أو الاعتباريين من مساهمي الشركة أو يجمع بينهم اتفاق على التنسيق عند التصويت في اجتماعات الجمعية العامة للشركة أو في مجلس إدارتها.

• السيطرة أو التحكم: كل وضع أو اتفاق أو ملكية لأسهم أو حصص أياً كانت نسبتها تؤدي إلى التحكم في تعيين أغلبية أعضاء مجلس الإدارة أو تؤثر في القرارات الصادرة عنه أو عن الجمعية العامة للشركة.

• مجلس الإدارة: هو السلطة المسئولة عن وضع الأهداف والاستراتيجيات ومتابعة أداء إدارة الشركة طبقاً لنظامها الأساسي.

• رئيس مجلس الإدارة: هو عضو مجلس الإدارة الذي يختاره أعضاء المجلس من بينهم ليرأس اجتماعات المجلس، ويكون الممثل القانوني للشركة.

• العضو المنتدب: هو عضو مجلس الإدارة الذي ينتدبه المجلس ليقوم بالإدارة الفعلية للشركة، ويعتلي هرم السلطة التنفيذية بها، ويحدد مجلس الإدارة اختصاصاته ومكافأته.

• الرئيس التنفيذي: هو الشخص الذي يتم تعيينه من قبل مجلس الإدارة ليقوم بتنفيذ كافة الأعمال اليومية للشركة، ويخضع للإشراف المباشر من العضو المنتدب للشركة، ويحدد مجلس الإدارة اختصاصاته وصلاحياته ومخصصاته وتفويضاته في التوقيع عن الشركة، كما يحدد المجلس راتبه الشهري أو السنوي الذي يتقاضاه.

• عضو مجلس الإدارة التنفيذي: هو عضو مجلس الإدارة الذي يشغل منصباً تنفيذياً في الشركة.

• عضو مجلس الإدارة غير التنفيذي: هو عضو مجلس الإدارة الذي لا يشغل منصباً تنفيذياً في الشركة ولا يتقاضى راتباً شهرياً أو سنوياً منها بخلاف ما يتقاضاه عن عضويته بمجلس الإدارة، ولا يجوز له أن يقدم أي استشارات أو خدمات مدفوعة الأجر سواء للشركة أو شركاتها التابعة أو الأطراف المرتبطة بها.

• عضو مجلس الإدارة المستقل: هو عضو غير تنفيذي بمجلس الإدارة وغير مساهم بالشركة ويتم تعيينه كعضو من ذوي الخبرة، تنحصر علاقته بالشركة في عضويته بمجلس إدارتها. وهذا العضو لا يمثل الملاك وليس له تعاملات جوهرية مع الشركة ولا يتقاضى منها أجراً أو عمولات أو أتعاب باستثناء ما يتقاضاه مقابل عضويته بمجلس الإدارة. وليس له مصلحة خاصة بالشركة، كما لا تربطه صلة نسب أو قرابة بأيٍ من مساهميها، أو أعضاء مجلس إدارتها، أو قياداتها التنفيذية حتى الدرجة الثانية. وهو أيضاً ليس من كبار العاملين بالشركة أو مستشاريها أو مراقبي حساباتها خلال الثلاث سنوات السابقة على تعيينه في المجلس، كما يجب ألا تتجاوز مدة عضويته كمستقل بالمجلس ست سنوات متتالية كحد أقصى وإلا أصبح عضواً غير مستقل.

• لجان مجلس الإدارة: هي لجان منبثقة عن مجلس الإدارة يشكلها المجلس من بين أعضائه بهدف مساعدته في انجاز مهامه، ويقوم المجلس بتحديد صلاحياتها واختصاصاتها ومتابعة أعمالها للتأكد من فعالية دورها.

• أمين سر مجلس الإدارة: هو الشخص المسئول عن الإعداد والتنسيق لاجتماعات مجلس الإدارة ولجانه وكذلك اجتماعات الجمعية العامة، وتسجيل محاضر الاجتماعات وتوثيقها ومتابعة تنفيذ القرارات المتخذة، ويعمل أيضاً كمستشار لجميع أعضاء المجلس فيما يخص تطبيقات الحوكمة ودون تعارض مع دور الإدارات المعنية الأخرى.

• إدارة علاقات المستثمرين: هي إدارة إستراتيجية تجمع بين مهارات علم التمويل، والاتصال الفعال، والتسويق، ومعرفة القوانين الخاصة بأسواق المال للوصول إلي طريقة اتصال فعالة متبادلة بين الشركة وكل من مجتمع الاستثمار والأطراف المهتمة بالشركة للوصول إلي تقييم عادل للورقة المالية.

• أصحاب المصالح: كل من لهم مصالح مرتبطة بالشركة على اختلاف أنواعها مثل العاملين بالشركة والعملاء والموردين والموزعين والدائنين والجهات الرقابية.

• الداخليين: يقصد بهم كبار المديرين بالشركة وأعضاء مجلس إدارتها وأعضاء مجالس إدارات شركاتها المرتبطة وممثليهم وأزواجهم وأولادهم القصر، وكذلك كل من في إمكانه الحصول أو الاطلاع على أياً من المعلومات الداخلية للشركة.

• الأطراف ذات العلاقة: يقصد بهم كل من تربطهم بالشركة علاقة مباشرة أو غير مباشرة تتيح لهم التأثير على قرارات الشركة سواء كانت تلك العلاقة من خلال مواقعهم في الشركة أو الشركات المرتبطة بها أو امتلاكهم نسبة مؤثرة من أسهم الشركة أو الشركات المرتبطة بها.

• عقود المعاوضة: هي عقود تبرم بين الشركة وبين أعضاء مجلس إدارتها أو المساهمين الرئيسيين بها، وتأخذ موافقة الجمعية العامة على تلك العقود قبل تنفيذها.

• التصويت التراكمي: هو أسلوب تصويت يستخدم في الجمعية العامة للمساهمين، ويتيح لكل مساهم عدد من الأصوات يساوي عدد الأسهم التي يمتلكها بحيث يمكنه التصويت بها كلها لصالح مرشح واحد أو توزيعها بين من يختارهم من المرشحين دون حدوث تكرار لهذه الأصوات مما يتيح فرصة أكبر لتمثيل صغار المساهمين في مجلس إدارة الشركة.

• المسئولية الاجتماعية والبيئية للشركات: هي الالتزام المستمر من قبل الشركة في المساهمة في التنمية الاقتصادية والاجتماعية بما يحث على العمل بطريقة مسئولة تجاه جميع أصحاب المصالح والمجتمع الذي تعمل فيه الشركة وتأثيرها على البيئة المحيطة بها.

