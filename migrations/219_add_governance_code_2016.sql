هو الشخص الذي يعتلي قمة الإدارة التنفيذية العليا في الشركة، وفيما يلي عرض لبعض مسئولياته ومهامه في ضوء الصلاحيات الممنوحة له من مجلس الإدارة:

• تنفيذ الإستراتيجية وخطة الشركة السنوية الموضوعة والمعتمدة من مجلس الإدارة.

• رئاسة العمل التنفيذي بالشركة وتصريف أمورها اليومية، والإشراف على سير العمل في جميع إدارات وأقسام الشركة ومتابعة الأداء لجميع الأنشطة، واتخاذ ما يراه من قرارات لانتظام العمل وتحقيق الأهداف، وكذلك العمل على زيادة رضاء العملاء عن الشركة.

• العمل على تنفيذ كافة السياسات واللوائح والنظم الداخلية للشركة والمعتمدة من مجلس الإدارة.

• اقتراح الموضوعات التي تطرح في الاجتماعات الدورية لمجلس الإدارة بالتشاور مع رئيس المجلس.

• الإشراف على إعداد التقارير الدورية المالية وغير المالية عن نتائج أعمال الشركة وتقييم أداءها، وكذلك تقرير حوكمة الشركات، ومراجعة كافة الردود على استفسارات مراقبي الحسابات قبل إعداد هذه التقارير.

• المشاركة الفعالة في بناء وتنمية ثقافة القيم الأخلاقية داخل الشركة واقتراح نظم الإثابة والتحفيز وآليات تتابع السلطة التي يعتمدها المجلس لضمان ولاء العاملين وتعظيم قيمة الشركة.

• تحديد اختصاصات ومسئوليات كافة العاملين بالشركة وفقاً للوائح العمل المعمول بها وقرارات مجلس الإدارة.

2/2/6 دور أمين سر مجلس الإدارة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/2 المحور الثاني: مجلس الإدارة_

يعتبر منصب أمين سر مجلس الإدارة من المناصب الحيوية والمؤثرة في الشركة، ويجوز للشركة تشكيل وحدة تنظيمية لأمانة السر. ولا يقتصر دور أمين السر على تدوين محاضر الاجتماعات فحسب، بل يتجاوز ذلك ليمتد لتكوين رابطة مستمرة بين أعضاء المجلس ببعض وبينهم وبين إدارة الشركة، وأيضاً يكون مصدراً للمعلومات التي يطلبونها. ويجب أن يمنحه مجلس الإدارة الصلاحيات اللازمة للقيام بعمله بكفاءة وتدريبه عليها بشكل مستمر.

ويفضل أن يكون أمين السر موظفاً على درجة وظيفية مناسبة تمكنه من لعب دور المحرك والوسيط بين أعضاء المجلس والإدارة العليا للشركة ومن ضمن مهامه على سبيل المثال ما يلي:

• الإعداد والتحضير وإدارة لوجستيات اجتماعات المجلس واللجان، ومعاونة رئيس المجلس في إعداد جدول أعمال الاجتماعات، وتحضير المعلومات والبيانات والتفاصيل الخاصة بهذه الموضوعات وارسالها إلى الأعضاء قبل الاجتماع بوقت كافي.

• معاونة رئيس المجلس في الإعداد والتحضير لاجتماعات الجمعية العامة للمساهمين وإدارة لوجستياتها.

• تبنى نشر فهم مبادئ الحوكمة بين أعضاء مجلس الإدارة والقيادات العليا وجميع العاملين بالشركة بما لا يتعارض مع دور الإدارات المعنية الأخرى بالشركة.

• متابعة استصدار وتنفيذ قرارات مجلس الإدارة وإبلاغ الإدارات المعنية بها وكذلك إعداد تقارير متابعة لما تم بشأنها.

• حفظ وتوثيق كل ما يتعلق بقرارات المجلس والموضوعات المعروضة عليه، مع التأكد من حصول المجلس على المعلومات الهامة في الوقت المناسب.

• التنسيق مع كافة لجان المجلس بما يكفل الاتصال الفعال بين تلك اللجان ومجلس الإدارة.

• التنسيق مع اللجان المعنية في إطار إتاحة ما يلزم من معلومات لمساندة رئيس المجلس في عملية تقييم أعضاء المجلس وأعضاء اللجان، والمقترحات التي يقدمها المجلس للجمعية العامة فيما يخص اختيار أو استبدال أحد الأعضاء.

• العمل على أن يكون أعضاء المجلس على دراية بأهم ما قد يستحدث من مسئوليات إشرافية أو قانونية نتيجة حدوث تطورات في أنشطة الشركة أو في الإطار القانوني الخاضعة له، وذلك في حدود مسئولياته ودون تعارض مع دور الإدارات المعنية بهذه الموضوعات.

• تقديم المعلومات اللازمة عن الشركة للأعضاء الجدد وتقديمهم لباقي الأعضاء.

2/3 المحور الثالث: لجان مجلس الإدارة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات_

لمجلس الإدارة تكوين لجان من أعضائه غير التنفيذيين والمستقلين، وطبقاً لأفضل الممارسات الدولية لحوكمة الشركات يفضل ألا يكون من بين أعضاء اللجان عضواً تنفيذياً من مجلس إدارة الشركة.

تشكل كل لجنة من عدد لا يقل عن ثلاثة أعضاء، ويجوز دمج بعض اللجان ذات الاختصاصات المتقاربة في لجنة واحدة، وذلك مع عدم مخالفة القوانين والتعليمات الرقابية المنظمة لعمل لجان المجلس. وتقوم اللجان بعرض تقاريرها وتوصياتها على مجلس الإدارة لاتخاذ ما يلزم من قرارات، مع الاعتبار أن اللجان لا تأخذ قرارات نيابة عن المجلس، بل يقتصر دورها فقط على رفع التوصيات للمجلس لاتخاذ القرارات المناسبة بشأنها.

تجتمع اللجان مرة واحدة على الأقل كل ثلاثة أشهر، ويكون اجتماع اللجنة صحيحاً بحضور نصف عدد أعضاء اللجنة أو الحد الأدنى من تشكيلها وهو 3 أعضاء، وتتخذ القرارات بالتوصيات التي ترفع للمجلس بأغلبية أصوات الأعضاء الحاضرين. وفي حالة تساوي الأصوات يرجح الجانب الذي يضم رئيس اللجنة.

يجب أن يكون تشكيل اللجان التابعة لمجلس الإدارة وفقاً للائحة عمل تعتمد من مجلس الإدارة، تتضمن تحديد مهام اللجنة ومدة عملها والصلاحيات الممنوحة لها خلال هذه المدة وكيفية رقابة المجلس عليها والمعاملة المالية لها. وعلى اللجنة أن تحيط المجلس علماً بما تقوم به أو تتوصل إليه من نتائج أو ما تقدمه من توصيات بشفافية مطلقة. وعلى المجلس أن يتابع عمل اللجان بشكل دوري للتحقق من قيامها بالأعمال المسندة إليها، حيث أن اللجان ليست وسيلة لكي يتنصل المجلس من مسئولياته أو ينقلها إلى جهة أخرى، بل هو المسئول عن أداء تلك اللجان وأداء الشركة ككل.

للجان المجلس أن تستعين بمستشارين خارجيين لمساعدتها في أداء مهامها على نفقة الشركة، مع مراعاة أن يوافق المجلس مسبقاً على ذلك مع الأخذ في الاعتبار تجنب تعارض المصالح.

يجب أن يتضمن التقرير السنوي والموقع الالكتروني للشركة عرضاً مختصراً عن تشكيل كل لجنة وعدد اجتماعاتها خلال السنة، ويجب أن يحضر رؤساء اللجان اجتماعات الجمعية العامة للشركة.

وفيما يلي عرض لبعض اللجان المنبثقة عن مجلس الإدارة وفقاً لأفضل الممارسات الدولية في حوكمة الشركات:

2/3/1 لجنة المراجعة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/3 المحور الثالث: لجان مجلس الإدارة_

يقوم مجلس الإدارة بتشكيل لجنة المراجعة بحيث تتمتع بالاستقلالية في أداء عملها. ويكون للجنة المراجعة لائحة عمل تعتمد من المجلس، تحدد نطاق عملها ومسئولياتها واختصاصاتها بما يتماشى مع القوانين والتعليمات الرقابية. ولتحقيق استقلالية لجنة المراجعة، فإن اللجنة تختار رئيسها ويتم الموافقة على تشكيلها ومعايير اختيار أعضائها وبرنامج عملها والمقابل المادي لأعضائها ورئيسها، وتكليفها بأداء مهامها بموجب قرار يصدر من مجلس الإدارة.

ويتم تشكيل لجنة المراجعة من أعضاء مجلس الإدارة غير التنفيذيين والمستقلين أو من خارج الشركة على أن يكون من بينهم عضواً واحداً على الأقل ممن لديهم معرفة ودراية بالأمور المالية والمحاسبية.

وتتولى لجنة المراجعة المهام التالية على الأقل:

• دراسة نظام الرقابة الداخلية بالشركة ووضع تقرير مكتوب عن رأيها وتوصياتها بشأنه.

• دراسة القوائم المالية قبل عرضها على مجلس الإدارة والإدلاء برأيها وتوصياتها بخصوصها.

• دراسة السياسات المحاسبية المستخدمة والإدلاء برأيها وتوصياتها بخصوصها.

• التوصية لمجلس الإدارة بتعيين مراقب حسابات أو أكثر للشركة وكذلك مؤهلاتهم وكفاءتهم واستقلاليتهم، ويكون قرار تعيينهم وتحديد أتعابهم من اختصاص الجمعية العامة العادية للشركة.

• الاطلاع على خطة المراجعة لمراقب الحسابات والإدلاء بملاحظاتها عليها.

• دراسة ملاحظات وتوصيات مراقب الحسابات على القوائم المالية والأخرى الواردة في خطاب الإدارة الوارد من مراقب الحسابات ومتابعة ما تم بشأنها.

• التأكد من التزام الشركة بإتباع النظم واللوائح والقوانين الداخلية والخارجية طبقاً للتقارير المرفوعة إليها من إدارة الالتزام أو غيرها من الإدارات المعنية.

• التوصية بالموافقة على قيام مراقب الحسابات بعمليات إضافية غير مراجعة الحسابات، والتوصية بالموافقة على ما يتقاضاه عن تلك العمليات بما يتناسب مع أتعابه السنوية.

• مناقشة واعتماد الخطة السنوية لإدارة المراجعة الداخلية ومتابعة كفاءتها والتأكد من شموليتها لجميع إدارات وأنشطة الشركة.

• الإطلاع على تقارير المراجعة الداخلية وتحديد أوجه وأسباب القصور في الشركة ومتابعة الإجراءات التصحيحية لها.

• دراسة وتقييم نظام الإنذار المبكر بالشركة واقتراح ما يلزم لتحسينه وتطبيقه بفاعلية.

• دراسة وتقييم نظم تأمين والمعلومات والبيانات وكيفية حمايتها من أي اختراقات داخلية أو خارجية.

• دراسة الملاحظات أو المخالفات الواردة من الجهات الرقابية ومتابعة ما تم بشأنها.

• دعوة مراقب حسابات الشركة أو رئيس إدارة المراجعة الداخلية أو من تراه من داخل أو خارج الشركة لحضور اجتماعاتها كلما دعت الحاجة.

• تنفيذ ومتابعة أية أعمال أخرى يكلفها بها مجلس الإدارة.

2/3/2 لجنة الترشيحات
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/3 المحور الثالث: لجان مجلس الإدارة_

تشكل لجنة الترشيحات من أعضاء المجلس المستقلين وغير التنفيذيين على أن يكون رئيسها مستقل، وتختص على الأقل بالأتي:

• المراجعة الدورية والمستمرة للاحتياجات المطلوبة من المهارات المناسبة لعضوية مجلس الإدارة ووظائف الإدارة العليا وإعداد بيان بالمؤهلات المطلوبة في ظل تطبيق خطة تتابع السلطة.

• تحديد مسئوليات أعضاء المجلس من التنفيذيين وغير التنفيذيين والمستقلين، ووضع التوصيف الوظيفي للقيادات التنفيذية العليا بالشركة.

• التحقق بصفة مستمرة من استقلالية أعضاء المجلس المستقلين والتأكد من عدم وجود أي تعارض مصالح إذا كان العضو يشغل عضوية مجلس إدارة شركة أخرى.

2/3/3 لجنة المكافآت
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/3 المحور الثالث: لجان مجلس الإدارة_

تشكل لجنة المكافآت من أعضاء المجلس غير التنفيذيين والمستقلين، ويراعى عدم التفرقة بين ما يتقاضاه أعضاء المجلس غير التنفيذيين والمستقلين إلا في أضيق الحدود، واستناداً إلى أعمال ومهام محددة يتم تكليفهم بها أو لجان يشاركون في عضويتها، وتختص لجنة المكافآت على الأقل بالأتي:

• اقتراح سياسات واضحة لمكافآت واستحقاقات أعضاء مجلس الإدارة وأعضاء اللجان وكبار التنفيذيين بالشركة، والاستعانة بمعايير ترتبط بالأداء في تحديد تلك الاستحقاقات، ومراجعة تلك السياسات سنوياً بعد عمل الدراسات والاستقصاءات اللازمة فيما يختص بحزم المكافآت.

• وضع ومتابعة سياسة استرداد مكافآت واستحقاقات أعضاء مجلس الإدارة وأعضاء اللجان وكبار التنفيذيين بالشركة في حال قيامهم بأي انتهاكات أو اختلاسات من مقدرات الشركة.

• فيما يتعلق بأسهم التحفيز، يجب أن يراعى فيها ألا تكون حافزاً للحاصلين عليها على اتخاذ قرارات تحقق مصلحة الشركة في الأجل القصير فقط، وإنما يجب أن تكون أيضاً مرتبطة بما يحسن أداء الشركة على المدى الطويل.

• إعداد تقرير سنوي مفصل عن كافة المكافآت والمزايا والمنافع التي يتحصل عليها أعضاء المجلس والإدارة العليا للعرض على الجمعية العامة.

2/3/4 لجنة إدارة المخاطر
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/3 المحور الثالث: لجان مجلس الإدارة_

هي لجنة تشكل من أعضاء مجلس الإدارة غير التنفيذيين والمستقلين، ويمكن دعوة العضو المنتدب أو مدير إدارة المخاطر بالشركة أو أي من المديرين التنفيذيين لحضور اجتماعاتها كلما دعت الحاجة.

وتختص لجنة إدارة المخاطر على الأقل بالأتي:

• وضع الأطر التنفيذية والإجراءات والقواعد التي يعتمدها المجلس، واللازمة للتعامل مع كافة أنواع المخاطر التي قد تواجه الشركة مثل المخاطر الإستراتيجية، مخاطر التشغيل، مخاطر السوق، مخاطر الائتمان، مخاطر السمعة، مخاطر نظم المعلومات وحماية البيانات، وجميع أنواع المخاطر التي من شأنها التأثير على نشاط واستدامة الشركة.

• مساعدة مجلس الإدارة في تحديد وتقييم مستوى المخاطر الممكن للشركة قبوله، والتأكد من عدم تجاوز الشركة لهذا الحد من المخاطر.

• الإشراف والتحقق من مدى فاعلية إدارة المخاطر بالشركة في تنفيذ الأعمال المسندة إليها، والتأكد من أنها تقوم بعملها بشكل كافي في حدود الاختصاصات المقررة لها، وكذلك التأكد من استقلالية موظفي إدارة المخاطر عن الإدارة التنفيذية بالشركة.

• إعداد تقرير دوري عن نتائج أعمالها وتوصياتها للعرض على مجلس الإدارة لاتخاذ اللازم بشأنه.

2/3/5 لجنة الحوكمة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/3 المحور الثالث: لجان مجلس الإدارة_

هي لجنة تشكل من أعضاء مجلس الإدارة غير التنفيذيين والمستقلين، ويقع على عاتقها مسئولية ما يلي على سبيل المثال:

• التقييم الدوري لنظام الحوكمة بالشركة وصياغة الأدلة والمواثيق والسياسات الداخلية الخاصة بكيفية تطبيق قواعد الحوكمة داخل الشركة.

• إعداد تقرير سنوي عن مدى التزام الشركة بقواعد حوكمة الشركات، مع وضع إجراءات مناسبة لاستكمال تطبيق تلك القواعد.

• مراجعة التقرير السنوي للشركة وتقرير مجلس الإدارة وبالأخص فيما يتعلق ببنود الإفصاح وغيرها من البنود ذات الصلة بحوكمة الشركات.

• حفظ وتوثيق ومتابعة التقارير الخاصة بتقييم أداء المجلس.

• دراسة ملاحظات الجهات الرقابية على تطبيق الحوكمة بالشركة وأخذها في الاعتبار ومتابعة ما تم بشأنها.

2/3/6 لجان أخرى
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/3 المحور الثالث: لجان مجلس الإدارة_

يمكن لمجلس الإدارة تشكيل لجان أخرى تكلف بموضوعات معينة بحسب حاجة وطبيعة عمل الشركة، وعلى مجلس الإدارة تحديد مدة عمل وصلاحيات هذه اللجان وتشكيلها ومعاملاتها المالية وتنظيم كيفية عملها.

ومن هذه اللجان على سبيل المثال لا الحصر ما يلي:

أ. اللجنة التنفيذية: عادة ما تكون في المؤسسات المالية، ولا مانع من تشكيلها في كافة أنواع الشركات بحسب الحاجة إليها، وتتكون من أعضاء المجلس التنفيذيين وكبار القيادات التنفيذية بالشركة ويرأسها عضو مجلس الإدارة المنتدب أو الرئيس التنفيذي للشركة، وتكون مسئولة عن انجاز الأعمال اليومية للشركة، كما يقوم مجلس الإدارة بمراقبة أدائها وتقييمها بشكل دوري للتأكد من فعاليتها.

ب. لجنة الاستثمار: هي لجنة تشكل عادة في المؤسسات المالية كما لا يوجد ما يمنع من تشكيلها في كافة أنواع الشركات بحسب الحاجة إليها، وتشكل من أعضاء مجلس الإدارة وأعضاء من الإدارة العليا كالرئيس التنفيذي أو مدير الاستثمار أو مدير التمويل أو الخبراء الإكتواريين بالشركة، بهدف معاونة المجلس في تحديد وتوظيف عوائد ومدخرات الشركة أو عملائها في استثمارات تدر أفضل عائد طبقاً للسياسة الاستثمارية المعتمدة من مجلس الإدارة، مما يمكنها من تحقيق أفضل عائد لعملائها أو استيفاء التزاماتها قصيرة وطويلة الأجل.

ج. لجنة المسئولية الاجتماعية: تقوم برفع توصياتها للمجلس بشأن سبل الالتزام بالمسئولية الاجتماعية تجاه المجتمع والبيئة التي تعمل فيها الشركة، مما يضمن استدامة الشركة على المدى الطويل وزيادة ارتباطها بالمجتمع.

د. لجنة السلامة والصحة المهنية: تشكل عادة في الشركات الصناعية، وتكون معنية بمراقبة ومتابعة تنفيذ التوصيات الخاصة بالسلامة والصحة المهنية للعاملين في مصانع الشركة ومواقعها الميدانية.

ه. لجنة حماية البيئة: تكون مسئولة عن السياسات البيئية الواجب إتباعها من قبل الشركة في إطار المحافظة على البيئة.

و. لجنة حماية حملة الوثائق: عادة ما تشكل في شركات التأمين، بهدف وضع إجراءات مناسبة وآليات فعالة لمعالجة شكاوى وتظلمات حملة الوثائق ومراجعتها دورياً، وكذلك تعمل على ضمان الامتثال للمتطلبات القانونية المنصوص عليها في الإطار التنظيمي والقانوني الذي تعمل فيه الشركة، وأيضاًَ ضمان كفاية الإفصاحات المطلوبة عن المعلومات الجوهرية التي تهم حملة الوثائق.

