2/4/1 نظام الرقابة الداخلية
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/4 المحور الرابع: البيئة الرقابية_

نظام الرقابة الداخلية هو مجموعة السياسات والإجراءات والأدلة واللوائح التي تعد بواسطة الإدارات المعنية بالشركة وتعتمد من مجلس الإدارة، بالإضافة إلى أن هذا النظام يقوم بتحديد الاختصاصات والفصل التام بين المسئوليات والمهام حيث يتم مراعاة ذلك عند إعداد الهيكل التنظيمي للشركة.

ونظام الرقابة الداخلية كذلك هو تخطيط التنظيم الإداري للشركة وكل ما يرتبط به من وسائل أو مقاييس تستخدم داخل الشركة للمحافظة على أصولها، وتقوم لجنة المراجعة بتقييم نظام الرقابة الداخلية للشركة بشكل دوري ورفع التوصيات لمجلس الإدارة بشأنه.

ومن ضمن أهداف نظام الرقابة الداخلية بالشركة على سبيل المثال ما يلي:

• تحقيق الفصل التام بين مسئوليات وسلطات كافة العاملين بالشركة.

• ضمان دقة وجودة المعلومات، بحيث توفر سواء للشركة أو لغيرها المعلومات الصحيحة والدقيقة عن الشركة.

• حماية أصول الشركة المادية من الأخطار التي يمكن أن تتعرض لها، وتوثيق وتسجيل تلك الأصول بسجلات الشركة.

• زيادة الكفاءة الإنتاجية للشركة وتحقيق أهدافها بأقل التكاليف وبنفس الجودة.

• ضمان دقة تنفيذ التعليمات، بهدف التأكد من أن جميع التعليمات قد تم تنفيذها كما ينبغي.

• ضمان تطبيق قواعد حوكمة الشركات، وذلك عن طريق التنفيذ الدقيق لمختلف تعليمات وقواعد الحوكمة.

2/4/2 إدارة المراجعة الداخلية
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/4 المحور الرابع: البيئة الرقابية_

المراجعة الداخلية نشاط مستقل وموضوعي، مصمم لإضافة قيمة وتحسين أداء عمليات الشركة ليساعدها على تحقيق أهدافها من خلال تبني أسلوب منهجي ومنظم يهدف إلى تقييم وسائل ونظم الرقابة الداخلية وإجراءات إدارة المخاطر في الشركة، والتأكد من سلامة تطبيق قواعد الحوكمة بها علي نحو سليم فيما يخص كافة الإدارات والأنشطة التنفيذية والمالية والقانونية.

يتولى إدارة المراجعة الداخلية مسئول متفرغ بالشركة، ويكون من القيادات الإدارية بها، وتكون تبعيته الفنية إلى لجنة المراجعة، ويتبع إدارياً العضو المنتدب أو الرئيس التنفيذي للشركة.

يكون تعيين وعزل مدير إدارة المراجعة الداخلية وتحديد معاملته المالية بناءً على توصية من لجنة المراجعة، ويقوم العضو المنتدب على إثرها بإصدار قرار بذلك، ولا يجوز تغيير معاملته المالية أو أي مزايا أخرى يحصل عليها دون الرجوع إلى لجنة المراجعة.

يجب أن تكون لمدير إدارة المراجعة الداخلية كافة الصلاحيات اللازمة للقيام بعمله على أكمل وجه، كما يجب إمداد إدارة المراجعة الداخلية بالوسائل والأدوات والتجهيزات اللازمة للقيام بعملها بكفاءة.

تقوم لجنة المراجعة بتحديد أهداف ومهام وصلاحيات إدارة المراجعة الداخلية، ويرفع ذلك لمجلس إدارة الشركة لاعتماده، كما يقوم مدير إدارة المراجعة الداخلية بتقديم تقرير ربع سنوي على الأقل إلى لجنة المراجعة يوضح به نتائج أعماله.

على الشركة تشجيع وتدعيم استقلالية المراجعين الداخليين من خلال توفير قنوات الاتصال المباشر بينها وبين المجلس ولجانه، مع ضرورة التأكد من سهولة حصول العاملين بإدارة المراجعة الداخلية على التقارير والمعلومات الهامة المتعلقة بقطاعات الشركة.

يتم وضع نظم وإجراءات المراجعة الداخلية بناء على تصور ودراسة للمخاطر التي تواجه الشركة، على أن يستعان في ذلك بآراء وتقارير مجلس الإدارة ومراقبي الحسابات ومديري الشركة، وأن يتم تحديث ومتابعة وتقييم تلك المخاطر بشكل دوري.

ومن أهم المسئوليات التي تقع على عاتق إدارة المراجعة الداخلية على سبيل المثال لا الحصر ما يلي:

• تقييم مدى كفاءة نظام الرقابة الداخلية بالشركة ورفع التقارير للجنة المراجعة بالملاحظات التي تم التوصل إليها.

• تقييم مدى التزام جميع إدارات الشركة بتنفيذ أعمالها وفقاً لإجراءات العمل والسياسات الموضوعة بدون تعارض مع اختصاصات الإدارات المعنية الأخرى.

• تقييم كفاءة الإجراءات والسياسات الموضوعة ومدى تناسبها مع تطورات العمل والسوق.

• متابعة تصويب الملاحظات الواردة بتقارير المراجعة الداخلية والخارجية والأخرى الواردة من الجهات الرقابية.

2/4/3 إدارة المخاطر
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/4 المحور الرابع: البيئة الرقابية_

مجلس إدارة الشركة مسئول بشكل عام عن إدارة المخاطر على النحو الذي يتفق مع طبيعة نشاط الشركة وحجمها والسوق التي تعمل به. وللشركة تأسيس إدارة مستقلة للمخاطر طبقاً لاحتياجاتها. وتقع على المجلس مسئولية وضع إستراتيجية لتحديد المخاطر التي قد تواجه الشركة وكيفية التعامل معها، وكذلك مستوى المخاطر المقبول لدى الشركة.

ينبغي تطبيق مبدأ الفصل بين المهام والمسئوليات بين العاملين في إدارة المخاطر لتفادي أي تعارض في المصالح، مع ضمان أن يكون لإدارة المخاطر اتصال مباشر مع المجلس ولجنة المخاطر أو لجنة المراجعة في حال عدم وجود لجنة المخاطر، بحيث تقوم إدارة المخاطر برفع تقاريرها الدورية وفقاً للأهمية النسبية للمعلومات التي توصلت إليها.

ومن مسئوليات إدارة المخاطر على سبيل المثال ما يلي:

• تحليل المخاطر التي قد تتعرض لها الشركة وإجراء هذا التحليل بدقة وفي وقت مناسب ومبكر.

• تحديد مستوى المخاطر الذي يمكن للشركة قبوله من حجم المخاطر المختلفة التي قد تواجه الشركة اعتماداً على تأثيرها ومدى إمكانية تحققها.

• وضع سياسة للمخاطر ومؤشرات محددة لقياس ومتابعة ومراقبة الخطر المحيط بالشركة.

• قياس مدى استمرار ملائمة وفاعلية السياسات فيما يختص بقياس ومتابعة ومراقبة المخاطر، وإجراء أي تعديلات مطلوبة بشأنها طبقاً لتطورات السوق والبيئة المحيطة بالشركة داخلياً وخارجياً.

• التأكد من توافر نظم معلومات واتصال مناسبة وفعالة فيما يتعلق بعملية متابعة ومراقبة المخاطر بحيث تتيح للإدارة العليا ولجنة المخاطر تلقي تقارير دورية من إدارة المخاطر تعكس مدى التزام الشركة بحدود المخاطر الموضوعة، وتوضح التجاوزات عن هذه الحدود وأسبابها والخطة المقترحة لمعالجتها.

• تقديم تقارير دقيقة ومعبرة، بحيث تمكن المعنيين من اتخاذ القرارات المناسبة بشأنها.

2/4/4 إدارة الالتزام
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/4 المحور الرابع: البيئة الرقابية_

وظيفة إدارة الالتزام هي وظيفة مستقلة تحدد وتقيم وتقدم النصح والمشورة وتراقب وتعد التقارير حول مخاطر عدم الالتزام بالقوانين والنظم والتعليمات الرقابية الصادرة عن الجهات المختلفة، تجنباً للإضرار بسمعة الشركة أو تعرضها لعقوبات ناتجة عن عدم الالتزام.

كما يعد الالتزام مسئولية شاملة ومتعددة الجوانب للدرجة التي لا يمكن معها أن تترك فقط لفئة معينة من المختصين لتحمل مسئولياتها، ولذلك لا تقع مسئولية الالتزام على إدارة الالتزام بالشركة فحسب، بل تمتد لجميع العاملين بالشركة ككل، بدءاً من مجلس الإدارة والإدارة العليا وانتهاءاً لجميع العاملين بالشركة.

مسئولية وضع السياسات المتعلقة بوظيفة إدارة الالتزام تقع على كاهل الإدارة العليا، ويقوم مجلس الإدارة بدوره في اعتماد تلك السياسات، ويجب التأكد من إحاطة كافة العاملين بتلك السياسات.

مسئول الالتزام تكون تبعيته التقريرية للجنة المراجعة، بينما يتبع إدارياً العضو المنتدب أو الرئيس التنفيذي أو رئيس مجلس الإدارة.

ولعل من أبرز مسئوليات إدارة الالتزام على سبيل المثال ما يلي:

• المتابعة الدائمة والتأكد من التزام كافة العاملين بالشركة بالقوانين الملزمة والضوابط والتعليمات الرقابية الصادرة عن الجهات المختلفة بما في ذلك نظم وسياسات الحوكمة.

• التأكد من ومتابعة مدى التزام كافة العاملين باللوائح والسياسات والمواثيق الداخلية بما في ذلك ميثاق الأخلاق والسلوك المهني.

• التأكد من وجود ومراجعة خطة تحديث بيانات العملاء.

• التأكد من عدم وجود ممارسات غير مشروعة أو غير أخلاقية بالشركة بما فيها ممارسات غسل الأموال والفساد وتمويل الإرهاب، وتلقي البلاغات والتحقيق فيها بشكل موضوعي وسري وعرضها على لجنة المراجعة ومتابعة ما تم بشأنها، مع ضمان حماية المبلغين.

2/4/5 إدارة الحوكمة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/4 المحور الرابع: البيئة الرقابية_

تهدف إدارة الحوكمة بالشركة إلى المساعدة على توطيد وإرساء مبادئ الحوكمة، ومتابعة تطبيقها وزيادة فاعليتها، وتكون تبعيتها الفنية والتقريرية للجنة الحوكمة أو مجلس الإدارة، بخلاف تبعيتها الإدارية للعضو المنتدب أو الرئيس التنفيذي أو رئيس مجلس الإدارة. ويتمثل دور إدارة الحوكمة على سبيل المثال فيما يلي:

• مراقبة مدى توافر المبادئ والعناصر الأساسية التي تساعد على تطوير وتحسين الأداء بالشركة بما يساهم في تحقيق الأهداف الإستراتيجية المحددة من قِبل مجلس الإدارة.

• مراقبة تطبيق مبدأ الإفصاح والشفافية وثقافة الحوكمة في كافة أعمال وأنشطة الشركة.

• تحسين وتطوير الإطار العام ومبادئ العمل بالشركة من خلال ميثاق قواعد السلوك المهني الخاص بالشركة مع تحديد مسئوليتها الاجتماعية تجاه العاملين والمجتمع ككل.

• مراقبة تطبيق سياسة تجنب تعارض المصالح على كافة العاملين بالشركة.

• العمل على تطبيق مفهوم الشفافية والوضوح والعدالة في التعامل مع جميع المساهمين.

• العمل على وضوح العلاقات فيما بين مجلس الإدارة وأصحاب المصالح.

• وضع أدلة الحوكمة الداخلية للشركة وصياغة السياسات الداخلية المختلفة التي تنظم العلاقة بين كافة العاملين، وكذلك المساهمة في إعداد التقرير عن مدى التزام الشركة بحوكمة الشركات.

2/4/6 مراقب الحسابات
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/4 المحور الرابع: البيئة الرقابية_

يعين مراقب الحسابات ممن تتوافر فيهم الشروط المنصوص عليها في قانون مزاولة مهنة المحاسبة والمراجعة، بما في ذلك الكفاءة والسمعة والخبرة الكافية، وأن تكون خبرته وكفاءته وقدراته متناسبة مع حجم وطبيعة نشاط الشركة ومن تتعامل معهم.

تقوم الجمعية العامة بناءً على ترشيح من مجلس الإدارة وبعد توصية لجنة المراجعة، بتعيين مراقب حسابات أو أكثر للشركة، ويكون قرار تعيينه وتقدير أتعابه من اختصاص الجمعية العامة العادية للشركة.

يجب أن يكون مراقب الحسابات مستقلاً تماماً عن الشركة وعن أعضاء مجلس إدارتها، فلا يكون مثلاً مساهماً فيها أو عضواً في مجلس إدارتها، أو تربطه صلة قرابة بأي من أعضاء مجلس إدارتها أو إدارتها العليا حتى الدرجة الثانية، أو أن يقوم بصفة دائمة بأي عمل فني أو إداري أو استشاري فيها، ويجب أن يكون محايداً فيما يبديه من أراء، كما يجب أن يكون عمله محصناً ضد تدخل مجلس الإدارة.

لا يجوز أن يتعاقد مجلس الإدارة مع مراقب حسابات الشركة لأداء أية أعمال إضافية غير مرتبطة بعمله كمراقب حساباتها بشكل مباشر أو غير مباشر، إلا بعد أخذ موافقة لجنة المراجعة، وبشرط ألا يكون هذا العمل الإضافي من الأعمال المحظور علي مراقب الحسابات القيام بها. ويجب أن تتناسب أتعاب أداء الأعمال الإضافية مع طبيعة وحجم الأعمال المطلوبة. وعلى لجنة المراجعة عند النظر في الموافقة علي أداء مراقب الحسابات للأعمال الإضافية وتحديد أتعابه عنها أن تراعي عدم تأثير ذلك علي استقلاليته، مع ضرورة الإفصاح عن ذلك في الجمعية العامة للمساهمين وفي التقرير السنوي.

لا يعين مراقب الحسابات كشخص طبيعي لأكثر من خمس سنوات، ولا يجب إعادة تعيينه قبل انقضاء ثلاث سنوات علي انتهاء عمله كمراقب حسابات للشركة، ويفضل للشركات الكبرى تعيين مراقبين اثنين لحساباتها.

يجب أن يسلم مراقب الحسابات نسخة من تقريره علي التقرير الذي تعده الشركة عن مدي التزامها بمبادئ الحوكمة إلى الجهة الإدارية طبقاً لقواعد الحوكمة والإفصاح المعمول بها، ويقدم هذا التقرير أيضاً إلى الجمعية العامة للمساهمين.

3/1 مقدمة عن الإفصاح والشفافية
_الموضع: الباب الثالث — الإفصاح والشفافية_

يلعب توافر المعلومات دوراً مهماً في صناعة القرار وتقييم الأداء والمعرفة بظروف الشركة وتقييم مصداقية الشركة مع من تتعامل معهم. لذلك تعتبر الشفافية والإفصاح عن الأمور المالية وغير المالية من الأعمدة الرئيسية لحوكمة الشركات التي من شأنها أن تؤثر على كفاءة ومصداقية وتوازن الأسواق وتحقيق العدالة والحماية للمستثمرين وأصحاب المصالح مما يدعم مناخ الاستثمار والاقتصاد ككل.

والإفصاح يعنى إتباع سياسة الوضوح الكامل وإظهار جميع الحقائق والمعلومات المالية وغير المالية والأحداث الجوهرية عن الشركة والتي تهم المستثمرين والأطراف ذات الصلة وكافة أطراف مجتمع الاستثمار، ووضعها في متناول تلك الأطراف بشكل عادل وفي الوقت المناسب ليتسنى لهم اتخاذ القرارات المناسبة المبنية على معلومات صحيحة ودقيقة. أما الشفافية فمفهومها أشمل بحيث أنها توفر المناخ الذي يتيح للكافة المعلومات أو البيانات من أجل تيسير اتخاذ القرارات.

ويجب في المعلومات التي يفصح عنها أن تكون دورية وموثقة وذات مصداقية وقابلة للقياس والمقارنة، وأن تقدم في الوقت المناسب وتكون واضحة وغير مضللة لمستخدميها، وأن تقدم للكافة في ذات الوقت من خلال قنوات الإفصاح المتاحة المختلفة. كما يجب الإفصاح الفوري عن كافة الأحداث الجوهرية فور حدوثها. وفي جميع الأحوال يجب أن يؤخذ في الاعتبار ألا يؤثر الإفصاح على الوضع التنافسي للشركة في الأسواق التي تعمل فيها.

3/2 المعلومات الجوهرية والإفصاح المالي وغير المالي
_الموضع: الباب الثالث — الإفصاح والشفافية_

يجب أن تفصح الشركة من خلال الوسائل المختلفة عن معلومات الشركة المالية التي تهم المساهمين وأصحاب المصالح، مثل قوائمها المالية السنوية والدورية وتقارير مراقب الحسابات السنوية والدورية، وكذلك تقرير مجلس الإدارة والسياسات المحاسبية والموازنات التقديرية وطرق تقييم الأصول وتوزيعات الأرباح.

وعلى الشركة أن تقوم بالإفصاح أيضاً عن معلومات الشركة غير المالية التي تهم المساهمين والمستثمرين الحاليين والمرتقبين، ومنها المعلومات الداخلية التي تتضمن أهداف الشركة ورؤيتها وطبيعة نشاطها وخطط الشركة وإستراتيجيتها المستقبلية، وتشكيل مجلس الإدارة ولجانه وكبار التنفيذيين والكفاءات الإدارية بالشركة والسير الذاتية لهم وكذلك نظم رفع الكفاءات والتدريب والإثابة والرعاية للعاملين بها، وما يتقاضاه أعضاء المجلس ولجانه وكبار التنفيذيين من مكافآت وبدلات خلال السنة، وهيكل الملكية بالشركة شاملاً المساهمين الرئيسيين وأصحاب الحصص المؤثرة موضحاً الملاك المستفيدين بشكل مباشر وغير مباشر من تلك الحصص، وكذلك هياكل الملكية بالشركات الشقيقة والتابعة للشركة والمعاملات مع الأطراف ذات العلاقة وعقود المعاوضة. كما على الشركة الإفصاح عن أهم المخاطر التي قد تواجهها وسبل مواجهتها، وتغيير سياسة الاستثمار، بالإضافة إلى تقرير مدى التزامها بقواعد حوكمة الشركات بما يحقق لها أفضل معدلات استدامة ممكنة على المدى الطويل.

كما على الشركة الإفصاح أيضاً عن المعلومات الخارجية الجوهرية التي تؤثر عليها وإعداد مقارنات عنها والتي قد تؤثر على استمرارية الأعمال، مثل مدى توافر الثروات الطبيعية والمواد الخام والطاقة التي تعتمد عليها، والقدرة على التعامل مع تقلباتها.

وكذلك على الشركة الإفصاح لمساهميها وللجهات الرقابية عن أسهم الخزينة. وفى حالة شراء الشركة التابعة لأسهم الشركة القابضة المالكة لها، تطبق علي الأسهم المشتراه كافة قواعد أسهم الخزينة ولا يعتد بها في نصاب المساهمين ولا تشترك في التصويت على قرارات الجمعية العامة.

3/3 علاقات المستثمرين
_الموضع: الباب الثالث — الإفصاح والشفافية_

وظيفة علاقات المستثمرين هي أحد أبرز الأنشطة الرئيسية لتطبيق مبادئ حوكمة الشركات، حيث أنها وظيفة إستراتيجية مستقلة تهدف إلى تنشيط وتوطيد العلاقة مع المستثمرين الحاليين والمرتقبين، وفتح قنوات الاتصال بذوي العلاقة بسوق المال والاستثمار، وتوفير الإفصاح والشفافية اللازمين مما يكون له الأثر الإيجابي على ما يلي:

• رؤية المستثمرين لأداء الحالي للشركة وتوقعاتهم للأداء المستقبلي.

• تحقيق السيولة المناسبة لتداول أسهم الشركة في البورصة.

• خفض تكلفة التمويل على المدى الطويل.

• زيادة ثقة المتعاملين مع الشركة وأصحاب المصالح، وكذلك الترويج لزيادة المجموعات الداعمة للشركة.

ومسئول علاقات المستثمرين يجب أن يشترك في وضع إستراتيجية اتصال الشركة بسوق الاستثمار، وفتح قنوات التواصل مع المستثمرين ونقل وجهات نظر السوق وتخوفات المستثمرين لمجلس الإدارة بصفة مستمرة.

وكذلك فإن علاقات المستثمرين وسيلة تمكن مجلس الإدارة من فهم أسباب أداء أسهم الشركة، وانعكاس ذلك الأداء على قيمتها العادلة طبقاً لما توفره الشركة من معلومات عن أدائها وإمكانياتها ومستقبلها، ومدى التزام الشركة بقواعد الإفصاح والتواصل مع المستثمرين ومدى وضوح رؤيتهم وتقييم سوق الاستثمار لها.

وإدارة علاقات المستثمرين تتبع رئيس مجلس الإدارة أو العضو المنتدب وتقدم تقاريرها الدورية لهما، وذلك إيماناً من الشركة بأهمية دورها والفوائد التي تجنيها منها. ويجب على الشركة فهم ومساندة هذه الإدارة لتكون كأداة تواصل فعالة مع المساهمين وأصحاب المصالح والمتعاملين مع الشركة لضمان حصولها على نصيبها من اهتمام ومتابعة السوق.

يجب على مسئول علاقات المستثمرين حضور اجتماعات الجمعية العامة للشركة، كما يمكن دعوته لحضور اجتماعات مجلس الإدارة وذلك للتعرف على الأمور الداخلية للشركة وتوجهاتها الإستراتيجية. كما يجب عليه أن ينظم الاجتماعات والزيارات للمستثمرين الحاليين والمرتقبين للتعرف على الشركة وإدارتها العليا وتفاصيل أنشطتها وآدائها، ومسئول علاقات المستثمرين يجب أن يكون لديه دراية كاملة عن الشركة وموقفها المالي وأن يكون قادراً على الرد على أسئلة واستفسارات المستثمرين ومعرفة القرارات التي يكون لها تأثير على نتائج الأعمال، وكذلك معرفة ما يمكن الإفصاح عنه وما هو غير مصرح بالإفصاح عنه من خلال تطبيقه للقواعد المنظمة للإفصاح والشفافية في السوق.

ولعل من أبرز مهام وظيفة علاقات المستثمرين ما يلي:

• وضع إستراتيجية لبرنامج علاقات المستثمرين من خلال فهم السوق ومتطلبات الشركة، بحيث يقوم مسئول علاقات المستثمرين بتحديد الأولويات فيما يخص الأنشطة المطلوبة ووضع الإستراتيجية المطلوبة لتنفيذ تلك الأنشطة بالتعاون مع مجلس الإدارة.

• الاشتراك في وضع سياسة الإفصاح المتبعة في الشركة واعتمادها من مجلس الإدارة.

• الحفاظ علي المستثمرين الحاليين وجذب مستثمرين جدد من خلال توعية السوق بأعمال الشركة وبفرص النمو المستقبلية لها، والتعرف على العوامل التي تؤثر علي ربحيتها.

• التواصل مع المحللين والمستثمرين وممثلي الإعلام وتوفير المعلومات للحد من الشائعات والمفاجآت التي تؤدي إلى تقلبات في أسعار وأحجام التداول.

• تنظيم المعلومات الصادرة عن الشركة طبقاً لقواعد الإفصاح المعمول بها.

• إنشاء ومتابعة قاعدة بيانات المستثمرين سواء من حيث نوعية المستثمر أو موقعه الجغرافي.

• تعريف السوق بالأعضاء الجدد في مجلس الإدارة أو الإدارة العليا.

• تنظيم الحملات الترويجية والفعاليات عن الشركة طبقاً للخطة المعدة لذلك مسبقاً، وتسهيل زيارات المستثمرين لمواقع الشركة المختلفة.

• التواصل مع المستثمرين عبر أدوات الاتصال المختلفة مثل الموقع الالكتروني للشركة ومواقع التواصل الاجتماعي والتقارير الصحفية، والاشتراك في إعداد التقرير السنوي الذي يهتم به المستثمرين الحاليين والمرتقبين.

• إعداد تقرير الإفصاح المطلوب من الشركة وإعداد صفحات علاقات المستثمرين على الموقع الالكتروني للشركة وتحديثها بصفة مستمرة.

3/4 أدوات الإفصاح
_الموضع: الباب الثالث — الإفصاح والشفافية_

3/4/1 التقرير السنوي
_الموضع: الباب الثالث — الإفصاح والشفافية — 3/4 أدوات الإفصاح_

على الشركة أن تصدر تقريراً سنوياً يضم ملخص لتقرير مجلس الإدارة والقوائم المالية بالإضافة إلى كافة المعلومات الأخرى التي تهم المساهمين والمستثمرين الحاليين والمرتقبين وأصحاب المصالح الآخرين.

ولابد وأن تتسم لغة التقرير السنوي بالوضوح والسهولة حتى يتمكن القارئ العادي من فهمها، كما يفضل أن يصدر التقرير باللغتين العربية والإنجليزية لييسر على جميع الأطراف الإطلاع عليه أياً كانت جنسياتهم.

ويعد التقرير السنوي من أهم مصادر المعلومات للمستثمر الحالي والمرتقب عن الشركة ونشاطها وموقفها المالي. وهو بمثابة تقرير من إدارة الشركة لكافة المهتمين بها عن الأحداث التي تمت خلال السنة الماضية وما تهدف الشركة إلى تحقيقه خلال السنة القادمة. ويحتوي التقرير السنوي على ما يلي على الأقل:

• كلمة رئيس مجلس الإدارة و/أو العضو المنتدب.

• الرؤية والهدف.

• إستراتيجية الشركة.

• تاريخ الشركة وأهم المحطات التي مرت بها.

• هيكل الملكية.

• الإدارة العليا وتشكيل مجلس الإدارة.

• تحليل السوق الذي تعمل به الشركة.

• مشروعات الشركة الحالية والمستقبلية.

• تحليل المركز المالي للشركة.

• تقرير عن الحوكمة.

• تقرير عن المسئولية الاجتماعية والبيئية للشركة.

• تقرير عن مناقشة الإدارة التنفيذية للأداء المالي للشركة.

• تقرير مراقب الحسابات والقوائم المالية المقارنة بنفس الفترات السابقة.

3/4/2 تقرير مجلس الإدارة
_الموضع: الباب الثالث — الإفصاح والشفافية — 3/4 أدوات الإفصاح_

على الشركة أن تصدر تقريراً سنوياً للعرض على الجمعية العامة والجهات الرقابية، ويكون موجها من رئيس المجلس إلى المساهمين على أن يتضمن على الأقل ما يلي:

• مناقشة النتائج المالية والموضوعات الجوهرية.

• الإنجازات الرئيسية للشركة أثناء السنة.

• تحليل لبيئة عمل وأسواق الشركة الرئيسية.

• إستراتيجية الشركة.

• التغيرات الرئيسية في هيكل الشركة الإداري.

• تشكيل مجلس الإدارة وعدد مرات انعقاده.

• تشكيل لجان المجلس وعدد مرات انعقادها.

• متوسط عدد العاملين بالشركة خلال السنة ومتوسط دخل العامل خلال نفس الفترة.

• سياسات إثابة وتحفيز العاملين بالشركة مثل عروض تملك الأسهم وغيرها.

• ما تم بشأن عقود المعاوضة المبرمة في العام السابق وكذلك عقود المعاوضة المعروضة للعام التالي.

• ما اتخذ من إجراءات ضد الشركة أو أعضاء مجلس إدارتها أو مديريها من قبل جهات رقابية أو قضائية.

• تقرير عن التزام الشركة بحوكمة الشركات والمسئولية الاجتماعية والبيئية.

3/4/3 تقرير الحوكمة
_الموضع: الباب الثالث — الإفصاح والشفافية — 3/4 أدوات الإفصاح_

وهو تقرير يوضح مدى الالتزام بتطبيق قواعد الحوكمة، وكذلك يوضح المبررات عن عدم الالتزام ببعض تلك التطبيقات طبقاً لقاعدة الالتزام أو التفسير. ويضم على الأقل ما يلي:

• المقدمة وإجراءات تطبيق الحوكمة.

• تشكيل مجلس الإدارة.

• تشكيل لجان المجلس.

• عدد اجتماعات المجلس واللجان المنبثقة عنه.

• الهيكل التنظيمي.

• خطة تتابع السلطة.

• تعاملات الداخليين على أسهم الشركة.

• العلاقات مع المساهمين.

• ما اتخذ من إجراءات ضد الشركة أو أعضاء مجلس إدارتها أو مديريها من قبل جهات رقابية أو قضائية.

• تقييم أداء المجلس والإدارة التنفيذية.

• تقييم نظام الرقابة الداخلية والالتزام.

• مدى الالتزام بقواعد الإفصاح.

• كل المعلومات الهامة ذات الصلة بحوكمة الشركات.

• الخطة الموضوعة لاستكمال تطبيقات الحوكمة.

3/4/4 تقرير الإفصاح
_الموضع: الباب الثالث — الإفصاح والشفافية — 3/4 أدوات الإفصاح_

وهو تقرير ربع سنوي يعد من قبل إدارة الشركة بمعاونة إدارة علاقات المستثمرين بها، ويضم على الأقل ما يلي:

• بيانات الاتصال بالشركة.

• مسئول علاقات المستثمرين وبيانات الاتصال به.

• هيكل المساهمين الذين يمتلكون نسبة 5% فأكثر من أسهم الشركة.

• هيكل المساهمين الإجمالي موضحاً به الأسهم حرة التداول.

• تفاصيل أسهم الخزينة لدى الشركة.

• التغيرات في مجلس إدارة الشركة وأخر تشكيل للمجلس.

• تشكيل اللجان المنبثقة عن مجلس الإدارة.

3/4/5 تقرير الاستدامة
_الموضع: الباب الثالث — الإفصاح والشفافية — 3/4 أدوات الإفصاح_

على الشركة أن تصدر تقرير متوازن عن الاستدامة، يشتمل على إنجازات الشركة في المجالات الاقتصادية والبيئية والاجتماعية. ويعرض هذا التقرير قيم ومبادئ الشركة ويوضح العلاقة بين إستراتيجيتها والتزاماتها تجاه المجتمع الذي تعمل فيه.

وعلى الشركة أن تراعي عند إعداد هذا التقرير ضمان تحقيق الشفافية والدقة والاكتمال والشمولية والحيادية، وأن تكون بيانات التقرير والأرقام الواردة فيه قابلة للمقارنة، وأن تكون المعلومات الواردة به ملائمة لاحتياجات أصحاب المصالح، وفي توقيتات منتظمة تسمح بتوفير المعلومات في الوقت المناسب للمستخدمين لمساعدتهم في اتخاذ القرار.

ويحقق الإفصاح عن الاستدامة مجموعة من المنافع تتمثل في دعم سمعة الشركة والتحسين المستمر في الأداء والالتزام بالتشريعات والتعليمات الرقابية في المجالات البيئية والاجتماعية، وكذلك كيفية إدارة مخاطر الشركة، فضلاً عن سبل تحفيز العاملين بها وجذب رؤوس الأموال. ويجب أن يتضمن تقرير الاستدامة الجوانب الآتية على الأقل:

• سياسة الحوكمة ورقابة السلوك المهني للعاملين.

• سياسة الشركة تجاه البيئة التي تعمل فيها وتأثيرها عليها.

• العلاقات الحكومية والمشاركات السياسية للشركة.

• سياسة الشركة الخاصة بعلاقات العاملين وحقوق الإنسان وسياسات ضمان عدم التمييز.

• جودة المنتجات والخدمات المقدمة من الشركة ونظام التعامل مع الشكاوى.

• ضمان استمرارية الأعمال وإدارة المخاطر والأزمات وحماية المعلومات.

• سياسات مكافحة الغش والفساد.

• سياسة المسئولية الاجتماعية والبيئية للشركة.

3/4/6 الموقع الالكتروني
_الموضع: الباب الثالث — الإفصاح والشفافية — 3/4 أدوات الإفصاح_

يجب أن يكون لدى الشركة موقع على شبكة المعلومات الدولية، ويفضل أن يكون الموقع باللغتين العربية والإنجليزية يتم من خلاله الإفصاح عن المعلومات المالية وغير المالية بأسلوب سهل للمستخدم، ويجب تحديثه بالمعلومات المنشورة بشكل مستمر وإتاحة إمكانية التواصل مع الشركة بسهولة مع الالتزام بمتابعة الرد على الرسائل والاستفسارات التي تتلقاها الشركة من خلاله.

ويجب أن يتضمن الموقع الالكتروني للشركة على الأقل ما يلي:

• نبذة عن الشركة ورؤيتها ورسالتها وإستراتيجيتها.

• تشكيل مجلس الإدارة ولجانه والإدارة العليا.

• معلومات عن نشاط الشركة ومنتجاتها ونطاق عملها.

• التقارير السنوية للشركة.

• القوائم المالية ونتائج الأعمال الدورية والسنوية المقارنة بفترات سابقة.

• صفحات علاقات المستثمرين وكيفية الاتصال المباشر بها.

• سياسة حوكمة الشركات.

• سياسة المسئولية الاجتماعية.

• كيفية تلقي مقترحات وشكاوى العملاء.

• عنوان وبيانات الاتصال بالشركة وفروعها.

4/1 ميثاق الأخلاق والسلوك المهني
_الموضع: الباب الرابع — مواثيق ولوائح وسياسات حوكمة الشركات — أولاً: المواثيق واللوائح_

يشمل مجموعة من القيم التي تعمل على ضبط وتنظيم قواعد السلوك الوظيفي وأخلاقيات المهنة داخل الشركة. ويحتوي على معايير السلوك التي يتعين على كل العاملين بالشركة إتباعها ومراعاتها في سائر المعاملات وفي كل موقع يؤدون فيه أعمالهم بما يؤثر إيجاباً على سمعة ومصداقية الشركة ونزاهة العاملين بها، بما يضمن حقوق مساهميها وكافة المتعاملين معها. ويجب أن يلتزم بهذا الميثاق كافة العاملين بالشركة.

4/2 لائحة عمل مجلس الإدارة
_الموضع: الباب الرابع — مواثيق ولوائح وسياسات حوكمة الشركات — أولاً: المواثيق واللوائح_

هي اللائحة التي تحكم أداء مجلس الإدارة، وتكون ملزمة لرئيس المجلس وكافة أعضاءه. وتحتوي على سبيل المثال ما يلي:

• دور مجلس الإدارة.

• تشكيل مجلس الإدارة.

• واجبات وسلطات مجلس الإدارة.

• علاقة المجلس مع المساهمين.

• عدد اجتماعات المجلس والنصاب الصحيح للاجتماعات.

• مسئوليات وواجبات رئيس المجلس.

• منهجية اتخاذ قرارات المجلس.

• تعارض المصالح.

• التعامل على أسهم الشركة.

• السرية.

• منهجية تقييم أداء أعضاء المجلس.

• مسئوليات أمين سر مجلس الإدارة.

4/3 لوائح عمل لجان المجلس
_الموضع: الباب الرابع — مواثيق ولوائح وسياسات حوكمة الشركات — أولاً: المواثيق واللوائح_

هي اللوائح التي تحكم عمل وأداء لجان مجلس الإدارة وتكون ملزمة لرؤساء وأعضاء تلك اللجان، وتشمل على سبيل المثال ما يلي:

• تشكيل اللجان ومسئولياتها ومهامها.

• النصاب الصحيح لاجتماعات اللجان.

• سلطات اللجان وعدد اجتماعاتها.

• منهجية إعداد محاضر اجتماعات اللجان.

• منهجية ودورية التقارير المعروضة على مجلس الإدارة عن نتائج أعمال اللجان.

4/4 سياسة تتابع السلطة (Succession Planning)
_الموضع: الباب الرابع — مواثيق ولوائح وسياسات حوكمة الشركات — ثانياً: السياسات_

تهدف هذه السياسة إلى خلق إجراءات وتقييم عمليات الاختيار والتعيين والترقي في إطار تأمين أفضل العناصر المؤهلة للشركة في المواقع المناسبة، وفي نفس الوقت تشجيع التطوير المهني والنهوض بالموظفين الحاليين، ووضع خطة تتابع السلطة على مستوى الإدارة التنفيذية في الظروف الطارئة أو على المدى القصير والطويل مع التركيز علي التخطيط لتتابع السلطة للعناصر الرئيسية من خلال دليل إجراءات الموارد البشرية بالشركة وإعداد قائمة بالمرشحين لشغل الوظائف الرئيسية بشكل دوري وفعال بما يحقق قيمة مضافة للشركة وضمان لاستدامتها.

وتضم هذه السياسة على سبيل المثال ما يلي:

• هدف السياسة.

• نطاق تطبيقها.

• مبادئ السياسة والتي تشمل:

– الاستدامة واستمرارية النشاط.

– العدالة.

– الفاعلية والكفاءة.

– الشفافية والموضوعية.

4/5 سياسة الإفصاح
_الموضع: الباب الرابع — مواثيق ولوائح وسياسات حوكمة الشركات — ثانياً: السياسات_

تهدف هذه السياسة إلى تنظيم عملية الإفصاح عن المعلومات التزاماً بقواعد الإفصاح والشفافية التي تهدف إلى ضرورة إطلاع كافة المتعاملين مع الشركة على المعلومات التي تهمهم بصورة متساوية وعادلة.

وتضم هذه السياسة ما يلي على سبيل المثال:

• هدف السياسة.

• مجال تطبيقها.

• تحديد وتعريف الإفصاحات المالية وغير المالية الواجب الإفصاح عنها دورياً بخلاف الأحداث الجوهرية.

• وسائل الإفصاح المعتمدة من الشركة (الموقع الالكتروني– التقارير الدورية المختلفة- البيانات الصحفية– المؤتمرات - إلخ).

• الأشخاص المسموح لهم بالإفصاح.

• المعلومات التي لا يجب الإفصاح عنها.

• ما يجب عمله عند الإفصاح غير المقصود عن معلومة جوهرية.

4/6 سياسة الإبلاغ عن المخالفات (Whistleblowing)
_الموضع: الباب الرابع — مواثيق ولوائح وسياسات حوكمة الشركات — ثانياً: السياسات_

تهدف هذه السياسة إلى تشجيع العاملين بالشركة أو المتعاملين معها بالإبلاغ عن أي ممارسات مخالفة لقواعد السلوك الأخلاقي أو أية أعمال غير قانونية، وتطبيق إجراءات فعالة فيما يخص مبدأي المساءلة والمحاسبة ومن ثم تعزيز معايير الأمانة والنزاهة في كافة أنشطة الشركة المختلفة. كما توفر السياسة حماية الشخص الذي قام بالإبلاغ لضمان تشجيع العاملين بالشركة وغيرهم للمبادرة بالكشف عن المخالفات والإبلاغ عنها مع ضمان السرية التامة للشخص المبلغ أخذاً في الاعتبار أن عملية الإبلاغ تتم بناء على مستندات أو معلومات موضوعية.

وتحتوي هذه السياسة على سبيل المثال على الأتي:

• هدف السياسة.

• اللجنة المشكلة لمراجعة الحالات المتعلقة بالسلوك الأخلاقي وتقييم المخاطر المرتبطة بها.

• التوجيهات العامة لبيان سياسة الإبلاغ عن المخالفات وتشمل:

– إجراءات الإبلاغ.

– سرية المعلومات وسرية الهوية.

– حماية المبلغ.

– إجراءات التحقيق في المخالفات المبلغ عنها.

– بعض التعريفات (الاحتيال والاختلاس– القنوات المخصصة للإبلاغ عن المخالفات– الأمور غير الأخلاقية– المبلغ– الإبلاغ– إلخ).

