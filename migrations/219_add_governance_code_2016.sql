4/7/1 سياسة تعامل الداخليين
_الموضع: الباب الرابع — مواثيق ولوائح وسياسات حوكمة الشركات — ثانياً: السياسات — 4/7 سياسات تعارض المصالح_

هي سياسة تحكم عملية تداول الداخليين على أسهم الشركة طبقاً لقواعد الجهات الرقابية، وتضمن تفهم كافة الأطراف المعنية لتعريف التداول الداخلي وقواعد تنظيمه.

وتحتوي هذه السياسة على الآتي على سبيل المثال:

• هدف السياسة.

• تعريف المقصود بالتداول من قبل الداخليين.

• بعض التعريفات (الداخليين - الفترة المغلقة– المعلومات الداخلية– الأحداث الجوهرية– إلخ).

• سوء استخدام المعلومات الداخلية.

• القيود التي تضعها الجهات الرقابية والشركة على تعاملات الداخليين.

4/7/2 سياسة التعامل مع الأطراف ذات العلاقة والأطراف المرتبطة
_الموضع: الباب الرابع — مواثيق ولوائح وسياسات حوكمة الشركات — ثانياً: السياسات — 4/7 سياسات تعارض المصالح_

إن معاملات الأطراف ذات الصلة تمثل نوعاً من أنواع تعارض المصالح، لذا فإن الهدف من هذه السياسة هو وضع معايير لضبط معاملات الأطراف ذات العلاقة بما لا يخل بمصلحة الشركة ويحفظ حقوق مساهميها.

وتحتوي هذه السياسة على الآتي على سبيل المثال:

• هدف السياسة.

• تعريف المعاملات التي تخضع لهذه السياسة.

• تعريف مصطلح "الأطراف ذات العلاقة".

• معايير الموافقة على المعاملات مع الأطراف ذات العلاقة.

• اعتماد المعاملات مع الأطراف ذات العلاقة.

4/8 سياسة المسئولية الاجتماعية والبيئية
