ينعقد مجلس الإدارة على الأقل مرة كل ثلاثة أشهر، مع إمكانية استعانة المجلس بمن يراه من داخل أو خارج الشركة لمناقشة بعض الموضوعات الخاصة بعمل الشركة. ويتم الإفصاح في التقرير السنوي للشركة وتقرير مجلس الإدارة عن عدد الاجتماعات وعن أسماء الأعضاء الذين تغيبوا عن حضور اجتماعات المجلس أو اجتماعات اللجان المنبثقة عنه، ويراعى ألا يتغيب العضو عن أكثر من ثلث عدد اجتماعات مجلس الإدارة في السنة. على أن تتم الدعوة للاجتماعات في مواعيد وأماكن ووفقاً لترتيبات تيسر على الأعضاء الحضور.

لمجلس الإدارة أن يعقد اجتماعاته عن طريق وسائل الاتصال الحديثة مثل المؤتمر الهاتفي أو Video Conference على أن ينص النظام الأساسي للشركة على ذلك ويضع المجلس ضوابط استخدام تلك الوسائل في عقد الاجتماعات ومشاركة الأعضاء عن بعد.

2/2/3 دور مجلس الإدارة ومسئولياته
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/2 المحور الثاني: مجلس الإدارة_

مجلس إدارة الشركة هو الذي يتولى إدارة أمورها بناءً على تكليف من الجمعية العامة. لذلك فإن المسئولية النهائية عن الشركة تظل لدى المجلس، ولو قام بتشكيل لجان أو تفويض جهات أو أفراد آخرين في القيام ببعض أعماله، ويتم مسائلة المجلس ومحاسبته عن إدارة الشركة من قبل الجمعية العامة للمساهمين. وتؤخذ قرارات المجلس بالأغلبية، وفي حالة اضطرار المجلس لاتخاذ قرارات عن طريق التمرير نتيجة لظروف طارئة فلابد أن يكون التصويت على تلك القرارات بمشاركة جميع أعضاء المجلس.

يلعب مجلس إدارة الشركة دوراً مهماً وحاسماً في وضع الأهداف الإستراتيجية لها، وإقرار الخطط والسياسات العامة التي تهيمن على سير العمل بالشركة، وكذلك مراقبة أداء الإدارة التنفيذية، والتأكد من فعالية نظام الرقابة الداخلية وإدارة مخاطر الشركة، وتحديد الأسلوب الأمثل لتطبيق الحوكمة، واعتماد السياسات والمعايير المهنية الواجب إتباعها من قبل العاملين بما ينعكس على أدائهم وتصرفاتهم. ولذلك فإن لقرارات مجلس الإدارة تأثير كبير على أداء الشركة بما يضمن الحفاظ على أصولها وتعظيم ثروة مساهميها.

يجب على عضو مجلس الإدارة أن يعتبر نفسه ممثلاً لكافة المساهمين وملتزماً بالقيام بما يحقق مصالح الشركة عموماً ومراعاة حقوق المصالح الأخرى وليس ما يحقق مصالح المجموعة التي يمثلها أو التي قامت بالتصويت على تعيينه.

ومن ضمن مسئوليات ومهام مجلس الإدارة على سبيل المثال لا الحصر ما يلي:

• وضع الآليات والنظم التي تضمن التزام كافة العاملين بالشركة بالقوانين والمواثيق والسياسات الداخلية للشركة، ويكون مسئولاً كذلك عن وضع نظام للإنذار المبكر لكشف أي خلل أو انحراف قد يحدث، وضمان سرعة اتخاذ الإجراء المناسب. ولابد أن يتضمن هذا النظام سبل لحماية مصادر المعلومات والمبلغين عن الفساد والانحراف.

• الاجتماع بمديري الشركة للتشاور معهم في أياً من شئونها، سواء بحضور أعضاء المجلس التنفيذيين أو بدونهم، على أن يتم التنسيق معهم من خلال أمين سر مجلس الإدارة في تحديد المواعيد وإطلاعهم على ما سوف يتم التشاور بشأنه.

• وضع خطة تدريبية لأعضاء مجلس الإدارة تتضمن فكر وثقافة حوكمة الشركات ومهام عمل المجلس ولجانه وأية موضوعات أخرى يراها المجلس هامة لأعضائه.

• وضع خطة لتتابع السلطة داخل الشركة وذلك للوظائف الإدارية العليا فضلاً عن أعضاء مجلس الإدارة بما يضمن استدامة الشركة وسير أعمالها بشكل فعال.

• تحديد الصلاحيات التي يقوم بتفويضها لأحد أعضاءه أو لجانه أو غيرهم، وكذلك يجب على المجلس تحديد مدة التفويض، ودورية التقارير التي يحصل عليها من اللجان والإدارة التنفيذية، ومتابعة نتائج ممارسة تلك الصلاحيات المفوضة.

• طلب الحصول على رأي استشاري خارجي في أي من أمور الشركة، متى وافق على ذلك أغلبية أعضاء المجلس، وبشرط مراعاة أحكام تجنب تعارض المصالح، ومع ملاحظة أن استخدام المستشارين لا يعفي أعضاء المجلس من مسئوليتهم.

• وضع الإجراءات الوقائية والأدوات والآليات التي تعمل على تأمين تدفق المعلومات والسيطرة على دقة وسلامة البيانات داخل الشركة وحمايتها من التلاعب والاختراق سواء من داخل الشركة أو من خارجها مثل تأمين استخدام الانترنت وأجهزة المحمول ضد الاختراقات والقرصنة.

• الإشراف العام على عملية الإفصاح عن البيانات وقنوات الاتصال، وضمان نزاهة التقارير المالية والمحاسبية الصادرة عن الشركة، وكذلك ضمان استقلالية كل من نشاط المراجعة الداخلية والالتزام بالشركة.

• تعيين أمين سر لمجلس الإدارة من ذوى الكفاءة والفهم لكافة أعمال الشركة، كما يمكن للمجلس إنشاء وحدة تنظيمية لأمانة السر بحسب حجم واحتياجات الشركة.

2/2/4 مسئوليات رئيس مجلس الإدارة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/2 المحور الثاني: مجلس الإدارة_

رئيس مجلس الإدارة هو المسئول عن حسن أداء المجلس بشكل عام، ويقع على عاتقه مسئولية إرشاد وتوجيه المجلس وضمان فعالية أدائه. ويجب أن يتحلى بالخبرات المطلوبة والكفاءات والصفات الشخصية التي تمكنه من الوفاء بمسئولياته. ولعل من أبرز مهامه على الأقل ما يلي:

• توجيه الدعوة لانعقاد مجلس الإدارة ووضع جدول أعماله وإدارة جلساته.

• دعوة الجمعية العامة العادية وغير العادية للانعقاد للنظر في جدول الأعمال المعروض من مجلس الإدارة.

• التأكد من إتاحة المعلومات الكافية والدقيقة في الوقت المناسب لأعضاء المجلس والمساهمين.

• التأكد من أن اتخاذ القرارات يتم على أساس سليم وبناءً على دراية شاملة بالموضوعات مع ضرورة التأكد من وجود آلية مناسبة لضمان فعالية تنفيذ تلك القرارات في الوقت المناسب.

• تشجيع النقاش والنقد وضمان إمكانية التعبير عن الآراء المعارضة ومناقشتها في إطار عملية اتخاذ القرار.

• تلقي التقارير والتوصيات من كافة اللجان وعرضها على المجلس بصفة دورية لاتخاذ اللازم بشأنها.

• التأكد من قيام كل أعضاء المجلس بإجراء التقييم الذاتي الذي يبين مدى التزام العضو بواجبات وظيفته.

• التأكد من التزام المجلس بإنجاز مهامه على أكمل وجه بما يحقق أفضل مصلحة للشركة مع ضرورة تجنب تعارض المصالح.

• الحفاظ على روابط الثقة بين كافة أعضاء المجلس وخاصة بين الأعضاء التنفيذيين وغير التنفيذيين مع ضرورة تدعيم علاقة المجلس ككل بالإدارة العليا للشركة.

• التأكد من فعالية نظام الحوكمة المطبق بالشركة وكذلك فعالية أداء لجان المجلس.

2/2/5 مسئوليات عضو مجلس الإدارة المنتدب
