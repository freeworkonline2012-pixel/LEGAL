2/1/1 تشكيل الجمعية العامة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/1 المحور الأول: الجمعية العامة للمساهمين_

تتكون الجمعية العامة من كل مساهمي الشركة، كلٍ بحسب نسبة ما يمتلكه من أسهمها. وبينما يمكن أن ينص النظام الأساسي للشركة علي ألا يحضر اجتماع الجمعية العامة سوى المساهم الذي يمتلك عدد معين من الأسهم، إلا أن مثل هذا النص يجب أن يعتبر استثناءً من القاعدة التي تعطي كل مساهم حق حضور الجمعية العامة ولا يتم اللجوء إليه إلا عندما يتجاوز عدد المساهمين قدرة الشركة على تدبير مكان انعقاد الجمعية، مع ضرورة مراعاة أنه لا يجوز استخدام هذا الحق كوسيلة لتجاهل مساهمي الأقلية.

2/1/2 حضور الجمعية العامة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/1 المحور الأول: الجمعية العامة للمساهمين_

يجب حث وتوعية المساهمين على ضرورة حضور اجتماع الجمعية العامة للشركة، وترتيب موعد ومكان اجتماعها بما ييسر عليهم ويشجعهم على الحضور. وفي حالة الشركات ذات عدد الأعضاء الكبير فإنه وطبقاً لأفضل الممارسات الدولية يمكن للشركة استخدام الوسائل الالكترونية ونظم الاتصال المختلفة لإتاحة فرص نقل الوقائع أو تسجيلها للمساهمين في الخارج أو الداخل. وعلى الشركة أن تقوم بتسهيل إجراءات حضور المساهمين مع الالتزام بالقانون والنظام الأساسي للشركة فيما يختص بإجراءات الدعوة للجمعية العامة وكيفية إدارتها.

2/1/3 سير أعمال الجمعية العامة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/1 المحور الأول: الجمعية العامة للمساهمين_

يتم تعيين أمين سر للجمعية العامة وفارزي أصوات من غير أعضاء الجمعية العامة ومجلس الإدارة.

تتم إدارة الجمعية العامة على النحو الذي يسمح للمساهمين بالتعبير عن آرائهم في ضوء ما ينظمه القانون والنظام الأساسي وبما يتوافق مع جدول أعمال الجمعية، وعلى إدارة الشركة الإفصاح التام والكافي عن كل ما يتضمنه جدول أعمال الجمعية من موضوعات.

يكون كل موضوع معروض في جدول أعمال الجمعية العامة العادية أو غير العادية مصحوباً بالبيانات والمعلومات التي تمكن المساهمين من اتخاذ قراراتهم. ويجب أن يكون القصد من تقديم تلك المعلومات هو تمكين المساهمين من اتخاذ قراراتهم بشكل سليم ومدروس وليس مجرد استكمال الجوانب الشكلية للاجتماع، كما يجب الرد على كافة الاستفسارات الواردة من المساهمين سواء كانت مرسلة قبل الاجتماع لتضمينها ضمن جدول الأعمال أو تخصيص وقت كافي خلال الاجتماع للرد على تلك الاستفسارات.

2/1/4 قرارات الجمعية العامة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/1 المحور الأول: الجمعية العامة للمساهمين_

يفضل استخدام أسلوب "التصويت التراكمي" على أن ينص عليه في النظام الأساسي للشركة وذلك لتمثيل كافة المساهمين عند انتخاب أعضاء مجلس الإدارة بحيث تكون النتيجة النهائية معبرة عن التمثيل النسبي لكافة المساهمين. ويجب أن تقدم سيرة ذاتية مختصرة عن كل مرشح لعضوية مجلس إدارة الشركة إلى المساهمين عند دعوتهم لانتخاب المجلس.

يجب تسجيل التصويت على قرارات الجمعية العامة للشركة بدقة متناهية. وفى حالة نشوب أي خلاف بشأن صحة بعض الأصوات في التصويت على كل أو بعض القرارات المعروضة على الجمعية العامة، يؤخذ التصويت باعتبار صحة هذه الأصوات مرة وبطلانها مرة أخرى للعرض لاحقاً على الجهة الإدارية أو القضائية المختصة بحيث تستمر إجراءات الجمعية العامة في جميع الأحوال.

بما يتفق مع القوانين السارية والنظام الأساسي لكل شركة فمن حق مساهمي الأقلية الذين يمتلكون نسبة 5% على الأقل من رأس المال المصدر للشركة طلب إضافة بنود على جدول أعمال الجمعية العامة، وكذلك الاعتراض على قرارات الجمعية العامة للجهة الإدارية، والتي تقوم بدورها بوقف قرارات الجمعية العامة التي تصدر لصالح فئة الأغلبية ضد فئة الأقلية. كما أن من حق 3% فأكثر من المساهمين إلزام الشركة بعقد اجتماع جمعية عامة بالشكل الذي ينظمه القانون في إطار حماية حقوق مساهمي الأقلية.

يقوم أمين سر الجمعية بصياغة محضر اجتماع الجمعية العامة بحيث يشمل جميع المناقشات والأحداث والقرارات التي تمت في الاجتماع. وتقوم الشركة بالإفصاح عن القرارات التي تم اتخاذها وجميع الأحداث الجوهرية للكافة وفي نفس الوقت. ويجب أن تنشر الشركة محاضر اجتماع جمعياتها العامة على موقعها الالكتروني، فضلاً عن إتاحته مطبوعاً للجمهور كلما أمكن ذلك.

تلتزم الشركة المقيد لها أوراق مالية بالبورصة بموافاة الهيئة العامة للرقابة المالية والبورصة المصرية بقرارات الجمعية العامة العادية وغير العادية فور انتهائها، وبحد أقصى قبل بدء أول جلسة تداول تالية لانتهاء الاجتماع بما يحقق إتاحة المعلومات للجميع بشكل عادل.

في حالة المعاملات مع المجموعات المرتبطة والأطراف ذات الصلة أو إجراء عقود معاوضة، يجب أن يقوم مجلس الإدارة بأخذ الموافقة المسبقة من الجمعية العامة على تلك المعاملات أو العقود تجنباً لتعارض المصالح وبالتحديد مع كبار المساهمين، وأعضاء مجلس الإدارة، والداخليين، أو أي شركات أخرى ذات صلة. فيتعين أن يتم إجراء المعاملة بحيادية وموضوعية دون أن يحق للطرف المعني بعقد المعاوضة بالتصويت في الجمعية العامة، مع مراعاة عدم الإضرار بمصلحة الشركة وأصحاب المصالح الأخرى، مع ضرورة الإفصاح الكامل عن كل تلك المعاملات سواء عقود المعاوضة المعروضة للعام التالي أو ما تم بشأن عقود المعاوضة المبرمة في العام السابق.

2/2 المحور الثاني: مجلس الإدارة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات_

2/2/1 تشكيل مجلس الإدارة
_الموضع: الباب الثاني — المحاور الرئيسية لحوكمة الشركات — 2/2 المحور الثاني: مجلس الإدارة_

مع الالتزام بالقانون والنظام الأساسي لكل شركة، يشكل مجلس الإدارة من عدد مناسب من الأعضاء على نحو يمكنه من الاضطلاع بوظائفه وواجباته وبما في ذلك تشكيل لجانه. كما يجب أن تكون أغلبية أعضاء المجلس من غير التنفيذيين بينهم عضوين مستقلين على الأقل يتمتعون بمهارات فنية وتحليلية مما يجلب نفعاً للمجلس وللشركة. وطبقاً لأفضل الممارسات الدولية يتم مراعاة مزيج أعضاء المجلس دون التحيز لجنس أو عقيدة.

في جميع الأحوال يتعين عند اختيار الأعضاء المستقلين وغير التنفيذيين مراعاة أن يكون العضو قادراً على تخصيص الوقت والاهتمام الكافي للشركة وألا يكون هناك تعارضاً مع مصالح أخرى له.

يجب توفير المعلومات والبيانات والشرح الكافي عن الشركة لأعضاء مجلس الإدارة الجدد عند تعيينهم حتى يتمكنوا من الإلمام بكافة جوانبها العامة ونقاط القوة والضعف بها، وهيكلها الإداري وعناصر ميزانيتها، وكل ما يمكنهم من القيام بعملهم بفاعلية وعلى أكمل وجه. ويقوم أمين سر مجلس الإدارة بدور حلقة الوصل بين أعضاء المجلس وبعضهم البعض وبين مجلس الإدارة والإدارة العليا بالشركة.

يتولى مجلس الإدارة انتخاب رئيس المجلس وتعيين العضو المنتدب، ولا يفضل الجمع بين منصبي رئيس مجلس الإدارة والعضو المنتدب. وفي حال عدم إمكان ذلك يجب الإفصاح عن أسباب ذلك في التقرير السنوي والموقع الالكتروني للشركة. وفي هذه الحالة وطبقاً لأفضل الممارسات الدولية يتم تعيين نائب رئيس مجلس إدارة مستقل يرأس الاجتماعات التي تناقش أداء الإدارة التنفيذية.

2/2/2 سير اجتماعات مجلس الإدارة
