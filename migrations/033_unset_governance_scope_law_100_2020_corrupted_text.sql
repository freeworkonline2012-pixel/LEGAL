-- للتحقق منها مباشرة قبل بناء أى سؤال اختبار عليها — وهو بالضبط ما لم يحدث
-- بالتفصيل الكافى وقت كتابة migration 032 (اكتُفى وقتها بالتحقق من 951/2003
-- و205/2021 تحديداً، المذكورين صراحة فى تقرير التدقيق كمشكلة معروفة).
--
-- هذا التحقق كشف أن **100/2020** (قواعد حوكمة الشركات العاملة فى الأنشطة
-- المالية غير المصرفية) نصه تالف جزئياً بنمط مختلف عن 951/2003 و205/2021
-- (تلف كامل واضح): هنا خليط من فقرات عربية سليمة تماماً وفقرات أخرى معكوسة/
-- مشوَّهة **داخل نفس المادة**. تحديداً:
--   • المادة 2 (432 حرف): سليمة.
--   • المادة 3 (466 حرف): تالفة بالكامل ("تارررنح اساررراتاا اساخاطمرررر...").
--   • المادة 4 (28,626 حرف — كل "قواعد الحوكمة" المرفقة مضغوطة كمادة واحدة):
--     خليط — فقرات مرقّمة كاملة سليمة تماماً (مثل بنود اختصاصات لجنة
--     المراجعة ولجنة المخاطر) تتخللها فقرات أخرى مشوَّهة بنفس نمط 951/2003.
--
-- عرض مقتطف من هذه المادة كـ"أساس قانونى" لحكم حوكمة (متوافق/غير متوافق)
-- أخطر فعلياً من استبعاد قانون تالف بالكامل: خليط سليم/تالف قد يُقنع مستخدماً
-- بموثوقية النص بينما يُخفى شرطاً أو استثناءً حقيقياً فى الجزء المشوَّه. لا حل
-- مؤقت هنا (مثل فلترة عرض المقتطفات التالفة فقط) لأن التمييز الآلى بين
-- "فقرة سليمة" و"فقرة تالفة لكن تبدو نصاً" غير موثوق بما يكفى؛ الاستبعاد
-- الكامل من نطاق الاسترجاع هو نفس القرار الجذرى المتبع مع 951/2003 و205/2021.
--
-- ملاحظة تحقق: باقى الـ18 قانوناً المتبقية فُحصت ببحث نصى مباشر عن نفس نمط
-- التلف (توكينز معكوسة مميزة مثل "اسقاار"/"اسااتر" بدل "القرار"/"الشركة")
-- عبر كامل نصوصها — صفر تطابق فى كل الـ18، فلا حاجة لاستبعاد إضافى الآن.
--
-- النتيجة بعد هذه الهجرة: 18 (وليس 19) قانوناً/قراراً ضمن نطاق الحوكمة.
-- إعادة الوسم لـ100/2020 تنتظر إعادة استخراج نصه (OCR بجودة أعلى أو نسخ
-- يدوى من مصدر نظيف) وفصل المادة 4 الضخمة إلى مواد/بنود حقيقية منفصلة —
-- مهمة ترحيل بيانات كاملة، لا تصحيح هجرة.

BEGIN;

UPDATE laws SET governance_scope = false
WHERE law_no = 100 AND law_year = 2020 AND governance_scope = true;

DO $verify$
DECLARE
  v_count int;
  v_expected int := 18;
BEGIN
  SELECT count(*) INTO v_count FROM laws WHERE governance_scope = true;
  IF v_count <> v_expected THEN
    RAISE WARNING 'governance_scope: % law(s) tagged after correction, expected % — تحقّق يدوياً', v_count, v_expected;
  ELSE
    RAISE NOTICE 'governance_scope: % law(s) tagged as expected after excluding 100/2020', v_count;
  END IF;
END;
$verify$;

COMMIT;
