المادة 1 (الاصدار)
يعمل فى المسائل والمنازعات المتعلقة بالمواريث بالأحكام المرافقة لهذا القانون.

المادة 2 (الاصدار)
على وزير العدل تنفيذ هذا القانون، ويعمل به بعد شهر من تاريخ نشره بالجريدة الرسمية.

المادة 1
يستحق الإرث بموت المورث أو باعتباره ميتا بحكم القاضى.

المادة 2
يجب لاستحقاق الإرث تحقق حياة الوارث وقت موت المورث أو وقت الحكم باعتباره ميتا. ويكون الحمل مستحقا للإرث إذا توافر فيه ما نص عليه في المادة 43.

المادة 3
إذا مات اثنان ولم يعلم أيهما مات أولا فلا استحقاق لأحدهما فى تركة الآخر سواء أكان موتهما فى حادث واحد أم لا.

المادة 4
يؤدى من التركة بحسب الترتيب الآتى: أولا – ما يكفى لتجهيز الميت ومن تلزمه نفقته من الموت الى الدفن. ثانيا – ديون الميت. ثالثا – ما أوصى به فى الحد الذى تنفذ فيه الوصية. ويوزع ما بقى بعد ذلك على الورثة، فإذا لم يوجد ورثة قضى من التركة بالترتيب الآتى: أولا – استحقاق من أقر له الميت بنسب على غيره. ثانيا- ما أوصى به فيما زاد على الحد الذى تنفذ فيه الوصية فإذا لم يوجد أحد من هؤلاء آلت التركة أو ما بقى منها إلى الخزانة العامة.

المادة 5
من موانع الإرث قتل المورث عمدا سواء أكان القاتل فاعلا أصليا أم شريكا أم كان شاهد زور أدت شهادته إلى الحكم بالإعدام وتنفيذه إذا كان القتل بلا حق ولا عذر وكان القاتل عاقلا بالغا من العمر خمس عشرة سنة وتعد من الأعذار تجاوز حق الدفاع الشرعى.

المادة 6
لا توارث بين مسلم وغير مسلم. ويتوارث غير المسلمين بعضهم من بعض واختلاف الدارين لا يمنع من الإرث بين المسلمين ولا يمنع بين غير المسلمين إلا إذا كانت شريعة الدار الأجنبية تمنع من توريث الأجنبى عنها.

المادة 7
أسباب الإرث: الزوجية والقرابة والعصوبة السببية، يكون الإرث بالزوجية بطريق الفرض ويكون الإرث بالقرابة بطريق الفرض أو التعصيب أو بهما معا، أو بالرحم مع مراعاة قواعد الحجب والرد. فإذا كان لوارث جهتا إرث ورث بهما معا مع مراعاة أحكام المادتين 14، 37.

المادة 8
الفرض سهم مقدر للوارث فى التركة، ويبدأ فى التوريث بأصحاب الفروض وهم: الأب، الجد الصحيح وإن علا، الأخ لأم، الأخت لأم، الزوج، الزوجة، البنات، بنات الابن وان نزل، الأخوات لأب وأم، الأخوات لأب، الأم، الجدة الصحيحة وإن علت.

المادة 9
مع مراعاة حكم المادة 21 للأب فرض السدس إذا وجد للميت ولد أو ولد ابن وإن نزل والجد الصحيح هو الذى لا يدخل فى نسبته إلى الميت أنثى، وله فرض السدس على الوجه المبين فى الفقرة السابقة.

المادة 10
لأولاد الأم فرض السدس للواحد والثلث للاثنين فأكثر ذكورهم وإناثهم فى القسمة سواء. وفى الحالة الثانية إذا استغرقت الفروض التركة يشارك أولاد الأم الأخ الشقيق أو الأخوة الأشقاء بالانفراد أو مع أخت شقيقة أو أكثر، ويقسم الثلث بينهم جميعا على الوجه المتقدم.

المادة 11
للزوج فرض النصف عند عدم الولد وولد الأبن وان نزل والربع مع الولد أو ولد الابن وإن نزل. وللزوجة ولو كانت مطلقة رجعيا إذا مات الزوج وهى فى العدة أو الزوجات فرض الربع عند عدم الولد وولد الابن وان نزل، والثمن مع الولد أو ولد الابن وان نزل، وتعتبر المطلقة بائنا فى مرض الموت فى حكم الزوجة إذا لم ترض بالطلاق ومات المطلق فى ذلك المرض وهى فى عدته.

المادة 12
مع مراعاة حكم المادة 19: (أ) – للواحدة من البنات فرض النصف وللاثنتين فأكثر الثلثان. (ب)- ولبنات الابن الفرض المتقدم ذكره عند عدم وجود بنت أو بنت ابن أعلى منهن درجة، ولهن واحدة أو أكثر – السدس مع البنت أو بنت الابن الأعلى درجة.

المادة 13
مع مراعاة حكم المادتين 19، 20: أ- للواحدة من الأخوات الشقيقات فرض النصف وللاثنتين فأكثر الثلثان. ب- وللأخوات لأب الفرض المتقدم ذكره عند عدم وجود أخت شقيقة، ولهن واحدة أو أكثر السدس مع الأخت الشقيقة.

المادة 14
للأم فرض السدس مع الولد أو ولد الابن وإن نزل أو مع اثنين أو أكثر من الأخوة والأخوات ولها الثلث فى غير هذه الأحوال غير أنها إذا اجتمعت مع أحد الزوجين والأب فقط كان لها ثلث ما بقى بعد فرض الزوج. والجدة الصحيحة هى أم أحد الأبوين أو الجد الصحيح وإن علت وللجدة أو الجدات السدس، ويقسم بينهم على السواء لا فرق بين ذات قرابة وذات قرابتين.

المادة 15
إذا زادت أنصباء أصحاب الفروض على التركة قسمت بينهم بنسبة أنصبائهم فى الإرث.

القسم الثانى — فى الإرث بالتعصيب

المادة 16
إذا لم يوجد أحد من ذوى الفروض أو وجد ولم تستغرق الفروض التركة كانت التركة أو ما بقى منها بعد الفروض للعصبة من النسب.
والعصبة من النسب ثلاثة أنواع:
1- عصبة بالنفس.
2- عصبة بالغير.
3- عصبة مع الغير.

المادة 17
للعصبة بالنفس جهات أربع مقدم بعضها على بعض فى الإرث على الترتيب الآتى:
1- البنوة: وتشمل الأبناء وأبناء الابن وإن نزل.
2- الأبوة: وتشمل الأب والجد الصحيح وإن علا.
3- الاخوة: وتشمل الاخوة لأبوين والأخوة لأب وأبناء الأخ لأبوين وأبناء الأخ وإن نزل كل منهما.
4- العمومة: وتشمل أعمام الميت وأعمام أبيه وأعمام جده الصحيح وإن علا سواء كانوا لأبوين أم لأب وأبناء من ذكروا وأبناء أبنائهم وان نزلوا.

المادة 18
إذا اتحدت العصبة بالنفس فى الجهة كان المستحق للإرث أقربهم درجة للميت.
فإذا اتحدوا فى الجهة والدرجة كان التقديم بالقوة، فمن كان ذا قرابتين للميت قدم على من كان ذا قرابة واحدة.
فإذا اتحدوا فى الجهة والدرجة والقوة كان الإرث بينهم على السواء.

المادة 19
العصبة بالغير هن:
1- البنات مع الأبناء.
2- بنات الابن وإن نزل مع أبناء الابن وإن نزل إذا كانوا فى درجتهن مطلقا أو كانوا أنزل منهن إذا لم ترثن بغير ذلك.
3- الأخوات لأبوين مع الأخوة لأبوين والأخوات لأب مع الأخوة لأب.
ويكون الإرث بينهم فى هذه الأحوال للذكر مثل حظ الأنثيين.

المادة 20
العصبة مع الغير هن:
الأخوات لأبوين أو لأب من البنات أو بنات الابن وإن نزل ويكون لهن الباقى من التركة بعد الفروض. وفى هذه الحالة يعتبرون بالنسبة لباقى العصبات كالأخوة لأبوين أو لأب ويأخذون أحكامهم فى التقديم بالجهة والدرجة والقوة.

المادة 21
إذا اجتمع الأب أو الجد مع البنت أو بنت الابن وان نزل استحق السدس فرضا والباقى بطريق التعصيب.

المادة 22
إذا اجتمع الجد مع الأخوة والأخوات لأبوين أو لأب كانت له حالتان:
الأولى – أن يقاسمهم كأخ إن كانوا ذكورا فقط أو ذكورا وإناثا أو إناثا عصبن مع الفرع الوارث من الإناث.
الثانية – أن يأخذ الباقى بعد أصحاب الفروض بطريق التعصيب إذا كان مع أخوات لم يعصبن بالذكور أو مع الفرع الوارث من الإناث.
على أنه إذا كانت المقاسمة أو الإرث بالتعصيب على الوجه المتقدم تحرم الجد من الإرث أوتنقصه عن السدس واعتبر صاحب فرض بالسدس ولا يعتبر فى المقاسمة من كان محجوبا من الأخوة أو الأخوات لأب.

الباب الثالث — فى الحجب

المادة 23
الحجب هو أن يكون لشخص أهلية الإرث ولكنه لا يرث بسبب وجود وارث آخر والمحجوب يحجب غيره.

المادة 24
المحروم من الإرث لمانع من موانعه لا يحجب أحدا من الورثة.

المادة 25
تحجب الأم الجدة الصحيحة مطلقا وتحجب الجدة القريبة الجدة البعيدة ويحجب الأب الجدة لأب. كما يحجب الجد الصحيح الجدة إذا كانت اصلا له.

المادة 26
يحجب أولاد الأم كل من الأب والجد الصحيح وإن علا والولد وولد الابن وإن نزل.

المادة 27
يحجب كل من الابن وابن الابن وإن نزل بنت الابن التى تكون أنزل منه درجة ويحجبها أيضا بنتان أو بنتا ابن أعلا منهما درجة ما لم يكن معها من يعصبها طبقا لحكم المادة 19.

المادة 28
تحجب الأخت لأبوين كلا من الابن وابن الابن وإن نزل والأب.

المادة 29
تحجب الأخت لأب كل من الأب والابن وابن الابن وإن نزل كما يحجبها الأخ لأبوين والأخت لأبوين إذا كانت عصبة مع غيرها طبقا لحكم المادة 20.
والأختان لأبوين إذا لم يوجد أخ لأب.

المادة 30
إذا لم تستغرق الفروض التركة ولم توجد عصبة من النسب رد الباقى على غير الزوجين من أصحاب الفروض بنسبة فروضهم، ويرد باقى التركة إلى أحد الزوجين إذا لم يوجد عصبة من النسب أو أحد أصحاب الفروض النسبية أو أحد ذوى الأرحام.

المادة 31
إذا لم يوجد أحد من العصبة بالنسب ولا أحد من ذوى الفروض النسبية كانت التركة أو الباقى منها لذوى الأرحام.
وذوو الأرحام أربعة أصناف:
الصنف الأول: أولاد البنات وإن نزلوا، وأولاد بنات الابن وان نزلوا.
الصنف الثانى: الجد غير الصحيح وإن علا، والجدة غير الصحيحة وإن علت.
الصنف الثالث: أبناء الأخوة لأم وأولادهم وإن نزلوا، وأولاد الأخوات مطلقا وإن نزلوا.
الصنف الرابع: ويشمل ست طوائف:
الطائفة الأولى: أعمام الميت لأم وعماته وأخواله وخالاته لأبوين أو لأحدهما.
الطائفة الثانية: أولاد من ذكروا فى الفقرة السابقة وإن نزلوا، وبنات أعمام الميت لأبوين أو لأب وبنات أبنائهم وإن نزلوا.
الطائفة الثالثة: أعمام أبى الميت لأم وعماته وأخواله وخالاته لأبوين أو لأحدهما وأعمام أم الميت.
الطائفة الرابعة: أولاد من ذكروا فى الفقرة السابقة وإن نزلوا، وبنات أعمام أب الميت لأبوين أو لأب.
الطائفة الخامسة: أعمام أب أب الميت لأم، وأعمام أب أم الميت وعماتهما وأخوالهما وخالتهما.
الطائفة السادسة: أولاد من ذكروا فى الفقرة السابقة وان نزلوا، وبنات أب أب الميت لأبوين أو لأب.

المادة 32
الصنف الأول من ذوى الأرحام أولاهم بالميراث أقربهم إلى الميت درجة. فإن استووا فى الدرجة فولد صاحب الفرض أولى من ولد ذوى الرحم.

المادة 33
الصنف الثانى من ذوى الأرحام أولاهم بالميراث أقربهم الى الميت درجة فإن استووا فى الدرجة قدم من كان يدلى بصاحب فرض. وعند اختلاف الحيز يكون الثلثان لقرابة الأب والثلث لقرابة الأم.

المادة 34
الصنف الثالث من ذوى الأرحام أولاهم بالميراث أقربهم إلى الميت درجة، فإن استووا فى الدرجة وكان فيهم ولد عصب فهو أولى من ولد ذى الرحم.

المادة 35
فى الطائفة الأولى من طوائف الصنف الرابع المبينة بالمادة 31 إذا انفرد فريق الأب وهم أعمام الميت لأم وعماته، أو فريق الأم — يقدم من كان لأبوين على من كان لأب، وعند الاجتماع يكون الثلثان لقرابة الأب والثلث للأم. وذات الأحكام تطبق على الطائفتين الثالثة والخامسة.

المادة 36
فى الطائفة الثانية يقدم الأقرب منهم درجة، على الأبعد ولو من غير حيزه، ويتم الاستواء مع اتحاد الحيز بتقديم الأقوى قرابة. وعند كونهم من أولاد عاصب أو ذى رحم، يُفضَّل ولد العاصب على ولد ذى الرحم. وعند اختلاف الحيز يكون الثلثان لقرابة الأب والثلث لقرابة الأم. وما يصيب كل فريق يُقسم بالطريقة السابقة. والطائفتان الرابعة والسادسة تطبقان ذات الأحكام.

المادة 37
لا اعتبار لتعدد جهات القرابة فى وارث من ذوى الأرحام إلا عند اختلاف الحيز.

المادة 38
فى إرث ذوى الأرحام يكون للذكر مثل حظ الأنثيين.

المادة 39
العاصب السببى يشمل: 1- مولى العتاقة ومن أعتقه أو أعتق من أعتقه. 2- عصبة المعتق أو عصبة من أعتقه. كذلك من له الولاء على مورث أمة غير حرة الأصل بواسطة أبيه سواء بطريق الجر أم بغيره، أو بواسطة جدة بدون جر.

المادة 40
يرث المولى ذكرا أو أنثى معتقة على أى وجه كان العتق وعند عدمه يقوم مقامه عصبته بالنفس بالترتيب المبين بالمادة 17، بشرط ألا ينقص نصيب الجد عن السدس. عند عدمه ينتقل الإرث إلى معتق المولى ثم عصبته، وهكذا يرث من له الولاء على أب الميت ثم جده.

المادة 41
إذا أقر الميت بالنسب على غيره استحق المقر له التركة إذا كان مجهول النسب ولم يثبت نسبه من الغير ولم يرجع المقر عن إقراره. ويشترط فى هذه الحالة أن يكون المقر له حيا وقت موت المقر أو وقت الحكم باعتباره ميتا، وألا يقوم به مانع من موانع الإرث.

المادة 42
يوقف للحمل من تركة المتوفى أوفر النصيبين على تقدير أنه ذكر أو أنثى.

المادة 43
إذا توفى الرجل عن زوجته أو عن معتدته فلا يرثه حملها إلا إذا ولد حيا لخمسة وستين وثلثمائة يوم على الأكثر من تاريخ الوفاة أو الفرقة. ولا يرث الحمل غير أبيه إلا فى الحالتين الآتيتين: الأولى – أن يولد حيا لخمسة وستين وثلثمائة يوم على الأكثر من تاريخ الموت. أو الفرقة إن كانت أمه معتدة موت أو فرقة، ومات المورث أثناء العدة. الثانية – أن يولد حيا لسبعين ومائتى يوم على الأكثر من تاريخ وفاة المورث إن كان من زوجية قائمة وقت الوفاة.

المادة 44
إذا نقص الموقوف للحمل عما يستحقه يرجع بالباقى على من دخلت الزيادة فى نصيبه من الورثة وإذا زاد الموقوف للحمل عما يستحقه رد الزائد على من يستحقه من الورثة.

المادة 45
يوقف للمفقود من تركة مورثه نصيبه فيها فإن ظهر حيا أخذه وإن حكم بموته رد نصيبه إلى من يستحقه من الورثة وقت موت مورثه فإن ظهر حيا بعد الحكم بموته أخذ ما بقى من نصيبه بأيدى الورثة.

المادة 46
للخنثى المشكل وهو الذى لا يعرف أذكر هو أم أنثى أقل النصيبين وما بقى من التركة يعطى لباقى الورثة.

المادة 47
مع مراعاة المدة المبينة بالفقرة الأخيرة من المادة 43 يرث ولد الزنا وولد اللعان من الأم وقرابتها وترثهما الأم وقرابتها.

المادة 48
التخارج هو أن يتصالح الورثة على إخراج بعضهم من الميراث على شئ معلوم. فإذا تخارج أحد الورثة مع آخر منهم استحق نصيبه وحل محله فى التركة، وإذا تخارج أحد الورثة مع باقيهم فإن كان المدفوع له من التركة قسم نصيبه بينهم بنسبة انصبائهم فيها، وإن كان المدفوع من مالهم ولم ينص على عقد التخارج على طريقة قسمة نصيب الخارج قسم عليهم بالسوية بينهم.

المادة 49
مع عدم الإخلال بأية عقوبة أشد ينص عليها أى قانون آخر، يعاقب بالحبس مدة لا تقل عن ستة أشهر وبغرامة لا تقل عن عشرين ألف جنيه ولا تجاوز مائة ألف جنيه، أو بإحدى هاتين العقوبتين، كل من امتنع عمدًا عن تسليم أحد الورثة نصيبه الشرعى من الميراث، أو حجب سندًا يؤكد نصيبًا لوارث، أو امتنع عن تسليم ذلك السند حال طلبه من أى من الورثة الشرعيين. وتكون العقوبة فى حالة العود الحبس الذى لا تقل مدته عن سنة. ويجوز الصلح فى الجرائم المنصوص عليها فى هذه المادة فى أى حالة تكون عليها الدعوى ولو بعد صيرورة الحكم باتًا. ولكل من المجنى عليه أو وكيله الخاص، ولورثته أو وكيلهم الخاص، وكذلك للمتهم أو المحكوم عليه أو وكيلهما الخاص، إثبات الصلح فى هذه الجرائم أمام النيابة أو المحكمة بحسب الأحوال. ويترتب على الصلح انقضاء الدعوى الجنائية ولو كانت مرفوعة بطريق الإدعاء المباشر، وتأمر النيابة العامة بوقف تنفيذ العقوبة إذا تم الصلح أثناء تنفيذها، ولا يكون للصلح أثر على حقوق المضرور من الجريمة (معدلة بالقانون رقم 219 لسنة 2017).$inh77$, '1943-12-08', 'active'
