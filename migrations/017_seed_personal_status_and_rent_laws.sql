المادة 3
الطلاق المقترن بعدد لفظا أو اشارة لا يقع الا واحدة.

المادة 4
كنايات الطلاق وهي ما تحتمل الطلاق وغيره لا يقع بها الطلاق الا بالنية.

المادة 5
كل طلاق يقع رجعيا الا المكمل للثلاث والطلاق قبل الدخول والطلاق على مال وما نص على كونه بائنا في هذا القانون والقانون نمرة 25 سنة 1920.

المادة 5 مكررا
على المطلق أن يوثق إشهاد طلاقه لدى الموثق المختص خلال ثلاثين يوما من إيقاع الطلاق.

المادة 6
إذا ادعت الزوجة اضرار الزوج بها بما لا يستطاع معه دوام العشرة بين أمثالهما يجوز لها أن تطلب من القاضي التفريق وحينئذ يطلقها القاضي طلقة بائنة إذا ثبت الضرر وعجز عن الاصلاح بينهما فاذا رفض الطلب ثم تكررت الشكوى ولم يثبت الضرر بعث القاضي حكمين وقضى على الوجه المبين بالمواد.

المادة 6 مكررا
على الزوج أن يقدم للموثق إقرارا كتابيا يتضمن حالته الاجتماعية فإذا كان متزوجا فعليه أن يبين في الإقرار اسم الزوجة أو الزوجات اللاتي في عصمته وقت العقد الجديد ومحال إقامتهن وعلى الموثق إخطارهن بالزواج الجديد بكتاب موصى عليه. ويعتبر إضرارا بالزوجة اقتران زوجها بأخرى بغير رضاها ولو لم تكن قد اشترطت عليه في عقد زواجها عدم الزواج عليها وكذلك إخفاء الزوج على زوجته الجديدة أنه متزوج بسواها. ويسقط حق الزوجة في طلب التفريق بمضي سنة من تاريخ علمها بقيام السبب الموجب للضرر، ما لم تكن قد رضيت بذلك صراحة أو ضمنا.

المادة 7
يشترط في الحكمين أن يكونا عدلين من أهل الزوجين أن أمكن وإلا فمن غيرهم ممن لهم خبرة بحالهما وقدرة على الإصلاح بينهما.

المادة 8
يشتمل قرار بعث الحكمين على تاريخ بدء وانتهاء مأموريتهما على ألا تجاوز مدة ستة أشهر وتخطر المحكمة الحكمين والخصم بذلك.

المادة 9
لا يؤثر في سير عمل الحكمين امتناع أحد الزوجين عن حضور مجلس التحكيم متى تم إخطاره.

المادة 10
إذا عجز الحكمان عن الإصلاح فإن كانت الإساءة كلها من جانب الزوج اقترح الحكمان التطليق بطلقة بائنة دون مساس بشيء من حقوق الزوجة المترتبة على الزواج والطلاق.

المادة 11
على الحكمين أن يرفعا تقريرهما إلى المحكمة مشتملا على الأسباب التي بنى عليها فإن لم يتفقا بعثتهما مع ثالث.

المادة 11 مكررا
على الزوج أن يقر في وثيقة الزواج بحالته الاجتماعية، فإذا كان متزوجا فعليه أن يبين في الإقرار اسم الزوجة أو الزوجات اللاتي في عصمته ومحال إقامتهن، وعلى الموثق إخطارهن بالزواج الجديد بكتاب مسجل مقرون بعلم الوصول. ويجوز للزوجة التي تزوج عليها زوجها أن تطلب الطلاق منه إذا لحقها ضرر مادي أو معنوي يتعذر معه دوام العشرة بين أمثالهما ولو لم تكن قد اشترطت عليه في العقد ألا يتزوج عليها. فإذا عجز القاضي عن الإصلاح بينهما طلقها عليه طلقة بائنة. ويسقط حق الزوجة في طلب التطليق لهذا السبب بمضي سنة من تاريخ علمها بالزواج بأخرى، إلا إذا كانت قد رضيت بذلك صراحة أو ضمنا. ويتجدد حقها في طلب التطليق كلما تزوج بأخرى. وإذا كانت الزوجة الجديدة لم تعلم أنه متزوج بسواها ثم ظهر أنه متزوج فلها أن تطلب التطليق كذلك.

المادة 11 مكررا ثانيا
إذا امتنعت الزوجة عن طاعة الزوج دون حق توقف نفقة الزوجة من تاريخ الامتناع. وتعتبر ممتنعة دون حق إذا لم تعد لمنزل الزوجية بعد دعوة الزوج إياها للعودة بإعلان على يد محضر لشخصها أو من ينوب عنها، وعليه أن يبين في هذا الإعلان المسكن. وللزوجة الاعتراض على هذا أمام المحكمة الابتدائية خلال ثلاثين يوما من تاريخ هذا الإعلان، وعليها أن تبين في صحيفة الاعتراض الأوجه الشرعية التي تستند إليها في امتناعها عن طاعته وإلا حكم بعدم قبول اعتراضها. ويعتد بوقف نفقتها من تاريخ انتهاء ميعاد الاعتراض إذا لم تتقدم به في الميعاد. وعلى المحكمة عند نظر الاعتراض، أو بناء على طلب أحد الزوجين، التدخل لإنهاء النزاع بينهما صلحا باستمرار الزوجية وحسن المعاشرة، فإذا بان لها أن الخلاف مستحكم وطلبت الزوجة التطليق اتخذت المحكمة إجراءات التحكيم الموضحة في المواد من 7 إلى 11 من هذا القانون.

المادة 12
إذا غاب الزوج سنة فأكثر بلا عذر مقبول جاز لزوجته أن تطلب الى القاضي تطليقها بائنا إذا تضررت من بعده عنها.

المادة 13
ان أمكن وصول الرسائل الى الغائب ضرب له القاضي أجلا وأعذر اليه بأنه يطلقها عليه ان لم يحضر للإقامة معها.

المادة 14
للزوجة المحبوس المحكوم عليه نهائيا بعقوبة مقيدة للحرية مدة ثلاث سنين فأكثر أن تطلب الى القاضي بعد مضى سنة من حبسه التطليق عليه بائنا للضرر.

المادة 15
لا تسمع عند الانكار دعوى النسب لولد زوجة ثبت عدم التلاقي بينها وبين زوجها من حين العقد ولا لولد زوجة أتت به بعد سنه من غيبة الزوج عنها.

المادة 16
تقدر نفقة الزوجة بحسب حال الزوج وقت استحقاقها يسرا أو عسرا على ألا تقل النفقة فى حالة العسر عن القدر الذي يفي بحاجتها الضرورية.

المادة 17
لا تسمع الدعوى لنفقة عدة لمدة تزيد على سنة من تاريخ الطلاق. كما أنه لا تسمع عند الانكار دعوى الإرث بسبب الزوجية لمطلقة توفى زوجها بعد سنة من تاريخ الطلاق.

المادة 18
لا يجوز تنفيذ حكم بصفة صادر بعد العمل بهذا القانون لمدة تزيد على سنة من تاريخ الطلاق.

المادة 18 مكررا
الزوجة المدخول بها في زواج صحيح إذا طلقها زوجها دون رضاها ولا بسبب من قبلها تستحق فوق نفقة عدتها متعة تقدر بنفقة سنتين على الأقل.

المادة 18 مكررا ثانيا
إذا لم يكن للصغير مال فنفقته على أبيه. وتستمر نفقة الاولاد على أبيهم إلى أن تتزوج البنت أو تكسب ما يكفي نفقتها.

