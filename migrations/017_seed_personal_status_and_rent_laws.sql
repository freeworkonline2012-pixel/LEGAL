وتلتزم محاكم الأسرة بنظر الدعاوى التى تحال إليها، تطبيقًا لأحكام الفقرة السابقة دون عرضها على مكاتب تسوية المنازعات الأسرية المنصوص عليها فى القانون المرفق ولا تسرى الفقرة الأولى على الدعاوى المحكوم فيها أو الدعاوى المؤجلة للنطق بالحكم، وتبقى الأحكام الصادرة فى هذه الدعاوى خاضعة للقواعد المنظمة لطرق الطعن فيها السارية قبل العمل بهذا القانون.

المادة الثالثة
تستمر محكمة النقض ومحاكم الاستئناف والمحاكم الابتدائية فى نظر الطعون المرفوعة أمامها قبل تاريخ العمل بأحكام القانون المرفق عن الأحكام والقرارات الصادرة من المحاكم الجزئية والابتدائية ومحاكم الاستئناف على حسب الأحوال فى الدعاوى التى أصبحت بموجبه من اختصاص محاكم الأسرة.

المادة الرابعة
يصدر وزير العدل القرارات اللازمة لتنفيذ أحكام القانون المرفق، وذلك خلال ثلاثة أشهر من تاريخ صدوره.

المادة الخامسة
ينشر هذا القانون فى الجريدة الرسمية، ويعمل به اعتبارًا من أول أكتوبر سنة 2004.

قانون إنشاء محاكم الأسرة (القانون المرفق)

المادة 1
تنشأ بدائرة اختصاص كل محكمة جزئية محكمة للأسرة، يكون تعيين مقرها بقرار من وزير العدل.

المادة 2
تؤلف محكمة الأسرة من ثلاثة قضاه يكون أحدهم على الأقل بدرجة رئيس بالمحكمة الابتدائية، ويعاون المحكمة في الدعاوى المنصوص عليها في المادة (11) خبيران.

المادة 3
تختص محاكم الأسرة دون غيرها، بنظر جميع مسائل الأحوال الشخصية التي ينعقد الاختصاص بها للمحاكم الجزئية والابتدائية.

المادة 4
تنشأ نيابة متخصصة لشئون الأسرة تتولى المهام المخولة للنيابة العامة أمام محاكم الأسرة ودوائرها الاستئنافية.

المادة 5
تنشأ بدائرة اختصاص كل محكمة جزئية مكتب أو أكثر لتسوية المنازعات الأسرية، يتبع وزارة العدل.

المادة 6
يجب على من يرغب في إقامة دعوى بشأن إحدى مسائل الأحوال الشخصية أن يقدم طلباً لتسوية النزاع إلى مكتب تسوية المنازعات الأسرية المختص.

المادة 7
يصدر وزير العدل قرارًا يتضمن تشكيل مكاتب تسوية المنازعات الأسرية وتعيين مقار عملها وإجراءات تقديم طلبات التسوية إليها.

المادة 8
يجب أن تنتهى التسوية خلال خمسة عشر يومًا من تاريخ تقديم الطلب، فإذا تم الصلح يتولى رئيس مكتب التسوية إثباته في محضر.

المادة 9
