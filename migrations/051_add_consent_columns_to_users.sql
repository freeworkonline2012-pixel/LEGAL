-- 051_add_consent_columns_to_users.sql
--
-- المسار التقنى الأول من حل قانون حماية البيانات الشخصية المصرى 151/2020
-- (بند "الأساس القانونى للمعالجة" المُعلَّم 🔴 فى DPIA بتاريخ 2026-08-21،
-- والقرار المُسجَّل بتاريخ 2026-09-03 و2026-09-11). راجع نقاش صاحب المشروع
-- بتاريخ 2026-09-12: تنفيذ المسار التقنى فوراً، وتأجيل المسار القانونى
-- (الأساس القانونى الدقيق، إخطار مركز حماية البيانات) لجلسة لاحقة مع محامٍ.
--
-- هذه الهجرة تبنى البنية التحتية لتوثيق "موافقة صريحة" وقت التسجيل — بصرف
-- النظر عن الصياغة القانونية النهائية للنص الذى سيُعرَض على المستخدم (تلك
-- مسؤولية المحامى)، فإن وجود عمودى consent_given_at وconsent_version
-- ضرورى بنيوياً بأى حال: بدونهما، لا توجد وسيلة تقنية لإثبات متى ولأى نسخة
-- من سياسة الخصوصية وافق مستخدم معيّن — وهذا الإثبات نفسه جزء من الالتزام
-- القانونى، لا تفصيلة تقنية ثانوية.
--
-- idempotent بأمان (ADD COLUMN IF NOT EXISTS) — يُعاد تطبيقها فى كل نشر
-- (لا يوجد جدول تتبع migrations مُطبَّقة، راجع scripts/run-migration.js).

BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS consent_given_at timestamptz NULL;
ALTER TABLE users ADD COLUMN IF NOT EXISTS consent_version text NULL;

-- ⚠️ لا يوجد backfill لمستخدمين مُسجَّلين قبل هذه الهجرة: تسجيلهم تم فعلياً
-- قبل وجود آلية الموافقة الصريحة، فتسجيل قيمة consent_given_at اصطناعية
-- الآن (مثلاً NOW()) سيكون توثيقاً كاذباً لموافقة لم تُؤخَذ فعلياً بهذا
-- الشكل — أسوأ من ترك الحقل NULL بصراحة. القرار بشأن التعامل مع هذه الفئة
-- (مطالبتهم بإعادة الموافقة عبر بانر عند أول دخول تالٍ، مثلاً) قرار منتج/
-- قانونى منفصل، لا تُتَّخذ هنا.

COMMIT;
