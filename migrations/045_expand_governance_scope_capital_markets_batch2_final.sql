-- الدفعة الثانية والأخيرة من تدقيق نطاق الحوكمة لفئة capital_markets (تكملة
-- migrations/044): تقييم المستندات الأربعة الضخمة المؤجَّلة هناك صراحة
-- (636/2024، 11/2014، 95/1992، 135/1993) — آخر أربعة مستندات فى الفئة، وبهذا
-- تكتمل مراجعة الـ17 مستنداً كاملةً فى فئة capital_markets.
--
-- ==================== المنهجية (مطابقة لـ 044) ====================
-- نفس المعيار الثابت: هل يفرض المستند التزامات حوكمة/تأهيل (Fit & Proper)
-- على الكيان المرخَّص نفسه (تكوين مجلس إدارة، قواعد حوكمة صريحة، تعارض
-- مصالح، لجان رقابة داخلية) — أم ينظّم سوقاً أو منتجاً أو إجراءً تشغيلياً
-- بحتاً بلا شرط حوكمة/تأهيل على الكيان؟
--
-- نظراً لحجم هذه الأربعة (من 80 ألف حرف حتى 732 ألف حرف)، اعتُمد بحث
-- مستهدف بالكلمات المفتاحية (حوكمة، مجلس الإدارة، تعارض المصالح، لجنة
-- المراجعة، الإفصاح، مراقب الحسابات...) على المتن الفعلى المُستخرَج
-- برمجياً لكل مادة على حدة (لا العنوان، ولا قراءة خطية كاملة لنص بهذا
-- الحجم)، ثم قراءة كاملة للمواد التى أظهرت إشارة حوكمية فعلية قبل اتخاذ أى
-- قرار — بنفس صرامة الدفعة الأولى، فقط بمنهجية بحث مختلفة تتناسب مع الحجم.
--
-- ==================== القرارات ====================
--
-- ❌ استُبعد (1): 636/2024 — تعديل معايير المحاسبة المصرية بما يخص شهادات
--   خفض الانبعاثات الكربونية. استُخرج المتن الفعلى (16,922 حرفاً) وبُحث عن
--   كل الكلمات المفتاحية الحوكمية (مجلس إدارة، Fit & Proper، تعارض مصالح،
--   حوكمة، مسئول امتثال، ترخيص، سوابق جنائية، مساهم) — صفر نتيجة عدا
--   "ترخيص" (مرتين، فى سياق فنى محاسبى لا صلة له بترخيص كيانات). معيار
--   محاسبى تقنى بحت، لا يمس حوكمة الكيان المُصدِر. **يبقى خارج النطاق.**
--
-- ✅ أُدرِج (3):
--
--   • 11/2014 — قواعد قيد وشطب الأوراق المالية بالبورصة المصرية. يحتوى على
--     "الباب الرابع: الحوكمة وحماية حقوق الأقلية والقوائم المالية" كاملاً
--     (قُرئ بالكامل، المواد 37 حتى 47 مكرراً) — يفرض على كل شركة مقيدة:
--     تشكيل لجنة مراجعة (المادة 37: 3 أعضاء غير تنفيذيين على الأقل، أغلبية
--     مستقلين، رئيس مستقل)، تشكيل لجنة ترشيحات ومكافآت (المادة 37 مكرراً)
--     تفحص صراحة "معايير الاستقلال والملاءمة والنزاهة والكفاءة (Fit &
--     Proper)" لمرشحى عضوية مجلس الإدارة، ضوابط تعاملات الداخليين ومنع
--     التداول فى فترات الحظر (المادة 38)، حظر عقود المعاوضة مع أطراف
--     مرتبطة إال بموافقة الجمعية العامة (المادة 39)، ضوابط حضور المداولات
--     والتصويت والإفصاح عند تعارض المصالح (المادتان 39 مكرر و39 مكرر 1)،
--     ومحتوى إلزامى لتقرير مجلس الإدارة يشمل تقريراً سنوياً صريحاً عن مدى
--     تطبيق "قواعد الحوكمة" (المادة 40). هذا نمط Fit & Proper وحوكمة كيان
--     كامل ال لبس فيه، بل هو نفس درجة الجدية فى 58/2018 و42/2019 المُدرَجين
--     فعلاً فى 044. وجود أبواب أخرى فى نفس المستند (قواعد القيد والشطب
--     الفنية، الإفصاح الدورى) لا يمنع الإدراج: الاسترجاع فى الخدمة يتم على
--     مستوى المادة (FTS/دلالى) ال القانون كاملاً، فإدراج القانون كله ال
--     يُسرِّب محتوى غير حوكمى لأسئلة حوكمية، فقط يتيح استرجاع مواد الباب
--     الرابع الفعلية عند الحاجة.
--
--   • 95/1992 — قانون سوق رأس المال (القانون التأسيسى). بحث مستهدف على
--     137 مادة مُستخرَجة برمجياً أظهر: المادة 26 تشترط صراحة أن يتضمن قرار
--     ترخيص أى بورصة جديدة "تشكيل مجلس اإلدارة، وقواعد الحوكمة" وأن يتضمن
--     النظام األساسى "قواعد تجنب حاالت تعارض المصالح لدى أعضاء مجلس اإلدارة
--     والعاملين"؛ المادة 38 تشترط "قواعد تجنب تعارض المصالح" فى إدارة صناديق
--     االستثمار. هذا القانون هو األساس التشريعى الذى تُبنى عليه كل قرارات
--     الترخيص والحوكمة الالحقة فى القطاع (بما فيها 58/2018 و9/2021
--     المُدرَجين فعالً) — استبعاده بينما تُدرَج القرارات المبنية عليه تناقض
--     منهجى غير مبرَّر.
--
--   • 135/1993 — الالئحة التنفيذية لقانون سوق رأس المال. بحث مستهدف على
--     457 مادة مُستخرَجة برمجياً أظهر: المادة 124 تُلزم كل الشركات العاملة
--     فى مجال األوراق المالية صراحة بـ"االلتزام بقواعد الحوكمة التى يصدرها
--     مجلس إدارة الهيئة" (نص فعلى سارى بعد تعديل قرار رئيس مجلس الوزراء
--     3045/2023)؛ المادة 171 تُلزم الهيئة بوضع "قواعد حوكمة شركات
--     الصناديق"؛ 13 إشارة لـ"تعارض المصالح" و35 لـ"مراقب الحسابات" عبر
--     المستند. هذا التزام حوكمة صريح وعام على كل كيان مرخَّص فى القطاع، ال
--     مجرد إجراء تشغيلى.
--
-- ==================== الأثر على النطاق ====================
-- كان نطاق capital_markets = 4 (بعد 044). يصبح 7 (+3: 11/2014، 95/1992،
-- 135/1993). إجمالى governance_scope الكلى كان 22، يصبح 25.
--
-- التحقق: قابلة لإعادة التشغيل بأمان (idempotent) — WHERE governance_scope
-- IS DISTINCT FROM true يمنع أى تأثير عند إعادة التشغيل. 636/2024 لا يُلمَس
-- (يبقى غير مُدرَج، القرار سلبى فلا حاجة لأى UPDATE بشأنه).

BEGIN;

UPDATE laws SET governance_scope = true
WHERE country_code = 'EG'
  AND (law_no, law_year) IN ((11, 2014), (95, 1992), (135, 1993))
  AND category = 'capital_markets'
  AND governance_scope IS DISTINCT FROM true;

DO $verify$
DECLARE
  v_count int;
  v_expected int := 25;
  v_cm_count int;
  v_cm_expected int := 7;
BEGIN
  SELECT count(*) INTO v_count FROM laws WHERE governance_scope = true;
  SELECT count(*) INTO v_cm_count FROM laws WHERE governance_scope = true AND category = 'capital_markets';
  IF v_count <> v_expected OR v_cm_count <> v_cm_expected THEN
    RAISE WARNING 'governance_scope: % قانوناً موسوماً (منها % من capital_markets)، المتوقَّع % (منها %) — تحقّق يدوياً', v_count, v_cm_count, v_expected, v_cm_expected;
  ELSE
    RAISE NOTICE 'governance_scope: % قانوناً موسوماً كما هو متوقَّع (منها % من فئة capital_markets — اكتملت مراجعة الفئة بالكامل: 7 من 17 مُدرَجة)', v_count, v_cm_count;
  END IF;
END;
$verify$;

COMMIT;
