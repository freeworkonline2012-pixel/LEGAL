DECLARE
  v_expected int := 24;
  v_total int; v_found int; v_todo int; v_done int; v_skipped int;
  v_art_before int; v_ver_before int; v_upd_art int; v_upd_ver int; v_bad int;
BEGIN
  SELECT count(*) INTO v_total FROM m217_fix;
  IF v_total <> v_expected THEN
    RAISE EXCEPTION '[217] تحميل البيانات ناقص: % من %', v_total, v_expected;
  END IF;

  CREATE TEMP TABLE m217_tgt ON COMMIT DROP AS
    SELECT a.id AS article_id, f.old_md5, f.new_md5, f.new_body, md5(a.body) AS cur_md5
    FROM m217_fix f
    JOIN laws l ON l.country_code = 'EG' AND l.kind = f.kind AND l.law_no = f.law_no AND l.law_year = f.law_year
    JOIN articles a ON a.law_id = l.id AND a.article_no = f.article_no AND a.article_suffix_order = f.suffix;
  SELECT count(*) INTO v_found FROM m217_tgt;
  SELECT count(*) INTO v_done FROM m217_tgt WHERE cur_md5 = new_md5;
  SELECT count(*) INTO v_todo FROM m217_tgt WHERE cur_md5 = old_md5 AND old_md5 <> new_md5;
  v_skipped := v_total - v_done - v_todo;

  SELECT count(*) INTO v_art_before FROM articles;
  SELECT count(*) INTO v_ver_before FROM article_versions;

  INSERT INTO migration_217_backup (article_id, version_id, old_body)
    SELECT a.id, NULL, a.body FROM m217_tgt t JOIN articles a ON a.id = t.article_id
    WHERE t.cur_md5 = t.old_md5 AND t.old_md5 <> t.new_md5
    ON CONFLICT DO NOTHING;
  INSERT INTO migration_217_backup (article_id, version_id, old_body)
    SELECT v.article_id, v.id, v.body FROM m217_tgt t JOIN article_versions v ON v.article_id = t.article_id
    WHERE md5(v.body) = t.old_md5 AND t.old_md5 <> t.new_md5
    ON CONFLICT DO NOTHING;

  UPDATE article_versions v SET body = t.new_body
    FROM m217_tgt t
    WHERE v.article_id = t.article_id AND md5(v.body) = t.old_md5 AND t.old_md5 <> t.new_md5;
  GET DIAGNOSTICS v_upd_ver = ROW_COUNT;
  UPDATE articles a SET body = t.new_body
    FROM m217_tgt t
    WHERE a.id = t.article_id AND md5(a.body) = t.old_md5 AND t.old_md5 <> t.new_md5;
  GET DIAGNOSTICS v_upd_art = ROW_COUNT;

  IF (SELECT count(*) FROM articles) <> v_art_before OR (SELECT count(*) FROM article_versions) <> v_ver_before THEN
    RAISE EXCEPTION '[217] تغيّر عدد المواد أو النسخ';
  END IF;
  IF v_upd_art <> v_todo THEN
    RAISE EXCEPTION '[217] عدد المواد المعدلة % لا يطابق المتوقع %', v_upd_art, v_todo;
  END IF;
