مجلس إدارة الهيئة العامة للرقابة المالية

بعد الاطلاع على قانون سوق رأس المال الصادر بالقانون رقم (95) لسنة 1992 ولائحته التنفيذية؛
وعلى القانون رقم (10) لسنة 2009 بتنظيم الرقابة على الأسواق والأدوات المالية غير المصرفية؛
وعلى قرار رئيس الجمهورية رقم (192) لسنة 2009 بإصدار النظام الأساسي للهيئة العامة للرقابة المالية؛
وعلى قرار مجلس إدارة الهيئة رقم (8) لسنة 2014 بشأن تنظيم عمل لجان الرقابة الشرعية للمنتجات المالية الصادرة وفقاً لأحكام الشريعة الإسلامية؛
وعلى خطاب الأزهر الشريف بشأن الموافقة على ضوابط تشكيل واشتراطات عضوية لجان الرقابة الشرعية لإصدارات الصكوك المتوافقة مع أحكام الشريعة الإسلامية؛
