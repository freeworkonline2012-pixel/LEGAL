قرر

(المادة الأولى) (2)
تُشكل لجنة مركزية للرقابة الشرعية تتولى القيام بما يلي:
1. اعتماد إصدار الصكوك المتوافقة مع أحكام الشريعة الإسلامية المقدمة من الجهات المصدرة لها وتشرف من الناحية الشرعية على إصدارات هذه الصكوك واستخدام حصيلتها، كما تقوم بمراجعة التقارير ربع السنوية التي تقدم للهيئة من قبل لجان الرقابة الشرعية الفرعية بالمؤسسات العاملة في الأنشطة المالية غير المصرفية التي تجيز إصدار الصكوك التي تتوافق مع أحكام الشريعة الإسلامية خلال الفترة من إصدار الصكوك وحتى الاسترداد وفقاً لقواعد ومعايير الإفصاح الصادرة عن الهيئة.
2. اعتماد إصدار المنتجات المالية غير المصرفية المتوافقة مع أحكام الشريعة الإسلامية.
3. اعتماد قيد لجان الرقابة الشرعية الفرعية في السجل المخصص لذلك لكافة الأنشطة المالية غير المصرفية.
4. تنمية وتطوير أدوات ومنتجات الأنشطة المالية غير المصرفية المتوافقة مع أحكام الشريعة الإسلامية.
ويكون للجنة إبداء أي إيضاحات أو ملاحظات على أي من بنود الإصدار أو بعضها إذا ارتأت أنها غير متوافقة مع أحكام الشريعة الإسلامية، وتلتزم الشركة أو الجهة بالإفصاح عن تلك الإيضاحات أو الملاحظات. (3)

(المادة الثانية)
تُشكل اللجنة المشار إليها بالمادة الأولى من هذا القرار من سبعة أعضاء تكون غالبيتهم من أبرز علماء الشريعة الإسلامية والمتخصصين الذين لديهم خبرة واسعة في المجالات الاقتصادية والمحاسبية والأنشطة المالية المصرفية وغير المصرفية المرتبطة بمجالات التمويل الإسلامي. (4)
ويصدر بتشكيل اللجنة قرار من مجلس إدارة الهيئة لمدة ثلاث سنوات قابلة للتجديد بعد موافقته على ذلك.
ويكون للجنة أمانة فنية من موظفي الهيئة الذين يحددهم رئيس الهيئة، ويكون رئيسها أميناً عاماً للجنة، وتتولى الأمانة الفنية للجنة تدوين محاضر جلساتها ومتابعة تنفيذ قراراتها وحفظ قيودها وسجلاتها، والتنسيق بين الإدارات المختلفة بالهيئة وطلب البيانات والأبحاث في الموضوعات المرتبطة بعمل لجنة الرقابة الشرعية المركزية وفقاً للقواعد والإجراءات التي يعتمدها رئيس الهيئة، وكذا التنسيق والاتصال مع المؤسسات ولجان الرقابة الشرعية بالدول الإسلامية في ضوء المهام التي يحددها رئيس لجنة الرقابة الشرعية المركزية.
ولمجلس إدارة الهيئة إعادة تشكيل اللجنة وله إعفاء بعض أعضائها وذلك بقرار مسبب بعد توجيه إنذار مشفوع بالمبررات وتحديد مدة للتصحيح، وبعد الاستماع إلى وجهات نظر هيئة الرقابة الشرعية أو أعضائها المقرر إعفائهم.

(المادة الثالثة) (5)
يجب أن يتوافر في أعضاء لجنة الرقابة الشرعية المركزية الشروط الآتية:
1. أن يتم قيد أعضاء اللجنة في سجل خاص يعد لهذا الغرض لدى الهيئة للأعضاء الذين يوافق مجلس إدارة الهيئة على انضمامهم للجنة.
2. ألا يكون مساهماً رئيسياً أو عضو مجلس إدارة في أي من الشركات التي تزاول أنشطة مالية غير مصرفية، خلال السنتين السابقتين على العضوية.
وعلى مجلس إدارة الشركات المشار إليها ورئيس لجنة الرقابة الشرعية المركزية موافاة الهيئة بأي حالات تعارض في المصالح ممكنة أو محتملة.
وإذا كان عضو لجنة الرقابة الشرعية المركزية عضواً بإحدى لجان الرقابة الشرعية الفرعية، يتم استبعاد تصويته على القرارات حال عرض موضوعات تخص اللجنة الفرعية التي يكون عضواً بها.

(المادة الرابعة) (6)
تختص لجنة الرقابة الشرعية المركزية بما يلي:
1. الاشتراك مع الهيئة في وضع نماذج العقود والاتفاقيات الخاصة بإصدار الصكوك والأدوات والعقود والمنتجات المالية غير المصرفية التي تتوافق مع أحكام الشريعة الإسلامية للتأكد من خلوها من المحظورات الشرعية.
2. وضع المعايير والأطر والأحكام العامة للجانب الشرعي في إصدارات الصكوك والأدوات والعقود والمنتجات المالية غير المصرفية التي تتوافق مع أحكام الشريعة الإسلامية.
3. إبداء الرأي والتصنيف الشرعي لطلبات إصدارات الصكوك وفقاً لأحكام الشريعة الإسلامية بحسب توافقها، إظهاراً لحجم المخاطر لمراعاة حقوق حاملي الصكوك وعرضها على مجلس إدارة الهيئة، مع تقديم مقترحات عملية للجهة المصدرة لتصحيحها أو تغيير التصنيف إن أمكن، وكذا إبداء الرأي والتصنيف الشرعي في الطلبات والتقارير التي تقدم إليها دورياً من الهيئة أو لجان الرقابة الشرعية الفرعية.
4. إبداء الرأي والمشورة فيما يعهد إليها من التقارير التي تقدم اليها دورياً من لجنة الرقابة الشرعية الفرعية بالمؤسسات العاملة في الأنشطة المالية غير المصرفية للتحقق من استمرار التعامل في صكوك المصدرة وفقاً لأحكام الشريعة الإسلامية من تاريخ الإصدار وحتى الاسترداد وفقاً لمبادئ الشريعة الإسلامية وأحكامها وطبقاً لمعايير وقواعد الإفصاح الصادرة عن الهيئة في هذا الشأن.
5. دراسة المشاكل الشرعية التي تواجه إصدارات الصكوك خلال عمر الصك وكذا المنتجات المالية غير المصرفية (إن وجدت) وإبداء الرأي فيها واقتراح الحلول لها.
6. مراجعة استفسارات لجان الرقابة الشرعية الفرعية بالمؤسسات العاملة في الأنشطة المالية غير المصرفية وإصدار الفتاوى الشرعية في أحكام قيد وتداول أو استرداد أي من إصدارات الصكوك أو فيما يتعلق بالمنتجات المالية غير المصرفية أو غيرها من الموضوعات التي يطلب في شأنها فتوى شرعية.
7. مساعدة الهيئة في وضع برامج تدريب أعضاء لجان الرقابة الشرعية الفرعية بالمؤسسات المالية غير المصرفية أو العاملين المختصين بما يؤدى إلى استيعاب الصيغ الإسلامية والجوانب الفقهية والشرعية في إصدارات الصكوك أو المنتجات المالية غير المصرفية التي تتوافق مع أحكام الشريعة الإسلامية.
8. وضع ضوابط عمل وحوكمة اللجان الشرعية الفرعية.
9. إنشاء قاعدة بيانات عن الأنشطة المالية غير المصرفية التي تتوافق مع أحكام الشريعة الإسلامية بمصر والدول الإسلامية، وحصر الفتاوى والمراجع المرتبطة بها.
10. اتخاذ ما يلزم للتنسيق مع لجان الرقابة الشرعية المركزية بالدول الإسلامية.
11. تقديم تقرير سنوي لمجلس إدارة الهيئة عن السلامة الشرعية لإصدارات الصكوك والمنتجات المالية غير المصرفية القائمة بالسوق بناءً على دراسة مستوفية لذلك الغرض ووفقاً للتقارير الدورية المقدمة إليها من قبل لجان الرقابة الشرعية الفرعية المعتمدة لتلك الإصدارات، كما يجب أن يتضمن التقرير ما قامت به اللجنة لتنشيط وتطوير المنتجات المالية غير المصرفية التي تتوافق مع أحكام الشريعة الإسلامية.
12. إصدار لائحة لتنظيم أعمالها وتحديد اجتماعاتها.
13. النظر والبت في المنازعات المحالة إليها التي تنشأ بين المؤسسات العاملة في الأنشطة المالية غير المصرفية ولجان الرقابة الشرعية الفرعية عن أي من الفتاوى أو الجوانب الفقهية وذلك للنظر في التفسيرات الخاصة بالمقررات الشرعية.
كما تختص اللجنة بأي أمور أخرى تتفق مع أغراضها وفقاً لما يسنده إليها رئيس الهيئة.

ويكون للجنة في سبيل تحقيق الاختصاصات المنصوص عليها في هذا القرار ما يلي:
(أ) الاطلاع على أي مستندات أو وثائق أو سجلات أو عقود أو مكاتبات ترى أنها لازمة وضرورية لتمكينها من أداء مهامها للتوصل إلى مدى التزام اللجان الشرعية الفرعية مع الأحكام الشرعية.
(ب) إجراء تفتيش على أعمال لجان الرقابة الشرعية الفرعية بالمؤسسات المالية غير المصرفية التي يوكل إليها مهام إبداء الرأي في إصدارات الصكوك أو المنتجات المالية غير المصرفية بغرض التأكد من سلامة تطبيق الجوانب الشرعية في أعمالها.
(ج) تلتزم لجان الرقابة الشرعية الفرعية بإمداد الأمانة الفنية للجنة الرقابة الشرعية المركزية بأي تقارير أو فتاوى صدرت منهم للمؤسسات العاملة في الأنشطة المالية غير المصرفية خلال ثلاثة أشهر على الأكثر من إصدارها.
وعلى الأمانة الفنية للجنة الرقابة الشرعية حصر وجمع الفتاوى التي تخص الأنشطة المالية غير المصرفية المتوافقة مع أحكام الشريعة الإسلامية من المنظمات والمؤسسات الإسلامية.
وللجنة أن تستعين في ذلك بمن تراه ضرورياً من العاملين بالهيئة، وذلك بعد موافقة رئيس الهيئة أو من يفوضه في ذلك.

(المادة الخامسة)
تعقد لجنة الرقابة الشرعية المركزية اجتماعها الأول بدعوة من رئيس الهيئة أو من يفوضه في ذلك، وتنتخب اللجنة في هذا الاجتماع من بين أعضائها رئيساً لها ونائباً للرئيس.
وتجتمع اللجنة بدعوة من رئيسها أو نائبه عند غيابه مرة على الأقل كل شهر ويكون اجتماعها صحيحاً بحضور أغلبية أعضائها على أن يكون من بينهم الرئيس أو نائبه، وتتخذ قراراتها بأغلبية أعضائها وفي حالة التساوي يُرجح الجانب الذي منه الرئيس. (7)

(المادة السادسة)
تُشكل لجان فرعية للرقابة الشرعية من عدد من الأعضاء لا يقل عن ثلاثة ولا يزيد على خمسة، تكون غالبيتهم من المتخصصين في الفقه والمعاملات ويفضل إلمامهم بنواحي الاقتصاد والمحاسبة والقانون.
ويجب أن يكون عضو اللجنة من المقيدين بالهيئة بسجل أعضاء لجان الرقابة الشرعية وفقاً لقرار مجلس إدارة الهيئة رقم (8) لسنة 2014 بشأن تنظيم عمل لجان الرقابة الشرعية للمنتجات المالية الصادرة وفقاً لأحكام الشريعة الإسلامية.

(المادة السابعة)
يعين أعضاء لجنة الرقابة الشرعية الفرعية من قبل الجمعية العامة لمساهمي الشركة أو السلطة المختصة في غيرها من الجهات لمدة ثلاث سنوات قابلة للتجديد، على أن يتم إخطار لجنة الرقابة الشرعية المركزية بذلك. (8)
وتكون اجتماعات لجنة الرقابة الشرعية الفرعية دورية مرة على الأقل كل شهر.

(المادة الثامنة)
تُعرض على لجنة الرقابة الشرعية الفرعية للمؤسسات العاملة في الأنشطة المالية غير المصرفية، المستندات أو المذكرات أو نشرات الاكتتاب أو مذكرات المعلومات أو العقود أو الأدوات المالية الاستثمارية التي يطلق عليها متوافقة مع أحكام الشريعة الإسلامية أو غيرها من المستندات اللازمة لممارسة نشاطها، للاطلاع والدراسة الكاملة من كافة الجوانب الشرعية في ضوء فتاوى لجنة الرقابة الشرعية المركزية ومقرراته، ويكون للجنة إما إقرار ما هو معروض عليها كما هو بعد التأكد من الالتزام بالمعايير الشرعية أو بعد إدخال بعض التعديلات الضرورية أو رده أحياناً في حالة تعذر الإقرار أو التعديل، ويصدر قرار بأغلبية أعضائها. (9)
وتسجل فتاوى وقرارات اللجنة في سجلات خاصة بذلك، وتحفظ لمدة لا تقل عن خمس سنوات.

(المادة الثامنة مكرراً) (10)
يشترط فيمن يتقدم للقيد في سجل أعضاء لجان الرقابة الشرعية الفرعية بالهيئة، ما يلي:
1. أن يكون حاصلاً على درجة العالمية (الدكتوراه) من جامعة الأزهر أو ما يعادلها في أحد التخصصات ذات العلاقة.
2. أن يكون له دراستين علميتين متخصصتين على الأقل منشورتين في دورية علمية في مجالات المعاملات المالية أو المحاسبية أو الاقتصادية المتوافقة مع الشريعة الإسلامية.
3. ألا يكون قد سبق الحكم عليه بعقوبة جناية أو جنحة في جريمة ماسة بالشرف أو الأمانة أو إحدى الجرائم المنصوص عليها في قوانين الشركات أو التجارة أو أحد القوانين الواردة بالمادة الثالثة من قانون تنظيم الرقابة على الأسواق والأدوات المالية غير المصرفية المشار إليه، ما لم يكن قد رُد إليه اعتباره.
ويجوز الاستثناء من البندين الأول والثاني من شروط القيد الواردة بهذه المادة إذا توافرت إحدى الشروط التالية فيمن يتقدم للقيد:
1. أن يكون قد شغل منصب مفتي جمهورية مصر العربية.
2. أن يأتي ترشيحه من فضيلة الإمام الأكبر شيخ الأزهر الشريف أو مفتي جمهورية مصر العربية.
3. أن يقدم ما يفيد أنه قد سبق له عضوية لجان رقابة شرعية مماثلة في بنوك أو مؤسسات مالية أو صناديق استثمار لمدة ثلاث سنوات سابقة.
ويكون القيد في سجل الهيئة المشار إليه لمدة ثلاث سنوات، تُجدد بناءً على طلب كتابي من المتقدم وبشرط استيفاء متطلبات استمرار القيد التي تحددها الهيئة.
ويكون مقابل خدمات القيد أو تجديده مبلغ ثلاثة آلاف جنيه، تُسدد مع تجديد الطلب.

