import { SegmentationService } from './segmentation.service';

const seg = (t: string) => new SegmentationService().segment(t);
const nums = (t: string) => seg(t).clauses.map((c) => c.declaredNumber);
const BODY = 'يلتزم الطرف الأول بتسليم الطرف الثانى الوحدة المبيعة فى الموعد المتفق عليه كتابةً';
const L = (n: string) => [n, BODY, `${BODY} ويقر الطرف الأول بذلك`];

/** عقد البيع فى إنتاج الجولة 85: «oalall o gl» (الخامس) يُسترجع بالخطوة المعزولة، و«اليد السادس» سطر قصير آخر كلمة فيه ترتيبى. */
const sale = [
  'عقد بيع وحدة إدارية',
  ...L('البند الأول'), ...L('البند الثانى'), ...L('البند الثالث'), ...L('البند الرابع'),
  'oalall o gl',
  '5 يلتزم الطرف الأول بتسليم الطرف الثانى الوحدة المبيعة فى موعد غايته 2/1/2013 م',
  'بالمواصفات الآتية .',
  '2/5 يلتزم الطرف الأول بعمل توكيل رسمى عام غير قابل للإلغاء للطرف الثانى بالبيع',
  'لرقابه القضاء',
  'اليد السادس',
  'قبل الطرف الثانى أن يكون عضواً فى اتحاد الملاك بنصيب فى الأرض والأجزاء المشتركة',
  'عبارة عن إثنين قيراط من أربعة وعشرون قيراط الملحق بهذا العقد وتوابعه',
  'يقر الطرف الأول بأن ملكية العقار قد آلت إليه بموجب العقد المشهر رقم 3394 بتاريخ 2007',
  'مأمورية شهر عقارى الدقى وذلك عن الأرض والمبانى بالإقامة والتشييد من ماله الخاص',
  ...L('البند الثامن'), ...L('البند التاسع'),
].join('\n');

describe('الجولة 86 — الاسترجاع بالتكرار حتى الثبات', () => {
  it('«اليد السادس» يُقرأ بعد استرجاع الخامس (كان يفشل لأن خطوة الترتيبى تجرى قبل استرجاع الخامس)', () => {
    const r = seg(sale);
    const ns = r.clauses.map((c) => c.declaredNumber);
    expect(ns).toContain(5);
    expect(ns).toContain(6);
    const c6 = r.clauses.find((c) => c.declaredNumber === 6)!;
    expect(c6.text).toContain('عضواً فى اتحاد الملاك');
    const c5 = r.clauses.find((c) => c.declaredNumber === 5)!;
    expect(c5.text).not.toContain('عضواً فى اتحاد');
    // السابع ضاع كلياً من القراءة ولا دليل عليه: يبقى فى تنبيه الترقيم ولا يُخمَّن
    expect(ns).not.toContain(7);
    expect(r.warnings.join(' ')).toMatch(/غير متسلسل/);
  });

  it('لا تغيير حين لا يوجد سطر الترتيبى', () => {
    const t = sale.replace('اليد السادس', '');
    expect(nums(t)).not.toContain(6);
  });

  it('ترتيبى مختلف («الطرف السادس» جملة) لا يصير عنواناً حتى مع التكرار', () => {
    const t = sale.replace('اليد السادس', 'الطرف السادس');
    expect(nums(t)).not.toContain(6);
  });
});

/** وكالة: متن البند 15 ينتهى بسطر ذيل «بصدر هذا العقد .» بعد فراغ، ثم عنوان 16 ضائع (فراغ) ثم متنه. */
const agency = (tail: string) =>
  [
    'عقد وكالة',
    ...L('البند الثالث عشر'), ...L('البند الرابع عشر'),
    'البند الخامس عشر',
    'يقر كل من طرفى هذا العقد بانه اتخذ العنوان الموضح بصدر هذا العقد محلاً مختاراً له تتم فيه',
    'كافة المراسلات والمكاتبات الرسمية فيما بينهما بخصوص هذا العقد وفى حالة تغييره يلتزم أى',
    'منهما باخطار الطرف الاخر بذلك بخطاب مسجل بعلم الوصول خلال مدة اقصاها خمسة عشر يوماً من',
    'التغيير والا صحت الاجراءات القانونية والمراسلات الرسمية على العنوان المذكور فى صدر العقد',
    '',
    tail,
    '',
    'اتفق الطرفان على ان تختص محاكم الجيزة الابتدائية بدوائرها المختلفة بنظر اى نزاع قد ينشا',
    'البند السابع عشر',
    'تحرر هذا العقد من نسختين بيد كل طرف نسخة للعمل بموجبها عند الحاجة وللاستناد إليها قانوناً',
  ].join('\n');

describe('الجولة 86 — ذيل فقرة لا يُعد فقرة مستقلة', () => {
  it('«بصدر هذا العقد .» ذيل البند 15: يُستعاد البند 16 من فاصل الفقرات ويبقى الذيل فى 15', () => {
    const r = seg(agency('بصدر هذا العقد .'));
    expect(r.clauses.map((c) => c.declaredNumber)).toEqual([13, 14, 15, 16, 17]);
    const c15 = r.clauses.find((c) => c.declaredNumber === 15)!;
    const c16 = r.clauses.find((c) => c.declaredNumber === 16)!;
    expect(c15.text).toContain('بصدر هذا العقد .');
    expect(c16.text.startsWith('اتفق الطرفان على ان تختص')).toBe(true);
    expect(r.warnings.some((w) => w.includes('البند السادس عشر') && w.includes('فاصل الفقرات'))).toBe(true);
  });

  it('فقرة وسطى طويلة (≥ 25 حرفاً) ليست ذيلاً: ثلاث فقرات لرقم ناقص واحد فلا تخمين', () => {
    expect(nums(agency('بصدر هذا العقد وفقاً لما سبق ذكره فى هذا الموضع بالتفصيل .'))).not.toContain(16);
  });
});
