/** هل يحوى نص العقد مؤشراً على نشاط القانون القطاعى؟ */
function hasSignal(law: SectorLaw, normalizedText: string): boolean {
  let text = law.stripInsurerNames ? withoutInsurerNames(normalizedText) : normalizedText;
  for (const re of law.stripPatterns ?? []) text = text.replace(re, ' ');
  return law.signals.some((re) => matchesLoose(re, text));
}

/** مؤشر علاقة عمل بعد حذف عبارات نفى سريان قانون العمل. */
function hasEmploymentSignal(normalizedText: string): boolean {
  let text = normalizedText;
  for (const re of EMPLOYMENT_NEGATIONS) text = text.replace(re, ' ');
  return EMPLOYMENT_SIGNALS.some((re) => matchesLoose(re, text));
}

export interface LawScopeContext {
  /** نص العقد كله موحَّداً (norm) — يُحسب مرة واحدة لكل عقد. */
  normalizedText: string;
  family: PlaybookFamily | null;
}

export function lawScopeContext(contractText: string, family: PlaybookFamily | null): LawScopeContext {
  return { normalizedText: norm(contractText), family };
}

/** true = المادة تصلح مرشّحة لهذا العقد. قانون غير قطاعى ⇒ true دائماً. */
export function articleInLawScope(ctx: LawScopeContext, a: { lawNo: number | null; lawYear: number | null; articleNo?: number }): boolean {
  if (a.lawNo == null || a.lawYear == null) return true;
  // مواد عقد العمل فى القانون المدنى (674-698): تُعامل معاملة قانون العمل نفسه
  if (a.lawNo === 131 && a.lawYear === 1948 && a.articleNo !== undefined && isEmploymentRegimeArticle({ lawNo: a.lawNo, lawYear: a.lawYear, articleNo: a.articleNo })) {
    return ctx.family === 'employment' || hasEmploymentSignal(ctx.normalizedText);
  }
  // الجولة 89: باب الإيجار فى المدنى (558-634) لعقد إيجار أو عقد يدل نصه على علاقة إيجار
  if (a.lawNo === 131 && a.lawYear === 1948 && a.articleNo !== undefined && a.articleNo >= CIVIL_LEASE_FIRST && a.articleNo <= CIVIL_LEASE_LAST) {
    return ctx.family === 'lease' || LEASE_SIGNALS.some((re) => matchesLoose(re, ctx.normalizedText));
  }
  const law = SECTOR_LAWS.find((l) => l.lawNo === a.lawNo && l.lawYear === a.lawYear);
  if (!law) return true;
  if (law.onlyFamilies && !(ctx.family && law.onlyFamilies.includes(ctx.family))) return false;
  if (ctx.family && law.allowFamilies?.includes(ctx.family)) return true;
  // قانون عام محجوب عن أسر بعينها: الأسرة المجهولة والأسر الأخرى تقبله دون مؤشر
  if (law.blockFamilies) return !(ctx.family && law.blockFamilies.includes(ctx.family)) || hasSignal(law, ctx.normalizedText);
  return hasSignal(law, ctx.normalizedText);
}

