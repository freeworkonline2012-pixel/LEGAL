import { SegmentationService } from './segmentation.service';
import { findAlternativeHeads, findTolerantBareHeads } from './clause-headings-alt';

// نص اصطناعى بنفس «شكل» عقد الإنتاج الذى فقد عنوانه الثانى (لا نص ولا أسماء من عقد حقيقى)
const body = (w: string) => `${w} يلتزم الطرف المعنى بما هو مبين فى هذا البند وفق ما تقتضيه طبيعة الخدمة المتفق عليها بين الطرفين.`;
const SCANNED = [
  'عقد خدمات',
  'اتفاقية الخدمات المهنية',
  '1- شركة الاولى المحدودة — مصر ش .م.م خاضعة لاحكام القانون',
  'سجل تجارى رقم 111 وينوب عنها فى التوقيع الاول بصفته العضو المنتدب',
  '2- شركة الثانية المحدودة — مصر ش .م.م',
  'سجل تجارى رقم 222 وينوب عنها الثانى بصفته العضو المنتدب',
  '(الطرف الاول)',
  'ثانيا : شركة المزود - توصية بسيطة - سجل تجارى',
  '(الطرف الثانى)',
  'حيث ان الطرف الثانى يقوم باعمال التحليل ورغب الطرف الاول فى الاستفادة من خدماته.',
  '1. نطاق الخدمات',
  body('يوافق مقدم الخدمة على تزويد العميل بالخدمات التالية'),
  '٠ مراجعة الوثائق',
  '٠ تقييم المخاطر',
  '',
  '3. الرسوم وشروط الدفع',
  body('يتم الاتفاق على إجمالى الرسوم'),
  'العمل بواقع 100 يوم فى السنه',
  '',
  '4. السرية',
  body('يتفق الطرفان على سرية المعلومات'),
  '',
  '5. مسؤوليات الأطراف',
  body('مزود الخدمة يقدم خدمات احترافية'),
  '',
  '6. تحديد المسؤولية',
  body('لا يكون اى من الطرفين مسؤولا عن الاضرار غير المباشرة'),
  '',
  '7 الملكية الفكرية',
  body('تصبح المخرجات ملكا للعميل'),
  '',
  '8. الإنهاء',
  body('يجوز انهاء هذه الاتفاقية'),
  '10 على الفور من قبل اى من الطرفين اذا انتهك الطرف الاخر التزاماته ولم يعالج الاخلال خلال مهلة',
  'أيام.',
].join('\n');

describe('الجولة 106 — «N. العنوان» الذى ضاع منه رقم', () => {
  const seg = new SegmentationService();

  it('العناوين 1،3،4،5،6،7،8 تُقرأ بنوداً (لا فقرات تقريبية) والرقم 7 بلا نقطة يُلتقط', () => {
    const r = seg.segment(SCANNED);
    expect(r.clauses.map((c) => c.declaredNumber)).toEqual([1, 3, 4, 5, 6, 7, 8]);
    expect(r.warnings.join(' ')).not.toContain('فقرات تقريبية');
  });

  it('كتلة تعريف الأطراف تبقى ديباجة (لا بنداً) وسطر «1- شركة…» ليس عنواناً', () => {
    const r = seg.segment(SCANNED);
    expect(r.preamble).toContain('الطرف الثانى');
    expect(r.preamble).toContain('1- شركة');
    expect(r.clauses[0].title).toContain('نطاق الخدمات');
    expect(r.clauses[0].label).toContain('1');
  });

  it('الرقم المفقود يُنبَّه إليه (ترقيم غير متسلسل) ولا يُسنَد آلياً', () => {
    const r = seg.segment(SCANNED);
    expect(r.warnings.some((w) => w.includes('غير متسلسل'))).toBe(true);
  });

  it('«10 على الفور…» (بند فرعى مقروء 10) و«100 يوم» لا يُعدّان عناوين', () => {
    const heads = findTolerantBareHeads(SCANNED);
    expect(heads.map((h) => h.declaredNumber)).toEqual([1, 3, 4, 5, 6, 7, 8]);
  });

  it('تسلسل متصل 1..5 كالسابق (الصارم يكفى): لا يتغير', () => {
    const t = ['مقدمة', ...[1, 2, 3, 4, 5].flatMap((n) => [`${n}. عنوان ${n}`, body('نص')])].join('\n');
    expect(findAlternativeHeads(t).map((h) => h.declaredNumber)).toEqual([1, 2, 3, 4, 5]);
  });

  it('لا يُقبل: أقل من 4 عناوين، أو ما يبدأ بعد الرقم 2، أو فقد أكثر من الربع', () => {
    expect(findTolerantBareHeads(['1. أ', 'نص', '3. ب', 'نص', '4. ج', 'نص'].join('\n'))).toEqual([]);
    expect(findTolerantBareHeads(['5. أ', 'نص', '6. ب', 'نص', '7. ج', 'نص', '8. د', 'نص'].join('\n'))).toEqual([]);
    // 1 ثم 3 ثم 5 ثم 7: المفقود 3 من 7 > ربع
    expect(findTolerantBareHeads(['1. أ', 'نص', '3. ب', 'نص', '5. ج', 'نص', '7. د', 'نص'].join('\n'))).toEqual([]);
  });

  it('قائمة رقمية داخل متن لا تحل محل العنوان الحقيقى المتخطّى عنه رقمه التالى موجود لاحقاً', () => {
    const t = [
      '1. الاول',
      'نص يشمل:',
      '2. بند فرعى',
      '3. بند فرعى آخر',
      '2. الثانى',
      'نص',
      '3. الثالث',
      'نص',
      '4. الرابع',
      'نص',
    ].join('\n');
    // الرقم 2 الأول (القائمة) يُقبل تالياً مباشراً كما كان الحال فى السلسلة الصارمة؛ المهم ألا يُفقد العقد كله
    expect(findTolerantBareHeads(t).length).toBeGreaterThanOrEqual(4);
  });

  it('أرقام عابرة (الاختبار القديم) تبقى بلا بنود', () => {
    const r = seg.segment('نص عقد بلا ترقيم.\nالمبلغ 5. يدفع.\n7. شىء عابر\nخاتمة.');
    expect(r.clauses).toHaveLength(0);
  });
});
