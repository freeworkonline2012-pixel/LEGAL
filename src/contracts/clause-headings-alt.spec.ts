import { SegmentationService } from './segmentation.service';

const seg = (t: string) => new SegmentationService().segment(t);

/** أنماط ترقيم ظهرت فى عقود حقيقية اختُبرت (اتفاقية سرية «1. العنوان / 1.1»، وعقد خدمات «**المادة 1: …**») وكانت تُقسَّم إلى صفر بند. */
describe('ترقيم بديل: «المادة N» و«N. العنوان»', () => {
  it('«**المادة 1: عنوان**» بعلامات Markdown حرفية: بنود متسلسلة بعناوينها', () => {
    const r = seg(
      'عقد خدمات\n**بين:** شركة ألفا (طرف أول) وشركة بيتا (طرف ثان)\n### **بنود العقد:**\n\n' +
        '**المادة 1: تعيين الوكالة**\nيعيّن العميل الوكالة لتقديم الخدمات.\n\n' +
        '**المادة 2: نطاق الخدمات**\nتلتزم الوكالة بتقديم الخدمات التالية.\n- **مدة الخدمة:** شهر.\n\n' +
        '**المادة 3: المقابل**\nيدفع العميل مبلغ 10000 جنيه شهرياً.\n',
    );
    expect(r.clauses.map((c) => c.declaredNumber)).toEqual([1, 2, 3]);
    expect(r.clauses.map((c) => c.label)).toEqual(['المادة 1', 'المادة 2', 'المادة 3']);
    expect(r.clauses[0].title).toBe('تعيين الوكالة');
    expect(r.clauses[2].text).toContain('10000');
    expect(r.warnings).toEqual([]);
    expect(r.preamble).toContain('ألفا');
  });

  it('«1. العنوان» بند رئيسى، و«1.1» و«2.3» فروع داخل متنه لا بنود مستقلة', () => {
    const r = seg(
      'اتفاقية سرية\nبين ألفا وبيتا\n\n1. المعلومات السرية\n1.1 التعريف:\nكل المعلومات غير العامة.\n1.2 الاستثناءات:\nلا تشمل العامة.\n\n' +
        '2. حقوق الملكية الفكرية\n2.1 الملكية:\nللشركة وحدها.\n2.2 التنازل:\nيتنازل المصمم.\n\n3. الأفعال المحظورة\nيتعهد المصمم بعدم الكشف.\n',
    );
    expect(r.clauses.map((c) => c.declaredNumber)).toEqual([1, 2, 3]);
    expect(r.clauses[0].title).toBe('المعلومات السرية');
    expect(r.clauses[0].text).toContain('الاستثناءات');
    expect(r.clauses[1].text).toContain('التنازل');
  });

  it('«المادة الأولى/الثانية» بالكلمات المؤنثة', () => {
    const r = seg('بين ألفا وبيتا\nالمادة الأولى: الموضوع\nنص أول.\nالمادة الثانية: الثمن\nنص ثان.\nالمادة الثالثة: المدة\nنص ثالث.\n');
    expect(r.clauses.map((c) => c.declaredNumber)).toEqual([1, 2, 3]);
  });

  it('أرقام عابرة لا تكوّن تسلسلاً 1،2،3 لا تُعدّ بنوداً (فيبقى التحذير)', () => {
    const r = seg('نص عقد بلا ترقيم.\nالمبلغ 5. يدفع.\n7. شىء عابر\nخاتمة.');
    expect(r.clauses).toHaveLength(0);
    expect(r.warnings.some((w) => w.includes('لم يُعثَر على أى بند'))).toBe(true);
  });

  it('النمط الأصلى «البند الأول» له الأولوية ولا يتأثر بقوائم رقمية داخل المتن', () => {
    const r = seg('البند الأول: أ\nيشمل:\n1. شىء\n2. شىء\n3. شىء\nالبند الثانى: ب\nنص.\n');
    expect(r.clauses.map((c) => c.declaredNumber)).toEqual([1, 2]);
  });

  it('«البندالثامن» بلا مسافة (التصاق من المسح) عنوان بند', () => {
    const r = seg('البند السابع: أ\nنص.\nالبندالثامن : عدم التداول\nنص.\nالبند التاسع: ج\nنص.\n');
    expect(r.clauses.map((c) => c.declaredNumber)).toEqual([7, 8, 9]);
  });
});
