import { classifyClauseCriteria, scopedLawsForClause } from './criteria.util';

/**
 * اختبار حى (عقد بلاك بيلتس): بند «حقوق الملكية الفكرية للبرامج» استشهد بالمادة 802 مدنى بدل قانون 82/2002، لأن مصنِّف المواضيع
 * كان يطابق «ملكية فكرية» ولا يطابق «الملكية الفكرية». الصياغات المعرَّفة بـ«ال» تُصنَّف الآن كنكراتها.
 */
const lawNos = (text: string) => scopedLawsForClause([], null, text).map((s) => `${s.lawNo}/${s.lawYear}`);

describe('الصياغات المعرَّفة بـ«ال» فى ربط البند بالقانون المخصص له', () => {
  it('بند الملكية الفكرية فى العقد الحى يُربط بقانون 82/2002', () => {
    expect(lawNos('تظل حقوق الملكية الفكرية للبرامج للطرف الأول ولا يجوز للطرف الثانى تسويقها أو بيعها.')).toContain('82/2002');
  });

  it.each([
    ['الملكية الفكرية', '82/2002'],
    ['حقوق الملكية الفكرية', '82/2002'],
    ['الشفرة المصدرية للنظام', '82/2002'],
    ['العلامة التجارية للشركة', '82/2002'],
    ['براءة الاختراع', '82/2002'],
    ['يحال النزاع إلى هيئة التحكيم', '27/1994'],
    ['اتفاق التحكيم', '27/1994'],
    ['البيانات الشخصية للعملاء', '151/2020'],
  ])('«%s» ⇒ %s', (text, law) => {
    expect(lawNos(text)).toContain(law);
  });

  it('لا يُربط بند لا صلة له بأى قانون مخصص (لا إفراط)', () => {
    expect(lawNos('يلتزم الطرف الثانى بسداد الدفعة الأولى خلال عشرة أيام من توقيع العقد.')).toEqual([]);
    // «المحكمة» لا تُعدّ تحكيماً
    expect(lawNos('تختص المحكمة المختصة بنظر أى نزاع.')).not.toContain('27/1994');
  });

  it('المصنِّف يوسم الصياغات المعرَّفة كنكراتها', () => {
    expect(classifyClauseCriteria(null, 'الشرط الجزائى')).toContain('compensation');
    expect(classifyClauseCriteria(null, 'يسرى الإعفاء فى حالة القوة القاهرة')).toContain('force_majeure');
    expect(classifyClauseCriteria(null, 'الفسخ دون حكم قضائى')).toContain('exit');
  });
});
