import { firstPerClause, type OfficeRule } from './office-rules-kit';

/**
 * قواعد المكتب المضافة فى الجولة 95 (بموافقة المالك، من مراجعة دفعة العقود الاصطناعية 2). كلها قواعد حتمية بالاقتباس الحرفى، لا مادة قانونية فيها،
 * وتُعرض «ممارسة تعاقدية للمكتب لا نصاً قانونياً». درجتها «متوسط» عمداً: هى اختلال تجارى لا مخالفة نص آمر، فلا ترفع مستوى المخاطرة العام وحدها.
 */

// ===================== إثبات أو تقدير بجهة يختارها أحد الطرفين وحده =====================

const PARTY_ONE =
  '(?:ال)?(?:مؤجر[ء-ي]*|مقرض[ء-ي]*|مالك[ء-ي]*|ممول[ء-ي]*|شركه|طرف الاول|مورد[ء-ي]*|مقاول[ء-ي]*|رب العمل|بائع[ء-ي]*|موكل[ء-ي]*|صاحب العمل|مرخص[ء-ي]*|مانح[ء-ي]*)';
const DETERMINER_NOUN = '(?:تقرير|رايه?|شهاده|خبير[ء-ي]*|خبره|جهه|جهات|لجنه|مكتب|مهندس[ء-ي]*|استشاري|محكم[ء-ي]*|تحكيم|هيئه|مختبر|معمل|فاحص)';
const CHOOSE_VERB = '(?:تختار[ء-ي]*|يختار[ء-ي]*|تعين[ء-ي]*|يعين[ء-ي]*|تحدد[ء-ي]*|يحدد[ء-ي]*|تندب[ء-ي]*|يندب[ء-ي]*|ترشح[ء-ي]*|يرشح[ء-ي]*|تكلف[ء-ي]*|يكلف[ء-ي]*)';
/** «تقرير تختاره المؤجرة» / «جهة تحددها الشركة»: الاسم قبل الفعل، والفاعل طرف واحد */
const CHOSEN_BY_ONE_A = new RegExp(`${DETERMINER_NOUN}[^.\\n]{0,25}?${CHOOSE_VERB}\\s+${PARTY_ONE}`);
/** «تختار المؤجرة خبيراً» / «يعين المقرض محكماً» */
const CHOSEN_BY_ONE_B = new RegExp(`${CHOOSE_VERB}\\s+${PARTY_ONE}\\s+(?:ال)?${DETERMINER_NOUN}`);
/** اتفاق الطرفين أو تعيين محايد/قضائى ينفى الانفراد */
const JOINT_OR_NEUTRAL = /(?:يتفق عليه[ما]?|بالاتفاق بين|باتفاق الطرفين|يختاره[ما]? الطرفان|تختاره[ما]? الطرفان|محايد|ندبه المحكمه|تعينه المحكمه|نقابه|خبراء وزاره العدل|مكتب الخبراء)/;

const RULE_ONE_SIDED_DETERMINER: OfficeRule = {
  id: 'one_sided_determiner',
  families: null,
  excludeFamilies: ['employment', 'unknown'],
  enabled: true,
  severity: 'متوسط',
  title: 'إثبات واقعة أو تقديرها يتوقف على خبير أو جهة يختارها أحد الطرفين وحده',
  explanation:
    'قاعدة المكتب: لا يُترك إثبات واقعة جوهرية (كالقوة القاهرة أو سبب التلف أو العيب) أو الفصل فى نزاع لتقرير خبير أو جهة أو محكّم يختاره أحد الطرفين وحده؛ ' +
    'بل يُتفق عليه بين الطرفين أو يعينه طرف محايد (نقابة أو خبير قضائى أو المحكمة). ' +
    'ورد فى العقد نص يجعل الإثبات أو الفصل بيد جهة يختارها طرف واحد، فيصير الطرف الآخر مقيَّداً بتقرير لا يملك الاعتراض على اختيار من أصدره.',
  suggestion: 'استبدال العبارة بخبير أو جهة يتفق عليها الطرفان، أو تعيّنها نقابة أو جهة محايدة أو المحكمة عند عدم الاتفاق، مع حق كل طرف فى تقديم تقرير مضاد وعرض الخلاف على القضاء.',
  provenance: 'مصدر القاعدة: مراجعة الدفعة الاصطناعية 2 (إيجار ج: بندا الصيانة والمسئولية، تمويل أ/ج: التحكيم) وقرار المالك فى الجولة 95؛ تحتاج عقوداً حقيقية لتأكيد تعميمها.',
  evaluate: (clauses) => firstPerClause(clauses, (n, clauseNorm) => (CHOSEN_BY_ONE_A.test(n) || CHOSEN_BY_ONE_B.test(n)) && !JOINT_OR_NEUTRAL.test(clauseNorm)),
};

// ===================== إنهاء مبكر بإرادة أحد الطرفين دون تعويض =====================

const EARLY_TERMINATION = /(?:انها[ء-ي]*|ينهي[ء-ي]*|تنهي[ء-ي]*|فسخ[ء-ي]*)[^.\n]{0,60}قبل\s+(?:انتهاء\s+)?(?:ال)?(?:م[دذ]ه|ميعاد|موعد|الاجل)/;
const NO_COMPENSATION = /(?:دون|بدون|بغير|بلا)\s+(?:ال)?(?:التزام\s+)?(?:ب)?(?:اي\s+)?(?:تعويض|مقابل)/;

const RULE_EARLY_TERMINATION_NO_COMPENSATION: OfficeRule = {
  id: 'early_termination_no_compensation',
  families: null,
  excludeFamilies: ['employment', 'unknown'],
  enabled: true,
  severity: 'متوسط',
  title: 'إنهاء العقد قبل مدته بإرادة أحد الطرفين دون تعويض الطرف الآخر',
  explanation:
    'قاعدة المكتب: إذا احتفظ أحد الطرفين بحق إنهاء العقد قبل انتهاء مدته (لحاجته أو لهدم أو ترميم أو غيره) فيُنص على تعويض الطرف الآخر عمّا أنفقه فى التجهيزات والتحسينات وما لم يستهلكه منها، وعلى مهلة كافية للإخلاء. ' +
    'ورد فى العقد إنهاء مبكر بإرادة أحد الطرفين صراحةً «دون» تعويض أو التزام بمقابل، فيتحمل الطرف الآخر وحده خسارة استثماره فى مدة كان يعتمد على استمرارها.',
  suggestion: 'النص على تعويض عادل عن التجهيزات والتحسينات غير المستهلكة وعن نفقات النقل، ومهلة إخطار لا تقل عن ثلاثة أشهر، أو قصر الإنهاء المبكر على الإخلال أو الضرورة القاهرة.',
  provenance: 'مصدر القاعدة: مراجعة الدفعة الاصطناعية 2 (إيجار ج بند المدة) وقرار المالك فى الجولة 95؛ تحتاج عقوداً حقيقية لتأكيد تعميمها.',
  evaluate: (clauses) => firstPerClause(clauses, (n) => EARLY_TERMINATION.test(n) && NO_COMPENSATION.test(n.slice(Math.max(0, n.search(EARLY_TERMINATION))))),
};

export const R95_OFFICE_RULES: OfficeRule[] = [RULE_ONE_SIDED_DETERMINER, RULE_EARLY_TERMINATION_NO_COMPENSATION];
