// ===================== ق2: دورية تحويل المبالغ المحصلة بلا موعد ولا جزاء =====================

const PERIODIC_TRANSFER =
  /(?:تحويل|يحول|تحول|سداد|يسدد|توريد|يورد|دفع)[^.]{0,100}(?:المبالغ|المحصل|المتحصلات|الحصيله)[^.]{0,100}(?:اسبوعي|اسبوعيا|شهري|شهريا|يومي|يوميا|كل (?:اسبوع|شهر|يوم|اسبوعين|نصف شهر)|دوري|دوريه)|(?:المبالغ|المحصل|المتحصلات)[^.]{0,80}(?:تحول|يتم تحويلها|تسدد|يتم سدادها)[^.]{0,60}(?:اسبوعي|شهري|يومي|كل (?:اسبوع|شهر|يوم))/;
const TRANSFER_DEADLINE =
  /يوم (?:ال)?(?:احد|اثنين|ثلاثاء|اربعاء|خميس|سبت|جمعه)|(?:خلال|في موعد اقصاه|بحد اقصي|لا يتجاوز|لا يتاخر)[^.]{0,40}\d+\s*(?:ايام|يوم|ساعه|ساعات)|موعد اقصاه|بحد اقصي|في اول يوم عمل|اخر يوم عمل/;
const TRANSFER_PENALTY = /(?:غرامه|فائده|فوائد|تعويض|جزاء|شرط جزائي)[^.]{0,80}(?:تاخير|تاخر|التاخر)|(?:تاخير|تاخر|التاخر)[^.]{0,100}(?:غرامه|فائده|فوائد|تعويض|جزاء|شرط جزائي)/;
const TRANSFER_TOPIC = /تحويل|المبالغ المحصله|التحصيل|توريد|سداد/;

const RULE_TRANSFER_TERMS: OfficeRule = {
  id: 'collected_funds_transfer_terms',
  families: ['services', 'agency'],
  enabled: true,
  severity: 'عالٍ',
  title: 'تحويل المبالغ المحصلة بدورية عامة دون يوم محدد أو مهلة قصوى أو جزاء تأخير',
  explanation:
    'قاعدة المكتب: تحويل المبالغ التى يحصلها مقدم الخدمة لحساب العميل يُحدَّد بيوم أو مهلة قصوى معلومة من تاريخ التحصيل أو نهاية الفترة، ويُرتَّب على التأخير فيه جزاء (غرامة أو فائدة)، ' +
    'لأن هذه المبالغ مال العميل فى يد غيره. ورد فى العقد تحويل بدورية عامة (أسبوعياً/شهرياً) ولم يُرصد معها يوم محدد أو مهلة قصوى أو جزاء على التأخير (أو بعض ذلك)، فيصعب إثبات التأخير والمطالبة بأثره.',
  suggestion:
    'نص يحدد يوم التحويل أو مهلة لا تتجاوز عدداً محدداً من أيام العمل بعد نهاية فترة التحصيل، وغرامة أو فائدة تأخير عن كل يوم، وحق العميل فى الإنهاء عند تكرار التأخير.',
  provenance: PROVENANCE,
  evaluate: (clauses) => {
    if (!isCollection(clauses)) return [];
    const hits = firstPerClause(clauses, (n) => PERIODIC_TRANSFER.test(n));
    if (hits.length === 0) return [];
    const ok = hits.some((h) => TRANSFER_DEADLINE.test(normD(h.clause.clauseText)));
    let penalty = false;
    for (const { n } of eachSentence(clauses)) if (TRANSFER_TOPIC.test(n) && TRANSFER_PENALTY.test(n)) penalty = true;
    return ok && penalty ? [] : hits;
  },
};

