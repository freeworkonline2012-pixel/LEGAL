// ===================== ق6: شرائح العمولة =====================

const FEE_WORD = /عموله|عمولات|رسوم|اتعاب|مقابل|نسبه/;
const TIER_CUE = /اقل من|اكثر من|اكبر من|اعلي من|يزيد عن|لا يزيد|حتي|شريح|من \d+ الي \d+|\d+\s*[:\-]\s*\d+/;
const TIER_CLARIFY =
  /(?:الشريحه|شريحه)\s+(?:فقط|وحدها)|علي (?:كامل|اجمالي|مجموع|جميع) (?:الحجم|حجم|العمليات|المعاملات)|(?:كامل|اجمالي) (?:ال)?حجم|الجزء (?:الزائد|المتبقي|الذي)|ما يزيد عن|تراكمي|بالتدرج|بحسب الشريحه|وفق الشريحه|الشريحه التي يقع فيها/;
const PCT = /(\d+(?:[.,]\d+)?)\s*[%٪]/g;

function pctValues(raw: string): string[] {
  return [...toLatinDigits(raw).matchAll(PCT)].map((m) => m[1].replace(',', '.'));
}

const RULE_TIERS_AMBIGUOUS: OfficeRule = {
  id: 'commission_tiers_ambiguous',
  families: ['services', 'agency'],
  enabled: true,
  severity: 'عالٍ',
  title: 'شرائح العمولة دون بيان هل تسرى على كامل الحجم أم على الشريحة وحدها',
  explanation:
    'قاعدة المكتب: عند تدرج العمولة بحسب حجم المعاملات يُنص صراحة على طريقة التطبيق: هل تسرى النسبة المقررة للشريحة على كامل الحجم متى بلغه، أم على الجزء الواقع فى الشريحة فقط، ويُضرب مثال حسابى. ' +
    'ورد فى العقد جدول شرائح بنسب مختلفة دون هذا البيان، فيختلف المبلغ المستحق اختلافاً جوهرياً بحسب التفسير ويُنازَع فيه عند أول تسوية.',
  suggestion: 'نص يوضح أن النسبة تسرى على الجزء الواقع فى كل شريحة (أو على كامل الحجم) ويحدد الفترة التى يُحتسب عليها الحجم (شهرى/سنوى)، مع مثال رقمى مرفق بالجدول.',
  provenance: PROVENANCE,
  evaluate: (clauses) => {
    const out: OfficeRuleHit[] = [];
    for (const clause of clauses) {
      const cn = norm(clause.clauseText);
      if (!FEE_WORD.test(cn) || TIER_CLARIFY.test(cn)) continue;
      const rows = [...eachSentence([clause])];
      const pctRows = rows.filter((r) => pctValues(r.sentence).length > 0);
      const values = new Set(pctRows.flatMap((r) => pctValues(r.sentence)));
      if (values.size < 2) continue;
      if (!pctRows.some((r) => TIER_CUE.test(normD(r.sentence)))) continue;
      for (const r of pctRows.slice(0, 3)) out.push({ clause, sentence: r.sentence });
    }
    return out;
  },
};

// ===================== ق7: عمولة ثابتة + نسبة بلا «لكل عملية» =====================

const FIXED_PLUS_PCT =
  /\d+(?:[.,]\d+)?\s*[%٪]\s*(?:\+|و|زائد|بالاضافة الى|بالإضافة إلى)\s*\d+(?:[.,]\d+)?\s*(?:جنيه|ج\.?\s?م|جم|EGP)|\d+(?:[.,]\d+)?\s*(?:جنيه|ج\.?\s?م|جم|EGP)\s*(?:\+|و|زائد)\s*\d+(?:[.,]\d+)?\s*[%٪]/i;
const PER_TRANSACTION = /لكل (?:عمليه|معامله|عمليات|قسط|دفعه|مدفوع)|عن كل (?:عمليه|معامله|دفعه|قسط)|علي كل (?:عمليه|معامله)|كل عمليه|كل معامله|per transaction/i;

const RULE_FIXED_PLUS_PERCENT: OfficeRule = {
  id: 'fixed_fee_plus_percent_unspecified',
  families: ['services', 'agency'],
  enabled: true,
  severity: 'عالٍ',
  title: 'عمولة بمبلغ ثابت مع نسبة دون بيان أن الثابت يُحتسب عن كل عملية أم عن الفترة',
  explanation:
    'قاعدة المكتب: إذا جمعت العمولة بين نسبة ومبلغ ثابت يُنص على وحدة احتساب الثابت: عن كل عملية أم عن كل شهر أم عن العقد كله. ' +
    'ورد فى العقد عمولة بنسبة مضافاً إليها مبلغ ثابت دون هذا البيان، فإن فُسِّر الثابت عن كل عملية تضاعفت الكلفة الفعلية على العميل بحسب عدد العمليات، وهو تفسير مرجح لمصلحة مقدم الخدمة عند الغموض.',
  suggestion: 'نص يقرر صراحة وحدة احتساب المبلغ الثابت (عن كل عملية ناجحة مثلاً) أو سقفاً شهرياً له، مع مثال حسابى لعملية بقيمة محددة.',
  provenance: PROVENANCE,
  evaluate: (clauses) => {
    const out: OfficeRuleHit[] = [];
    for (const clause of clauses) {
      const cn = norm(clause.clauseText);
      if (PER_TRANSACTION.test(cn)) continue;
      for (const { sentence } of eachSentence([clause])) {
        if (FIXED_PLUS_PCT.test(toLatinDigits(sentence)) && !PER_TRANSACTION.test(norm(sentence))) {
          out.push({ clause, sentence });
          break;
        }
      }
    }
    return out;
  },
};

