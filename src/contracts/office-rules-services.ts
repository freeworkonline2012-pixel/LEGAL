/**
 * قواعد المكتب لعقود الخدمات والتحصيل (الجولة 62) — من منظور العميل (متلقى الخدمة)، بحسب حكم المستشار على ملاحظات الدفعة 2
 * (جدول 2026-11-07). كلها حتمية وموثَّقة بالاقتباس الحرفى حيث يوجد نص، وقواعد «الغياب» تُصدر الملاحظة بلا اقتباس (أو باقتباس سياق)،
 * وتُوسم «غير مؤكدة» على العقود الممسوحة ذات التحذيرات كسائر ادعاءات الغياب.
 *
 * ⚠️ حدود: ممارسة تعاقدية للمكتب لا نصوص قانونية؛ لا تُذكر مادة قانونية فى أى منها (قرار المستشار: مخاطرة تعاقدية فقط). والعينة عقد تحصيل واحد؛
 * فالقواعد تعمل على صيغ عامة لا على ألفاظ ذلك العقد، وتحتاج عقوداً أخرى لتأكيد تعميمها.
 */

const PROVENANCE = 'مصدر القاعدة: حكم المستشار على ملاحظة فى عقد خدمات تحصيل واحد (الدفعة 2، نوفمبر 2026)؛ عينة صغيرة تحتاج عقوداً أخرى للتأكيد.';

const COLLECTION = /تحصيل|متحصلات|المبالغ المحصله|الحصيله/;
const isCollection = (clauses: LevelClause[]): boolean => COLLECTION.test(fullNorm(clauses));

/** موضع سياق لقاعدة غياب: جملة ذات صلة تُقتبس إن وُجدت، وإلا موضع بلا اقتباس (تُصدَر الملاحظة على العقد ككل). */
function contextHit(clauses: LevelClause[], re: RegExp): OfficeRuleHit[] {
  const h = firstSentenceMatching(clauses, re);
  if (h) return [h];
  return clauses.length > 0 ? [{ clause: clauses[0], sentence: '' }] : [];
}

const anyText = (clauses: LevelClause[], re: RegExp): boolean => re.test(fullNorm(clauses));

// ===================== ق1: حصرية مفروضة على العميل وحده =====================

const BIND_CLIENT_A = /(?:لا يجوز|لا يحق|يحظر|يمتنع)\s+(?:علي |ل)?(?:ال|ل)?(?:عميل|مستفيد|تاجر)(?![ء-ي])[^.]{0,260}منافس/;
const BIND_CLIENT_B = /(?:يتعهد|يلتزم|تتعهد|تلتزم)\s+(?:ال)?(?:عميل|مستفيد|تاجر)\s+بعدم[^.]{0,200}منافس/;
const BIND_PROVIDER = /(?:لا يجوز|لا يحق|يحظر|يمتنع|يتعهد|يلتزم)\s+(?:علي |ل)?(?:ال|ل)?(?:مقدم|شركه|مزود|طرف اول)[^.]{0,200}منافس|كل (?:من )?الطرفين[^.]{0,200}منافس/;

