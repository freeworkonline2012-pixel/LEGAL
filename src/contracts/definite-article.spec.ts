import { checkMissingClauses, stripDefiniteArticle } from './contract-level';
import { buildPlaybook } from './playbook';

/**
 * اختبار حى (عقد بلاك بيلتس الممسوح): بند القوة القاهرة نفسه أُعلن «غير مرصود» لأن النمط «قوه قاهره» لا يطابق «القوه القاهره».
 * هذا الملف يثبت أن الصياغات المعرَّفة بـ«ال» تُرصد كما تُرصد نكرتاها، فى كشف البنود الناقصة وفى الدليل التفاوضى.
 */
const PAD = 'يلتزم الطرف الأول بتنفيذ الأعمال المبينة وتسليمها وفق الجدول المتفق عليه بين الطرفين فى هذا العقد ويقر الطرف الثانى بذلك.';
const SERVICES = 'عقد خدمات أو مقاولة أو توريد';

const BLACKBELTS_CLAUSE_12 =
  'أتفق الطرفان على أن كلا منهما لايكون مسئولا قبل الطرف الأخر عن التأخيرفى تنفيذ أى من إلتزاماته الواردة فى هذا العقد وذلك فى حالة إذا كان التأخير فى التنفيذ يرجع لأحد الأسباب القهرية التى نص عليها القانون المصرى. أما فى حالة وجود أسباب أخرى خارجه عن إرادة ايآ منهما ففى هذه الحالة يلتزم الطرف المتأخر فى التنفيذ بإخطار الطرف الأخر بخطاب مسجل بعلم الوصول.';

const missing = (text: string, id: string) =>
  checkMissingClauses([{ clauseIndex: 1, clauseLabel: 'البند الأول', clauseTitle: null, clauseText: `${PAD} ${text}` }], { contractType: SERVICES, textMayBeIncomplete: false }).some(
    (f) => f.id === `missing:${id}`,
  );

describe('الصياغات المعرَّفة بـ«ال» فى كشف البنود غير المرصودة', () => {
  it('stripDefiniteArticle يحذف ال وما التصق بها من حروف و/ف/ب/ك/ل فى أول الكلمة فقط', () => {
    expect(stripDefiniteArticle('فى حاله القوه القاهره والحادث المفاجي بالتاخير')).toBe('فى حاله قوه قاهره حادث مفاجي تاخير');
    expect(stripDefiniteArticle('الا')).toBe('الا'); // أقل من حرفين بعد ال لا يُحذف
  });

  it('بند القوة القاهرة فى العقد الحى لا يُعلَن غير مرصود', () => {
    expect(missing(BLACKBELTS_CLAUSE_12, 'force_majeure')).toBe(false);
  });

  const PRESENT: Array<[string, string[]]> = [
    ['force_majeure', ['فى حالة القوة القاهرة لا يسأل أى طرف', 'الظروف القاهرة', 'الحادث المفاجئ', 'الأسباب القهرية', 'الظروف الطارئة', 'والقوة القاهرة']],
    ['delay_penalty', ['غرامة التأخير عن كل يوم', 'الشرط الجزائى', 'التعويض الاتفاقى', 'غرامة عن كل أسبوع تأخير', 'جزاء التأخير', 'يدفع غرامات تأخير']],
    ['intellectual_property', ['حقوق الملكية الفكرية', 'الملكية الفكرية للبرامج', 'الشفرة المصدرية', 'حقوق المؤلف']],
    ['governing_law', ['يخضع هذا العقد للقانون المصرى', 'تختص المحاكم المصرية', 'محكمة القاهرة المختصة', 'يحال النزاع إلى التحكيم', 'القانون الواجب التطبيق']],
    ['notices', ['الموطن المختار للطرفين', 'العنوان المبين بصدر العقد', 'الإخطارات تتم بخطاب مسجل']],
    ['amendments', ['لا يجوز تعديل العقد إلا كتابة', 'إلا باتفاق كتابى']],
    ['confidentiality', ['السرية التامة', 'المعلومات السرية', 'عدم إفشاء الأسرار']],
    ['acceptance', ['محضر تسليم', 'محضر الاستلام', 'يعتبر مقبولا', 'الفحص والاستلام']],
    ['warranty', ['الضمان لمدة سنة', 'العيوب الخفية', 'فترة الصيانة']],
    ['termination', ['فسخ هذا العقد', 'إنهاء العقد', 'يجوز إنهاء هذا العقد', 'إلغاء العقد']],
    ['payment', ['الثمن الإجمالى', 'سداد الدفعة الأولى', 'الأتعاب']],
    ['liability', ['يتحمل الطرف الأول المسئولية', 'الحد الأقصى للتعويض']],
  ];
  for (const [id, phrases] of PRESENT) {
    it(`${id}: كل صياغة معرَّفة أو منكَّرة تُرصد`, () => {
      const failed = phrases.filter((p) => missing(p, id));
      expect(failed).toEqual([]);
    });
  }

  it('لا يزال يُعلن الغياب فعلاً حين لا يوجد نص ذو صلة (لا إفراط فى المطابقة)', () => {
    expect(missing('يلتزم الطرف الثانى بالسداد خلال عشرة أيام', 'force_majeure')).toBe(true);
    expect(missing('يلتزم الطرف الثانى بالسداد خلال عشرة أيام', 'delay_penalty')).toBe(true);
    expect(missing('يلتزم الطرف الثانى بالسداد خلال عشرة أيام', 'intellectual_property')).toBe(true);
  });
});

describe('الصياغات المعرَّفة بـ«ال» فى الدليل التفاوضى', () => {
  const rowStatus = (text: string, topicLabel: RegExp) => {
    const pb = buildPlaybook({
      contractType: SERVICES,
      clientRole: 'طالب الخدمة (صاحب العمل / العميل)',
      clauses: [{ clauseIndex: 1, clauseLabel: 'البند الأول', clauseTitle: null, clauseText: text }],
    })!;
    return pb.rows.find((r) => topicLabel.test(r.label))!.status;
  };
  it('الشرط الجزائى وغرامة التأخير والملكية الفكرية تُرصد', () => {
    expect(rowStatus('الشرط الجزائى عن التأخير عشرة فى المائة من قيمة العقد.', /التأخير|الجزاء/)).not.toBe('missing');
    expect(rowStatus('تظل الملكية الفكرية للبرامج للطرف الأول.', /الملكية/)).not.toBe('missing');
  });
});
