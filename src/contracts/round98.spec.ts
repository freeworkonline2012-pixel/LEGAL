describe('R98 — مسح الاثنى عشر عقداً (نسخ ب النظيفة بلا إصابة)', () => {
  const dir = '/home/claude/r90_synth/out/';
  (fs.existsSync(dir) ? it : it.skip)('مسح المصادر', () => {
    const bad: string[] = [];
    for (const f of fs.readdirSync(dir).filter((x) => /^دفعة2_.*_ب\.txt$/.test(x))) {
      const t = fs.readFileSync(dir + f, 'utf8');
      const type = /إيجار/.test(f) ? 'عقد إيجار' : /تمويل/.test(f) ? 'عقد تمويل' : /توريد/.test(f) ? 'عقد توريد' : 'عقد مقاولة';
      const hit = officeRuleFindings([cl(0, t)], { contractType: type, textMayBeIncomplete: false }).filter((x) => R98_IDS.some((r) => x.id === `office:${r}`));
      if (hit.length) bad.push(`${f}: ${hit.map((h) => h.id).join(',')}`);
    }
    expect(bad).toEqual([]);
  });
});
