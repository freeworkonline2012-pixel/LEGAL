import { firstPerClause, type OfficeRule } from './office-rules-kit';

/**
 * قواعد المكتب المضافة فى الجولة 97 (بموافقة المالك، من مراجعة إعادة الاثنى عشر عقداً بعد R96). عيوب تجارية كان المدقق المستقل يستبعدها لأن سند النموذج القانونى
 * غير منطبق مع بقاء اختلال البند تجارياً (توريد أ بنود 6/9/11، تمويل أ بند 3 وبند 6). كلها قواعد حتمية بالاقتباس الحرفى، لا مادة قانونية فيها،
 * وتُعرض «ممارسة تعاقدية للمكتب لا نصاً قانونياً». درجتها «متوسط» عمداً: اختلال تجارى لا مخالفة نص آمر، فلا ترفع مستوى المخاطرة العام وحدها.
 */

const PARTY =
  '(?:ال)?(?:مورد[ء-ي]*|مقرض[ء-ي]*|ممول[ء-ي]*|بائع[ء-ي]*|مؤجر[ء-ي]*|مقاول[ء-ي]*|مالك[ء-ي]*|شركه|طرف الاول)';
/** عبارة تجعل الحكم تبادلياً أو مشروطاً بإنذار/علاج فتنفى الانفراد */
const MUTUAL = /(?:لكل (?:من )?(?:ال)?طرف|اي (?:من )?(?:ال)?طرف|كلا الطرفين|كل من الطرفين|للطرفين)/;
const CURE_OR_NOTICE = /(?:بعد (?:ان)?ذار[ءه-ي]*|بعد اخطار[ءه-ي]* كتابه|لا (?:يعلق|يوقف|يحل|ينهي)[^.]{0,40}الا)/;
const NON_EXCLUSIVE = /غير حصري|لا يلتزم[^.]{0,40}بشراء|دون التزام بحد ادني|ليس حصري/;

// ===================== 1) استئثار طويل: شراء كل الاحتياجات من طرف واحد لمدة تزيد عن سنتين =====================

const ALL_NEEDS = /(?:كل|جميع)\s+(?:ال)?احتياجات[ء-ي]*[^.\n]{0,60}(?:من|لدي)[^.\n]{0,40}(?:وحده|دون غيره|حصرا|حصريا)/;
const YEARS_3PLUS = /(?:لمده|مدته|طوال|خلال)\s+(?:ال)?(?:ثلاث|اربع|خمس|ست|سبع|ثمان[ء-ي]*|تسع|عشر|[3-9]|\d{2,})\s*(?:\(\s*\d+\s*\)\s*)?سنوات|(?:لمده|مدته)\s+(?:ال)?(?:ثلاث|اربع|خمس|ست|سبع|ثمان[ء-ي]*|تسع|عشر)\s+سنه/;

const RULE_LONG_EXCLUSIVE_PURCHASE: OfficeRule = {
  id: 'long_exclusive_purchase',
  families: ['services', 'sale', 'agency', 'licence'],
  excludeFamilies: ['employment', 'unknown'],
  protects: 'requester',
  enabled: true,
  severity: 'متوسط',
  title: 'استئثار طويل: التزام المشترى بشراء كل احتياجاته من طرف واحد لأكثر من سنتين',
  explanation:
    'قاعدة المكتب: لا يُلزَم المشترى أو العميل بشراء كل احتياجاته من مورد واحد لمدة تتجاوز سنتين، وإن قُبل الاستئثار فيُقابَل بالتزام المورد بالتوريد فى المواعيد والجودة المتفق عليها، ' +
    'ويُعفى المشترى من الالتزام متى عجز المورد أو أخل بالتوريد، وتُحدَّد المنتجات والنطاق المشمول. ورد فى العقد استئثار بكل الاحتياجات من طرف واحد لمدة طويلة، ' +
    'فيتحمل المشترى تبعة عجز المورد وارتفاع أسعاره دون بديل.',
  suggestion: 'تقصير المدة إلى سنتين على الأكثر قابلة للتجديد بالاتفاق، وجعل الاستئثار تبادلياً أو غير حصرى، والنص على حق المشترى فى الشراء من الغير عند عجز المورد أو تأخره أو ارتفاع سعره عن سعر السوق.',
  provenance: 'مصدر القاعدة: مراجعة الدفعة الاصطناعية 2 (توريد أ بند 9) وقرار المالك فى الجولة 97؛ تحتاج عقوداً حقيقية لتأكيد تعميمها.',
  evaluate: (clauses) => firstPerClause(clauses, (n, clauseNorm) => ALL_NEEDS.test(n) && YEARS_3PLUS.test(n) && !NON_EXCLUSIVE.test(clauseNorm)),
};

// ===================== 2) حد أدنى إلزامى للشراء (take-or-pay) =====================

const MIN_PURCHASE = /(?:حد (?:ال)?ادني|علي الاقل|لا يقل عن|لا تقل عن)[^.\n]{0,60}(?:شراء|يشتري|عبوه|وحده|كميه)|(?:يلتزم|تلتزم)[^.\n]{0,25}بشراء[^.\n]{0,60}(?:علي الاقل|لا يقل|حد (?:ال)?ادني)/;
const PAY_REGARDLESS =
  /(?:سواء احتاج|احتاج(?:ها|ه)? ام لا|ام لم يحتج|سواء استلم|ولو لم (?:يحتج|يستلم|يطلب))|(?:ويدفع|ويسدد|يدفع|يسدد|تدفع|تسدد)[^.\n]{0,40}(?:ثمن|قيمه)[^.\n]{0,60}(?:العجز|ما لم يشتر|الكميات التي لم|دون (?:ان )?(?:يستلم|استلام))|(?:يرحل|ترحل)[^.\n]{0,40}العجز|يحسب ضمن (?:ال)?حد (?:ال)?ادني[^.\n]{0,40}(?:التالي|القادم)/;

const RULE_TAKE_OR_PAY: OfficeRule = {
  id: 'take_or_pay_minimum',
  families: ['services', 'sale', 'agency', 'licence'],
  excludeFamilies: ['employment', 'unknown'],
  protects: 'requester',
  enabled: true,
  severity: 'متوسط',
  title: 'حد أدنى إلزامى للشراء يُدفع ثمنه ولو لم تُستلم الكمية (take-or-pay)',
  explanation:
    'قاعدة المكتب: لا يُلتزم المشترى بدفع ثمن كميات لم يستلمها. وإن اتُّفق على حد أدنى فيُحدَّد بنسبة معقولة من الاحتياج المقدَّر، ويُعفى منه عند تقصير المورد أو القوة القاهرة، ' +
    'ولا يُرحَّل العجز إلى الأشهر التالية بثمنه كاملاً. ورد فى العقد التزام بحد أدنى للشراء مع دفع ثمنه كاملاً سواء استُلم أم لا (أو ترحيل العجز ودفع ثمنه)، ' +
    'فيتحمل المشترى كلفة بضاعة لم يحتجها ولم يستلمها.',
  suggestion: 'قصر الالتزام على الكميات التى صدرت بها أوامر توريد، أو تحديد حد أدنى معقول (مثل 50% من التقدير) مع إعفاء عند تقصير المورد، والنص على عدم ترحيل العجز أو على سداد التعويض عن الضرر الفعلى فقط.',
  provenance: 'مصدر القاعدة: مراجعة الدفعة الاصطناعية 2 (توريد أ بند 3، توريد ج بند 3) وقرار المالك فى الجولة 97؛ تحتاج عقوداً حقيقية لتأكيد تعميمها.',
  evaluate: (clauses) => firstPerClause(clauses, (n) => MIN_PURCHASE.test(n) && PAY_REGARDLESS.test(n)),
};

// ===================== 3) تعليق أو إنهاء أحادى فى أى وقت بتقدير طرف واحد =====================

const SUSPEND_VERB = '(?:انهاء[ء-ي]*|تعليق[ء-ي]*|ايقاف[ء-ي]*|وقف[ء-ي]*)';
const SUSPEND_OBJECT = '(?:التوريد|التوريدات|الخدمه|الخدمات|الاعمال|التنفيذ|الصرف|التمويل|العقد)';
const DISCRETION = /(?:في اي وقت|اذا راي|ما يراه|ما يري|حسب تقديره|بتقديره|وفق تقديره|براي[ءه-ي]*|وحده)/;
const SUSPEND_A = new RegExp(`(?:^|\\s)و?(?:ل|لل)${PARTY}\\s+(?:(?:ال)?[ء-ي]+\\s+){0,2}?${SUSPEND_VERB}\\s+${SUSPEND_OBJECT}`);
const SUSPEND_B = new RegExp(`(?:^|\\s)و?(?:ل|لل)${PARTY}\\s+(?:ان\\s+)?(?:ينهي|تنهي|يعلق|تعلق|يوقف|توقف)[ء-ي]*\\s+${SUSPEND_OBJECT}`);

const RULE_UNILATERAL_SUSPENSION: OfficeRule = {
  id: 'unilateral_suspension_or_termination',
  families: ['services', 'sale', 'finance', 'agency', 'licence'],
  excludeFamilies: ['employment', 'unknown'],
  protects: 'requester',
  enabled: true,
  severity: 'متوسط',
  title: 'حق تعليق التنفيذ أو إنهاء العقد لطرف واحد فى أى وقت بتقديره دون إنذار أو مهلة تصحيح',
  explanation:
    'قاعدة المكتب: لا يُعلَّق التوريد أو الخدمة أو التمويل ولا يُنهى العقد إلا عند إخلال جوهرى ثابت أو تأخر فى سداد مستحق غير متنازع عليه، وبعد إنذار كتابى ومهلة تصحيح معقولة، وبحق متبادل للطرفين. ' +
    'ورد فى العقد حق تعليق أو إنهاء لطرف واحد «فى أى وقت» أو «إذا رأى» أو بتقديره وحده، فيصير استمرار التزامات الطرف الآخر معلقاً على مشيئة خصمه.',
  suggestion: 'قصر التعليق على التأخر فى سداد مبلغ مستحق غير متنازع عليه بعد إنذار كتابى ومهلة لا تقل عن ثلاثين يوماً، وجعل حق الإنهاء متبادلاً عند الإخلال الجوهرى بعد مهلة تصحيح.',
  provenance: 'مصدر القاعدة: مراجعة الدفعة الاصطناعية 2 (توريد أ بند 11، توريد ج بند 11) وقرار المالك فى الجولة 97؛ تحتاج عقوداً حقيقية لتأكيد تعميمها.',
  evaluate: (clauses) =>
    firstPerClause(clauses, (n) => (SUSPEND_A.test(n) || SUSPEND_B.test(n)) && DISCRETION.test(n) && !MUTUAL.test(n) && !CURE_OR_NOTICE.test(n)),
};

// ===================== 4) حلول الأجل أو المطالبة بكامل القرض بتقدير المقرض أو دون إنذار =====================

const DEMAND_OR_ACCEL = /(?:يحل اجل|حلول اجل|تحل اجل|يستحق (?:ال)?سداد[^.\n]{0,20}فورا)|(?:ان|ل)\s*يطالب[^.\n]{0,40}(?:بسداد|بالسداد)\s+(?:كامل|كل|جميع)|(?:المطالبه|يطالب)[^.\n]{0,30}(?:بسداد|بالسداد)\s+(?:كامل|كل|جميع)/;
const LENDER_DISCRETION =
  /(?:في اي وقت|متي طلب|متي شاء|دون (?:ا)?نذار|بدون (?:ا)?نذار|بغير (?:ا)?نذار|حسب تقدير[ءه-ي]*|بتقدير[ءه-ي]*|وفق تقدير[ءه-ي]*|(?:اذا )?راي (?:ال)?(?:مقرض|ممول|بنك)[ء-ي]*(?: وحده)?|براي (?:ال)?(?:مقرض|ممول|بنك)|وحده)/;

const RULE_LENDER_ACCELERATION: OfficeRule = {
  id: 'lender_discretionary_acceleration',
  families: ['finance'],
  protects: 'requester',
  enabled: true,
  severity: 'متوسط',
  title: 'حلول أجل القرض أو المطالبة بكامله فى أى وقت أو بتقدير المقرض أو دون إنذار',
  explanation:
    'قاعدة المكتب: لا يحل أجل القرض ولا يُطالَب بكامله قبل ميعاده إلا لسبب محدد موضوعى (كالتأخر فى عدد محدد من الأقساط المتتالية أو إخلال جوهرى) وبعد إنذار كتابى ومهلة تصحيح، ' +
    'ولا يُترك لتقدير المقرض وحده أو لطلبه متى شاء. ورد فى العقد حلول أجل أو مطالبة بكامل المبلغ بتقدير المقرض أو فى أى وقت أو دون إنذار، فتنتفى مدة القرض وجدول السداد المتفق عليهما عملياً.',
  suggestion: 'حصر أسباب حلول الأجل فى التأخر عن ثلاثة أقساط متتالية أو الإخلال بالتزام جوهرى لم يُصحَّح خلال ثلاثين يوماً من إنذار كتابى، وحذف عبارات «فى أى وقت» و«بتقدير المقرض» و«دون إنذار».',
  provenance: 'مصدر القاعدة: مراجعة الدفعة الاصطناعية 2 (تمويل أ بنود 3 و6، تمويل ج بند 6) وقرار المالك فى الجولة 97؛ تحتاج عقوداً حقيقية لتأكيد تعميمها.',
  evaluate: (clauses) => firstPerClause(clauses, (n, clauseNorm) => DEMAND_OR_ACCEL.test(n) && LENDER_DISCRETION.test(n) && !CURE_OR_NOTICE.test(clauseNorm)),
};

export const R97_OFFICE_RULES: OfficeRule[] = [RULE_LONG_EXCLUSIVE_PURCHASE, RULE_TAKE_OR_PAY, RULE_UNILATERAL_SUSPENSION, RULE_LENDER_ACCELERATION];
