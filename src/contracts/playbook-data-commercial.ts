/**
 * المطابقة تُجرَّب على الجملة كما هى وعلى الجملة بلا «ال» التعريف، فالنمط المنكَّر («معايير») يطابق «معايير» و«المعايير» معاً،
 * والنمط المعرَّف («المعايير») لا يطابق إلا الصيغة المعرَّفة نفسها. لذلك تُكتب أنماط هذه المحاور بأى صيغة ثم تُنكَّر هنا آلياً
 * (كلمة تبدأ بـ«ال» وما بعدها ثلاثة أحرف فأكثر؛ «الغير» مستثناة لأن «غير» كلمة شائعة بمعنى آخر). لا يمس هذا دوال الاختبار (test)،
 * فهى تُكتب منكَّرة يدوياً.
 */
function indefinite(re: RegExp): RegExp {
  const src = re.source.replace(/(^|[\s|(:?])ال(?=[\u0621-\u064a]{3})(?!غير)/g, '$1');
  return new RegExp(src, re.flags);
}

