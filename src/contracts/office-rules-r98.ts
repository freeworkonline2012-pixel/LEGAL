interface RuleSeed {
  id: string;
  families: OfficeRule['families'];
  title: string;
  explanation: string;
  suggestion: string;
  source: string;
  test: (n: string, clauseNorm: string) => boolean;
}

function mk(seed: RuleSeed): OfficeRule {
  return {
    id: seed.id,
    families: seed.families,
    excludeFamilies: ['employment', 'unknown'],
    protects: 'requester',
    enabled: true,
    severity: 'متوسط',
    title: seed.title,
    explanation: seed.explanation,
    suggestion: seed.suggestion,
    provenance: `مصدر القاعدة: مراجعة الدفعة الاصطناعية 2 (${seed.source}) وقرار المالك فى الجولة 98؛ تحتاج عقوداً حقيقية لتأكيد تعميمها.`,
    evaluate: (clauses) => firstPerClause(clauses, seed.test),
  };
}

