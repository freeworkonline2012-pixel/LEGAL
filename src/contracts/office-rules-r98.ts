import { firstPerClause, type OfficeRule } from './office-rules-kit';

/**
 * قواعد المكتب لعقد الإيجار المضافة فى الجولة 98 (بموافقة المالك، من مراجعة إعادة الاثنى عشر عقداً: إيجار أ التقط 4 من 13 فقط لأن بقية بنوده اختلالات تجارية بلا مادة منطبقة).
 * كلها قواعد حتمية بالاقتباس الحرفى، بلا مادة قانونية، وتُعرض «ممارسة تعاقدية للمكتب لا نصاً قانونياً». درجتها «متوسط» عمداً: اختلال تجارى لا مخالفة نص آمر،
 * فلا ترفع مستوى المخاطرة العام وحدها. الأنماط مكتوبة على النص الموحَّد (ى→ي، ة→ه، حذف الهمزات وعلامة %، والأرقام باقية).
 */

const LESSOR = '(?:ال)?مؤجر[ء-ي]*';
