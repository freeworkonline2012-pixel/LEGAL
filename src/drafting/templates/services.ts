/**
 * قالب «عقد خدمات»: مقدم خدمة (الطرف الأول) وعميل (الطرف الثانى).
 * الصياغة متوازنة عمداً (لا تميل لطرف)، وكل حد رقمى يأتى من إجابة المستخدم ويُتحقق من حدوده فى الكتالوج.
 */

import { lam, countPhrase, endOfTerm, formatDate, groupDigits, moneyPhrase, percent } from '../drafting-text';
import type { ClauseDef, Ctx, TemplateOutput } from '../drafting.types';
import { closingLines, commonLawyerNotes, disputesClause, generalClause, noticesClause, preambleLines, type Labels } from './common';

const LABELS: Labels = { first: 'مقدم الخدمة', second: 'العميل' };

function round2(n: number): number {
  return Math.round(n * 100) / 100;
}

/** جدول الدفعات: [وصف، المبلغ] بحيث يساوى مجموعها الإجمالى تماماً (الباقى فى آخر دفعة). */
export function paymentSchedule(v: Record<string, string>): Array<{ label: string; amount: number }> {
  const total = Number(v.price_total);
  if (v.payment_plan === 'advance_balance') {
    const advance = round2((total * Number(v.advance_percent)) / 100);
    return [
      { label: `دفعة مقدمة تمثل ${percent(Number(v.advance_percent))} من إجمالى المقابل، تُسدد خلال المهلة المبينة فى الفقرة (2) من هذا البند بعد توقيع هذا العقد`, amount: advance },
      { label: 'الباقى عند القبول النهائى لكل المخرجات', amount: round2(total - advance) },
    ];
  }
  if (v.payment_plan === 'three_stage') {
    const a = round2((total * Number(v.advance_percent_3)) / 100);
    const m = round2((total * Number(v.middle_percent)) / 100);
    return [
      { label: `دفعة مقدمة تمثل ${percent(Number(v.advance_percent_3))} من إجمالى المقابل، تُسدد خلال المهلة المبينة فى الفقرة (2) من هذا البند بعد توقيع هذا العقد`, amount: a },
      { label: `دفعة تمثل ${percent(Number(v.middle_percent))} من إجمالى المقابل عند التسليم المرحلى للمخرجات الجوهرية`, amount: m },
      { label: 'الباقى عند القبول النهائى لكل المخرجات', amount: round2(total - a - m) },
    ];
  }
  const months = Number(v.duration_months);
  const each = round2(total / months);
  const last = round2(total - each * (months - 1));
  const rows = [{ label: `${months === 1 ? 'قسط واحد' : `${months} أقساط شهرية`} ${months === 1 ? '' : 'متساوية'}`.trim(), amount: each }];
  if (months > 1 && last !== each) rows.push({ label: 'القسط الأخير (يشمل فروق التقريب)', amount: last });
  return rows;
}

