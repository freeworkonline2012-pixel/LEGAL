/**
 * بنود مشتركة بين كل أنواع العقود (ديباجة، إخطارات، قانون واجب وتسوية منازعات، أحكام عامة، ختام).
 * النصوص ثابتة ومحكَّمة؛ المتغير فقط ما يدخله المستخدم أو يُشتق من إجاباته.
 */

import type { ClauseDef, Ctx } from '../drafting.types';
import { dayAndDate } from '../drafting-text';

export interface Labels {
  /** تسمية الطرف الأول: «مقدم الخدمة» */
  first: string;
  /** تسمية الطرف الثانى: «العميل» */
  second: string;
}

function partyLine(order: 'أولاً' | 'ثانياً', name: string, rep: string | undefined, address: string, label: string, ordinal: 'الأول' | 'الثانى'): string {
  const who = rep ? `${name} (الممثل فى هذا العقد: ${rep})` : name;
  const alias = label === `الطرف ${ordinal}` ? `«${label}»` : `«${label}» أو «الطرف ${ordinal}»`;
  return `${order}: ${who}. العنوان المختار: ${address}. (ويُسمى فيما بعد ${alias}).`;
}

/** الديباجة: التاريخ والأطراف وإقرار الأهلية. */
export function preambleLines(v: Record<string, string>, labels: Labels, subjectLine: string): string[] {
  return [
    `إنه فى ${dayAndDate(v.contract_date)} تم الاتفاق والتراضى بين كل من:`,
    partyLine('أولاً', v.party1_name, v.party1_rep, v.party1_address, labels.first, 'الأول'),
    partyLine('ثانياً', v.party2_name, v.party2_rep, v.party2_address, labels.second, 'الثانى'),
    subjectLine,
    'وقد أقر كل من الطرفين بأهليته القانونية للتعاقد، وبأن من وقّع عنه مفوض بذلك، واتفقا على ما يلى، ويُعد التمهيد السابق جزءاً لا يتجزأ من هذا العقد.',
  ];
}

export function noticesClause(labels: Labels): ClauseDef {
  return {
    key: 'notices',
    title: 'الإخطارات والعناوين المختارة',
    paragraphs: () => [
      `(1) يتخذ كل طرف العنوان المبين بصدر هذا العقد موطناً مختاراً له، وتكون كل الإخطارات والمراسلات المتعلقة بالعقد صحيحة ومنتجة لآثارها متى وُجهت إليه على هذا العنوان.`,
      `(2) يتم الإخطار كتابة، إما بالتسليم باليد مقابل توقيع المستلم، أو بخطاب مسجل بعلم الوصول، أو بشركة شحن معتمدة بإيصال استلام. ويُعتبر الإخطار قد تم فى تاريخ التسليم الثابت بالإيصال أو بعلم الوصول.`,
      `(3) إذا غيّر أى من ${labels.first} أو ${labels.second} عنوانه وجب عليه إخطار الطرف الآخر بالعنوان الجديد كتابة، وإلا ظل العنوان القديم منتجاً لآثاره.`,
    ],
  };
}

export function disputesClause(v: Record<string, string>): ClauseDef {
  const city = v.forum_city;
  return {
    key: 'disputes',
    title: 'القانون الواجب التطبيق وتسوية المنازعات',
    paragraphs: () => {
      const lines = ['(1) يخضع هذا العقد ويفسر وفقاً لأحكام القانون المصرى.'];
      if (v.forum === 'arbitration') {
        lines.push(
          '(2) يسعى الطرفان أولاً إلى حل أى نزاع ينشأ عن هذا العقد أو يتعلق به ودياً خلال 30 (ثلاثين) يوماً من إخطار أحدهما الآخر كتابة بوجود النزاع.',
          `(3) إذا لم يُحل النزاع ودياً خلال تلك المدة، يُحال إلى التحكيم وفقاً لأحكام قانون التحكيم فى المواد المدنية والتجارية رقم 27 لسنة 1994، أمام هيئة مكونة من ثلاثة محكمين، يعين كل طرف محكماً ويتفق المحكمان على المحكم الثالث رئيساً للهيئة. ويكون مقر التحكيم مدينة ${city}، ولغته العربية، ويفصل المحكمون فى النزاع وفق القانون المصرى.`,
          '(4) يكون حكم هيئة التحكيم نهائياً وملزماً للطرفين وفقاً للقانون، ولا يمنع هذا الشرط أى طرف من اللجوء إلى القضاء المختص لاستصدار أمر وقتى أو تحفظى.',
        );
      } else {
        lines.push(
          '(2) يسعى الطرفان أولاً إلى حل أى نزاع ينشأ عن هذا العقد أو يتعلق به ودياً خلال 30 (ثلاثين) يوماً من إخطار أحدهما الآخر كتابة بوجود النزاع.',
          `(3) إذا لم يُحل النزاع ودياً خلال تلك المدة، تختص به محاكم ${city} دون غيرها، ما لم تقض قواعد الاختصاص الآمرة بغير ذلك.`,
        );
      }
      return lines;
    },
  };
}

export function generalClause(): ClauseDef {
  return {
    key: 'general',
    title: 'أحكام عامة',
    paragraphs: (c: Ctx) => {
      void c;
      return [
        '(1) يمثل هذا العقد الاتفاق الكامل بين الطرفين بشأن موضوعه، ويلغى كل تفاهم أو مراسلة أو عرض سابق عليه فى الموضوع نفسه.',
        '(2) لا يجوز تعديل أى حكم من أحكام هذا العقد إلا بمحرر مكتوب موقع من الطرفين.',
        '(3) لا يجوز لأى طرف التنازل عن حقوقه أو التزاماته الناشئة عن هذا العقد للغير إلا بموافقة كتابية مسبقة من الطرف الآخر.',
        '(4) إذا حُكم ببطلان أى حكم من أحكام هذا العقد أو عدم نفاذه، ظلت بقية الأحكام صحيحة ونافذة.',
        '(5) تسامح أى طرف فى المطالبة بحق من حقوقه لا يعتبر تنازلاً عنه.',
        '(6) حُرر هذا العقد من نسختين أصليتين، تسلم كل طرف نسخة للعمل بموجبها.',
      ];
    },
  };
}

export function closingLines(v: Record<string, string>, labels: Labels): string[] {
  return [
    `الطرف الأول (${labels.first}): ${v.party1_name}${v.party1_rep ? ` — الممثل: ${v.party1_rep}` : ''}    التوقيع:`,
    `الطرف الثانى (${labels.second}): ${v.party2_name}${v.party2_rep ? ` — الممثل: ${v.party2_rep}` : ''}    التوقيع:`,
  ];
}

/** ملاحظات المراجعة العامة (ليست من نص العقد). */
