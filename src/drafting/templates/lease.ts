/**
 * قالب «عقد إيجار»: مؤجر (الطرف الأول) ومستأجر (الطرف الثانى). صياغة متوازنة.
 * لا تُذكر مواد قوانين الإيجار عمداً: تطبيقها يتوقف على تاريخ العقد ونوع العين، فيُترك لمراجعة المحامى (انظر ملاحظات المراجعة).
 */

import { lam, countPhrase, endOfTerm, formatDate, moneyPhrase, percent } from '../drafting-text';
import type { ClauseDef, Ctx, TemplateOutput } from '../drafting.types';
import { closingLines, commonLawyerNotes, disputesClause, generalClause, noticesClause, preambleLines, type Labels } from './common';

const LABELS: Labels = { first: 'المؤجر', second: 'المستأجر' };

const PURPOSE: Record<string, string> = {
  residential: 'السكنى',
  commercial: 'التجارى',
  administrative: 'الإدارى (المكتبى)',
};
const PERIOD_MONTHS: Record<string, number> = { monthly: 1, quarterly: 3, annual: 12 };
const PERIOD_LABEL: Record<string, string> = { monthly: 'شهرى', quarterly: 'ربع سنوى', annual: 'سنوى' };

export function buildLease(role: string, v: Record<string, string>): TemplateOutput {
  void role;
  const months = Number(v.duration_months);
  const end = endOfTerm(v.start_date, months);
  const rent = Number(v.rent_amount);
  const deposit = Number(v.deposit_amount);
  const increase = Number(v.annual_increase);
  const earlyDays = Number(v.early_termination_days);
  const periodMonths = PERIOD_MONTHS[v.rent_period];
  const periods = months / periodMonths;
  const advance = v.rent_in_advance === 'yes';

  const clauses: ClauseDef[] = [
    {
      key: 'subject',
      title: 'موضوع العقد والعين المؤجرة',
      paragraphs: () => [
        `(1) أجّر ${LABELS.first} ${lam(LABELS.second)}، واستأجر الأخير منه، العين الموصوفة فيما يلى: ${v.property_description}، الكائنة فى: ${v.property_address} (ويشار إليها فيما بعد بـ«العين المؤجرة»).`,
        `(2) يقر ${LABELS.first} بأن له صفة التأجير بموجب ${v.ownership_basis}، وبأن العين المؤجرة خالية من أى حق للغير يمنع انتفاع ${LABELS.second} بها، ويضمن له التعرض الصادر منه أو من الغير المستند إلى حق سابق على هذا العقد.`,
      ],
    },
    {
      key: 'use',
      title: 'الغرض من الاستعمال والتأجير من الباطن',
      paragraphs: () => [
        `(1) خُصصت العين المؤجرة للاستعمال ${PURPOSE[v.use_purpose]} وحده، ولا يجوز ${lam(LABELS.second)} تغيير هذا الغرض إلا بموافقة كتابية مسبقة من ${LABELS.first}.`,
        v.sublet === 'permitted_notice'
          ? `(2) يجوز ${lam(LABELS.second)} تأجير العين المؤجرة كلها أو بعضها من الباطن أو النزول عن الإيجار للغير بعد إخطار ${LABELS.first} كتابة قبل التأجير أو النزول بمدة معقولة، بشرط ألا يتغير الغرض المبين فى هذا البند وألا تجاوز مدة التأجير من الباطن مدة هذا العقد، ويبقى ${LABELS.second} مسئولاً قبل ${LABELS.first} عن تنفيذ التزامات هذا العقد.`
          : v.sublet === 'prohibited'
          ? `(2) لا يجوز ${lam(LABELS.second)} تأجير العين المؤجرة كلها أو بعضها من الباطن، ولا النزول عن الإيجار للغير، ولا إشراك الغير فى الانتفاع بها.`
          : `(2) لا يجوز ${lam(LABELS.second)} تأجير العين المؤجرة كلها أو بعضها من الباطن أو النزول عن الإيجار للغير إلا بموافقة كتابية مسبقة من ${LABELS.first}، ويبقى ${LABELS.second} مسئولاً قبله عن تنفيذ التزامات هذا العقد.`,
      ],
    },
    {
      key: 'term',
      title: 'مدة الإيجار',
      paragraphs: () => [
        `(1) مدة هذا العقد ${countPhrase(months, 'month')}، تبدأ فى ${formatDate(v.start_date)} وتنتهى فى ${formatDate(end)}.`,
        '(2) ينتهى العقد بانتهاء مدته المحددة، ولا يتجدد إلا باتفاق كتابى جديد بين الطرفين، مع مراعاة ما تقضى به القواعد القانونية الآمرة التى تحكم العلاقة الإيجارية.',
        earlyDays > 0
          ? `(3) يجوز ${lam(LABELS.second)} إنهاء العقد قبل انتهاء مدته بإخطار كتابى يوجهه إلى ${LABELS.first} قبل الإنهاء بمدة ${countPhrase(earlyDays, 'day')}، على أن يسدد الأجرة المستحقة حتى تاريخ الإنهاء وأن يرد العين المؤجرة وفق أحكام هذا العقد.`
          : `(3) لا يجوز ${lam(LABELS.second)} إنهاء العقد قبل انتهاء مدته إلا باتفاق كتابى مع ${LABELS.first} أو وفق أحكام الفسخ المبينة فيه.`,
      ],
    },
    {
      key: 'rent',
      title: 'الأجرة وطريقة السداد',
      paragraphs: (c: Ctx) => [
        `(1) الأجرة ${PERIOD_LABEL[v.rent_period]} قدرها ${moneyPhrase(rent)} عن كل فترة، وعدد الفترات خلال مدة العقد ${periods} (${PERIOD_LABEL[v.rent_period]})، وتسدد ${advance ? 'مقدماً فى أول كل فترة' : 'فى آخر كل فترة'}.`,
        `(2) يسدد ${LABELS.second} الأجرة بتحويل بنكى إلى الحساب البنكى الذى يخطره به ${LABELS.first} كتابة أو بإيصال استلام موقع من ${LABELS.first}، ولا يُعتد بأى سداد لا يثبت بإحدى هاتين الوسيلتين.`,
        increase > 0
          ? `(3) تُزاد الأجرة بنسبة ${percent(increase)} من الأجرة السارية فى بداية كل سنة إيجارية تالية للسنة الأولى، بما لا يخالف القواعد القانونية الآمرة بشأن زيادة الأجرة.`
          : '(3) تبقى الأجرة ثابتة طوال مدة هذا العقد ولا تزاد إلا باتفاق كتابى بين الطرفين.',
        `(4) يترتب على التأخر فى سداد الأجرة ما هو مبين فى ${c.ref('default')}.`,
      ],
    },
    {
      key: 'deposit',
      title: 'التأمين ورده',
      paragraphs: () =>
        deposit > 0
          ? [
              `(1) سلّم ${LABELS.second} إلى ${LABELS.first} عند توقيع هذا العقد مبلغ تأمين قدره ${moneyPhrase(deposit)} لضمان تنفيذ التزاماته، ويقر ${LABELS.first} باستلامه بتوقيعه على هذا العقد.`,
              '(2) لا يحتسب مبلغ التأمين من الأجرة أثناء مدة العقد ولا يُنتج فائدة.',
              `(3) يرد ${LABELS.first} مبلغ التأمين إلى ${LABELS.second} خلال ${countPhrase(30, 'day')} من تاريخ رد العين المؤجرة وانتهاء العقد، بعد خصم ما يثبت استحقاقه من أجرة غير مسددة أو من تلفيات تجاوز الاستعمال المعتاد، ويقدم بياناً كتابياً بما خصمه وسببه.`,
            ]
          : [`(1) لا يلتزم ${LABELS.second} بسداد مبلغ تأمين لضمان تنفيذ التزاماته بموجب هذا العقد، ولا يُستحق على أى طرف تأمين أو وديعة بمناسبته.`],
    },
    {
      key: 'handover',
      title: 'تسليم العين المؤجرة وحالتها',
      paragraphs: () => [
        `(1) يسلم ${LABELS.first} العين المؤجرة إلى ${LABELS.second} فى تاريخ بدء المدة خالية من الأشخاص والأشياء، فى حالة جيدة صالحة للانتفاع بها فى الغرض المخصصة له.`,
        `(2) يحرر الطرفان عند التسليم محضر استلام موقعاً منهما يثبت حالة العين المؤجرة ومشتملاتها وقراءات العدادات، ويعتبر ${LABELS.second} مستلماً لها بالحالة المثبتة به.`,
      ],
    },
    {
      key: 'maintenance',
      title: 'الصيانة والإصلاحات والمرافق',
      paragraphs: () => [
        `(1) يتحمل ${LABELS.first} أعمال الصيانة والإصلاحات الجوهرية والإنشائية اللازمة للإبقاء على العين المؤجرة صالحة للانتفاع بها، ويقوم بها بعد إخطاره كتابة بالحاجة إليها وخلال مدة معقولة.`,
        `(2) يتحمل ${LABELS.second} أعمال الصيانة الدورية والإصلاحات الصغيرة المعتادة الناشئة عن الاستعمال، وكل تلف ينشأ عن خطئه أو عن سوء استعماله أو استعمال من يسأل عنهم.`,
        `(3) يتحمل ${LABELS.second} قيمة استهلاكه من المياه والكهرباء والغاز والاتصالات وغيرها من المرافق طوال مدة العقد، ويسدد ${LABELS.first} ما يتعلق بالعين المؤجرة من ضرائب ورسوم عقارية تفرض على المالك.`,
      ],
    },
    {
      key: 'duties',
      title: 'التزامات المستأجر الأخرى',
      paragraphs: () => [
        `(1) يلتزم ${LABELS.second} بالمحافظة على العين المؤجرة واستعمالها بعناية الشخص المعتاد، وألا يُحدث بها تغييراً أو إضافة جوهرية إلا بموافقة كتابية مسبقة من ${LABELS.first}.`,
        `(2) يمكّن ${LABELS.second} ${LABELS.first} من معاينة العين المؤجرة فى مواعيد مناسبة بعد إخطاره بها قبل المعاينة بمدة معقولة، وفى أى وقت فى حالة الضرورة العاجلة.`,
      ],
    },
    {
      key: 'default',
      title: 'التأخر فى السداد والفسخ',
      paragraphs: () => [
        `(1) إذا تأخر ${LABELS.second} عن سداد أى أجرة بعد انقضاء ${countPhrase(Number(v.rent_grace_days), 'day')} من تاريخ استحقاقها، وجه إليه ${LABELS.first} إخطاراً كتابياً بالسداد خلال ${countPhrase(15, 'day')} من تسلمه.`,
        `(2) إذا لم يسدد ${LABELS.second} خلال المهلة الواردة بالإخطار، جاز ${lam(LABELS.first)} طلب فسخ العقد وطلب الإخلاء بالطريق القانونى، مع حقه فى المطالبة بالأجرة المستحقة حتى تاريخ الرد.`,
        `(3) إذا أخل أى من الطرفين بأى التزام جوهرى آخر ولم يتداركه خلال ${countPhrase(15, 'day')} من تسلمه إخطاراً كتابياً بالإخلال، جاز للطرف الآخر طلب فسخ العقد مع التعويض إن كان له مقتضى.`,
        '(4) لا يترتب على التأخر فى سداد الأجرة أى فوائد أو غرامات إضافية غير ما ورد فى هذا البند.',
      ],
    },
    {
      key: 'return',
      title: 'رد العين المؤجرة عند انتهاء العقد',
      paragraphs: () => [
        `(1) يرد ${LABELS.second} العين المؤجرة إلى ${LABELS.first} فور انتهاء العقد أو فسخه، خالية من الأشخاص والأشياء، بالحالة التى تسلمها بها حسب محضر الاستلام، فيما عدا ما ينشأ عن الاستعمال المعتاد.`,
        '(2) يحرر الطرفان عند الرد محضراً موقعاً منهما، وإذا امتنع أحدهما عن الحضور أو التوقيع جاز للآخر إثبات الحالة بإنذار رسمى أو بأى طريق قانونى.',
      ],
    },
    noticesClause(LABELS),
    disputesClause(v),
    generalClause(),
  ];

  const notes = [
    ...commonLawyerNotes(v),
    'قوانين الإيجار: ما يترتب على انتهاء مدة العقد (الامتداد القانونى من عدمه) وحدود زيادة الأجرة يتوقفان على القانون الذى يحكم العلاقة الإيجارية (بحسب تاريخ التعاقد ونوع العين سكنى أو غير سكنى) والتعديلات التى تطرأ عليه؛ هذه المسودة لم تحسم ذلك، فتحقق منه مع محاميك قبل التوقيع.',
    'تحقق من سند ملكية المؤجر بمستند رسمى حديث (عقد مسجل أو شهادة من الشهر العقارى)، وأرفق صورته بنسختك.',
    `الأجرة ${moneyPhrase(rent)} عن كل فترة (${PERIOD_LABEL[v.rent_period]}): راجع التزامات الضريبة العقارية وأى ضريبة دمغة أو تسجيل أو توثيق تتعلق بنوع عقدك.`,
  ];

  return {
    title: 'عقد إيجار',
    contractTypePhrase: 'عقد إيجار',
    preamble: preambleLines(v, LABELS, `وحيث إن ${LABELS.first} يرغب فى تأجير العين الموصوفة فى هذا العقد، وإن ${LABELS.second} يرغب فى استئجارها.`),
    clauses,
    closing: closingLines(v, LABELS),
    lawyerNotes: notes,
  };
}
