/**
 * قالب «اتفاقية عدم إفصاح وسرية»: من طرف واحد أو متبادلة.
 */

import { countPhrase, endOfTerm, formatDate, moneyPhrase } from '../drafting-text';
import type { ClauseDef, Ctx, TemplateOutput } from '../drafting.types';
import { closingLines, commonLawyerNotes, disputesClause, generalClause, noticesClause, preambleLines, type Labels } from './common';

export function buildNda(role: string, v: Record<string, string>): TemplateOutput {
  void role;
  const mutual = v.direction === 'mutual';
  const labels: Labels = mutual ? { first: 'الطرف الأول', second: 'الطرف الثانى' } : { first: 'الطرف المفصح', second: 'الطرف المتلقى' };
  const end = endOfTerm(v.start_date, Number(v.term_months));
  const compensation = Number(v.agreed_compensation);

  const clauses: ClauseDef[] = [
    {
      key: 'definitions',
      title: 'التعريفات وتحديد المعلومات السرية',
      paragraphs: () => [
        mutual
          ? '(1) يُقصد بـ«الطرف المفصح» الطرف الذى يفصح عن معلومات سرية للطرف الآخر، وبـ«الطرف المتلقى» الطرف الذى يتلقاها، ويجوز أن يكون كل من الطرفين مفصحاً ومتلقياً بحسب الحال.'
          : `(1) يُقصد بـ«الطرف المفصح» ${v.party1_name}، وبـ«الطرف المتلقى» ${v.party2_name}.`,
        `(2) المعلومات السرية هى كل معلومة أو بيان أو مستند غير متاح للعامة يفصح عنه الطرف المفصح للطرف المتلقى بمناسبة الغرض المبين فى البند التالى، أياً كانت صورته (مكتوبة أو شفاهية أو إلكترونية أو مرئية)، وسواء وُسمت بأنها سرية أو لم توسم متى كانت طبيعتها أو ظروف الإفصاح تدل على سريتها، وتشمل على سبيل المثال المعلومات التجارية والمالية والفنية وقوائم العملاء والخطط والأكواد المصدرية والتصاميم.`,
      ],
    },
    {
      key: 'purpose',
      title: 'الغرض من الإفصاح',
      paragraphs: () => [
        `(1) يفصح ${mutual ? 'كل من الطرفين للآخر' : 'الطرف المفصح للطرف المتلقى'} عن المعلومات السرية لغرض واحد هو: ${v.purpose} (ويشار إليه فيما بعد بالغرض).`,
        '(2) لا يجوز للطرف المتلقى استعمال المعلومات السرية فى أى غرض آخر، ولا يترتب على الإفصاح أى التزام على أى طرف بإتمام تعاقد أو تعاون بينهما.',
      ],
    },
    {
      key: 'obligations',
      title: 'التزامات الطرف المتلقى',
      paragraphs: () => [
        '(1) يلتزم الطرف المتلقى بالمحافظة على سرية المعلومات السرية وبذل العناية نفسها التى يبذلها فى حماية معلوماته السرية الخاصة، على ألا تقل عن عناية الشخص المعتاد.',
        '(2) لا يجوز للطرف المتلقى إفشاء المعلومات السرية لأى شخص، إلا لمن يحتاج إليها من العاملين لديه أو مستشاريه المهنيين لتحقيق الغرض، بشرط أن يكونوا ملتزمين بالسرية بما لا يقل عن التزامات هذه الاتفاقية، ويكون الطرف المتلقى مسئولاً عن أى إخلال منهم.',
        '(3) لا يجوز للطرف المتلقى نسخ المعلومات السرية أو تحليلها هندسياً أو تفكيكها إلا بالقدر اللازم للغرض.',
        '(4) يخطر الطرف المتلقى الطرف المفصح كتابة فور علمه بأى إفشاء أو استعمال غير مصرح به للمعلومات السرية، ويتعاون فى الحد من آثاره.',
      ],
    },
    {
      key: 'exceptions',
      title: 'استثناءات من السرية',
      paragraphs: () => [
        '(1) تستثنى من نطاق السرية المعلومات التى يثبت الطرف المتلقى أنها:',
        '- كانت معلومات عامة متاحة للجمهور وقت الإفصاح أو أصبحت متاحة للجمهور دون إخلال منه بهذه الاتفاقية؛ أو',
        '- كانت فى حوزته بصورة مشروعة قبل إفصاح الطرف المفصح بها؛ أو',
        '- وصلت إليه من الغير بصورة مشروعة دون التزام بالسرية؛ أو',
        '- توصل إليها بصورة مستقلة دون استعمال المعلومات السرية.',
        '(2) إذا طُلب من الطرف المتلقى الإفصاح عن معلومات سرية بموجب أمر قضائى أو حكم أو قانون، فله الإفصاح بالقدر المطلوب فقط بعد إخطار الطرف المفصح كتابة فى أقرب وقت ممكن ليتخذ ما يراه من إجراءات حماية.',
      ],
    },
    {
      key: 'term',
      title: 'مدة الاتفاقية ومدة الالتزام بالسرية',
      paragraphs: (c: Ctx) => [
        `(1) تسرى هذه الاتفاقية اعتباراً من ${formatDate(v.start_date)} ولمدة ${countPhrase(Number(v.term_months), 'month')} تنتهى فى ${formatDate(end)}، وهى مدة الإفصاح، ما لم تنته قبل ذلك وفق ${c.ref('termination')}.`,
        `(2) يستمر التزام الطرف المتلقى بالسرية بعد انتهاء هذه الاتفاقية لأى سبب لمدة ${countPhrase(Number(v.confidentiality_years), 'year')} تبدأ من تاريخ انتهائها.`,
      ],
    },
    {
      key: 'return',
      title: 'رد المعلومات أو إتلافها',
      paragraphs: () => [
        `(1) يلتزم الطرف المتلقى، خلال ${countPhrase(Number(v.return_days), 'day')} من طلب الطرف المفصح كتابة أو من انتهاء هذه الاتفاقية، بأن يرد كل مستند أو وسيط يحوى معلومات سرية أو أن يتلفه نهائياً، بحسب اختيار الطرف المفصح.`,
        '(2) يقدم الطرف المتلقى عند الطلب إقراراً كتابياً بتمام الرد أو الإتلاف، على أنه يجوز له الاحتفاظ بنسخة واحدة فقط بالقدر الذى تفرضه عليه القوانين أو اللوائح، مع بقائها خاضعة للسرية.',
      ],
    },
    {
      key: 'remedy',
      title: 'جزاء الإخلال بالسرية',
      paragraphs: () => [
        '(1) يقر الطرف المتلقى بأن الإخلال بهذه الاتفاقية قد يُلحق بالطرف المفصح ضرراً يصعب جبره بالتعويض وحده، وللطرف المفصح فضلاً عن حقه فى التعويض أن يلجأ إلى القضاء المستعجل لاتخاذ ما يلزم من إجراءات وقتية أو تحفظية لمنع الإفشاء أو وقفه.',
        compensation > 0
          ? `(2) اتفق الطرفان على تعويض اتفاقى قدره ${moneyPhrase(compensation)} عن كل إخلال ثابت بالتزامات السرية، وذلك دون الإخلال بحق الطرف المفصح فى المطالبة بتعويض أكبر إذا أثبت أن الضرر الذى لحقه يجاوزه. ولا يستحق هذا التعويض إذا أثبت الطرف المتلقى أن الطرف المفصح لم يلحقه ضرر، وللقاضى أن يخفضه إذا أثبت أن التقدير كان مبالغاً فيه إلى درجة كبيرة.`
          : '(2) يكون التعويض عن الإخلال بالسرية وفق القواعد العامة فى المسئولية بقدر الضرر الذى يثبت أنه لحق بالطرف المفصح.',
        '(3) لا تسرى حدود المسئولية أو الإعفاء منها على الغش أو الخطأ الجسيم.',
      ],
    },
    {
      key: 'rights',
      title: 'ملكية المعلومات وعدم الترخيص',
      paragraphs: () => [
        '(1) تظل المعلومات السرية وكل ما يتعلق بها من حقوق ملكية فكرية مملوكة للطرف المفصح وحده، ولا يُعد الإفصاح عنها ترخيصاً أو منحاً لأى حق فيها للطرف المتلقى غير حق الاطلاع عليها للغرض.',
        '(2) تُقدَّم المعلومات السرية كما هى دون ضمان لدقتها أو اكتمالها، إلا ما يتفق عليه الطرفان كتابة فى اتفاق آخر.',
      ],
    },
    {
      key: 'termination',
      title: 'الإنهاء',
      paragraphs: () => [
        `(1) يجوز لأى من الطرفين إنهاء هذه الاتفاقية فى أى وقت بإخطار كتابى يوجهه إلى الطرف الآخر قبله بمدة ${countPhrase(30, 'day')}، ويكتفى فى هذه الحالة بوقف الإفصاح الجديد.`,
        '(2) لا يؤثر إنهاء الاتفاقية أو انتهاؤها على التزامات السرية والرد والإتلاف والجزاء، فتبقى سارية على المعلومات التى أُفصح عنها قبل الإنهاء طوال المدة المحددة لذلك.',
      ],
    },
    noticesClause(labels),
    disputesClause(v),
    generalClause(),
  ];

  const notes = [
    ...commonLawyerNotes(v),
    'عرّفت الاتفاقية المعلومات السرية بمعيار الطبيعة وظروف الإفصاح لا بالوسم وحده؛ إن أردت حصرها فى فئات بعينها فبيّنها لمحاميك.',
    compensation > 0
      ? `التعويض الاتفاقى (${moneyPhrase(compensation)}): للقاضى سلطة تخفيضه وبطلان أى اتفاق على خلاف ذلك (المادة 224 من القانون المدنى)، وقد صيغ البند محافظاً على ذلك.`
      : 'لم يُحدد تعويض اتفاقى: يُترك التعويض للقواعد العامة ويحتاج المضرور إلى إثبات الضرر؛ فكّر مع محاميك فى تحديد تعويض اتفاقى معقول.',
    'لا يجوز الإعفاء من المسئولية عن الغش أو الخطأ الجسيم (المادة 217 من القانون المدنى)، وقد استُثنيا صراحة فى بند الجزاء.',
  ];

  return {
    title: 'اتفاقية عدم إفصاح وسرية',
    contractTypePhrase: 'اتفاقية عدم إفصاح وسرية',
    preamble: preambleLines(
      v,
      labels,
      mutual
        ? 'وحيث إن الطرفين يرغبان فى تبادل معلومات سرية فيما بينهما لغرض مشروع، ويريدان تنظيم حمايتها.'
        : `وحيث إن ${labels.first} يرغب فى إطلاع ${labels.second} على معلومات سرية لغرض مشروع، ويريد تنظيم حمايتها.`,
    ),
    clauses,
    closing: closingLines(v, labels),
    lawyerNotes: notes,
  };
}
