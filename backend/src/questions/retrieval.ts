/**
 * ⚠️ بند P1 (2026-09-25، نفس التقرير أعلاه): كاشف محافظ عمداً (على غرار
 * isEndOfRelationshipTopic) — يتفعّل فقط حين يذكر نص السؤال صراحة أن العقد
 * غير محدد المدة (أو مرادفاً مباشراً كـ"دائم"/"مفتوح")، أو يصف تحديداً إنهاء
 * بلا إخطار أو بلا مبرر أو "تعسفياً" — لا كل سؤال عن نهاية علاقة عمل عموماً
 * (ذلك نطاق isEndOfRelationshipTopic الأوسع أعلاه، الذى يبقى بلا تغيير).
 * التبرير: تفعيل هذه الحزمة على كل سؤال "نهاية علاقة" حتى لو كان عن عقد
 * محدد المدة فقط بلا أى بُعد يتعلق بعقد غير محدد المدة يُضيف نداء DeepSeek
 * بلا فائدة متوقَّعة غالباً (قاعدة الكفاءة) ويوسّع السياق المُرسَل للتوليد
 * بلا داعٍ. الكاشف محافظ لتقليل الإيجابيات الكاذبة (نفس فلسفة وتحذيرات
 * isEndOfRelationshipTopic أعلاه) — قد يفوّت صياغات نادرة غير متوقَّعة، وهذا
 * مقبول لأن بوابة selectIndefiniteTerminationBundleArticles اللاحقة (فى
 * DeepseekGenerationService) هى خط الدفاع الحقيقى ضد الإدراج غير المبرَّر،
 * لا هذا الكاشف وحده.
 */
export function isIndefiniteContractTerminationTopic(text: string): boolean {
  const normalized = normalizeArabic(toEnglishDigits(text));
  // ⚠️ "تعسف" بجذرها فقط (لا "فصل تعسفى" مُركَّبة كما فى المحاولة الأولى):
  // اكتُشف من فشل اختبار وحدة حقيقى أن "تعسفياً" (لاحقة نصب بالألف الممدودة
  // + تنوين، لا ألف مقصورة "تعسفى" التى كانت مطابَقة فقط) لا تُطابَق حين
  // تُشتَرط ملاصقتها لكلمة "فصل" تحديداً — نفس درس \b لا يصلح للعربية
  // المُوثَّق فى isEndOfRelationshipTopic أعلاه، لكن هنا الحل أبسط: الجذر
  // "تعسف" نادر بما يكفى فى سياق قانون العمل ليكون إشارة قوية بذاته دون
  // اشتراط كلمة مجاورة محدَّدة (يغطى "تعسفى"/"تعسفياً"/"تعسفيا" كلها كسلسلة
  // فرعية واحدة).
  const pattern =
    /غير\s*محدده?\s*(?:ال)?مده|(?:عقد|علاقه)\s*(?:عمل\s*)?(?:دائم|مفتوح)|بلا\s*(?:ال)?اخطار|دون\s*(?:ال)?اخطار|بغير\s*(?:ال)?اخطار|مهله\s*(?:ال)?اخطار|تعسف|(?:بلا|دون|بغير)\s*مبرر|(?:بلا|دون|بغير)\s*سبب\s*مشروع/;
  return pattern.test(normalized);
}

export function detectCrossReferencedArticles(text: string, excludeArticleNo?: number): number[] {
  const normalized = normalizeArabic(toEnglishDigits(text));
  const found = new Set<number>();

  // "المادة"/"مادة" (مفردة) → بعد normalizeArabic تصبح "الماده"/"ماده"
  // (ة → ه). "المواد" (جمع) و"المادتين"/"مادتين" (مثنى) لا تحتويان ة فتبقيان
  // كما هما. الصيغ الأربع مجمَّعة هنا صراحة بدل الاعتماد على جذر مشترك —
  // الجمع "مواد" لا يشارك بادئة حرفية واحدة مع "ماده"/"مادتين" (ترتيب
  // الحروف مختلف: م-و-ا-د مقابل م-ا-د-...).
  const articleWord = '(?:المواد|مواد|المادتين|مادتين|الماده|ماده)';
  // ⚠️ إصلاح جذرى 2026-09-24 (اكتُشف من تحقيق حى مباشر بعد نشر هذه الدالة
  // بالفعل — لا تخميناً): المثال المحفِّز الأصلى لهذه الدالة نفسها (المادة
  // 154 من قانون العمل 14/2025، راجع تعليق الوحدة أعلاه) لا يزال يفشل حياً
  // فى الإنتاج رغم نشر الإصلاح — تحقَّق مباشرة (node -e ضد dist/ المبنية
  // فعلياً من نفس هذا الملف) أن detectCrossReferencedArticles ترجع [] على
  // النص الحقيقى المُخزَّن فى قاعدة البيانات لهذه المادة تحديداً: "...المواد
  // ) (٩٥، ۸۸، ۸۷من هذا القانون..." — الأقواس معكوسة الترتيب (") (" بدل
  // "(...)")، عطل استخراج نص شائع (على الأرجح تحويل bidi من مصدر PDF/RTL
  // أصلى) لا علاقة له بمنطق هذه الدالة. **هذا ليس عطلاً معزولاً فى مادة
  // واحدة**: بحث مباشر عبر كل ملفات migrations/*.sql (لا تخميناً) وجد **558
  // حالة مطابقة** لنمط "كلمة مادة/مواد متبوعة مباشرة بقوس معكوس" عبر عشرات
  // القوانين المختلفة — إصلاح المادة 154 فقط عبر migration مُفرد كان سيُصلح
  // حالة واحدة ظاهرة ويترك 557 حالة أخرى غير مكتشَفة بنفس العطل الصامت
  // (detectCrossReferencedArticles تفشل بصمت دائماً — لا خطأ يُرفَع، فلا توجد
  // وسيلة عملية لاكتشاف كل حالة يدوياً). الحل الجذرى الصحيح إذاً: تعميم
  // مقاومة الدالة لهذا النمط الشائع من عطل الاستخراج بدل تصحيح النص المصدر
  // حالة بحالة — [\\s:()]* (بدل [:(]؟ الأصلية) تستوعب أى مزيج من مسافات/نقطتين
  // رأسيتين/أقواس مفتوحة ومغلقة بأى ترتيب أو تكرار بين كلمة "مادة" وبداية
  // الأرقام، فتُطابق كلاً من الصيغة السليمة "(87، 88، 95)" والصيغة المعطوبة
  // ") (٩٥، ۸۸، ۸۷" على حد سواء. لا خطر تلفيق إضافى (نفس ضمان التعليق الأصلى
  // أعلاه: رقم غير موجود فعلياً كمادة يُتجاهَل بصمت عند استعلام DB اللاحق).
  const pattern = new RegExp(`${articleWord}[\\s:()]*((?:\\d+\\s*[،,و]?\\s*)+)`, 'g');

  for (const m of normalized.matchAll(pattern)) {
    const nums = m[1].match(/\d+/g) ?? [];
    for (const n of nums) {
      const parsed = Number.parseInt(n, 10);
      if (Number.isInteger(parsed) && parsed > 0) {
        found.add(parsed);
      }
    }
  }

  // ⚠️ P2 (2026-09-26 — إصلاح مؤجَّل من "تقرير تحليل شامل لفجوات إجابة
  // المنصة مقارنة بالمرجع 9.5"، بموافقة صريحة بترتيب الفجوات وحلها فوراً):
  // نمط إحالة إضافي بصيغة نطاق ("المواد من (158 إلى (175") لا يطابقه النمط
  // العام أعلاه، لأن كلمة "من" تفصل بين "المواد" وأول رقم فتكسر شرط
  // التلاصق المباشر [\s:()]* المطلوب هناك. مثال حقيقى متحقَّق منه مباشرة من
  // نص المادة 157 (قانون العمل 14/2025) المُخزَّن فعلياً فى migrations/003_
  // seed_real_laws.sql: "مع مراعاة أحكام المواد من (158 إلى (175" — القوسان
  // معكوسا الترتيب لنفس اضطراب bidi الموثَّق أعلاه، فلا يُعتمَد على شكل قوس
  // بعينه. بعد normalizeArabic تصبح "إلى" دائماً "الي" (إ→ا، ى→ي) فلا حاجة
  // لمطابقة بديل منفصل لصيغتها غير المُطبَّعة.
  //
  // الحل: نمط مستقل يطابق "من [رقم] ... الي [رقم]" صراحة، ثم يُوسَّع برمجياً
  // لكل الأعداد الصحيحة بين الطرفين شاملة (لا فقط الطرفين، كما كان سيحدث لو
  // مُرِّر النطاق للنمط العام أعلاه). حماية من عطل استخراج/تبديل أرقام
  // (bidi) يُنتج مدى ضخماً غير منطقى: أى مدى أكبر من MAX_RANGE_SPAN يُتجاهَل
  // بالكامل بدل توليد مئات الأرقام الوهمية — نفس فلسفة "لا تلفيق" الموثَّقة
  // أعلاه (رقم غير موجود فعلياً كمادة فى نفس القانون يُتجاهَل بصمت لاحقاً
  // عند استعلام DB الحتمى على أى حال، فلا خطر تلفيق حتى بلا هذا الحارس —
  // لكنه يمنع مئات استعلامات DB بلا فائدة فى حالة عطل استخراج نادرة).
  const MAX_RANGE_SPAN = 50;
  const rangePattern = new RegExp(
    `${articleWord}\\s*من\\s*[\\s:()]*([0-9]+)\\s*[\\s:()]*الي\\s*[\\s:()]*([0-9]+)`,
    'g',
  );

  for (const m of normalized.matchAll(rangePattern)) {
    const start = Number.parseInt(m[1], 10);
    const end = Number.parseInt(m[2], 10);
    if (
      Number.isInteger(start) &&
      Number.isInteger(end) &&
      start > 0 &&
      end >= start &&
      end - start < MAX_RANGE_SPAN
    ) {
      for (let n = start; n <= end; n += 1) {
        found.add(n);
      }
    }
  }

  if (excludeArticleNo) {
    found.delete(excludeArticleNo);
  }

  return Array.from(found)
    .sort((a, b) => a - b)
    .slice(0, MAX_CROSS_REFERENCE_ARTICLES);
}
